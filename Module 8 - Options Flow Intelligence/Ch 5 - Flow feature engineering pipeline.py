import numpy as np
import pandas as pd
from scipy import stats
from scipy.signal import savgol_filter
from sklearn.preprocessing import QuantileTransformer
from typing import Dict, List, Optional, Tuple
import warnings
warnings.filterwarnings('ignore')

class OptionsFlowFeatureEngine:
    """
    Industrial-strength feature engineering for options flow signals.

    Key design principles:
    1. No look-ahead bias: all features computed strictly from past data
    2. Regime-invariant: features normalized to be comparable across market states
    3. Greeks-aware: features weighted by option sensitivities
    4. Multi-timeframe: captures flow at multiple time horizons
    """

    # Lookback periods for multi-timeframe features (in days)
    LOOKBACKS = [1, 3, 5, 10, 21, 63]

    # EWM decay rates (half-life in days)
    EWM_HALFLIFES = [2, 5, 10, 21]

    def __init__(
        self,
        normalize: bool = True,
        winsorize_pct: float = 0.01
    ):
        self.normalize = normalize
        self.winsorize_pct = winsorize_pct
        self.qt = QuantileTransformer(output_distribution='normal', random_state=42)
        self.feature_names_: List[str] = []

    def compute_pcr_features(
        self,
        df_oi: pd.DataFrame,
        df_vol: pd.DataFrame
    ) -> pd.DataFrame:
        """
        Put-Call Ratio features: OI-based and volume-based,
        at multiple DTE bands.
        """
        features = pd.DataFrame(index=df_oi.index)

        # Total PCR
        puts_oi = df_oi[df_oi['option_type'] == 'P']['oi'].groupby(level='date').sum()
        calls_oi = df_oi[df_oi['option_type'] == 'C']['oi'].groupby(level='date').sum()
        features['pcr_oi'] = puts_oi / calls_oi.clip(lower=1)

        puts_vol = df_vol[df_vol['option_type'] == 'P']['volume'].groupby(level='date').sum()
        calls_vol = df_vol[df_vol['option_type'] == 'C']['volume'].groupby(level='date').sum()
        features['pcr_vol'] = puts_vol / calls_vol.clip(lower=1)

        # Normalize PCR (z-score relative to trailing 252-day window)
        for col in ['pcr_oi', 'pcr_vol']:
            rolling_mean = features[col].rolling(252, min_periods=63).mean()
            rolling_std = features[col].rolling(252, min_periods=63).std()
            features[f'{col}_zscore'] = (features[col] - rolling_mean) / rolling_std.clip(lower=1e-6)

        # PCR Momentum
        for lb in [5, 21]:
            features[f'pcr_vol_mom_{lb}d'] = features['pcr_vol'] - features['pcr_vol'].shift(lb)

        return features

    def compute_oi_features(
        self,
        df_oi: pd.DataFrame,
        df_spot: pd.DataFrame
    ) -> pd.DataFrame:
        """
        Open Interest change features: captures accumulation / distribution.
        """
        features = pd.DataFrame(index=df_spot.index)

        # Total OI
        total_oi = df_oi.groupby('date')['oi'].sum()
        features['total_oi'] = total_oi
        features['oi_change_1d'] = total_oi.diff(1)
        features['oi_change_5d'] = total_oi.diff(5)

        # OI vs Volume (distinguishing new positions vs turnover)
        total_vol = df_oi.groupby('date')['volume'].sum()
        features['oi_vol_ratio'] = total_oi / total_vol.clip(lower=1)

        # Net OI (calls - puts, signed by direction)
        call_oi = df_oi[df_oi['option_type'] == 'C'].groupby('date')['oi'].sum()
        put_oi = df_oi[df_oi['option_type'] == 'P'].groupby('date')['oi'].sum()
        features['net_oi_dir'] = call_oi - put_oi  # positive = more calls outstanding

        # Normalized OI change
        features['oi_change_norm'] = features['oi_change_1d'] / features['total_oi'].shift(1).clip(lower=1)

        return features

    def compute_gex_features(
        self,
        df_options: pd.DataFrame,
        spot_col: str = 'spot'
    ) -> pd.DataFrame:
        """
        Gamma Exposure features.
        Critical for understanding market-maker hedging flows and vol regimes.
        """
        features = pd.DataFrame(index=df_options.index.get_level_values('date').unique())

        # Compute GEX per contract: OI * Gamma * Spot^2 * 100
        df_options = df_options.copy()
        df_options['gex'] = (
            df_options['oi'] *
            df_options['gamma'] *
            df_options['spot'] ** 2 *
            100
        )

        # MMs are short what public is long (approximation)
        # For calls: MMs are short calls -> short gamma -> negative contribution
        # For puts: MMs are short puts -> short gamma -> negative contribution
        # When public is NET buyer of options, MMs have negative GEX
        df_options['mm_gex'] = np.where(
            df_options['net_customer_direction'] == 'BUY',
            -df_options['gex'],  # MMs are short
            +df_options['gex']   # MMs are long
        )

        total_gex = df_options.groupby('date')['mm_gex'].sum()
        features['gex'] = total_gex
        features['gex_norm'] = total_gex / total_gex.abs().rolling(63).mean().clip(lower=1e6)

        # GEX change
        features['gex_change_1d'] = features['gex'].diff(1)
        features['gex_ma5'] = features['gex'].rolling(5).mean()
        features['gex_regime'] = np.sign(features['gex'])  # +1 = long gamma = low vol regime

        return features

    def compute_iv_surface_features(
        self,
        df_iv: pd.DataFrame
    ) -> pd.DataFrame:
        """
        Implied volatility surface features derived from flow-driven IV changes.
        """
        features = pd.DataFrame(index=df_iv.index)

        # ATM IV levels and changes
        for tenor in ['1m', '3m', '6m', '1y']:
            col = f'atm_iv_{tenor}'
            if col in df_iv.columns:
                features[col] = df_iv[col]
                features[f'{col}_chg_1d'] = df_iv[col].diff(1)
                features[f'{col}_chg_5d'] = df_iv[col].diff(5)
                features[f'{col}_zscore'] = (
                    (df_iv[col] - df_iv[col].rolling(252).mean()) /
                    df_iv[col].rolling(252).std().clip(lower=1e-6)
                )

        # Skew features
        if all(c in df_iv.columns for c in ['put_iv_25d', 'call_iv_25d']):
            features['skew_25d'] = df_iv['put_iv_25d'] - df_iv['call_iv_25d']
            features['skew_25d_chg'] = features['skew_25d'].diff(1)
            features['skew_25d_ma10'] = features['skew_25d'].rolling(10).mean()

        # Term structure
        if all(c in df_iv.columns for c in ['atm_iv_1m', 'atm_iv_3m']):
            features['term_slope_1m3m'] = df_iv['atm_iv_3m'] - df_iv['atm_iv_1m']
            features['term_slope_chg'] = features['term_slope_1m3m'].diff(1)

        # IV rank and percentile
        for tenor in ['1m', '3m']:
            col = f'atm_iv_{tenor}'
            if col in df_iv.columns:
                rolling_max = df_iv[col].rolling(252).max()
                rolling_min = df_iv[col].rolling(252).min()
                features[f'iv_rank_{tenor}'] = (
                    (df_iv[col] - rolling_min) /
                    (rolling_max - rolling_min).clip(lower=1e-6)
                )

        return features

    def compute_flow_imbalance_features(
        self,
        df_trades: pd.DataFrame,
        direction_col: str = 'signed_direction'
    ) -> pd.DataFrame:
        """
        Multi-timeframe flow imbalance features.
        direction_col: +1 for buys, -1 for sells (from direction classifier).
        """
        features = pd.DataFrame(index=pd.date_range(
            df_trades.index.min(), df_trades.index.max(), freq='D'
        ))

        # Daily flow imbalance (OIB = Order Imbalance)
        df_trades['signed_size'] = df_trades[direction_col] * df_trades['size']
        df_trades['signed_premium'] = df_trades[direction_col] * df_trades['size'] * df_trades['exec_price'] * 100
        df_trades['signed_delta_notional'] = df_trades[direction_col] * df_trades['delta'] * df_trades['size'] * df_trades['spot'] * 100

        daily = df_trades.resample('1D').agg({
            'signed_size': 'sum',
            'signed_premium': 'sum',
            'signed_delta_notional': 'sum',
            'size': 'sum'
        })

        daily['oib_size'] = daily['signed_size'] / daily['size'].clip(lower=1)
        daily['oib_premium'] = daily['signed_premium'] / (daily['size'] * 100).clip(lower=1)
        daily['oib_delta'] = daily['signed_delta_notional'] / (daily['size'] * 100).clip(lower=1)

        # Merge into features
        features = features.join(daily[['oib_size', 'oib_premium', 'oib_delta']])

        # Multi-timeframe rolling averages
        for lb in self.LOOKBACKS:
            features[f'oib_delta_{lb}d'] = features['oib_delta'].rolling(lb).mean()

        # EWM features (faster-reacting)
        for hl in self.EWM_HALFLIFES:
            features[f'oib_delta_ewm_{hl}d'] = features['oib_delta'].ewm(halflife=hl).mean()

        # Flow momentum (recent - historical)
        features['flow_mom_short'] = features['oib_delta_5d'] - features['oib_delta_21d']
        features['flow_mom_long'] = features['oib_delta_21d'] - features['oib_delta_63d']

        return features.fillna(0)

    def build_master_feature_set(
        self,
        df_trades: pd.DataFrame,
        df_oi: pd.DataFrame,
        df_iv: pd.DataFrame,
        df_spot: pd.DataFrame
    ) -> pd.DataFrame:
        """
        Build the complete feature matrix used in downstream ML models.
        """
        print("Computing PCR features...")
        pcr_feats = self.compute_pcr_features(df_oi, df_oi)

        print("Computing OI features...")
        oi_feats = self.compute_oi_features(df_oi, df_spot)

        print("Computing IV surface features...")
        iv_feats = self.compute_iv_surface_features(df_iv)

        print("Computing flow imbalance features...")
        flow_feats = self.compute_flow_imbalance_features(df_trades)

        # Merge all
        master = pd.concat([pcr_feats, oi_feats, iv_feats, flow_feats], axis=1)

        # Winsorize and normalize
        if self.normalize:
            for col in master.columns:
                lo = master[col].quantile(self.winsorize_pct)
                hi = master[col].quantile(1 - self.winsorize_pct)
                master[col] = master[col].clip(lo, hi)

        # Cross-sectional z-score normalization
        master = (master - master.rolling(252, min_periods=63).mean()) / \
                 master.rolling(252, min_periods=63).std().clip(lower=1e-6)

        self.feature_names_ = master.columns.tolist()
        return master.dropna(how='all')


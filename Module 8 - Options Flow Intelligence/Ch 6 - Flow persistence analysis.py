import numpy as np
import pandas as pd
from statsmodels.tsa.statespace.kalman_filter import KalmanFilter
from statsmodels.tsa.stattools import acf, q_stat, grangercausalitytests
from statsmodels.regression.linear_model import OLS
from statsmodels.tools import add_constant
import matplotlib.pyplot as plt
from typing import Dict, Tuple

class FlowPersistenceAnalyzer:
    """
    Comprehensive toolkit for analyzing options flow persistence.
    """

    def __init__(self, max_lags: int = 20):
        self.max_lags = max_lags

    def compute_flow_acf(
        self,
        flow_series: pd.Series,
        alpha: float = 0.05
    ) -> Dict:
        """
        Compute ACF with confidence intervals and Ljung-Box test.
        """
        acf_vals, confint, qstat, pvalues = acf(
            flow_series.dropna(),
            nlags=self.max_lags,
            alpha=alpha,
            qstat=True
        )

        # Half-life of persistence: first lag where ACF < 1/e
        half_life = None
        for k, rho in enumerate(acf_vals[1:], start=1):
            if rho < 1 / np.e:
                half_life = k
                break

        return {
            'acf': acf_vals,
            'conf_int': confint,
            'q_stat': qstat,
            'p_values': pvalues,
            'half_life': half_life,
            'persistent_lags': [k for k, p in enumerate(pvalues, start=1) if p < alpha]
        }

    def estimate_persistent_component(
        self,
        flow_series: pd.Series,
        ar_coeff_init: float = 0.5,
        noise_ratio_init: float = 0.3
    ) -> Tuple[pd.Series, pd.Series, Dict]:
        """
        Estimate persistent component via Kalman filter.
        Returns: persistent_series, noise_series, parameters
        """
        n = len(flow_series)
        F = flow_series.values

        # Initialize parameters
        phi = ar_coeff_init  # AR coefficient for persistent component
        sigma_eta_sq = np.var(F) * noise_ratio_init  # persistent innovation variance
        sigma_n_sq = np.var(F) * (1.0 - noise_ratio_init)  # noise variance

        # Kalman filter variables
        P_filter = np.zeros(n)  # filtered persistent component
        Sigma = np.zeros(n)  # filtered covariance

        # Initialization
        Sigma_pred = sigma_eta_sq / (1.0 - phi ** 2 + 1e-8)  # stationary variance
        P_pred = 0.0

        for t in range(n):
            if np.isnan(F[t]):
                P_filter[t] = phi * P_pred
                Sigma[t] = phi ** 2 * Sigma_pred + sigma_eta_sq
                P_pred = P_filter[t]
                Sigma_pred = Sigma[t]
                continue

            # Innovation
            v_t = F[t] - P_pred

            # Innovation covariance
            S_t = Sigma_pred + sigma_n_sq

            # Kalman gain
            K_t = Sigma_pred / S_t

            # Update
            P_filter[t] = P_pred + K_t * v_t
            Sigma[t] = (1.0 - K_t) * Sigma_pred

            # Predict next step
            P_pred = phi * P_filter[t]
            Sigma_pred = phi ** 2 * Sigma[t] + sigma_eta_sq

        persistent = pd.Series(P_filter, index=flow_series.index, name='persistent_flow')
        noise = pd.Series(F - P_filter, index=flow_series.index, name='noise_flow')

        return persistent, noise, {
            'phi': phi,
            'signal_to_noise': sigma_eta_sq / sigma_n_sq
        }

    def granger_causality_test(
        self,
        flow_series: pd.Series,
        return_series: pd.Series,
        max_lag: int = 5
    ) -> pd.DataFrame:
        """
        Test whether flow Granger-causes returns at multiple lags.
        """
        df = pd.concat([return_series, flow_series], axis=1).dropna()
        df.columns = ['returns', 'flow']

        results = grangercausalitytests(df, maxlag=max_lag, verbose=False)

        summary = []
        for lag, result in results.items():
            ssr_f = result[0]['ssr_ftest']
            summary.append({
                'lag': lag,
                'F_stat': ssr_f[0],
                'p_value': ssr_f[1],
                'df_denom': ssr_f[2],
                'significant': ssr_f[1] < 0.05
            })
        return pd.DataFrame(summary)

    def compute_flow_decay_function(
        self,
        flow_series: pd.Series,
        return_series: pd.Series,
        max_horizon: int = 21
    ) -> pd.DataFrame:
        """
        For each horizon h, estimate: R_{t+1,...,t+h} = alpha + beta_h * F_t + eps
        Tracks how the predictive coefficient evolves with horizon.
        """
        results = []

        for h in range(1, max_horizon + 1):
            # Cumulative return over next h days
            cum_ret = return_series.rolling(h).sum().shift(-h)

            df = pd.concat([cum_ret, flow_series], axis=1).dropna()
            df.columns = ['cum_ret', 'flow']

            X = add_constant(df['flow'])
            y = df['cum_ret']

            model = OLS(y, X).fit(cov_type='HC3')

            results.append({
                'horizon': h,
                'beta': model.params['flow'],
                'beta_se': model.bse['flow'],
                't_stat': model.tvalues['flow'],
                'p_value': model.pvalues['flow'],
                'r_squared': model.rsquared,
                'significant': model.pvalues['flow'] < 0.05
            })

        df_results = pd.DataFrame(results)

        # Estimate peak and decay half-life
        peak_horizon = df_results.loc[df_results['beta'].abs().idxmax(), 'horizon']
        betas = df_results['beta'].values
        b_max = betas[peak_horizon - 1]

        decay_half_life = None
        for h in range(peak_horizon, max_horizon):
            if abs(betas[h]) < abs(b_max) / 2:
                decay_half_life = h - peak_horizon
                break

        df_results.attrs['peak_horizon'] = peak_horizon
        df_results.attrs['decay_half_life'] = decay_half_life

        print("\n=== Flow Persistence Summary ===")
        print(f" Peak predictive horizon: {peak_horizon} days")
        print(f" Signal half-life: {decay_half_life} days")
        print(f"Max t-stat: {df_results['t_stat'].abs().max():.2f} at h={peak_horizon}")

        return df_results


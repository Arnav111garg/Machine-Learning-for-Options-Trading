from collections import defaultdict, deque
from dataclasses import dataclass
from typing import Optional, List, Deque
import numpy as np
import pandas as pd
from datetime import datetime, timedelta
import lightgbm as lgb

@dataclass
class OpraMessage:
    timestamp: float      # Unix timestamp (microseconds)
    symbol: str           # Underlying ticker
    strike: float         # Strike price
    expiry: str           # YYYYMMDD
    option_type: str      # 'C' or 'P'
    price: float          # Execution price
    size: int             # Number of contracts
    exchange: str         # Exchange code (CBOE, PHLX, etc.)
    condition: str        # Trade condition code
    bid: float            # NBBO bid at time of trade
    ask: float            # NBBO ask at time of trade

@dataclass
class SweepEvent:
    contract_id: str      # (symbol, strike, expiry, type)
    start_time: float
    end_time: float
    messages: List[OpraMessage]
    total_size: int
    num_exchanges: int
    avg_price: float
    direction: str        # 'BUY' or 'SELL' or 'UNKNOWN'
    sweep_score: float
    notional_usd: float
    is_high_conviction: bool

class RealTimeSweepDetector:
    """
    Production-grade real-time sweep detector with ML scoring.
    Processes OPRA messages at ~5-10M messages/day.
    """
    def __init__(
        self,
        time_window_ms: float = 300.0,  # 300 ms clustering window
        min_exchanges: int = 2,          # Minimum exchanges to be a sweep
        min_size: int = 100,            # Minimum total contracts
        ml_model_path: Optional[str] = None
    ):
        self.time_window_us = time_window_ms * 1000  # Convert to microseconds
        self.min_exchanges = min_exchanges
        self.min_size = min_size

        # Sliding window buffer: contract_id -> deque of messages
        self.buffer: dict[str, Deque[OpraMessage]] = defaultdict(deque)
        self.last_clean_time: float = 0.0

        # ADV lookup (pre-computed, updated daily)
        self.adv_lookup: dict[str, float] = {}

        # ML sweep scoring model
        self.ml_model = None
        if ml_model_path:
            self.ml_model = lgb.Booster(model_file=ml_model_path)

    def _contract_id(self, msg: OpraMessage) -> str:
        return f"{msg.symbol}_{msg.strike:.2f}_{msg.expiry}_{msg.option_type}"

    def _expire_messages(self, contract_id: str, current_time: float) -> None:
        """ Remove messages outside the time window. """
        buf = self.buffer[contract_id]
        while buf and (current_time - buf[0].timestamp) > self.time_window_us:
            buf.popleft()

    def _compute_sweep_score(self, messages: List[OpraMessage]) -> float:
        """Rule-based sweep score [0, 1]."""
        if not messages:
            return 0.0

        exchanges = {m.exchange for m in messages}
        total_size = sum(m.size for m in messages)
        time_span = messages[-1].timestamp - messages[0].timestamp

        # Ask-hit rate (buy aggressiveness)
        ask_hits = sum(1 for m in messages if m.price >= m.ask * 0.999)
        bid_hits = sum(1 for m in messages if m.price <= m.bid * 1.001)

        exch_score = min(1.0, len(exchanges) / 6.0)
        speed_score = 1.0 - min(1.0, time_span / self.time_window_us)
        size_score = min(1.0, total_size / 500.0)  # 500 contracts = max score
        aggression = max(ask_hits, bid_hits) / len(messages)

        score = (0.30 * exch_score +
                 0.25 * speed_score +
                 0.25 * size_score +
                 0.20 * aggression)
        return float(score)

    def _compute_ml_score(self, event: SweepEvent) -> float:
        """ML-enhanced sweep scoring using trained model."""
        if self.ml_model is None:
            return event.sweep_score

        msgs = event.messages
        avg_bid = np.mean([m.bid for m in msgs])
        avg_ask = np.mean([m.ask for m in msgs])

        features = np.array([[
            event.num_exchanges,
            event.total_size,
            (event.end_time - event.start_time) / 1000.0,  # ms
            event.sweep_score,
            event.notional_usd,
            (event.avg_price - avg_bid) / (avg_ask - avg_bid + 1e-10),
            len(msgs),
            np.std([m.price for m in msgs]),
            np.std([m.size for m in msgs]),
        ]])

        return float(self.ml_model.predict(features)[0])

    def _infer_direction(self, messages: List[OpraMessage]) -> str:
        """
        Infer whether the sweep is buy or sell.
        Uses Lee-Ready rule as primary, with refinements.
        """
        buy_volume = sum(
            m.size for m in messages
            if m.price >= (m.bid + m.ask) / 2
        )
        sell_volume = sum(
            m.size for m in messages
            if m.price < (m.bid + m.ask) / 2
        )
        total = buy_volume + sell_volume
        if total == 0:
            return 'UNKNOWN'
        ratio = buy_volume / total
        if ratio > 0.65:
            return 'BUY'
        elif ratio < 0.35:
            return 'SELL'
        return 'UNKNOWN'

    def process_message(
        self,
        msg: OpraMessage,
        spot_price: float,
        delta: float,
        iv: float
    ) -> Optional[SweepEvent]:
        """
        Process a single OPRA message.
        Returns a SweepEvent if a new sweep is detected, else None.
        """
        cid = self._contract_id(msg)

        # Expire old messages from buffer
        self._expire_messages(cid, msg.timestamp)

        # Add new message
        self.buffer[cid].append(msg)

        # Check if current buffer constitutes a sweep
        msgs = list(self.buffer[cid])
        if len(msgs) < 2:
            return None

        exchanges = {m.exchange for m in msgs}
        total_size = sum(m.size for m in msgs)

        if len(exchanges) < self.min_exchanges:
            return None
        if total_size < self.min_size:
            return None

        # Compute scores
        rule_score = self._compute_sweep_score(msgs)
        direction = self._infer_direction(msgs)
        avg_price = sum(m.price * m.size for m in msgs) / total_size
        notional = total_size * 100 * abs(delta) * spot_price

        event = SweepEvent(
            contract_id = cid,
            start_time = msgs[0].timestamp,
            end_time = msgs[-1].timestamp,
            messages = msgs.copy(),
            total_size = total_size,
            num_exchanges = len(exchanges),
            avg_price = avg_price,
            direction = direction,
            sweep_score = rule_score,
            notional_usd = notional,
            is_high_conviction = (rule_score > 0.7 and total_size > 500)
        )

        ml_score = self._compute_ml_score(event)
        event.sweep_score = 0.5 * rule_score + 0.5 * ml_score

        # Clear buffer to avoid double-counting
        self.buffer[cid].clear()

        return event if event.sweep_score >= 0.4 else None


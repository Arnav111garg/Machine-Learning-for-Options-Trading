# Backtest : Sweep Alpha Analysis
# ================================================================
def compute_sweep_alpha(
    sweep_events: List[SweepEvent],
    underlying_prices: pd.DataFrame,
    holding_period_days: List[int] = [1, 2, 3, 5, 10]
) -> pd.DataFrame:
    """
    Compute the predictive alpha of buy sweeps vs sell sweeps.
    """
    results = []

    for event in sweep_events:
        if event.direction not in ['BUY', 'SELL']:
            continue

        event_date = pd.Timestamp(event.start_time / 1e6, unit='s').date()
        symbol = event.contract_id.split('_')[0]

        if symbol not in underlying_prices.columns:
            continue

        for h in holding_period_days:
            try:
                p0 = underlying_prices.loc[str(event_date), symbol]
                p_h = underlying_prices.iloc[
                    underlying_prices.index.get_loc(str(event_date)) + h
                ][symbol]
                ret = (p_h - p0) / p0
                signed_ret = ret if event.direction == 'BUY' else -ret

                results.append({
                    'symbol': symbol,
                    'date': event_date,
                    'direction': event.direction,
                    'sweep_score': event.sweep_score,
                    'total_size': event.total_size,
                    'holding_days': h,
                    'underlying_return': ret,
                    'signed_return': signed_ret,
                    'is_high_conviction': event.is_high_conviction
                })
            except (KeyError, IndexError):
                continue

    df = pd.DataFrame(results)

    # Summary statistics
    print("\n=== Sweep Alpha Analysis ===")
    for h in holding_period_days:
        subset = df[df['holding_days'] == h]
        if len(subset) == 0:
            continue
        all_mean = subset['signed_return'].mean() * 10000  # bps
        hc_mean = subset[subset['is_high_conviction']]['signed_return'].mean() * 10000
        t_stat = (subset['signed_return'].mean() / (subset['signed_return'].std() / np.sqrt(len(subset)))) if len(subset) > 1 else np.nan

        print(f"H={h:2d}d: Mean ={all_mean:6.1f}bps | "
              f"HC ={hc_mean:6.1f}bps | t={t_stat:.2f} | N={len(subset)}")

    return df


import numpy as np
import pandas as pd
import xgboost as xgb
from sklearn.preprocessing import LabelEncoder
from sklearn.model_selection import StratifiedKFold
from sklearn.metrics import classification_report, confusion_matrix
import matplotlib.pyplot as plt
import seaborn as sns
from typing import Tuple, List, Dict

class OptionsFlowClassifier:
    """
    Multi-class options flow classifier using gradient boosted trees.
    Handles the full taxonomy: speculative / hedging / spread / MM / arb
    """
    FLOW_CLASSES = [
        'speculative_directional',
        'speculative_volatility',
        'speculative_event',
        'hedging_delta',
        'hedging_portfolio',
        'hedging_tail',
        'spread_vertical',
        'spread_calendar',
        'market_maker',
        'arbitrage'
    ]

    def __init__(self, n_estimators: int = 1000, max_depth: int = 6):
        self.n_estimators = n_estimators
        self.max_depth = max_depth
        self.model = None
        self.le = LabelEncoder()
        self.feature_names = None

    def _engineer_features(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Comprehensive feature engineering pipeline for options flow.
        Input: raw options trade dataframe
        Output: feature matrix
        """
        features = pd.DataFrame()

        # --- Moneyness features ---
        features['log_moneyness'] = np.log(df['strike'] / df['forward'])
        features['abs_log_moneyness'] = features['log_moneyness'].abs()
        features['moneyness_normalized'] = features['log_moneyness'] / df['iv'] / np.sqrt(df['dte'] / 252.0)

        # --- Time features ---
        features['dte'] = df['dte']
        features['log_dte'] = np.log(df['dte'].clip(1))
        features['sqrt_dte'] = np.sqrt(df['dte'])

        # --- Size features ---
        features['log_size'] = np.log(df['size'])
        features['norm_size'] = df['size'] / df['adv_20d']
        features['premium_paid'] = df['size'] * 100.0 * df['exec_price']
        features['notional_equiv'] = df['size'] * 100.0 * df['delta'].abs() * df['spot']
        features['log_premium'] = np.log(features['premium_paid'].clip(1))

        # --- Execution quality features ---
        spread = df['ask'] - df['bid']
        features['exec_vs_mid'] = (df['exec_price'] - (df['bid'] + df['ask']) / 2.0) / (spread / 2.0)
        features['spread_pct'] = spread / ((df['bid'] + df['ask']) / 2.0)
        features['is_near_ask'] = (features['exec_vs_mid'] > 0.7).astype(float)
        features['is_near_bid'] = (features['exec_vs_mid'] < -0.7).astype(float)

        # --- Options characteristics ---
        features['is_call'] = (df['option_type'] == 'C').astype(float)
        features['delta'] = df['delta']
        features['abs_delta'] = df['delta'].abs()
        features['gamma'] = df['gamma']
        features['vega'] = df['vega']
        features['theta'] = df['theta']
        features['vanna'] = df['vanna']  # dDelta / dVol

        # --- Implied vol features ---
        features['iv'] = df['iv']
        features['iv_rank'] = df['iv_rank']
        features['iv_vs_hv_20'] = df['iv'] - df['hv_20']
        features['skew_25d'] = df['put_iv_25d'] - df['call_iv_25d']
        features['term_structure'] = df['iv_3m'] - df['iv_1m']

        # --- Market context ---
        features['vix'] = df['vix']
        features['spot_ret_5d'] = df['spot_ret_5d']
        features['spot_vol_20d'] = df['spot_vol_20d']

        # --- Multi-leg indicators ---
        features['is_multi_leg'] = df['is_multi_leg'].astype(float)
        features['num_legs'] = df['num_legs']
        features['is_spread'] = df['is_spread'].astype(float)

        # --- Interaction features ---
        features['size_x_aggression'] = features['norm_size'] * features['is_near_ask']
        features['otm_x_dte'] = features['abs_log_moneyness'] * np.log(features['dte'] + 1.0)
        features['iv_rank_x_size'] = features['iv_rank'] * features['log_size']

        # --- Exchange features ---
        features['num_exchanges'] = df['num_exchanges']  # sweeps > 1
        features['is_sweep'] = (df['num_exchanges'] > 1).astype(float)

        return features

    def train(
        self,
        df_train: pd.DataFrame,
        labels: pd.Series,
        df_val: pd.DataFrame = None,
        val_labels: pd.Series = None
    ) -> Dict:
        """
        Train the flow classifier with cross-validation.
        """
        X_train = self._engineer_features(df_train)
        y_train = self.le.fit_transform(labels)
        self.feature_names = X_train.columns.tolist()

        dtrain = xgb.DMatrix(X_train, label=y_train, feature_names=self.feature_names)

        params = {
            'objective': 'multi:softprob',
            'num_class': len(self.FLOW_CLASSES),
            'max_depth': self.max_depth,
            'learning_rate': 0.05,
            'n_estimators': self.n_estimators,
            'subsample': 0.8,
            'colsample_bytree': 0.8,
            'min_child_weight': 10,  # prevents overfitting on rare classes
            'gamma': 0.1,
            'reg_alpha': 0.1,
            'reg_lambda': 1.0,
            'eval_metric': ['mlogloss', 'merror'],
            'seed': 42,
            'tree_method': 'hist'  # faster for large datasets
        }

        evals = [(dtrain, 'train')]
        if df_val is not None:
            X_val = self._engineer_features(df_val)
            y_val = self.le.transform(val_labels)
            dval = xgb.DMatrix(X_val, label=y_val, feature_names=self.feature_names)
            evals.append((dval, 'val'))

        self.model = xgb.train(
            params,
            dtrain,
            num_boost_round=self.n_estimators,
            evals=evals,
            early_stopping_rounds=50,
            verbose_eval=100
        )

        # Feature importance analysis
        fi = self.model.get_score(importance_type='gain')
        fi_df = pd.DataFrame(list(fi.items()), columns=['feature', 'importance'])
        fi_df = fi_df.sort_values('importance', ascending=False)

        return {'feature_importance': fi_df}

    def predict_proba(self, df: pd.DataFrame) -> np.ndarray:
        """ Returns K-dimensional probability vector for each trade. """
        X = self._engineer_features(df)
        dtest = xgb.DMatrix(X, feature_names=self.feature_names)
        probs = self.model.predict(dtest)
        return probs.reshape(-1, len(self.FLOW_CLASSES))

    def predict(self, df: pd.DataFrame) -> np.ndarray:
        probs = self.predict_proba(df)
        return self.le.inverse_transform(probs.argmax(axis=1))

    def get_high_confidence_trades(
        self,
        df: pd.DataFrame,
        confidence_threshold: float = 0.75
    ) -> pd.DataFrame:
        """ Filter to trades where classifier confidence exceeds threshold. """
        probs = self.predict_proba(df)
        max_probs = probs.max(axis=1)
        labels = self.le.inverse_transform(probs.argmax(axis=1))

        result = df.copy()
        result['flow_type'] = labels
        result['confidence'] = max_probs
        result['is_speculative'] = result['flow_type'].str.startswith('speculative')

        return result[result['confidence'] >= confidence_threshold]

# ================================================================
# Evaluation utilities
# ================================================================
def evaluate_classifier(
    clf: OptionsFlowClassifier,
    df_test: pd.DataFrame,
    y_test: pd.Series
) -> None:
    """ Comprehensive evaluation with confusion matrix and metrics. """
    y_pred = clf.predict(df_test)

    print("=" * 60)
    print(" FLOW CLASSIFICATION REPORT ")
    print("=" * 60)
    print(classification_report(
        y_test,
        y_pred,
        target_names=clf.FLOW_CLASSES
    ))

    # Confusion matrix heatmap
    cm = confusion_matrix(y_test, y_pred, labels=clf.le.classes_)
    cm_norm = cm.astype('float') / cm.sum(axis=1)[:, np.newaxis]

    fig, ax = plt.subplots(figsize=(12, 10))
    sns.heatmap(
        cm_norm,
        annot=True,
        fmt='.2f',
        cmap='Blues',
        xticklabels=clf.FLOW_CLASSES,
        yticklabels=clf.FLOW_CLASSES,
        ax=ax
    )
    ax.set_xlabel('Predicted Flow Type', fontsize=12)
    ax.set_ylabel('True Flow Type', fontsize=12)
    ax.set_title(
        'Flow Classification Confusion Matrix (Normalized)',
        fontsize=14,
        fontweight='bold'
    )
    plt.tight_layout()
    plt.savefig('flow_confusion_matrix.png', dpi=150)
    plt.show()


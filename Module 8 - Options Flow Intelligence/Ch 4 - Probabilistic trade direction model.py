import numpy as np
import pandas as pd
from sklearn.ensemble import GradientBoostingClassifier, RandomForestClassifier
from sklearn.calibration import CalibratedClassifierCV
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import roc_auc_score, accuracy_score
import lightgbm as lgb
from typing import Tuple

class TradeDirectionClassifier:
    """
    ML-based trade direction inference for options markets.
    Uses a calibrated ensemble of multiple algorithms.

    Ground truth labels come from:
    - FINRA TAQ data with buyer / seller identifiers
    - Large sweep trades where direction is unambiguous
    - Negotiated trades reported with side
    """

    def __init__(self):
        # Primary model: LightGBM (best for tabular financial data)
        self.lgbm = lgb.LGBMClassifier(
            n_estimators=500,
            max_depth=6,
            learning_rate=0.05,
            subsample=0.8,
            colsample_bytree=0.8,
            min_child_samples=20,
            reg_alpha=0.1,
            reg_lambda=0.5,
            random_state=42,
            verbose=-1
        )

        # Secondary: Random Forest for diversity
        self.rf = RandomForestClassifier(
            n_estimators=200,
            max_depth=8,
            min_samples_leaf=20,
            n_jobs=-1,
            random_state=42
        )

        # Calibration wrapper
        self.lgbm_cal = CalibratedClassifierCV(self.lgbm, cv=5, method='isotonic')
        self.rf_cal = CalibratedClassifierCV(self.rf, cv=5, method='isotonic')

        self.scaler = StandardScaler()
        self.is_fitted = False

    def _engineer_features(self, df: pd.DataFrame) -> np.ndarray:
        """
        Build feature matrix from raw trade data.
        All features are normalized to be interpretable.
        """
        n = len(df)
        features = np.zeros((n, 25))

        mid = (df['bid'] + df['ask']) / 2
        spread = (df['ask'] - df['bid']).clip(lower=1e-6)

        # === Lee-Ready signal (as a feature, not label) ===
        # Position in spread: 1 = at ask, 0 = at bid, 0.5 = at mid
        features[:, 0] = ((df['exec_price'] - df['bid']) / spread).clip(0, 1)

        # === Tick-based features ===
        price_chg = df['exec_price'].diff()
        features[:, 1] = np.sign(price_chg)
        # current tick
        features[:, 2] = np.sign(price_chg.shift(1))
        # lag-1 tick
        features[:, 3] = np.sign(price_chg.shift(2))
        # lag-2 tick
        features[:, 4] = price_chg.rolling(5).sum() / spread
        # 5-tick trend

        # === Quote position features ===
        features[:, 5] = (df['exec_price'] >= df['ask']).astype(float)  # at/above ask
        features[:, 6] = (df['exec_price'] <= df['bid']).astype(float)  # at/below bid
        features[:, 7] = (df['exec_price'] == mid).astype(float)        # exact mid

        # === Size features ===
        rolling_avg_size = df['size'].rolling(20, min_periods=5).mean()
        features[:, 8] = np.log1p(df['size'])
        features[:, 9] = df['size'] / rolling_avg_size.clip(lower=1)    # relative size
        features[:, 10] = (df['size'] >= df['size'].quantile(0.90)).astype(float)  # large trade

        # === Spread features ===
        features[:, 11] = spread / mid.clip(lower=1e-4)                 # % spread
        features[:, 12] = np.log1p(spread / mid.clip(lower=1e-4))

        # === Options-specific ===
        features[:, 13] = df['delta'].abs()                             # |delta|
        features[:, 14] = df['iv']                                      # implied vol
        features[:, 15] = df['iv'] - df['hv_20']                        # vol premium
        features[:, 16] = df['gamma'] * df['spot'] ** 2 / df['spot']    # dollar gamma
        features[:, 17] = (df['option_type'] == 'C').astype(float)      # is call

        # === Market state features ===
        features[:, 18] = df['spot_ret_5min']                           # spot momentum
        features[:, 19] = df['spot_vol_5min']                           # spot vol
        features[:, 20] = df['vix'] / 100.0                             # VIX level
        features[:, 21] = df['bid_qty'] / (df['bid_qty'] + df['ask_qty'] + 1e-3)  # queue imbalance

        # === Time-of-day features ===
        features[:, 22] = df['time_of_day_sin']  # sin(2*pi*time / 6.5 hr)
        features[:, 23] = df['time_of_day_cos']  # cos(2*pi*time / 6.5 hr)

        # === Recent flow imbalance ===
        features[:, 24] = df['flow_imbalance_5min']  # (buy vol - sell vol) / total vol

        return features

    def fit(
        self,
        df_train: pd.DataFrame,
        y_train: np.ndarray
    ) -> 'TradeDirectionClassifier':
        """
        y_train: +1 for buyer-initiated, -1 for seller-initiated.
        Ground truth from high-confidence subset (e.g., trades at ask/bid).
        """
        X_train = self._engineer_features(df_train)
        X_scaled = self.scaler.fit_transform(X_train)

        y_binary = (y_train > 0).astype(int)  # Convert to {0, 1}

        # Fit both models
        self.lgbm_cal.fit(X_train, y_binary)  # LightGBM prefers unscaled
        self.rf_cal.fit(X_scaled, y_binary)

        self.is_fitted = True
        return self

    def predict_proba_buy(self, df: pd.DataFrame) -> np.ndarray:
        """
        Returns P(buyer-initiated) for each trade.
        Ensemble of LightGBM and Random Forest.
        """
        X = self._engineer_features(df)
        X_scaled = self.scaler.transform(X)

        p_lgbm = self.lgbm_cal.predict_proba(X)[:, 1]
        p_rf = self.rf_cal.predict_proba(X_scaled)[:, 1]

        # Weighted ensemble (LightGBM typically outperforms RF here)
        return 0.65 * p_lgbm + 0.35 * p_rf

    def predict_direction(
        self,
        df: pd.DataFrame,
        confidence_threshold: float = 0.60
    ) -> np.ndarray:
        """
        Returns +1 (buy), -1 (sell), or 0 (uncertain) for each trade.
        """
        probs = self.predict_proba_buy(df)
        directions = np.zeros(len(probs))
        directions[probs >= confidence_threshold] = +1
        directions[probs <= 1 - confidence_threshold] = -1
        return directions

    def compute_order_imbalance(
        self,
        df: pd.DataFrame,
        weights: str = 'dollar_premium'
    ) -> pd.Series:
        """
        Compute weighted order imbalance: (Buy Vol - Sell Vol) / Total Vol

        Parameters
        ----------
        weights : 'count' | 'size' | 'dollar_premium' | 'delta_notional'
        """
        proba_buy = self.predict_proba_buy(df)

        if weights == 'count':
            w = np.ones(len(df))
        elif weights == 'size':
            w = df['size'].values
        elif weights == 'dollar_premium':
            w = (df['size'] * 100 * df['exec_price']).values
        elif weights == 'delta_notional':
            w = (df['size'] * 100 * df['delta'].abs() * df['spot']).values
        else:
            raise ValueError(f"Unknown weight type: {weights}")

        buy_weight = (proba_buy * w).sum()
        sell_weight = ((1 - proba_buy) * w).sum()
        total = buy_weight + sell_weight

        if total < 1e-6:
            return pd.Series(0.0, index=df.index)

        return pd.Series((buy_weight - sell_weight) / total, index=df.index)

# ================================================================
# Signed Options Order Flow Metrics
# ================================================================
def compute_sofi(
    df_trades: pd.DataFrame,
    direction_clf: TradeDirectionClassifier,
    time_groupby: str = '1D'
) -> pd.DataFrame:
    """
    Compute Signed Options Flow Imbalance (SOFI) at the contract level.

    SOFI is the core alpha signal from options flow research:
    Pan & Poteshman (2006): SOFI predicts next-day returns significantly.
    """
    df = df_trades.copy()
    df['p_buy'] = direction_clf.predict_proba_buy(df)

    # Signed volume: positive = buy pressure, negative = sell pressure
    df['signed_vol_raw'] = (2 * df['p_buy'] - 1) * df['size']

    # Delta-weighted signed volume (directional signal in underlying units)
    df['signed_delta_vol'] = df['signed_vol_raw'] * df['delta']

    # Vega-weighted signed volume (volatility signal)
    df['signed_vega_vol'] = df['signed_vol_raw'] * df['vega']

    # Group by symbol and time period
    df['timestamp'] = pd.to_datetime(df['timestamp'], unit='us')
    df = df.set_index('timestamp')

    grouped = df.groupby(['symbol', pd.Grouper(freq=time_groupby)])

    sofi = grouped.agg(
        total_volume=('size', 'sum'),
        raw_imbalance=('signed_vol_raw', 'sum'),
        delta_weighted_imbalance=('signed_delta_vol', 'sum'),
        vega_weighted_imbalance=('signed_vega_vol', 'sum'),
        avg_prob_buy=('p_buy', 'mean'),
        trade_count=('size', 'count')
    ).reset_index()

    # Normalize to [-1, 1]
    sofi['sofi'] = sofi['raw_imbalance'] / sofi['total_volume'].clip(lower=1)
    sofi['sofi_delta'] = sofi['delta_weighted_imbalance'] / sofi['total_volume'].clip(lower=1)

    return sofi


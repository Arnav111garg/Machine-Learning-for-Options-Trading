import numpy as np
import pandas as pd
from sklearn.cluster import DBSCAN, KMeans
from sklearn.preprocessing import StandardScaler
from sklearn.mixture import GaussianMixture
from scipy.stats import kstest
from typing import List, Dict, Tuple, Optional

class InstitutionalFootprintDetector:
    """
    Detects and characterizes institutional options activity.

    Methods:
    1. Size-based clustering to identify institutional-sized trades
    2. Temporal pattern analysis for accumulation detection
    3. Cross-contract correlation for large hedge fund activity
    4. Strike concentration analysis
    """

    # Institutional trade thresholds (by market cap tier)
    INST_THRESHOLDS = {
        'mega_cap': {'min_contracts': 500, 'min_premium': 5_000_000},
        'large_cap': {'min_contracts': 250, 'min_premium': 1_000_000},
        'mid_cap': {'min_contracts': 100, 'min_premium': 250_000},
        'small_cap': {'min_contracts': 50, 'min_premium': 100_000}
    }

    def __init__(self, market_cap_tier: str = 'large_cap'):
        self.threshold = self.INST_THRESHOLDS[market_cap_tier]
        self.scaler = StandardScaler()

    def classify_trade_origin(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Classify each trade as likely institutional, semi-institutional, or retail.
        Uses size, time, strike pattern, and execution characteristics.
        """
        df = df.copy()
        size_score = (
            (df['size'] >= self.threshold['min_contracts']).astype(float) * 0.4 +
            (df['dollar_premium'] >= self.threshold['min_premium']).astype(float) * 0.4
        )

        # Feature 2: Time of day (institutions prefer open/close)
        df['hour'] = pd.to_datetime(df['timestamp']).dt.hour
        df['minute'] = pd.to_datetime(df['timestamp']).dt.minute
        time_minutes = df['hour'] * 60 + df['minute']
        is_open_window = ((time_minutes >= 9*60+30) & (time_minutes <= 10*60)).astype(float)
        is_close_window = (time_minutes >= 15*60).astype(float)
        time_score = (is_open_window + is_close_window) * 0.1

        # Feature 3: Strike precision (institutional = model-derived vs. round)
        # Round strikes: strikes that are multiples of $5 or $10
        strikes_mod5 = (df['strike'] % 5 == 0).astype(float)
        strikes_mod10 = (df['strike'] % 10 == 0).astype(float)
        strike_precision_score = (1.0 - 0.5 * strikes_mod5 - 0.3 * strikes_mod10) * 0.1

        # Feature 4: Complex structure detection
        complex_score = df.get('is_multi_leg', pd.Series(0.0, index=df.index)).astype(float) * 0.1

        # Feature 5: IV impact (did the trade move the vol surface?)
        iv_impact = df.get('iv_change_after_trade', pd.Series(0.0, index=df.index)).abs()
        iv_score = (iv_impact > 0.005).astype(float) * 0.1  # >50 bps vol move

        # Combined institutional score [0, 1]
        df['institutional_score'] = (
            size_score + time_score + strike_precision_score + complex_score + iv_score
        ).clip(0.0, 1.0)

        df['origin'] = pd.cut(
            df['institutional_score'],
            bins=[-0.01, 0.33, 0.67, 1.01],
            labels=['retail', 'semi_institutional', 'institutional']
        )

        return df

    def detect_accumulation_campaign(
        self,
        df_oi: pd.DataFrame,
        lookback_days: int = 21,
        min_growth_rate: float = 0.10
    ) -> pd.DataFrame:
        """
        Detect systematic OI buildup suggesting institutional accumulation.
        """
        campaigns = []

        for contract_id, contract_df in df_oi.groupby('contract_id'):
            contract_df = contract_df.sort_index()

            if len(contract_df) < lookback_days:
                continue

            # Compute rolling OI growth
            oi = contract_df['open_interest']
            oi_change = oi.diff()
            cum_oi_growth = oi_change.rolling(lookback_days).sum()

            # Consistency: what fraction of days had positive OI change?
            positive_days = (oi_change > 0).rolling(lookback_days).sum()
            consistency = positive_days / lookback_days

            # Signal: sustained OI growth with consistency
            signal = (cum_oi_growth / oi.shift(lookback_days).clip(lower=1.0)) * consistency

            # Flag campaigns
            threshold = np.percentile(signal.dropna().abs(), 90)
            active_days = signal[signal.abs() > threshold]

            if len(active_days) > 0:
                for date, score in active_days.items():
                    campaigns.append({
                        'contract_id': contract_id,
                        'date': date,
                        'oi_growth_rate': cum_oi_growth.loc[date] / oi.shift(lookback_days).loc[date],
                        'consistency': consistency.loc[date],
                        'accumulation_score': score,
                        'direction': 'ACCUMULATE' if score > 0 else 'DISTRIBUTE',
                        'oi_level': oi.loc[date]
                    })

        df_campaigns = pd.DataFrame(campaigns)
        if len(df_campaigns) > 0:
            return df_campaigns.sort_values('accumulation_score', ascending=False)
        return df_campaigns

    def estimate_institutional_position(
        self,
        df_campaigns: pd.DataFrame,
        df_spot: pd.DataFrame,
        delta_lookup: Dict[str, float]
    ) -> pd.DataFrame:
        """
        Estimate the underlying directional exposure implied by institutional campaigns.
        """
        results = []

        for _, campaign in df_campaigns.iterrows():
            cid = campaign['contract_id']
            delta = delta_lookup.get(cid, 0.5)
            spot = df_spot.get(campaign['date'], 0.0)

            # Direction: accumulation of calls = bullish, accumulation of puts = bearish
            option_type = cid.split('_')[3] if '_' in cid else 'C'
            type_sign = 1.0 if option_type == 'C' else -1.0
            direction_sign = 1.0 if campaign['direction'] == 'ACCUMULATE' else -1.0

            directional_exposure = (
                campaign['oi_level'] * 100.0 * delta * spot * type_sign * direction_sign
            )

            results.append({
                **campaign,
                'option_type': option_type,
                'delta': delta,
                'directional_exposure_usd': directional_exposure,
                'implied_view': 'BULLISH' if directional_exposure > 0 else 'BEARISH'
            })

        return pd.DataFrame(results)

    def compute_dark_pool_premium(
        self,
        df_trades: pd.DataFrame
    ) -> pd.DataFrame:
        """
        Estimate the 'dark pool premium' price premium paid by large institutional trades.
        """
        results = []

        for contract_id, cdf in df_trades.groupby('contract_id'):
            # Small vs large trades
            size_median = cdf['size'].median()
            large_trades = cdf[cdf['size'] > 5.0 * size_median]
            small_trades = cdf[cdf['size'] <= 5.0 * size_median]

            if len(large_trades) < 5 or len(small_trades) < 5:
                continue

            # Mid-normalized execution prices
            large_mid = (large_trades['bid'] + large_trades['ask']) / 2.0
            large_spread = large_trades['ask'] - large_trades['bid']
            large_normalized = (large_trades['exec_price'] - large_mid) / large_spread.clip(lower=1e-6)

            small_mid = (small_trades['bid'] + small_trades['ask']) / 2.0
            small_spread = small_trades['ask'] - small_trades['bid']
            small_normalized = (small_trades['exec_price'] - small_mid) / small_spread.clip(lower=1e-6)

            # T-test for difference
            from scipy.stats import ttest_ind
            t_stat, p_val = ttest_ind(large_normalized, small_normalized)

            results.append({
                'contract_id': contract_id,
                'large_exec_normalized': large_normalized.mean(),
                'small_exec_normalized': small_normalized.mean(),
                'dark_pool_premium': large_normalized.mean() - small_normalized.mean(),
                't_stat': t_stat,
                'p_value': p_val,
                'num_large_trades': len(large_trades),
                'num_small_trades': len(small_trades)
            })

        df_results = pd.DataFrame(results)
        if len(df_results) > 0:
            return df_results.sort_values('dark_pool_premium', ascending=False)
        return df_results


class FlowFollowingExecutor:
    """
    Options-based implementation of flow-following strategy.

    Instead of trading equity, we follow identified smart money
    by trading options in the SAME direction and similar structure.

    Key advantage: leverage + asymmetric payoff
    Key risk: time decay (theta) if timing is wrong
    """
    def __init__(
        self,
        max_premium_at_risk: float = 0.02, # 2% of portfolio per trade
        min_smart_money_score: float = 0.70,
        execution_lag_minutes: float = 15.0 # Wait 15 min to confirm signal
    ):
        self.max_premium = max_premium_at_risk
        self.min_sms = min_smart_money_score
        self.exec_lag = execution_lag_minutes

    def generate_follow_trade(
        self,
        detected_event: dict,
        portfolio_value: float,
        current_positions: dict,
        available_strikes: pd.DataFrame
    ) -> Optional[dict]:
        """
        Generate a follow-trade recommendation for a detected smart money event.

        Principles:
        1. Same direction (bullish / bearish) as detected flow
        2. Similar expiry (or slightly longer to avoid time-decay rush)
        3. Slightly more OTM (avoid crowding the exact same strike)
        4. Smaller size (never more than 20% of detected event size)
        """
        sms = detected_event.get('smart_money_score', 0)
        if sms < self.min_sms:
            return None

        direction = detected_event.get('direction')
        symbol = detected_event.get('symbol')
        detected_strike = detected_event.get('strike')
        detected_expiry = detected_event.get('expiry')
        option_type = detected_event.get('option_type')

        if not all([direction, symbol, detected_strike, detected_expiry]):
            return None

        # Filter available strikes
        avail = available_strikes[
            (available_strikes['symbol'] == symbol) &
            (available_strikes['option_type'] == option_type) &
            (available_strikes['expiry'] == detected_expiry)
        ].copy()

        if avail.empty:
            return None

        # Select slightly more OTM strike (for better leverage)
        spot = detected_event.get('spot', detected_strike)
        if direction == 'BULLISH' and option_type == 'C':
            # Want call slightly more OTM
            candidates = avail[avail['strike'] >= detected_strike * 1.01]
        elif direction == 'BEARISH' and option_type == 'P':
            # Want put slightly more OTM
            candidates = avail[avail['strike'] <= detected_strike * 0.99]
        else:
            candidates = avail

        if candidates.empty:
            candidates = avail

        # Pick candidate with best liquidity (tightest spread)
        candidates = candidates.copy()
        candidates['spread_pct'] = (candidates['ask'] - candidates['bid']) / candidates['mid']
        best = candidates.nsmallest(1, 'spread_pct').iloc[0]

        # Size: based on max premium at risk
        max_premium_dollars = portfolio_value * self.max_premium
        num_contracts = int(max_premium_dollars / (best['ask'] * 100))
        num_contracts = max(1, min(num_contracts, detected_event.get('total_size', 1000) // 5))

        return {
            'action': 'ENTER',
            'symbol': symbol,
            'option_type': option_type,
            'strike': best['strike'],
            'expiry': detected_expiry,
            'num_contracts': num_contracts,
            'side': 'BUY',
            'limit_price': best['ask'] * 1.002, # Slight premium for fill probability
            'max_price': best['ask'] * 1.01,
            'rationale': f"Following {direction} smart money (SMS={sms:.2f})",
            'detected_event_id': detected_event.get('id'),
            'target_exit_days': 3,
            'stop_loss_pct': 0.50 # Exit if position loses 50% of premium
        }


import numpy as np
import pandas as pd
from scipy.optimize import minimize
from typing import Dict, List, Tuple, Optional
import warnings

class FlowAlphaStrategy:
    """
    Complete flow-based long/short equity strategy.

    Alpha: Options flow signals (sweeps, blocks, SOFI, smart money)
    Risk model: Barra-style factor model
    Execution: Model-aware transaction cost optimization

    Designed for:
    - Universe: Russell 1000 (liquid names with significant options activity)
    - Holding period: 3-7 business days
    - Leverage: 1.5x-2.0x gross
    - Target vol: 8-12% annualized
    """
    def __init__(
        self,
        target_vol: float = 0.10, # 10% annual portfolio vol
        max_gross_leverage: float = 2.0,
        max_position_pct: float = 0.05, # 5% max per position
        min_signal_percentile: float = 0.70, # Only trade top/bottom 30%
        transaction_cost_bps: float = 10.0, # Assumed TC
        signal_halflife_days: float = 5.0
    ):
        self.target_vol = target_vol
        self.max_gross = max_gross_leverage
        self.max_pos = max_position_pct
        self.min_signal_pct = min_signal_percentile
        self.tc = transaction_cost_bps / 10000
        self.signal_halflife = signal_halflife_days

    def compute_cfas(
        self,
        signals: pd.DataFrame,
        ic_weights: Optional[np.ndarray] = None
    ) -> pd.Series:
        """
        Compute Composite Flow Alpha Score from individual signals.
        """
        # Normalize each signal cross-sectionally
        z_scores = signals.sub(signals.mean(axis=1), axis=0)
        z_scores = z_scores.div(signals.std(axis=1).clip(lower=1e-8), axis=0)

        # Cap at 3 sigma
        z_scores = z_scores.clip(-3, 3)

        if ic_weights is None:
            # Equal weighting (fallback)
            cfas = z_scores.mean(axis=1)
        else:
            cfas = z_scores @ ic_weights

        # Final cross-sectional standardization
        cfas = (cfas - cfas.mean()) / cfas.std().clip(lower=1e-8)
        return cfas

    def score_to_weights(
        self,
        cfas: pd.Series,
        cov_matrix: pd.DataFrame,
        benchmark_weights: Optional[pd.Series] = None
    ) -> pd.Series:
        """
        Convert alpha scores to portfolio weights via mean-variance optimization.

        Objective: maximize alpha - lambda * tracking error ^2
        Subject to:
        - Sum of weights = 0 (long-short, market neutral)
        - |w_i| <= max_position_pct
        - Gross exposure <= max_gross_leverage
        - Portfolio vol <= target_vol
        """
        n = len(cfas)
        stocks = cfas.index

        # Threshold: only include signals above percentile threshold
        lo_pct = cfas.quantile(1 - self.min_signal_pct)
        hi_pct = cfas.quantile(self.min_signal_pct)

        active_mask = (cfas >= lo_pct) | (cfas <= hi_pct)
        cfas_active = cfas[active_mask]

        if len(cfas_active) < 5:
            return pd.Series(0.0, index=stocks)

        cov_active = cov_matrix.loc[cfas_active.index, cfas_active.index].values
        alpha = cfas_active.values
        n_active = len(alpha)

        # Risk aversion: calibrate to achieve target_vol
        # lambda = alpha variance / (2 * target_vol^2 * num_stocks)
        lambda_risk = 1.0 / (2 * (self.target_vol ** 2) * n_active)

        def objective(w):
            return -(alpha @ w) + lambda_risk * (w @ cov_active @ w)

        def objective_grad(w):
            return -alpha + 2 * lambda_risk * (cov_active @ w)

        constraints = [
            {'type': 'eq', 'fun': lambda w: np.sum(w)} # Market neutral
        ]

        bounds = [(-self.max_pos, self.max_pos)] * n_active

        w0 = (alpha / (np.abs(alpha).sum() + 1e-8)) * 0.5 # Initial guess

        result = minimize(
            objective,
            w0,
            jac=objective_grad,
            method='SLSQP',
            constraints=constraints,
            bounds=bounds,
            options={'maxiter': 1000, 'ftol': 1e-9}
        )

        if not result.success:
            warnings.warn(f"Optimization failed: {result.message}")

        weights_active = pd.Series(result.x, index=cfas_active.index)

        # Scale to target gross exposure
        gross = weights_active.abs().sum()
        if gross > self.max_gross:
            weights_active *= self.max_gross / gross

        # Fill in zeros for inactive stocks
        weights = pd.Series(0.0, index=stocks)
        weights[weights_active.index] = weights_active

        return weights

    def compute_turnover_and_tc(
        self,
        new_weights: pd.Series,
        old_weights: pd.Series
    ) -> Tuple[float, float]:
        """
        Compute portfolio turnover and estimated transaction costs.
        """
        weight_changes = (new_weights - old_weights).fillna(new_weights)
        turnover = weight_changes.abs().sum() / 2 # Two-sided turnover
        tc_drag = turnover * self.tc
        return turnover, tc_drag

    def backtest(
        self,
        all_signals: pd.DataFrame, # [dates x stocks]
        returns: pd.DataFrame, # [dates x stocks]
        cov_matrices: Dict[str, pd.DataFrame], # date -> covariance matrix
        rebalance_freq: str = 'W' # Weekly rebalance
    ) -> pd.DataFrame:
        """
        Full backtest of the flow alpha strategy.

        Returns DataFrame with:
        - portfolio_return: daily P&L
        - gross_exposure: daily gross
        - net_exposure: daily net
        - turnover: realized at each rebalance
        """
        portfolio_returns = []
        rebalance_dates = pd.date_range(
            all_signals.index[0],
            all_signals.index[-1],
            freq=rebalance_freq
        )

        current_weights = pd.Series(0.0, index=all_signals.columns)

        for date in all_signals.index:
            # Daily P&L from current positions
            day_ret = (current_weights * returns.loc[date]).sum()

            result = {
                'date': date,
                'portfolio_return': day_ret,
                'gross_exposure': current_weights.abs().sum(),
                'net_exposure': current_weights.sum(),
                'turnover': 0.0,
                'tc_drag': 0.0
            }

            # Rebalance if needed
            if date in rebalance_dates:
                cfas = self.compute_cfas(all_signals.loc[:date].tail(21))
                cov = cov_matrices.get(str(date.date()), cov_matrices[max(cov_matrices.keys())])
                new_weights = self.score_to_weights(cfas, cov)

                # Apply transaction costs
                turnover, tc_drag = self.compute_turnover_and_tc(
                    new_weights, current_weights
                )
                result['turnover'] = turnover
                result['tc_drag'] = tc_drag
                result['portfolio_return'] -= tc_drag

                current_weights = new_weights

            portfolio_returns.append(result)

        df = pd.DataFrame(portfolio_returns).set_index('date')

        # Performance metrics
        self._print_performance_metrics(df)

        return df

    def _print_performance_metrics(self, results: pd.DataFrame) -> None:
        """Print key performance statistics."""
        r = results['portfolio_return']
        ann_ret = r.mean() * 252
        ann_vol = r.std() * np.sqrt(252)
        sharpe = ann_ret / ann_vol if ann_vol > 0 else 0

        # Drawdown
        cum = (1 + r).cumprod()
        peak = cum.cummax()
        dd = (cum - peak) / peak
        max_dd = dd.min()

        # Calmar
        calmar = ann_ret / abs(max_dd) if max_dd != 0 else 0

        print("\n" + "=" * 55)
        print(" FLOW ALPHA STRATEGY BACKTEST RESULTS ")
        print("=" * 55)
        print(f" Annualized Return : {ann_ret * 100:+.2f}%")
        print(f" Annualized Vol: {ann_vol * 100:.2f}%")
        print(f" Sharpe Ratio : {sharpe:.3f}")
        print(f"Max Drawdown : {max_dd * 100:.2f}%")
        print(f" Calmar Ratio : {calmar:.3f}")
        print(f"Avg Daily Turnover : {results['turnover'].mean() * 100:.2f}%")
        print(f"Avg TC Drag /Day: {results['tc_drag'].mean() * 10000:.1f}bps")
        print(f"Avg Gross Exposure : {results['gross_exposure'].mean():.2f}x")
        print("=" * 55)


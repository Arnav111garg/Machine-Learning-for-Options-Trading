import pandas as pd
import numpy as np
from scipy.stats import t as t_dist
from typing import Optional, Tuple, List, Dict
from collections import defaultdict
from dataclasses import dataclass, field

@dataclass
class BlockTrade:
    trade_id: str
    timestamp: float
    symbol: str
    strike: float
    expiry: str
    option_type: str  # 'C' or 'P'
    size: int
    exec_price: float
    bid: float
    ask: float
    spot: float
    delta: float
    gamma: float
    vega: float
    iv: float
    adv_20d: float
    # Computed fields
    ppm: float = field(init=False)
    size_vs_adv: float = field(init=False)
    dollar_premium: float = field(init=False)
    delta_notional: float = field(init=False)
    initiating_side: str = field(init=False)
    information_score: float = field(init=False)

    def __post_init__(self):
        spread = self.ask - self.bid
        if spread > 0:
            self.ppm = (self.exec_price - self.bid) / spread
        else:
            self.ppm = 0.5

        self.size_vs_adv = self.size / max(self.adv_20d, 1.0)
        self.dollar_premium = self.size * 100.0 * self.exec_price
        self.delta_notional = self.size * 100.0 * abs(self.delta) * self.spot

        # Lee-Ready rule for initiating side
        mid = (self.bid + self.ask) / 2.0
        if self.exec_price > mid:
            self.initiating_side = 'BUYER'
        elif self.exec_price < mid:
            self.initiating_side = 'SELLER'
        else:
            self.initiating_side = 'UNKNOWN'

        # Information score combining PPM, size, and spread
        ppm_score = abs(self.ppm - 0.5) * 2.0  # 0 at mid, 1 at ask/bid
        size_score = min(1.0, self.size_vs_adv / 0.10)  # Cap at 10% ADV
        spread_score = min(1.0, (self.ask - self.bid) / self.exec_price / 0.05)

        self.information_score = 0.4 * ppm_score + 0.4 * size_score + 0.2 * spread_score

class BlockTradeAnalyzer:
    """
    Comprehensive block trade detection, classification, and signal generation.
    """
    def __init__(
        self,
        min_size: int = 250,
        min_adv_fraction: float = 0.05,
        complex_match_window_minutes: float = 30.0
    ):
        self.min_size = min_size
        self.min_adv_fraction = min_adv_fraction
        self.complex_match_window_s = complex_match_window_minutes * 60.0

    def filter_blocks(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Filter raw trade dataframe to block trades only.
        """
        mask_abs = df['size'] >= self.min_size
        mask_rel = df['size'] >= self.min_adv_fraction * df['adv_20d']
        return df[mask_abs & mask_rel].copy()

    def classify_block_type(self, block: BlockTrade) -> str:
        """
        Classify a block trade into informational categories.
        """
        # Hedging pattern: deep ITM, long expiry, low information score
        if abs(block.delta) > 0.80 and block.information_score < 0.3:
            return 'INSTITUTIONAL_HEDGE'

        # Speculative pattern: OTM, high information score
        if abs(block.delta) < 0.35 and block.information_score > 0.6:
            return 'SPECULATIVE_DIRECTIONAL'

        # Volatility bet: near-ATM, high vega relative to delta
        vega_delta_ratio = abs(block.vega) / (abs(block.delta) + 1e-6)
        if 0.30 < abs(block.delta) < 0.70 and vega_delta_ratio > 2.0:
            return 'VOLATILITY_BET'

        # Tail risk: far OTM puts
        if block.option_type == 'P' and block.delta > -0.20:
            return 'TAIL_RISK_HEDGE'

        return 'UNCLASSIFIED'

    def detect_complex_blocks(
        self,
        blocks: List[BlockTrade]
    ) -> List[Dict]:
        """
        Detect complex multi-leg block structures (risk reversals, collars, etc.)
        """
        complex_trades = []
        used_indices = set()

        # Sort by timestamp
        sorted_blocks = sorted(blocks, key=lambda b: b.timestamp)

        for i, b1 in enumerate(sorted_blocks):
            if i in used_indices:
                continue

            for j, b2 in enumerate(sorted_blocks[i+1:], start=i+1):
                if j in used_indices:
                    continue

                # Check time proximity
                if b2.timestamp - b1.timestamp > self.complex_match_window_s:
                    break

                # Check same underlying, same expiry
                if b1.symbol != b2.symbol or b1.expiry != b2.expiry:
                    continue

                # Risk Reversal detection
                if (b1.option_type != b2.option_type and b1.symbol == b2.symbol):
                    call_b = b1 if b1.option_type == 'C' else b2
                    put_b = b1 if b1.option_type == 'P' else b2

                    # Similar size (within 20%)
                    size_ratio = min(call_b.size, put_b.size) / max(call_b.size, put_b.size)

                    if size_ratio > 0.80:
                        # Check if call strike > put strike
                        if call_b.strike > put_b.strike:
                            net_delta = call_b.delta * call_b.size - abs(put_b.delta) * put_b.size
                            net_premium = (call_b.exec_price - put_b.exec_price) * call_b.size
                            complex_trades.append({
                                'type': 'RISK_REVERSAL',
                                'symbol': b1.symbol,
                                'timestamp': b1.timestamp,
                                'call_strike': call_b.strike,
                                'put_strike': put_b.strike,
                                'expiry': b1.expiry,
                                'size': min(call_b.size, put_b.size),
                                'net_delta': net_delta,
                                'net_premium': net_premium,
                                'direction': 'BULLISH' if net_delta > 0 else 'BEARISH',
                                'legs': [b1, b2]
                            })
                            used_indices.update([i, j])

        return complex_trades

    def compute_kyle_lambda(
        self,
        blocks: List[BlockTrade],
        window: int = 20
    ) -> pd.Series:
        """
        Estimate Kyle's lambda (price impact) from block trade data.
        Regresses price changes on signed volume.
        """
        if len(blocks) < window:
            return pd.Series(dtype=float)

        results = []
        for idx in range(window, len(blocks)):
            subset = blocks[idx - window : idx]

            # Price changes (underlying)
            dp = np.diff([b.spot for b in subset])

            # Signed delta-notional flow
            signed_flow = np.array([
                b.delta_notional * (1 if b.initiating_side == 'BUYER' else -1)
                for b in subset[:-1]
            ])

            if np.std(signed_flow) < 1e-6:
                continue

            # OLS: dp = lambda * signed_flow + eps
            X = signed_flow.reshape(-1, 1)
            lam = np.linalg.lstsq(X, dp, rcond=None)[0][0]

            results.append({
                'timestamp': subset[-1].timestamp,
                'kyle_lambda': lam,
                'r_squared': np.corrcoef(signed_flow, dp)[0, 1] ** 2
            })

        return pd.DataFrame(results).set_index('timestamp')['kyle_lambda']

    def generate_signal(
        self,
        blocks: List[BlockTrade],
        lookback_hours: float = 24.0
    ) -> Dict[str, float]:
        """
        Generate directional signal from recent block activity.
        Returns signed score in [-1, 1] for each underlying.
        """
        signals = defaultdict(list)
        cutoff = blocks[-1].timestamp - lookback_hours * 3600 if blocks else 0

        for b in blocks:
            if b.timestamp < cutoff:
                continue

            block_type = self.classify_block_type(b)
            if block_type not in ['SPECULATIVE_DIRECTIONAL', 'VOLATILITY_BET']:
                continue

            # Directional signal construction
            # For calls: BUY = bullish, SELL = bearish
            # For puts: BUY = bearish, SELL = bullish
            direction_mult = 1.0 if b.option_type == 'C' else -1.0
            side_mult = 1.0 if b.initiating_side == 'BUYER' else -1.0

            weighted_signal = (
                direction_mult * side_mult *
                b.information_score *
                b.delta_notional
            )
            signals[b.symbol].append(weighted_signal)

        # Aggregate by symbol
        result = {}
        for symbol, sigs in signals.items():
            net = np.sum(sigs)
            normalization = max(abs(s) for s in sigs) * len(sigs)
            result[symbol] = np.clip(net / normalization if normalization > 0 else 0, -1, 1)

        return result


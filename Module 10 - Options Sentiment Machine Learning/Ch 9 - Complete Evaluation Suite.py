import numpy as np
import pandas as pd
from scipy.stats import spearmanr, t as t_dist
from typing import List, Dict, Optional, Tuple

class SignalEvaluator:
    """
    Comprehensive signal evaluation for options sentiment models.
    Implements: IC/IR, decay analysis, portfolio backtests, robustness tests.
    """

    def __init__(
        self,
        signal: pd.Series,
        returns: pd.Series,
        name: str = 'Signal'
    ):
        self.signal = signal
        self.returns = returns
        self.name = name

    def _align(self, fwd_h: int) -> pd.DataFrame:
        """Align signal and h-day forward returns, dropping NaN."""
        fwd = self.returns.rolling(fwd_h).sum().shift(-fwd_h)
        df = pd.DataFrame({'signal': self.signal, 'fwd_ret': fwd}).dropna()
        return df

    def ic_series(self, horizon: int = 5, window: int = 63) -> pd.Series:
        """Rolling IC time series."""
        df = self._align(horizon)
        ics = []
        for t in range(window, len(df)):
            sub = df.iloc[t - window : t]
            ic, _ = spearmanr(sub['signal'], sub['fwd_ret'])
            ics.append({'date': df.index[t], 'ic': ic})
        return pd.DataFrame(ics).set_index('date')['ic']

    def ic_stats(self, horizons: List[int] = [1, 2, 5, 10, 21]) -> pd.DataFrame:
        """IC/IR at multiple horizons with t-test and block bootstrap CI."""
        rows = []
        for h in horizons:
            df = self._align(h)
            # One-shot IC
            ic_full, pval = spearmanr(df['signal'], df['fwd_ret'])

            # Rolling IC for IR
            roll_ics = self.ic_series(horizon=h)
            ir = roll_ics.mean() / (roll_ics.std() + 1e-8)

            # Block bootstrap CI (block=21)
            B, block = 500, 21
            boot_ics = []
            ic_arr = roll_ics.dropna().values
            n = len(ic_arr)
            if n > block:
                for _ in range(B):
                    starts = np.random.randint(0, n - block, n // block)
                    sample = np.concatenate([ic_arr[s : s + block] for s in starts])[:n]
                    boot_ics.append(sample.mean())
                ci_lo, ci_hi = np.percentile(boot_ics, [2.5, 97.5])
            else:
                ci_lo, ci_hi = np.nan, np.nan

            rows.append({
                'Horizon': h,
                'IC': round(ic_full, 4),
                'p-value': round(pval, 4),
                'IR': round(ir, 3),
                'IC_CI_lo': round(ci_lo, 4) if not np.isnan(ci_lo) else ci_lo,
                'IC_CI_hi': round(ci_hi, 4) if not np.isnan(ci_hi) else ci_hi,
                'N': len(df)
            })

        return pd.DataFrame(rows).set_index('Horizon')

    def quintile_backtest(
        self,
        horizon: int = 5,
        tc_bps: float = 5.0
    ) -> Tuple[Dict, pd.DataFrame]:
        """
        Long-Short quintile portfolio backtest with transaction costs.
        Assumes single-asset (index) context; adapt for cross-sectional.
        """
        df = self._align(horizon)

        # Signal direction: positive signal = long, negative = short
        df['position'] = np.sign(df['signal'])
        df['position_lag'] = df['position'].shift(1).fillna(0)

        # Turnover (position changes)
        df['turnover'] = (df['position'] != df['position_lag']).astype(float)

        # Gross return
        df['gross_ret'] = df['position'] * df['fwd_ret']

        # Transaction costs (applied on turnover days)
        df['tc'] = df['turnover'] * tc_bps / 10000
        df['net_ret'] = df['gross_ret'] - df['tc']

        # Cumulative performance
        cum_gross = (1 + df['gross_ret']).cumprod()
        cum_net = (1 + df['net_ret']).cumprod()

        def max_dd(cum_series):
            peak = cum_series.cummax()
            dd = (cum_series - peak) / peak
            return dd.min()

        ann = 252 / horizon  # annualisation factor

        metrics = {
            'IC': spearmanr(df['signal'], df['fwd_ret'])[0],
            'Ann_Ret_Gross': df['gross_ret'].mean() * ann,
            'Ann_Ret_Net': df['net_ret'].mean() * ann,
            'Sharpe_Gross': df['gross_ret'].mean() / df['gross_ret'].astype(float).std() * np.sqrt(ann),
            'Sharpe_Net': df['net_ret'].mean() / df['net_ret'].astype(float).std() * np.sqrt(ann),
            'Max_DD': max_dd(cum_net),
            'Calmar': (df['net_ret'].mean() * ann) / abs(max_dd(cum_net) + 1e-8),
            'Hit_Rate': (df['net_ret'] > 0).mean(),
            'Turnover_Ann': df['turnover'].mean() * ann,
            'TC_Ann_bps': df['tc'].mean() * ann * 10000,
        }

        return metrics, df

    def sub_period_stability(
        self,
        horizon: int = 5,
        periods: Optional[List[Tuple[str, str, str]]] = None
    ) -> pd.DataFrame:
        """Test IC stability across market regimes."""
        if periods is None:
            periods = [
                ('GFC', '2008-01-01', '2009-12-31'),
                ('Recovery', '2010-01-01', '2013-12-31'),
                ('Low-Vol', '2014-01-01', '2019-12-31'),
                ('COVID', '2020-01-01', '2021-06-30'),
                ('Hikes', '2021-07-01', '2023-12-31'),
            ]

        rows = []
        df_full = self._align(horizon)

        for name, start, end in periods:
            sub = df_full.loc[start:end]
            if len(sub) < 30:
                continue
            ic, pval = spearmanr(sub['signal'], sub['fwd_ret'])
            rows.append({
                'Period': name,
                'Start': start,
                'End': end,
                'IC': round(ic, 4),
                'p-value': round(pval, 3),
                'N': len(sub)
            })

        return pd.DataFrame(rows).set_index('Period')

    def full_report(self, horizon: int = 5) -> None:
        """Print comprehensive evaluation report."""
        print(f"\n{'='*60}")
        print(f" SIGNAL EVALUATION REPORT : {self.name}")
        print(f"{'='*60}")

        print("\n1. IC/IR at Multiple Horizons :")
        print(self.ic_stats().to_string())

        print(f"\n2. Quintile Backtest (h={horizon}, TC=5 bps):")
        metrics, _ = self.quintile_backtest(horizon=horizon)
        for k, v in metrics.items():
            print(f"  {k:20s}: {v:.4f}" if isinstance(v, float) else f"  {k}: {v}")

        print("\n3. Sub-Period Stability :")
        print(self.sub_period_stability(horizon=horizon).to_string())
        print(f"{'='*60}\n")


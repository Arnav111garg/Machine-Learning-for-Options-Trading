import numpy as np
import pandas as pd
import torch
import torch.nn as nn
from sklearn.linear_model import RidgeCV
from sklearn.preprocessing import StandardScaler
from scipy.stats import spearmanr
from typing import List, Tuple, Optional

# Purged Time-Series Cross-Validator
class PurgedTimeSeriesCV:
    """
    Walk-forward CV with embargo period to prevent leakage.
    Standard in quantitative finance (Lopez de Prado, 2018).
    """
    def __init__(
        self,
        n_splits: int = 5,
        embargo_days: int = 21,
        min_train_size: int = 252
    ):
        self.n_splits = n_splits
        self.embargo = embargo_days
        self.min_train = min_train_size

    def split(self, X: pd.DataFrame):
        n = len(X)
        test_size = (n - self.min_train) // self.n_splits

        for i in range(self.n_splits):
            test_start = self.min_train + i * test_size
            test_end = min(test_start + test_size, n)
            train_end = test_start - self.embargo  # embargo gap

            if train_end < self.min_train:
                continue

            train_idx = list(range(0, train_end))
            test_idx = list(range(test_start, test_end))
            yield train_idx, test_idx

# LSTM Sentiment Model
class LSTMSentiment(nn.Module):
    """LSTM model for sequential sentiment features."""
    def __init__(
        self,
        input_dim: int,
        hidden_dim: int = 64,
        n_layers: int = 2,
        dropout: float = 0.4,
        output_dim: int = 1
    ):
        super().__init__()
        self.lstm = nn.LSTM(
            input_dim,
            hidden_dim,
            n_layers,
            batch_first=True,
            dropout=dropout if n_layers > 1 else 0.0
        )
        self.dropout = nn.Dropout(dropout)
        self.head = nn.Linear(hidden_dim, output_dim)

        # Weight initialisation (Xavier)
        for name, param in self.lstm.named_parameters():
            if 'weight_ih' in name:
                nn.init.xavier_uniform_(param.data)
            elif 'weight_hh' in name:
                nn.init.orthogonal_(param.data)
            elif 'bias' in name:
                nn.init.zeros_(param.data)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """x: (batch, seq_len, input_dim)"""
        out, _ = self.lstm(x)
        out = self.dropout(out[:, -1, :])  # take last sequence step
        return self.head(out)

# Scikit-learn wrapper for PyTorch LSTM training
class LSTMWrapper:
    def __init__(
        self,
        input_dim: int,
        epochs: int = 20,
        lr: float = 0.001,
        batch_size: int = 32
    ):
        self.input_dim = input_dim
        self.epochs = epochs
        self.lr = lr
        self.batch_size = batch_size
        self.model = LSTMSentiment(input_dim=input_dim)

    def fit(self, X: np.ndarray, y: np.ndarray):
        self.model.train()
        optimizer = torch.optim.Adam(self.model.parameters(), lr=self.lr)
        criterion = nn.MSELoss()

        X_t = torch.tensor(X, dtype=torch.float32)
        y_t = torch.tensor(y, dtype=torch.float32).view(-1, 1)
        dataset = torch.utils.data.TensorDataset(X_t, y_t)
        loader = torch.utils.data.DataLoader(dataset, batch_size=self.batch_size, shuffle=True)

        for epoch in range(self.epochs):
            for xb, yb in loader:
                optimizer.zero_grad()
                loss = criterion(self.model(xb), yb)
                loss.backward()
                optimizer.step()

    def predict(self, X: np.ndarray) -> np.ndarray:
        self.model.eval()
        X_t = torch.tensor(X, dtype=torch.float32)
        with torch.no_grad():
            return self.model(X_t).numpy().flatten()

# Sentiment Ensemble Model
class SentimentEnsemble:
    def __init__(self, lstm_input_dim: int):
        self.lstm = LSTMWrapper(input_dim=lstm_input_dim)
        self.ridge = RidgeCV(alphas=np.logspace(-3, 3, 10))
        self.scaler = StandardScaler()

    def fit(self, X_seq: np.ndarray, X_stat: np.ndarray, y: np.ndarray):
        self.lstm.fit(X_seq, y)
        lstm_preds = self.lstm.predict(X_seq)

        X_comb = np.hstack([X_stat, lstm_preds.reshape(-1, 1)])
        X_scaled = self.scaler.fit_transform(X_comb)
        self.ridge.fit(X_scaled, y)

    def predict(self, X_seq: np.ndarray, X_stat: np.ndarray) -> np.ndarray:
        lstm_preds = self.lstm.predict(X_seq)
        X_comb = np.hstack([X_stat, lstm_preds.reshape(-1, 1)])
        X_scaled = self.scaler.transform(X_comb)
        return self.ridge.predict(X_scaled)


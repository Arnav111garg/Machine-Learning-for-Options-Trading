import numpy as np
import pandas as pd
from sklearn.linear_model import RidgeCV
from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import TimeSeriesSplit
from scipy.stats import spearmanr

class CompositeSignalBuilder:
    """
    Build composite sentiment signals from multiple factor inputs.

    Implements: EW, IC-weighted, Ridge, PCA-based combination methods.
    """

    def __init__(
        self,
        forward_horizon: int = 5,
        ic_window: int = 63,
        n_pca_components: int = 3,
        ridge_alphas: list = None
    ):
        self.h = forward_horizon
        self.ic_window = ic_window
        self.n_pca = n_pca_components
        self.alphas = ridge_alphas or [0.01, 0.1, 1.0, 10.0, 100.0]

    def equal_weight(self, features: pd.DataFrame) -> pd.Series:
        """Equal-weighted z-score composite."""
        return features.mean(axis=1).rename('signal_ew')

    def ic_weighted(
        self,
        features: pd.DataFrame,
        returns: pd.Series
    ) -> pd.Series:
        """
        Rolling IC-weighted composite.
        Returns must be forward returns (already shifted).
        Avoids look-ahead by computing IC on lagged window.
        """
        n = len(features)
        signal = pd.Series(index=features.index, dtype=float, name='signal_icw')

        for t in range(self.ic_window, n):
            # IC computed on [t-window, t-1] (not including t)
            sub_feat = features.iloc[t - self.ic_window : t]
            sub_ret = returns.iloc[t - self.ic_window : t]

            ic_values = {}
            for col in features.columns:
                ic, _ = spearmanr(sub_feat[col].dropna(), sub_ret.dropna(), nan_policy='omit')
                ic_values[col] = max(ic, 0)  # keep only positive IC

            total_ic = sum(ic_values.values()) + 1e-10
            weights = {col: v / total_ic for col, v in ic_values.items()}

            signal.iloc[t] = sum(
                weights[col] * features.iloc[t][col]
                for col in features.columns
                if not np.isnan(features.iloc[t][col])
            )

        return signal

    def ridge_combo(
        self,
        features: pd.DataFrame,
        returns: pd.Series,
        n_train: int = 252
    ) -> pd.Series:
        """
        Walk-forward Ridge regression composite.
        Refit every 21 days on expanding window (min n_train days).
        """
        n = len(features)
        signal = pd.Series(index=features.index, dtype=float, name='signal_ridge')
        scaler = StandardScaler()
        model = RidgeCV(alphas=self.alphas, cv=TimeSeriesSplit(n_splits=5))

        for t in range(n_train, n, 21):  # Refit every 21 days
            X_train = features.iloc[:t].dropna()
            y_train = returns.iloc[:t].loc[X_train.index]
            common_idx = X_train.index.intersection(y_train.dropna().index)
            if len(common_idx) < 63:
                continue

            X = scaler.fit_transform(X_train.loc[common_idx])
            y = y_train.loc[common_idx].values

            model.fit(X, y)

            # Predict for remaining days until next refit
            end = min(t + 21, n)
            X_pred = features.iloc[t:end].dropna()
            if len(X_pred) > 0:
                X_scaled = scaler.transform(X_pred)
                preds = model.predict(X_scaled)
                signal.iloc[t : t + len(preds)] = preds

        return signal

    def pca_combo(
        self,
        features: pd.DataFrame,
        returns: pd.Series,
        n_train: int = 252
    ) -> pd.DataFrame:
        """
        PCA-based composite: decorrelate features, then regress on PCs.
        Returns signal + PC loadings for interpretability.
        """
        pca = PCA(n_components=self.n_pca, whiten=True)
        scaler = StandardScaler()

        X_all = features.dropna()
        X_sc = scaler.fit_transform(X_all)
        pcs = pca.fit_transform(X_sc)

        pc_df = pd.DataFrame(
            pcs, index=X_all.index,
            columns=[f'PC{k+1}' for k in range(self.n_pca)]
        )

        # Print PC loadings (for interpretability)
        loadings = pd.DataFrame(
            pca.components_.T,
            index=features.columns,
            columns=[f'PC{k+1}' for k in range(self.n_pca)]
        )

        # Ridge on PCs (walk-forward)
        signal = self.ridge_combo(pc_df, returns, n_train)
        signal.name = 'signal_pca'
        return signal, loadings, pca.explained_variance_ratio_

    def regime_conditional(
        self,
        features: pd.DataFrame,
        returns: pd.Series,
        vix: pd.Series
    ) -> pd.Series:
        """
        Regime-conditional composite. Separate Ridge model per VIX regime.
        """
        regimes = pd.cut(vix, bins=[0, 15, 25, 100], labels=['low', 'med', 'high'])
        signal = pd.Series(index=features.index, dtype=float, name='signal_regime')

        for regime in ['low', 'med', 'high']:
            mask = regimes == regime
            idx_r = features.index[mask]

            feat_r = features.loc[idx_r]
            ret_r = returns.loc[idx_r]

            if len(feat_r) < 126:
                # Fall back to EW if not enough data in this regime
                signal.loc[idx_r] = self.equal_weight(feat_r)
                continue

            sub_signal = self.ridge_combo(feat_r, ret_r, n_train=min(63, len(feat_r) // 2))
            signal.loc[idx_r] = sub_signal

        return signal

    def evaluate_all(
        self,
        features: pd.DataFrame,
        returns: pd.Series,
        vix: pd.Series
    ) -> pd.DataFrame:
        """
        Build and evaluate all composite methods. Return summary IC table.
        """
        fwd_returns = returns.shift(-self.h)  # h-day forward returns

        results = {}
        results['EW'] = self.equal_weight(features)
        results['IC_W'] = self.ic_weighted(features, fwd_returns)
        results['Ridge'] = self.ridge_combo(features, fwd_returns)
        results['PCA'], _, _ = self.pca_combo(features, fwd_returns)
        results['Regime'] = self.regime_conditional(features, fwd_returns, vix)

        # IC summary table
        summary = {}
        for name, sig in results.items():
            common = sig.dropna().index.intersection(fwd_returns.dropna().index)
            if len(common) > 30:
                ic, pval = spearmanr(sig.loc[common], fwd_returns.loc[common])
                summary[name] = {
                    'IC': round(ic, 4),
                    'IC_pval': round(pval, 4),
                    'ICIR': round(ic / (sig.rolling(63).apply(
                        lambda x: spearmanr(x, fwd_returns.loc[x.index])[0]
                    ).std() + 1e-8), 2),
                    'N_obs': len(common)
                }

        return pd.DataFrame(summary).T


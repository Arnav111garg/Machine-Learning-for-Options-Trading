import numpy as np
import pandas as pd
from scipy import stats
from typing import Dict, Optional

class PCRFeatureEngine:
    """
    Production-grade PCR feature construction for options sentiment ML.

    Assumptions:
    - Input df has columns: ['date', 'strike', 'expiry', 'type' (P/C),
      'volume', 'open_interest', 'premium', 'underlying_price', 'tte_days']
    """

    MATURITY_BUCKETS = {'short': (0, 7), 'med': (8, 30), 'long': (60, 9999)}
    MONEYNESS_BUCKETS = {'otm_put': (0.85, 0.95), 'atm': (0.97, 1.03), 'otm_call': (1.05, 1.15)}

    def __init__(self, lookback: int = 63, min_volume: int = 10):
        self.lookback = lookback
        self.min_volume = min_volume

    def _compute_pcr(self, df: pd.DataFrame, weight: str = 'dollar') -> pd.Series:
        """
        Compute PCR with specified weighting.

        weight: 'volume' | 'oi' | 'dollar'
        """
        if weight == 'volume':
            w_col = 'volume'
        elif weight == 'oi':
            w_col = 'open_interest'
        elif weight == 'dollar':
            # dollar = volume * premium
            df = df.copy()
            df['dollar'] = df['volume'] * df['premium']
            w_col = 'dollar'
        else:
            raise ValueError(f"Unknown weight: {weight}")

        puts = df[df['type'] == 'P'][w_col].sum()
        calls = df[df['type'] == 'C'][w_col].sum()

        if calls < self.min_volume:
            return np.nan
        return puts / calls

    def _zscore(self, series: pd.Series) -> pd.Series:
        """Rolling z-score with expanding minimum."""
        roll_mean = series.expanding(min_periods=10).mean()
        roll_std = series.expanding(min_periods=10).std()
        # Switch to fixed rolling after lookback
        mask = series.index >= series.index[min(self.lookback, len(series) - 1)]

        roll_mean[mask] = series.rolling(self.lookback).mean()[mask]
        roll_std[mask] = series.rolling(self.lookback).std()[mask]

        return (series - roll_mean) / roll_std.clip(lower=1e-8)

    def _percentile_rank(self, series: pd.Series) -> pd.Series:
        """Rolling percentile rank [0,1]."""
        return series.rolling(self.lookback).rank(pct=True)

    def build_features(self, daily_options: Dict[str, pd.DataFrame]) -> pd.DataFrame:
        """
        daily_options : dict mapping date_str -> DataFrame of that day's option chain.
        Returns : DataFrame of daily PCR features (one row per date).
        """
        records = []
        for date_str, df in sorted(daily_options.items()):
            rec = {'date': date_str}

            # Base PCR metrics
            rec['pcr_vol'] = self._compute_pcr(df, 'volume')
            rec['pcr_oi'] = self._compute_pcr(df, 'oi')
            rec['pcr_dollar'] = self._compute_pcr(df, 'dollar')

            # Maturity-stratified PCR
            for bucket, (lo, hi) in self.MATURITY_BUCKETS.items():
                sub = df[(df['tte_days'] >= lo) & (df['tte_days'] <= hi)]
                rec[f'pcr_{bucket}'] = self._compute_pcr(sub, 'dollar')

            # Moneyness-stratified PCR
            df = df.copy()
            df['moneyness'] = df['strike'] / df['underlying_price']
            for bucket, (lo, hi) in self.MONEYNESS_BUCKETS.items():
                sub = df[(df['moneyness'] >= lo) & (df['moneyness'] <= hi)]
                rec[f'pcr_{bucket}'] = self._compute_pcr(sub, 'volume')

            # Skew sentiment
            put_90 = df[(df['type'] == 'P') & (df['moneyness'].between(0.88, 0.92))]['volume'].sum()
            call_110 = df[(df['type'] == 'C') & (df['moneyness'].between(1.08, 1.12))]['volume'].sum()
            rec['pcr_skew'] = np.log((put_90 + 1) / (call_110 + 1))

            records.append(rec)

        feat = pd.DataFrame(records).set_index('date')

        # Time-series features
        base_cols = ['pcr_vol', 'pcr_oi', 'pcr_dollar']
        for col in base_cols:
            feat[f'{col}_log'] = np.log(feat[col].clip(lower=1e-4))
            feat[f'{col}_z'] = self._zscore(feat[col])
            feat[f'{col}_pct'] = self._percentile_rank(feat[col])
            feat[f'{col}_mom5'] = feat[col].diff(5)
            feat[f'{col}_mom21'] = feat[col].diff(21)
            feat[f'{col}_ma5'] = feat[col].rolling(5).mean()
            feat[f'{col}_ma21'] = feat[col].rolling(21).mean()

            # Cross-sectional acceleration
            feat[f'{col}_accel'] = feat[f'{col}_mom5'] - feat[f'{col}_mom21'] / 4

        # PCR term structure spread
        feat['pcr_term_spread'] = feat['pcr_long'] - feat['pcr_short']
        feat['pcr_term_spread_z'] = self._zscore(feat['pcr_term_spread'])

        return feat



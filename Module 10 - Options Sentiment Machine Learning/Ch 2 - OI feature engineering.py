import numpy as np
import pandas as pd
from scipy.stats import skew, kurtosis
from scipy.optimize import minimize_scalar

class OIFeatureEngine:
    """Open Interest feature construction for sentiment ML."""

    def compute_max_pain(
        self,
        oi_df: pd.DataFrame,
        spot: float,
        search_range: float = 0.15
    ) -> float:
        """
        Compute Max Pain price via grid search.

        oi_df : DataFrame with columns [strike, put_oi, call_oi]
        spot : Current underlying price
        """
        strikes = oi_df['strike'].values
        put_oi = oi_df['put_oi'].values
        call_oi = oi_df['call_oi'].values

        # Search grid: 15% around spot
        s_grid = np.linspace(spot * (1 - search_range),
                             spot * (1 + search_range), 500)

        def total_pain(S):
            call_pain = np.sum(call_oi * np.maximum(S - strikes, 0))
            put_pain = np.sum(put_oi * np.maximum(strikes - S, 0))
            return call_pain + put_pain

        pains = np.array([total_pain(s) for s in s_grid])
        return s_grid[np.argmin(pains)]

    def compute_gex(
        self,
        oi_df: pd.DataFrame,
        spot: float,
        r: float = 0.05,
        q: float = 0.0
    ) -> pd.DataFrame:
        """
        Compute Dealer Gamma Exposure (GEX) per strike.
        Assumes Black-Scholes gamma.
        """
        from scipy.stats import norm

        df = oi_df.copy()

        # Compute BS gamma for each option
        def bs_gamma(S, K, T, sigma, r, q):
            if T <= 0 or sigma <= 0:
                return 0.0
            d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
            return norm.pdf(d1) / (S * sigma * np.sqrt(T))

        df['gamma_per_share'] = df.apply(
            lambda row: bs_gamma(spot, row['strike'], row['tte_years'], row['iv'], r, q),
            axis=1
        )

        # Dollar gamma per 1% move = gamma * spot^2 * 0.01 * 100 (shares per contract)
        df['dollar_gamma'] = df['gamma_per_share'] * spot**2 * 0.01 * 100

        # GEX: long calls vs long puts (dealer is short what customers buy)
        # Assume customers are NET LONG calls and NET LONG puts
        # => Dealer is net short both => dealer gamma = -(call_gamma + put_gamma)
        # In practice, we use signed convention:
        df['gex'] = (df['call_oi'] - df['put_oi']) * df['dollar_gamma']

        return df

    def build_oi_features(
        self,
        oi_df: pd.DataFrame,
        spot: float
    ) -> dict:
        """
        Build comprehensive OI feature set.

        oi_df : per-strike OI data with [strike, put_oi, call_oi, iv, tte_years]
        """
        features = {}

        # Max Pain
        mp = self.compute_max_pain(oi_df, spot)
        features['max_pain'] = mp
        features['max_pain_dist'] = (mp - spot) / spot
        features['max_pain_dist_abs'] = abs(features['max_pain_dist'])

        # GEX
        gex_df = self.compute_gex(oi_df, spot)
        total_gex = gex_df['gex'].sum()
        features['gex_total'] = total_gex
        features['gex_sign'] = np.sign(total_gex)

        # Gamma wall : strike with largest |gex|
        features['gamma_wall'] = gex_df.loc[gex_df['gex'].abs().idxmax(), 'strike']
        features['gamma_wall_dist'] = (features['gamma_wall'] - spot) / spot

        # Zero-gamma level (linear interpolation)
        cum_gex = gex_df.sort_values('strike')['gex'].cumsum()
        sign_changes = np.where(np.diff(np.sign(cum_gex.values)))[0]

        if len(sign_changes) > 0:
            idx = sign_changes[0]
            k1, k2 = gex_df['strike'].iloc[idx], gex_df['strike'].iloc[idx + 1]
            g1, g2 = cum_gex.iloc[idx], cum_gex.iloc[idx + 1]
            features['zero_gamma'] = k1 - g1 * (k2 - k1) / (g2 - g1)
        else:
            features['zero_gamma'] = np.nan

        # OI Distribution Features
        total_oi = oi_df['put_oi'].sum() + oi_df['call_oi'].sum()
        oi_weights = (oi_df['put_oi'] + oi_df['call_oi']) / (total_oi + 1e-10)
        strikes = oi_df['strike'].values

        weighted_mean = np.average(strikes, weights=oi_weights)
        weighted_var = np.average((strikes - weighted_mean)**2, weights=oi_weights)

        features['oi_weighted_mean'] = weighted_mean
        features['oi_weighted_std'] = np.sqrt(weighted_var)
        features['oi_mean_dist'] = (weighted_mean - spot) / spot

        # OI entropy (concentration measure)
        p = oi_weights.clip(min=1e-10)
        features['oi_entropy'] = -np.sum(p * np.log(p))

        # OI PCR ratio at different moneyness bands
        moneyness = strikes / spot
        for lo, hi, name in [(0.85, 0.95, 'otm'), (0.95, 1.05, 'atm'), (1.05, 1.15, 'otc')]:
            mask = (moneyness >= lo) & (moneyness <= hi)
            sub = oi_df[mask]
            if sub.empty or sub['call_oi'].sum() == 0:
                features[f'oi_pcr_{name}'] = np.nan
            else:
                features[f'oi_pcr_{name}'] = sub['put_oi'].sum() / sub['call_oi'].sum()

        return features


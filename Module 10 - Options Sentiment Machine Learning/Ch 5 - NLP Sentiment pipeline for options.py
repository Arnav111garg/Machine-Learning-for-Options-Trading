import re
import numpy as np
import pandas as pd
from typing import List, Dict, Optional, Tuple
from dataclasses import dataclass

# Requires : pip install transformers torch scikit-learn

@dataclass
class DocumentSentiment:
    document_id: str
    timestamp: pd.Timestamp
    raw_text: str
    lm_score: float  # Loughran-McDonald
    finbert_pos: float
    finbert_neg: float
    finbert_neu: float
    uncertainty: float  # count of uncertain words
    composite: float  # final blended score

class FinancialNLPPipeline:
    """
    End-to-end NLP pipeline for financial documents.

    Features:
    - Loughran-McDonald lexicon scoring
    - FinBERT sentiment (transformers)
    - Uncertainty quantification
    - Position-weighted paragraph aggregation
    """

    # LM Negative words (subset for demonstration; full list has ~2300 words)
    LM_NEGATIVE = {
        'loss', 'losses', 'decline', 'declining', 'decreased', 'impairment',
        'write-off', 'restructuring', 'headwinds', 'challenging', 'difficult',
        'uncertainty', 'risk', 'volatile', 'pressure', 'weak', 'deteriorating',
        'adverse', 'negative', 'disappointing', 'missed', 'below', 'shortfall'
    }

    LM_POSITIVE = {
        'growth', 'increase', 'improvement', 'strong', 'record', 'exceeded',
        'outperformed', 'positive', 'robust', 'momentum', 'beat', 'above',
        'guidance', 'expand', 'accelerating', 'favorable', 'solid', 'profitable'
    }

    LM_UNCERTAIN = {
        'approximately', 'believe', 'could', 'depends', 'likely', 'may',
        'might', 'probably', 'seems', 'uncertain', 'unclear', 'variable',
        'possibly', 'estimate', 'expected', 'anticipate'
    }

    def __init__(self, use_finbert: bool = True):
        self.use_finbert = use_finbert
        self._finbert_model = None
        self._finbert_tokenizer = None

        if use_finbert:
            self._load_finbert()

    def _load_finbert(self):
        """Lazy load FinBERT to avoid startup overhead."""
        try:
            from transformers import AutoTokenizer, AutoModelForSequenceClassification
            import torch

            model_name = "ProsusAI/finbert"
            self._finbert_tokenizer = AutoTokenizer.from_pretrained(model_name)
            self._finbert_model = AutoModelForSequenceClassification.from_pretrained(model_name)
            self._finbert_model.eval()
            print("FinBERT loaded successfully.")
        except ImportError:
            print("transformers not available. Using lexicon-only mode.")
            self.use_finbert = False

    def _preprocess(self, text: str) -> str:
        """Clean financial text for NLP processing."""
        # Remove tables (lines with many numbers / pipes)
        text = re.sub(r'^\s*[\d \.\ ,\%\ $ \|\s ]{20,}\s*$', '', text, flags=re.MULTILINE)
        # Remove URLs
        text = re.sub(r'https?://\S+', '', text)
        # Normalise whitespace
        text = re.sub(r'\s+', ' ', text).strip()
        # Preserve sentence boundaries
        return text

    def _tokenise_words(self, text: str) -> List[str]:
        """Simple word tokeniser for lexicon matching."""
        words = re.findall(r"[a-z]+(?:[-'][a-z]+)*", text.lower())
        return words

    def lm_sentiment(self, text: str) -> Tuple[float, float, float]:
        """
        Loughran-McDonald sentiment scoring.
        Returns (positive_ratio, negative_ratio, uncertainty_ratio)
        """
        words = self._tokenise_words(text)
        n = max(len(words), 1)

        pos = sum(1 for w in words if w in self.LM_POSITIVE)
        neg = sum(1 for w in words if w in self.LM_NEGATIVE)
        unc = sum(1 for w in words if w in self.LM_UNCERTAIN)

        return pos / n, neg / n, unc / n

    def finbert_sentiment(self, text: str, max_length: int = 512) -> Tuple[float, float, float]:
        """
        FinBERT sentiment on single text chunk.
        Returns (positive_prob, negative_prob, neutral_prob).
        """
        if not self.use_finbert or self._finbert_model is None:
            return 0.33, 0.33, 0.33

        import torch

        inputs = self._finbert_tokenizer(
            text, return_tensors="pt",
            max_length=max_length, truncation=True, padding=True
        )

        with torch.no_grad():
            logits = self._finbert_model(**inputs).logits
            probs = torch.softmax(logits, dim=-1).squeeze().numpy()

        # FinBERT label order: [positive, negative, neutral]
        return float(probs[0]), float(probs[1]), float(probs[2])

    def paragraph_weighted_sentiment(self, text: str, position_weight: str = 'first_last') -> Dict:
        """
        Split document into paragraphs and aggregate with position weighting.
        position_weight : 'uniform' | 'first_last' | 'exponential_decay'
        """
        paragraphs = [p.strip() for p in text.split('\n\n') if len(p.strip()) > 50]
        n = len(paragraphs)

        if n == 0:
            return {'composite': 0.0, 'uncertainty': 0.0, 'n_paragraphs': 0}

        # Position weights
        if position_weight == 'first_last':
            # First and last paragraphs get 3x weight (opening / closing remarks most informative)
            weights = np.ones(n)
            weights[0] *= 3
            weights[-1] *= 3
            weights /= weights.sum()
        elif position_weight == 'exponential_decay':
            weights = np.exp(-0.1 * np.arange(n))
            weights /= weights.sum()
        else:
            weights = np.ones(n) / n

        para_scores = []
        for para in paragraphs:
            clean = self._preprocess(para)
            lm_pos, lm_neg, lm_unc = self.lm_sentiment(clean)

            if self.use_finbert and len(clean) > 20:
                fb_pos, fb_neg, fb_neu = self.finbert_sentiment(clean)
                # Blend LM and FinBERT (equal weight by default)
                composite = 0.5 * (lm_pos - lm_neg) + 0.5 * (fb_pos - fb_neg)
            else:
                composite = lm_pos - lm_neg

            para_scores.append({
                'composite': composite,
                'uncertainty': lm_unc
            })

        final_composite = sum(w * s['composite'] for w, s in zip(weights, para_scores))
        final_uncertainty = sum(w * s['uncertainty'] for w, s in zip(weights, para_scores))

        return {
            'composite': final_composite,
            'uncertainty': final_uncertainty,
            'n_paragraphs': n
        }

    def score_corpus(self, documents: List[Dict], position_weight: str = 'first_last') -> pd.DataFrame:
        """
        Score a list of documents.
        documents : list of dicts with keys ['id', 'timestamp', 'text', 'ticker']
        """
        records = []
        for doc in documents:
            result = self.paragraph_weighted_sentiment(
                doc['text'], position_weight=position_weight
            )
            records.append({
                'doc_id': doc.get('id', ''),
                'timestamp': doc['timestamp'],
                'ticker': doc.get('ticker', ''),
                'composite': result['composite'],
                'uncertainty': result['uncertainty'],
                'n_para': result['n_paragraphs']
            })

        df = pd.DataFrame(records)
        df['timestamp'] = pd.to_datetime(df['timestamp'])
        df = df.sort_values('timestamp')

        # Z-score per ticker
        df['composite_z'] = df.groupby('ticker')['composite'].transform(
            lambda x: (x - x.rolling(20, min_periods=5).mean()) /
            x.rolling(20, min_periods=5).std().clip(lower=1e-8)
        )

        return df


import numpy as np
import pandas as pd
from sklearn.feature_selection import mutual_info_regression
from scipy.optimize import minimize

class CrossSourceFusion:
    """
    Integrate signals from multiple data sources.
    Handles: alignment, correlation, diversification, feature selection.
    """

    def align_signals(
        self,
        signals: dict,
        reference_index: pd.DatetimeIndex,
        lag_days: int = 1
    ) -> pd.DataFrame:
        """
        Align all signals to a common daily index with proper look-ahead avoidance.

        signals: dict mapping signal_name -> pd.Series (can be higher / lower frequency)
        lag_days: minimum lag to apply (default 1: use yesterday's signal for today)
        """
        aligned = {}
        for name, series in signals.items():
            # Forward-fill to reference index (point-in-time)
            reindexed = series.reindex(reference_index, method='ffill')
            # Apply mandatory lag
            aligned[name] = reindexed.shift(lag_days)

        return pd.DataFrame(aligned).dropna(how='all')

    def compute_diversification_ratio(self, signals: pd.DataFrame) -> float:
        """
        Compute the Diversification Ratio of equal-weighted signal combination.
        """
        corr_matrix = signals.corr().values
        n = len(signals.columns)

        # Equal weight
        w = np.ones(n) / n
        individual_vols = signals.std().values
        portfolio_vol = np.sqrt(w @ corr_matrix @ w * np.outer(individual_vols, individual_vols).diagonal().mean())
        weighted_avg_vol = w @ individual_vols

        return weighted_avg_vol / (portfolio_vol + 1e-10)

    def maximum_diversification_weights(
        self,
        signals: pd.DataFrame,
        window: int = 63
    ) -> pd.Series:
        """
        Compute Maximum Diversification Portfolio weights for signal combination.
        Uses rolling covariance.
        """
        cov = signals.tail(window).cov().values
        vols = np.sqrt(np.diag(cov))
        n = len(vols)

        def neg_dr(w):
            port_vol = np.sqrt(w @ cov @ w)
            return -(w @ vols) / (port_vol + 1e-10)

        constraints = [{'type': 'eq', 'fun': lambda w: w.sum() - 1}]
        bounds = [(0, 1)] * n
        w0 = np.ones(n) / n

        result = minimize(
            neg_dr, w0, method='SLSQP',
            constraints=constraints, bounds=bounds
        )

        return pd.Series(result.x, index=signals.columns, name='mdp_weights')

    def mrmr_feature_selection(
        self,
        features: pd.DataFrame,
        target: pd.Series,
        k: int = 10
    ) -> list:
        """
        Minimum Redundancy Maximum Relevance (mRMR) feature selection.
        Returns top k features by mRMR criterion.
        """
        common = features.dropna().index.intersection(target.dropna().index)
        X = features.loc[common].values
        y = target.loc[common].values

        n_features = X.shape[1]
        feature_names = list(features.columns)

        # Relevance: MI between each feature and target
        relevance = mutual_info_regression(X, y)

        # Greedy mRMR selection
        selected = []
        remaining = list(range(n_features))

        # First feature: highest relevance
        best_idx = np.argmax(relevance)
        selected.append(best_idx)
        remaining.remove(best_idx)

        for _ in range(min(k - 1, n_features - 1)):
            mrmr_scores = []
            for i in remaining:
                # Redundancy: average MI with already-selected features
                redundancy = np.mean([
                    mutual_info_regression(X[:, [j]], X[:, i].reshape(-1, 1)).item()
                    for j in selected
                ])
                mrmr_scores.append(relevance[i] - redundancy)

            best_remaining = remaining[np.argmax(mrmr_scores)]
            selected.append(best_remaining)
            remaining.remove(best_remaining)

        return [feature_names[i] for i in selected]

    def build_cross_asset_features(
        self,
        primary_signals: pd.DataFrame,
        cross_asset_signals: dict,
        lags: list = [1, 3, 5]
    ) -> pd.DataFrame:
        """
        Build cross-asset lead-lag features.

        cross_asset_signals: dict mapping 'name' -> pd.Series
        """
        all_features = primary_signals.copy()

        for asset_name, series in cross_asset_signals.items():
            z_series = (series - series.rolling(63).mean()) / series.rolling(63).std().clip(lower=1e-8)

            for lag in lags:
                col_name = f'cross_{asset_name}_lag{lag}'
                all_features[col_name] = z_series.shift(lag).reindex(
                    primary_signals.index, method='ffill'
                )

        return all_features


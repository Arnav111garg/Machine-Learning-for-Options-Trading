import numpy as np
import pandas as pd
from scipy.stats import norm
from scipy.integrate import quad

class SentimentFactorEngine:
    """
    Compute core options sentiment factors from market data.
    """

    def __init__(self, lookback: int = 63):
        self.lookback = lookback

    def vrp(
        self,
        implied_vol: pd.Series,
        realised_vol: pd.Series
    ) -> pd.DataFrame:
        """
        Compute VRP features.
        Both series should be annualised vol (not variance).
        """
        df = pd.DataFrame({'iv': implied_vol, 'rv': realised_vol})

        df['vrp_level'] = df['iv'] - df['rv']
        df['vrp_ratio'] = df['iv'] / df['rv'].clip(lower=0.01)
        df['vrp_norm'] = (df['iv'] - df['rv']) / df['iv'].clip(lower=0.01)

        # Z-score
        for col in ['vrp_level', 'vrp_ratio', 'vrp_norm']:
            df[f'{col}_z'] = (
                (df[col] - df[col].rolling(self.lookback).mean()) /
                df[col].rolling(self.lookback).std().clip(lower=1e-8)
            )

        # Lagged features
        for lag in [5, 10, 21]:
            df[f'vrp_level_lag{lag}'] = df['vrp_level'].shift(lag)

        # VRP regime (tercile)
        df['vrp_regime'] = pd.qcut(
            df['vrp_level'].rolling(252).rank(pct=True),
            q=3,
            labels=['low', 'mid', 'high']
        )
        return df

    def iv_term_structure(
        self,
        iv_1m: pd.Series,
        iv_3m: pd.Series,
        iv_6m: pd.Series = None
    ) -> pd.DataFrame:
        """Compute IV term structure features."""
        df = pd.DataFrame({'iv_1m': iv_1m, 'iv_3m': iv_3m})
        if iv_6m is not None:
            df['iv_6m'] = iv_6m

        df['tss_1m_3m'] = (df['iv_3m'] - df['iv_1m']) / df['iv_1m'].clip(lower=0.01)

        if iv_6m is not None:
            df['tss_1m_6m'] = (df['iv_6m'] - df['iv_1m']) / df['iv_1m'].clip(lower=0.01)
            # Curvature: is the curve concave or convex?
            df['tss_curvature'] = df['iv_3m'] - 0.5 * (df['iv_1m'] + df['iv_6m'])

        # Term structure regime
        df['contango'] = (df['tss_1m_3m'] > 0).astype(int)

        # Z-score
        df['tss_z'] = (
            (df['tss_1m_3m'] - df['tss_1m_3m'].rolling(self.lookback).mean()) /
            df['tss_1m_3m'].rolling(self.lookback).std().clip(lower=1e-8)
        )
        return df

    def skew_features(
        self,
        rr_25: pd.Series,
        bf_25: pd.Series
    ) -> pd.DataFrame:
        """
        Compute risk reversal and butterfly features.
        rr_25: 25-delta risk reversal (call_vol - put_vol, typically negative)
        bf_25: 25-delta butterfly spread
        """
        df = pd.DataFrame({'rr': rr_25, 'bf': bf_25})

        for col in ['rr', 'bf']:
            df[f'{col}_z'] = (
                (df[col] - df[col].rolling(self.lookback).mean()) /
                df[col].rolling(self.lookback).std().clip(lower=1e-8)
            )
            df[f'{col}_pct'] = df[col].rolling(self.lookback).rank(pct=True)
            df[f'{col}_mom21'] = df[col].diff(21)
            df[f'{col}_extrema'] = (
                (df[f'{col}_pct'] > 0.90) | (df[f'{col}_pct'] < 0.10)
            ).astype(int)

        # Skew term structure
        df['skew_acceleration'] = df['rr'].diff(5) - df['rr'].diff(21) / 4

        return df

    def build_sentiment_vector(
        self,
        vrp_df: pd.DataFrame,
        tss_df: pd.DataFrame,
        skew_df: pd.DataFrame,
        pcr_z: pd.Series,
        gex_z: pd.Series,
        vix: pd.Series,
        vvix: pd.Series = None
    ) -> pd.DataFrame:
        """
        Assemble comprehensive sentiment feature vector.
        All inputs indexed by date.
        """
        vix_z = (vix - vix.rolling(self.lookback).mean()) / vix.rolling(self.lookback).std().clip(lower=1e-8)

        feat = pd.DataFrame({
            'vrp_norm_z': vrp_df['vrp_norm_z'],
            'rr_z': skew_df['rr_z'],
            'tss_z': tss_df['tss_z'],
            'bf_z': skew_df['bf_z'],
            'vix_z': vix_z,
            'pcr_z': pcr_z,
            'gex_z': gex_z,
            'vrp_regime_high': (vrp_df.get('vrp_regime') == 'high').astype(float),
            'contango': tss_df['contango'].astype(float),
        })

        if vvix is not None:
            vvix_z = (vvix - vvix.rolling(self.lookback).mean()) / vvix.rolling(self.lookback).std().clip(lower=1e-8)
            feat['vvix_z'] = vvix_z

        return feat.dropna()


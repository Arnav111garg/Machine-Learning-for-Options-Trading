import numpy as np
import pandas as pd
from scipy.stats import norm

class EventFeatureEngine:
    """
    Event-conditional feature engineering for options sentiment ML.

    Handles: Earnings, FOMC, Macro data releases, Index rebalancing
    """

    @staticmethod
    def implied_move(atm_call: float, atm_put: float, spot: float) -> float:
        """ATM straddle-based implied move (proportion of spot)."""
        return (atm_call + atm_put) / spot

    @staticmethod
    def event_strip_vol(
        sigma_pre: float,
        t_pre: float,
        sigma_post: float,
        t_post: float
    ) -> float:
        """
        Extract single-day event variance from two expiry IVs.

        sigma_pre : IV of expiry just before event (in years)
        t_pre : Days to that expiry / 252
        sigma_post : IV of expiry just after event
        t_post : Days to that expiry / 252

        Returns: Event day implied vol (annualised)
        """
        var_pre = sigma_pre**2 * t_pre
        var_post = sigma_post**2 * t_post

        event_var = var_post - var_pre  # variance attributed to event day
        event_var = max(event_var, 0)   # non-negativity constraint

        # Annualise: event_var is 1-day variance
        return np.sqrt(event_var * 252)

    def build_earnings_features(
        self,
        options_data: pd.DataFrame,
        earnings_history: pd.DataFrame,
        consensus: pd.DataFrame,
        t: pd.Timestamp,
        event_date: pd.Timestamp
    ) -> dict:
        """
        Build pre-earnings feature set.

        options_data : Current options chain (with [tte_days, iv, type, strike])
        earnings_history : Past actual EPS/Rev vs. estimates
        consensus : Current analyst estimates
        t: Current date
        event_date : Earnings announcement date
        """
        feat = {}
        spot = options_data['underlying_price'].iloc[0]

        # Days to event
        feat['dte'] = (event_date - t).days
        feat['dte_sq'] = feat['dte']**2  # non-linear relationship

        # Implied move from ATM straddle
        # Find options closest to event date
        pre_exp = options_data[options_data['expiry'] < event_date]
        post_exp = options_data[options_data['expiry'] >= event_date]

        if not post_exp.empty:
            # Nearest post-event expiry
            nearest_post = post_exp.groupby('expiry').first().index[0]
            atm_post = post_exp[
                (post_exp['expiry'] == nearest_post) &
                (abs(post_exp['strike'] / spot - 1) < 0.02)
            ]
            if not atm_post.empty:
                iv_post = atm_post['iv'].mean()
                t_post = (nearest_post - t).days / 252

                # Strip: if pre-event expiry exists
                if not pre_exp.empty:
                    nearest_pre = pre_exp.groupby('expiry').first().index[-1]
                    atm_pre = pre_exp[
                        (pre_exp['expiry'] == nearest_pre) &
                        (abs(pre_exp['strike'] / spot - 1) < 0.02)
                    ]
                    if not atm_pre.empty:
                        iv_pre = atm_pre['iv'].mean()
                        t_pre = (nearest_pre - t).days / 252
                        feat['event_vol'] = self.event_strip_vol(
                            iv_pre, t_pre, iv_post, t_post
                        )

                feat['iv_post'] = iv_post
                feat['implied_move'] = iv_post * np.sqrt(t_post) * 0.7979

        # Historical move vs. implied move
        if 'actual_move' in earnings_history.columns:
            hist_moves = earnings_history['actual_move'].abs().tail(8)
            feat['hist_move_mean'] = hist_moves.mean()
            feat['hist_move_std'] = hist_moves.std()
            if 'implied_move' in feat and feat['implied_move'] > 0:
                feat['move_ratio'] = feat['implied_move'] / feat['hist_move_mean']
                feat['move_zscore'] = (
                    (feat['implied_move'] - feat['hist_move_mean']) /
                    (feat['hist_move_std'] + 1e-4)
                )

        # Earnings quality from history
        if 'eps_surprise_pct' in earnings_history.columns:
            recent_eps = earnings_history['eps_surprise_pct'].tail(8)
            feat['eps_beat_rate'] = (recent_eps > 0).mean()
            feat['eps_beat_mean'] = recent_eps.mean()
            feat['eps_consistency'] = 1 - recent_eps.std() / (abs(recent_eps.mean()) + 1e-4)

        # IV run-up (pre-earnings vol expansion)
        if 'iv_history' in options_data.columns:
            iv_now = options_data['iv'].mean()
            feat['iv_runup_5d'] = iv_now - options_data['iv_history'].shift(5).mean()
            feat['iv_runup_21d'] = iv_now - options_data['iv_history'].shift(21).mean()

        # OI and PCR pre-earnings
        put_oi = options_data[options_data['type'] == 'P']['open_interest'].sum()
        call_oi = options_data[options_data['type'] == 'C']['open_interest'].sum()
        feat['pre_earnings_pcr_oi'] = put_oi / (call_oi + 1e-4)

        return feat

    def build_post_event_features(
        self,
        actual_move: float,
        implied_move: float,
        eps_actual: float,
        eps_estimate: float
    ) -> dict:
        """
        Post-event features for learning from outcomes.
        Used to train models that predict post-earnings IV crush.
        """
        return {
            'realised_vs_implied': actual_move / (implied_move + 1e-4),
            'eps_surprise_pct': (eps_actual - eps_estimate) / abs(eps_estimate + 1e-4),
            'iv_crush': None,  # computed from post-event IV
            'straddle_pnl': (abs(actual_move) - implied_move) / implied_move
        }


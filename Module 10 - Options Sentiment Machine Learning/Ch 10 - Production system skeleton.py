import numpy as np
import pandas as pd
import logging
import json
from datetime import datetime, timedelta
from typing import Optional, Dict, Any
from dataclasses import dataclass, asdict

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger('SentimentProduction')

@dataclass
class SignalOutput:
    """Structured output from production signal computation."""
    timestamp: str
    signal_value: float
    signal_z: float          # z-score vs. recent history
    confidence: float        # [0, 1]: model confidence
    features: Dict           # key feature values for attribution
    data_quality: float      # [0, 1]: fraction of features available
    model_version: str
    drift_psi: float         # PSI vs. training distribution
    trading_enabled: bool
    position_size: float     # vol-scaled, risk-adjusted

class ProductionSentimentSystem:
    """
    Production-ready options sentiment signal system.

    Design principles:
    - Fail-safe: always returns a valid signal or explicit None
    - Auditable: logs every computation step
    - Monitored: tracks feature drift and model health
    - Versioned: all model artifacts tagged with version
    """
    VERSION = "v2.1.0"
    MIN_DATA_QUALITY = 0.70      # Minimum fraction of features required
    MAX_PSI_THRESHOLD = 0.25     # Halt if PSI exceeds this
    IC_KILL_THRESHOLD = -0.02    # Halt if rolling IC below this for 21 days

    def __init__(
        self,
        model_path: str,
        feature_engine: Any,
        scaler_path: str,
        target_vol: float = 0.10
    ):
        self.model = self._load_model(model_path)
        self.features = feature_engine
        self.scaler = self._load_scaler(scaler_path)
        self.target_vol = target_vol

        # Runtime state
        self.signal_history = []
        self.ic_monitor = []
        self.is_live = True

        logger.info(f"ProductionSentimentSystem {self.VERSION} initialised")

    def _load_model(self, path: str):
        """Load model from versioned artifact store."""
        try:
            import joblib
            return joblib.load(path)
        except Exception as e:
            logger.error(f"Model load failed: {e}. Using fallback EW model.")
            return None

    def _load_scaler(self, path: str):
        """Load fitted scaler."""
        try:
            import joblib
            return joblib.load(path)
        except Exception as e:
            logger.error(f"Scaler load failed: {e}")
            return None

    def _check_data_quality(self, features: Dict) -> float:
        """Returns fraction of non-null features."""
        n_total = len(features)
        if n_total == 0:
            return 1.0
        n_valid = sum(1 for v in features.values()
                      if v is not None and not np.isnan(float(v) if not isinstance(v, str) else np.nan))
        return n_valid / n_total

    def _compute_psi(
        self,
        current_features: np.ndarray,
        reference_stats: Dict
    ) -> float:
        """Compute PSI for input drift detection."""
        psi_values = []
        means = reference_stats.get('means', [])
        stds = reference_stats.get('stds', [])
        for i, (mean, std) in enumerate(zip(means, stds)):
            if std < 1e-8:
                continue
            z_current = (current_features[i] - mean) / std
            # Use 5 equal-width buckets in z-score space
            buckets = np.linspace(-3, 3, 6)
            p_ref = np.diff(np.array([0.0228, 0.1587, 0.5, 0.8413, 0.9772, 1.0]))
            p_cur = np.histogram(z_current, bins=buckets)[0] / 1.0 + 1e-10
            p_cur = p_cur / p_cur.sum()
            psi = np.sum((p_cur - p_ref) * np.log(p_cur / (p_ref + 1e-10)))
            psi_values.append(psi)

        return float(np.mean(psi_values)) if psi_values else 0.0

    def _vol_scale_position(
        self,
        signal: float,
        recent_signal_std: float,
        recent_pnl_std: float
    ) -> float:
        """Volatility-scaled position sizing."""
        if recent_signal_std < 1e-8 or recent_pnl_std < 1e-8:
            return 0.0

        # Scale signal to unit z-score
        z = signal / recent_signal_std

        # Position = target_vol / recent_pnl_volatility * signal_z
        raw_size = self.target_vol / (recent_pnl_std * np.sqrt(252)) * z

        # Hard caps
        max_position = 0.20  # 20% max position
        return float(np.clip(raw_size, -max_position, max_position))

    def compute_signal(
        self,
        market_data: Dict,
        news_data: Optional[Dict] = None,
        reference_stats: Optional[Dict] = None
    ) -> Optional[SignalOutput]:
        """
        Main signal computation entry point.
        Returns SignalOutput or None if system is halted.
        """
        if not self.is_live:
            logger.warning("System is halted. No signal generated.")
            return None

        t_str = datetime.now().isoformat()
        logger.info(f"Computing signal at {t_str}")

        try:
            # Step 1: Feature Engineering
            features_dict = self.features.compute(market_data, news_data)
            data_quality = self._check_data_quality(features_dict)

            if data_quality < self.MIN_DATA_QUALITY:
                logger.warning(
                    f"Data quality {data_quality:.2f} below threshold "
                    f"{self.MIN_DATA_QUALITY}. Signal flagged."
                )
                # Return last valid signal with reduced confidence
                if self.signal_history:
                    last = self.signal_history[-1]
                    return SignalOutput(
                        timestamp=t_str,
                        signal_value=last.signal_value * 0.5,
                        signal_z=last.signal_z * 0.5,
                        confidence=data_quality * 0.5,
                        features=features_dict,
                        data_quality=data_quality,
                        model_version=self.VERSION,
                        drift_psi=0.0,
                        trading_enabled=False,
                        position_size=0.0
                    )

            # Step 2: Build Feature Vector
            feature_names = list(features_dict.keys())
            X = np.array([features_dict[k] if features_dict[k] is not None else 0.0 for k in feature_names]).reshape(1, -1)

            # Step 3: Drift Detection
            psi = 0.0
            if reference_stats:
                psi = self._compute_psi(X[0], reference_stats)
                if psi > self.MAX_PSI_THRESHOLD:
                    logger.error(
                        f"PSI={psi:.3f} exceeds threshold {self.MAX_PSI_THRESHOLD}. "
                        "Halting system."
                    )
                    self.is_live = False
                    return None

            # Step 4: Model Inference
            if self.model is not None and self.scaler is not None:
                X_sc = self.scaler.transform(X)
                raw_signal = float(self.model.predict(X_sc)[0])
            else:
                # Fallback: equal-weighted z-score composite
                raw_signal = float(X[0].mean())

            # Step 5: Signal Normalisation
            hist_signals = [s.signal_value for s in self.signal_history[-63:]]
            if len(hist_signals) >= 10:
                mu_s = np.mean(hist_signals)
                sig_s = np.std(hist_signals)
                signal_z = (raw_signal - mu_s) / (sig_s + 1e-8)
            else:
                signal_z = raw_signal  # insufficient history

            # Step 6: Position Sizing
            hist_stds = np.std(hist_signals) if len(hist_signals) > 5 else 0.02
            hist_pnl_std = 0.01  # estimate from live PnL in production
            pos_size = self._vol_scale_position(raw_signal, hist_stds, hist_pnl_std)

            # Step 7: IC Monitor
            trading_enabled = self.is_live and data_quality >= self.MIN_DATA_QUALITY

            output = SignalOutput(
                timestamp=t_str,
                signal_value=raw_signal,
                signal_z=signal_z,
                confidence=data_quality,
                features={k: round(float(v), 6) if v is not None else None for k, v in features_dict.items()},
                data_quality=data_quality,
                model_version=self.VERSION,
                drift_psi=psi,
                trading_enabled=trading_enabled,
                position_size=pos_size if trading_enabled else 0.0
            )

            self.signal_history.append(output)
            logger.info(
                f"Signal: {raw_signal:.4f} | z={signal_z:.2f} | "
                f"pos={pos_size:.4f} | quality={data_quality:.2f} | PSI={psi:.3f}"
            )
            return output

        except Exception as e:
            logger.error(f"Signal computation failed: {e}", exc_info=True)
            return None

    def daily_health_check(self) -> Dict:
        """
        Run daily system health checks.
        Returns health report dict.
        """
        today_str = datetime.now().strftime('%Y-%m-%d')
        report = {
            'timestamp': datetime.now().isoformat(),
            'version': self.VERSION,
            'is_live': self.is_live,
            'n_signals_today': len([s for s in self.signal_history if s.timestamp.startswith(today_str)]),
            'avg_quality_24h': np.mean([s.data_quality for s in self.signal_history[-252:]]) if self.signal_history else None,
            'avg_psi_24h': np.mean([s.drift_psi for s in self.signal_history[-252:]]) if self.signal_history else None,
        }
        logger.info(f"Health check: {json.dumps(report, indent=2)}")
        return report


import numpy as np
from scipy.optimize import curve_fit
import matplotlib.pyplot as plt

def skew_power_law(tau, A, gamma):
    """Power law: |S(tau)| = A / tau^gamma """
    return A / tau ** gamma

def fit_skew_term_structure(taus, skews_obs, plot=True):
    """
    Fit power-law model to observed skew term structure.

    Parameters:
    -----------
    taus : array of maturities (years)
    skews_obs : array of observed skew (negative, e.g., -0.15)
    """
    abs_skews = np.abs(skews_obs)

    # Fit power law via nonlinear least squares
    popt, pcov = curve_fit(skew_power_law, taus, abs_skews,
                           p0=[0.05, 0.4],
                           bounds=([0, 0], [1, 1]))
    A_fit, gamma_fit = popt

    print(f"Power-law fit: |S(tau)| = {A_fit:.4f} / tau^{gamma_fit:.4f}")
    print(f"Interpretation: gamma = {gamma_fit:.3f}")
    if gamma_fit < 0.35:
        print(" => Consistent with ROUGH volatility (gamma < 0.5)")
    else:
        print(" => Consistent with standard stochastic volatility (gamma ~ 0.5)")

    # Model comparison: Heston predicts gamma = 0.5 exactly
    heston_A = abs_skews[0] * taus[0]**0.5
    print(f"\nHeston (gamma = 0.5) implied A = {heston_A:.4f}")

    if plot:
        tau_fine = np.linspace(taus[0]*0.5, taus[-1]*1.2, 100)
        plt.figure(figsize=(8, 5))
        plt.scatter(taus, abs_skews * 100, s=80, zorder=5, label='Observed', color='navy')
        plt.plot(tau_fine, skew_power_law(tau_fine, A_fit, gamma_fit) * 100,
                 'r-', lw=2, label=fr'Power law ($\gamma$ = {gamma_fit:.3f})')
        plt.plot(tau_fine, skew_power_law(tau_fine, heston_A, 0.5) * 100,
                 'g--', lw=2, label=r'Heston ($\gamma$ = 0.5)')
        plt.xlabel('Maturity (years)')
        plt.ylabel('|Skew| (vol %)')
        plt.title('Skew Term Structure: Power-Law Fit')
        plt.legend()
        plt.grid(alpha=0.3)
        plt.savefig('skew_termstruct.png', dpi=150, bbox_inches='tight')

    return A_fit, gamma_fit

# Typical SPX skew by maturity
# skew = (25d put IV - 25d call IV), approximated by dIV/dk at k=0
taus_spx = np.array([1/12, 2/12, 3/12, 6/12, 9/12, 1.0, 1.5, 2.0])
skews_spx = np.array([-0.175, -0.135, -0.110, -0.085, -0.072, -0.062, -0.052, -0.045])

A, gamma = fit_skew_term_structure(taus_spx, skews_spx)
print(f"\nHurst exponent proxy: H = 0.5 - gamma = {0.5 - gamma:.3f}")


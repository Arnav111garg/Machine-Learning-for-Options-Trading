import numpy as np
import pandas as pd
from sklearn.linear_model import Ridge
from sklearn.ensemble import GradientBoostingRegressor
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_squared_error
import warnings ; warnings.filterwarnings('ignore')

class VolSurfaceForecastingPipeline:
    """
    Comprehensive vol surface forecasting:
    1. PCA dimensionality reduction
    2. Multiple forecasting models per factor
    3. Forecast combination
    4. Surface reconstruction with arbitrage repair
    """
    def __init__(self, pca_model, n_factors=3, forecast_horizon=5):
        self.pca = pca_model
        self.d = n_factors
        self.h = forecast_horizon
        self.models = {j: {} for j in range(n_factors)}
        self.scalers = {j: StandardScaler() for j in range(n_factors)}

    def build_features(self, scores, spot_returns=None, lags=[1, 2, 3, 5, 10, 21]):
        """
        Build feature matrix from lagged scores + macro features.
        scores: (T, d) factor scores
        Returns: X (T - max_lag, n_features), valid start index
        """
        T, d = scores.shape
        max_lag = max(lags)
        features_list = []

        for t in range(max_lag, T):
            row = []
            # Lagged factor scores
            for j in range(d):
                for l in lags:
                    row.append(scores[t - l, j])
            # HAR averages
            for j in range(d):
                row.append(scores[t - 5:t, j].mean()) # weekly avg
                row.append(scores[t - 21:t, j].mean()) # monthly avg
            # Spot returns
            if spot_returns is not None:
                for l in [1, 2, 5]:
                    if t - l >= 0:
                        row.append(spot_returns[t - l])
                row.append(spot_returns[t - 5:t].mean())
            features_list.append(row)

        return np.array(features_list), max_lag

    def fit(self, scores, spot_returns=None):
        """
        Train forecasting models for each factor.
        scores: (T, d)
        """
        X, max_lag = self.build_features(scores, spot_returns)

        for j in range(self.d):
            # Target: h-step ahead score
            y_raw = scores[max_lag + self.h:, j]
            X_raw = X[:len(y_raw)]

            # Scale features
            X_sc = self.scalers[j].fit_transform(X_raw)

            # Model 1: Ridge regression (linear)
            self.models[j]['ridge'] = Ridge(alpha=1.0).fit(X_sc, y_raw)

            # Model 2: Gradient Boosting (nonlinear)
            self.models[j]['gbm'] = GradientBoostingRegressor(
                n_estimators=100, max_depth=3, learning_rate=0.05, subsample=0.8
            ).fit(X_sc, y_raw)

            # Model 3: HAR (special case)
            # Just lag-1, lag-5-avg, lag-21-avg for this factor
            X_har = np.column_stack([
                scores[max_lag - 1:-self.h - 1, j], # lag 1
                np.array([scores[max(0, t - 6):t, j].mean() for t in range(max_lag, len(scores) - self.h)]),
                np.array([scores[max(0, t - 22):t, j].mean() for t in range(max_lag, len(scores) - self.h)]),
            ])[:len(y_raw)]
            self.models[j]['har'] = Ridge(alpha=0.01).fit(X_har, y_raw)

            # Compute in-sample RMSE
            y_pred_ridge = self.models[j]['ridge'].predict(X_sc)
            rmse = np.sqrt(mean_squared_error(y_raw, y_pred_ridge))
            print(f"Factor {j + 1}: Ridge RMSE = {rmse:.5f}")

    def predict(self, scores, spot_returns=None, weights=None):
        """
        Generate h-step ahead surface forecast.
        weights: dict {'ridge': w1, 'gbm': w2, 'har': w3} per factor
        None => equal weights
        Returns: predicted surface (p,)
        """
        X, max_lag = self.build_features(scores, spot_returns)
        X_last = X[-1:, :] # most recent observation's features

        pred_scores = np.zeros(self.d)
        for j in range(self.d):
            X_sc = self.scalers[j].transform(X_last)

            p_ridge = self.models[j]['ridge'].predict(X_sc)[0]
            p_gbm = self.models[j]['gbm'].predict(X_sc)[0]

            # HAR features
            X_har_last = np.array([[
                scores[-1, j],
                scores[-6:-1, j].mean() if len(scores) > 5 else scores[:, j].mean(),
                scores[-22:-1, j].mean() if len(scores) > 21 else scores[:, j].mean(),
            ]])
            p_har = self.models[j]['har'].predict(X_har_last)[0]

            if weights is None:
                pred_scores[j] = (p_ridge + p_gbm + p_har) / 3.0
            else:
                w = weights.get(j, {'ridge': 1/3, 'gbm': 1/3, 'har': 1/3})
                pred_scores[j] = w['ridge'] * p_ridge + w['gbm'] * p_gbm + w['har'] * p_har

        # Reconstruct surface
        surface_pred = self.pca.mean_ + pred_scores @ self.pca.components_[:self.d]
        return np.maximum(surface_pred, 0.01) # vol >= 1%

    def rolling_backtest(self, all_scores, all_surfaces, train_window=252, test_window=63):
        """
        Rolling-window backtest.
        Returns RMSE per surface point over test period.
        """
        T = len(all_scores)
        rmse_list = []

        for start in range(train_window, T - test_window - self.h, test_window):
            train_sc = all_scores[start - train_window:start]
            self.fit(train_sc)

            for t in range(test_window):
                current_sc = all_scores[start - train_window:start + t]
                pred_surf = self.predict(current_sc)
                actual_surf = all_surfaces[start + t + self.h]
                rmse_list.append(np.sqrt(np.mean((pred_surf - actual_surf) ** 2)))

        return np.array(rmse_list)


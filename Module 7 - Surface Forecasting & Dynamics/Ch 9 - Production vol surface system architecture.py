import numpy as np
from scipy.optimize import minimize
from dataclasses import dataclass
from typing import List
import warnings
warnings.filterwarnings('ignore')

@dataclass
class OptionQuote:
    """ Single option market quote """
    expiry: float       # time to expiry (years)
    strike: float       # absolute strike
    forward: float      # forward price
    bid_vol: float      # bid implied vol
    ask_vol: float      # ask implied vol

    @property
    def log_moneyness(self) -> float:
        return np.log(self.strike / self.forward)

    @property
    def mid_vol(self) -> float:
        return (self.bid_vol + self.ask_vol) / 2.0

    @property
    def bid_ask_vol(self) -> float:
        return self.ask_vol - self.bid_vol

class ProductionVolSurface:
    """
    Institutional-grade implied volatility surface system.
    Pipeline:
    1. Clean quotes
    2. Calibrate SSVI parameters per tenor
    3. Interpolate smoothly across strikes and maturities
    4. Compute local vol via Dupire
    5. Arbitrage repair if needed
    """
    def __init__(self, max_bid_ask_vol=0.05, min_option_vol=0.02):
        self.max_ba = max_bid_ask_vol
        self.min_vol = min_option_vol
        self.ssvi_params = {} # {tau: {'theta': theta, 'rho': rho, 'eta': eta, 'gamma': gamma}}

    # Step 1: Data Cleaning
    def clean_quotes(self, quotes: List[OptionQuote]) -> List[OptionQuote]:
        """ Remove illiquid and potentially erroneous quotes """
        clean = []
        for q in quotes:
            # Remove negative or tiny vols
            if q.mid_vol < self.min_vol:
                continue
            # Remove excessively wide bid-ask
            if q.bid_ask_vol > self.max_ba:
                continue
            # Remove puts too deep ITM (usually illiquid)
            if q.log_moneyness < -0.8:
                continue
            # Remove calls too deep ITM
            if q.log_moneyness > 0.5:
                continue
            clean.append(q)
        return clean

    # Step 2: SSVI Calibration
    def ssvi_w(self, k, theta, rho, phi):
        """ SSVI total variance """
        return 0.5 * theta * (1.0 + rho * phi * k + np.sqrt((phi * k + rho) ** 2 + 1.0 - rho ** 2))

    def ssvi_na_penalty(self, theta, rho, eta, gamma):
        """ SSVI no-arbitrage violation penalty """
        phi = eta / (theta ** gamma * (1.0 + theta) ** (1.0 - gamma))
        # Butterfly condition: 0 <= d(theta * phi)/d_theta <= 4/(1+|rho|)
        upper = 4.0 / (1.0 + abs(rho))
        # Penalty for violation
        violation = max(0.0, theta * phi - upper) + max(0.0, -theta * phi)
        return (violation ** 2) * 1e6

    def calibrate_ssvi_slice(self, tau, quotes_tau):
        """ Calibrate SSVI for a single maturity slice """
        k_obs = np.array([q.log_moneyness for q in quotes_tau])
        w_obs = np.array([q.mid_vol ** 2 * tau for q in quotes_tau])
        # Weight by inverse bid-ask
        wts = 1.0 / np.maximum([q.bid_ask_vol for q in quotes_tau], 0.001)

        # ATM total variance (theta)
        atm_idx = np.argmin(np.abs(k_obs))
        theta0 = w_obs[atm_idx]

        def obj(params):
            rho, eta, gamma = params
            if abs(rho) >= 0.99 or eta <= 0.0 or gamma <= 0.0 or gamma >= 1.0:
                return 1e10
            phi = eta / (theta0 ** gamma * (1.0 + theta0) ** (1.0 - gamma))
            w_fit = self.ssvi_w(k_obs, theta0, rho, phi)
            fit_err = np.sum(wts * (w_fit - w_obs) ** 2)
            na_pen = self.ssvi_na_penalty(theta0, rho, eta, gamma)
            return fit_err + na_pen

        x0 = [-0.7, 0.5, 0.5]
        bounds = [(-0.99, 0.0), (0.01, 5.0), (0.01, 0.99)]
        result = minimize(obj, x0, method='L-BFGS-B', bounds=bounds)

        rho_opt, eta_opt, gamma_opt = result.x
        return {'theta': theta0, 'rho': rho_opt, 'eta': eta_opt, 'gamma': gamma_opt}

    # Step 3: Surface Building
    def fit(self, quotes: List[OptionQuote]) -> None:
        """ Full pipeline: clean, calibrate, and build surface """
        clean_quotes = self.clean_quotes(quotes)
        print(f"Cleaned quotes: {len(clean_quotes)} / {len(quotes)}")

        # Group by maturity
        taus = sorted(set(q.expiry for q in clean_quotes))

        for tau in taus:
            tau_quotes = [q for q in clean_quotes if abs(q.expiry - tau) < 1e-4]
            if len(tau_quotes) < 4: # need minimum data points
                continue
            params = self.calibrate_ssvi_slice(tau, tau_quotes)
            self.ssvi_params[tau] = params
            print(f"tau = {tau:.3f}yr: theta = {params['theta']:.4f}, "
                  f"rho = {params['rho']:.3f}, eta = {params['eta']:.3f}, "
                  f"gamma = {params['gamma']:.3f}")

    def implied_vol(self, k: float, tau: float) -> float:
        """
        Query implied vol at (k, tau) via linear interpolation of calibrated slices.
        """
        cal_taus = sorted(self.ssvi_params.keys())
        if not cal_taus:
            return 0.0

        if tau <= cal_taus[0]:
            p = self.ssvi_params[cal_taus[0]]
            phi = p['eta'] / (p['theta'] ** p['gamma'] * (1.0 + p['theta']) ** (1.0 - p['gamma']))
            w = self.ssvi_w(k, p['theta'], p['rho'], phi)
        elif tau >= cal_taus[-1]:
            p = self.ssvi_params[cal_taus[-1]]
            phi = p['eta'] / (p['theta'] ** p['gamma'] * (1.0 + p['theta']) ** (1.0 - p['gamma']))
            w = self.ssvi_w(k, p['theta'], p['rho'], phi)
        else:
            # Interpolate: find bracketing maturities
            idx = np.searchsorted(cal_taus, tau)
            t1, t2 = cal_taus[idx - 1], cal_taus[idx]
            alpha = (tau - t1) / (t2 - t1)
            p1, p2 = self.ssvi_params[t1], self.ssvi_params[t2]

            phi1 = p1['eta'] / (p1['theta'] ** p1['gamma'] * (1.0 + p1['theta']) ** (1.0 - p1['gamma']))
            phi2 = p2['eta'] / (p2['theta'] ** p2['gamma'] * (1.0 + p2['theta']) ** (1.0 - p2['gamma']))

            w1 = self.ssvi_w(k, p1['theta'], p1['rho'], phi1)
            w2 = self.ssvi_w(k, p2['theta'], p2['rho'], phi2)
            w = (1.0 - alpha) * w1 + alpha * w2 # linear interp in total variance

        return np.sqrt(max(w / tau, 1e-6))

    def surface_grid(self, k_grid, tau_grid):
        """ Evaluate surface on a grid for visualization """
        IV = np.zeros((len(tau_grid), len(k_grid)))
        for i, tau in enumerate(tau_grid):
            for j, k in enumerate(k_grid):
                IV[i, j] = self.implied_vol(k, tau)
        return IV

# Example usage with synthetic quotes
def generate_test_quotes():
    """ Generate synthetic market quotes for testing """
    quotes = []
    taus = [1/12, 3/12, 6/12, 1.0, 2.0]
    for tau in taus:
        F = 100.0 # ATM forward
        for k in np.linspace(-0.4, 0.3, 15):
            # True vol from SVI
            a, b, rho, m, s = 0.008 * tau, 0.10, -0.70, 0.01, 0.15
            w = a + b * (rho * (k - m) + np.sqrt((k - m) ** 2 + s ** 2))
            mid_vol = np.sqrt(max(w / tau, 0.001))
            quotes.append(OptionQuote(
                expiry=tau,
                strike=F * np.exp(k),
                forward=F,
                bid_vol=mid_vol - 0.005,
                ask_vol=mid_vol + 0.005,
            ))
    return quotes

test_quotes = generate_test_quotes()
vol_sys = ProductionVolSurface()
vol_sys.fit(test_quotes)

# Query the surface
print(f"\nATM 3M implied vol: {vol_sys.implied_vol(0.0, 0.25) * 100:.2f}%")

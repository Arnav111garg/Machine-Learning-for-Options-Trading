import numpy as np
from scipy.linalg import solve_triangular

class VolSurfaceKalmanFilter:
    """
    State-space model for vol surface:
    f_{t+1} = A f_t + B x_t + w_t, w_t ~ N(0, Q) [state transition]
    sigma_t = Lambda f_t + v_t, v_t ~ N(0, R) [observation]

    where x_t = log-return of spot (exogenous input to capture spot-vol link)
    """
    def __init__(self, n_factors=3, obs_dim=120):
        self.d = n_factors
        self.p = obs_dim

    def initialise_params(self, surfaces):
        """Initialise with PCA"""
        from sklearn.decomposition import PCA
        pca = PCA(n_components=self.d)
        scores = pca.fit_transform(surfaces)

        self.Lambda = pca.components_.T # (p, d)
        self.R = np.diag(np.maximum(np.var(surfaces - scores @ pca.components_, axis=0), 1e-8))

        # AR(1) per factor
        self.A = np.diag([np.corrcoef(scores[:-1, j], scores[1:, j])[0, 1] for j in range(self.d)])
        self.B = np.zeros((self.d, 1)) # spot loading (to be estimated)
        self.Q = np.diag(np.var(np.diff(scores, axis=0), axis=0))

        # Initial state
        self.f0 = np.zeros(self.d)
        self.P0 = np.eye(self.d) * 1.0
        print(f"Initialised: A_diag={np.diag(self.A)}, Q_diag={np.diag(self.Q)}")

    def filter(self, surfaces, spot_returns=None):
        """
        Run Kalman filter. Returns filtered states and log-likelihood.
        surfaces: (T, p)
        spot_returns: (T,) or None
        """
        T, p = surfaces.shape
        if spot_returns is None:
            spot_returns = np.zeros(T)

        f_pred = np.zeros((T, self.d))
        P_pred = np.zeros((T, self.d, self.d))
        f_filt = np.zeros((T, self.d))
        P_filt = np.zeros((T, self.d, self.d))
        log_lik = 0.0

        f_prev, P_prev = self.f0.copy(), self.P0.copy()

        for t in range(T):
            # Predict
            u_t = np.array([spot_returns[t]])
            f_p = self.A @ f_prev + self.B @ u_t
            P_p = self.A @ P_prev @ self.A.T + self.Q

            f_pred[t] = f_p
            P_pred[t] = P_p

            # Update
            innovation = surfaces[t] - self.Lambda @ f_p
            S = self.Lambda @ P_p @ self.Lambda.T + self.R

            # Kalman gain (efficient via inverse/Cholesky equivalent)
            K = P_p @ self.Lambda.T @ np.linalg.inv(S)

            f_prev = f_p + K @ innovation
            P_prev = (np.eye(self.d) - K @ self.Lambda) @ P_p

            f_filt[t] = f_prev
            P_filt[t] = P_prev

            # Log-likelihood contribution
            sign, logdet = np.linalg.slogdet(S)
            log_lik -= 0.5 * (logdet + innovation @ np.linalg.solve(S, innovation))

        log_lik -= 0.5 * T * p * np.log(2 * np.pi)
        return f_filt, P_filt, f_pred, P_pred, log_lik

    def predict_surface(self, f_current, h_steps=5):
        """
        Predict next h_steps surfaces given current factor state.
        Returns (h_steps, p) surface forecasts.
        """
        forecasts = []
        f = f_current.copy()
        for h in range(h_steps):
            f = self.A @ f # assume zero drift in spot
            sigma_hat = self.Lambda @ f
            forecasts.append(sigma_hat)
        return np.array(forecasts)


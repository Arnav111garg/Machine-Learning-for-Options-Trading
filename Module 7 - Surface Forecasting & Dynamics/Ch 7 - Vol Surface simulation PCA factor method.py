import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import multivariate_normal

class VolSurfaceSimulator:
    """
    Simulate vol surface paths using PCA factor dynamics.
    Each factor follows a correlated OU process.
    """
    def __init__(self, pca_model, factor_params):
        """
        pca_model : fitted sklearn PCA object
        factor_params : dict with 'kappas', 'etas', 'corr_matrix'
        kappas : mean-reversion speeds (annualised)
        etas : factor volatilities (annualised)
        """
        self.pca = pca_model
        self.kappas = np.array(factor_params['kappas'])
        self.etas = np.array(factor_params['etas'])
        self.rho_mat = np.array(factor_params['corr_matrix'])
        self.d = len(self.kappas)

    def simulate_paths(self, z0, n_paths=1000, n_steps=252, dt=1/252, include_spot=True):
        """
        Simulate n_paths factor paths of n_steps steps.
        z0: initial factor scores (d,)
        Returns:
        z_paths : (n_paths, n_steps +1, d) - factor paths
        surf_paths : (n_paths, n_steps +1, p) - surface paths
        """
        # Cholesky decomposition of factor correlation
        L = np.linalg.cholesky(self.rho_mat[:self.d, :self.d])

        # Exact OU simulation at each step
        exp_kappa = np.exp(-self.kappas * dt) # (d,)
        var_step = self.etas**2 * (1 - exp_kappa**2) / (2 * self.kappas)

        z_paths = np.zeros((n_paths, n_steps + 1, self.d))
        z_paths[:, 0, :] = z0[np.newaxis, :]

        for t in range(1, n_steps + 1):
            # Correlated standard normals
            Z = np.random.randn(n_paths, self.d)  # (n_paths, d)
            Z_corr = Z @ L.T                      # (n_paths, d)

            # OU step
            z_prev = z_paths[:, t - 1, :]
            z_paths[:, t, :] = (exp_kappa * z_prev + np.sqrt(var_step) * Z_corr)

        # Reconstruct surfaces from factors
        mean_surface = self.pca.mean_             # (p,)
        # Slice to only use the first self.d components matching our factor dynamics
        components = self.pca.components_[:self.d] # (d, p)

        # surf = mean + factors @ components
        surf_paths = z_paths @ components + mean_surface[np.newaxis, np.newaxis, :]
        surf_paths = np.maximum(surf_paths, 0.01) # vol > 1%

        return z_paths, surf_paths

    def compute_var_cvar(self, surf_paths, portfolio_vega, alpha=0.01):
        """
        Compute daily VaR and CVaR for a vega-flat portfolio.
        portfolio_vega : (p,) vega sensitivity to each surface point
        alpha : confidence level
        """
        # P&L from surface change
        d_surf = np.diff(surf_paths, axis=1) # (n_paths, n_steps, p)
        pnl = d_surf @ portfolio_vega       # (n_paths, n_steps)

        # 1-day VaR/CVaR
        daily_pnl = pnl[:, 0] # first day P&L
        var = np.percentile(daily_pnl, alpha * 100)
        cvar = daily_pnl[daily_pnl <= var].mean()

        return var, cvar, daily_pnl

    def generate_stress_scenarios(self, z0, scenario_type='crisis'):
        """
        Generate specific stress scenarios.
        """
        scenarios = {
            'crash': np.array([-3.0, -1.5, 0.5] + [0] * (self.d - 3)),
            'vol_spike': np.array([4.0, 0.0, 1.0] + [0] * (self.d - 3)),
            'unwind': np.array([2.0, 1.0, 0.0] + [0] * (self.d - 3)),
            'low_vol': np.array([-2.0, 0.5, -0.5] + [0] * (self.d - 3)),
        }
        shocks = scenarios.get(scenario_type, np.zeros(self.d))
        z_stress = z0 + shocks[:self.d]
        return self.pca.mean_ + z_stress @ self.pca.components_[:self.d]


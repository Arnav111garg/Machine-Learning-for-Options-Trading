import numpy as np
from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler
import matplotlib.pyplot as plt
import matplotlib.gridspec as gridspec

def vol_surface_pca(surfaces, k_grid, tau_grid, n_components=6):
    """
    Full PCA analysis of a vol surface time series.

    Parameters:
    -----------
    surfaces : np.ndarray of shape (T, n_tau * n_k) - daily vol surfaces
    k_grid : np.ndarray - log-moneyness grid
    tau_grid : np.ndarray - maturity grid
    n_components : int - number of PCs to extract
    """
    T, p = surfaces.shape
    n_tau, n_k = len(tau_grid), len(k_grid)

    # Fit PCA
    pca = PCA(n_components=n_components)
    scores = pca.fit_transform(surfaces)

    # Explained variance
    ev_ratio = pca.explained_variance_ratio_
    print("Explained Variance:")
    for i, ev in enumerate(ev_ratio, 1):
        print(f" PC{i}: {ev * 100:.2f}% (cumulative : {np.cumsum(ev_ratio)[i-1]*100:.2f}%)")

    # Reshape loadings
    loadings = pca.components_  # (n_components, p)
    loadings_2d = loadings.reshape(n_components, n_tau, n_k)  # visualisable

    # Plot PC loadings as surfaces
    fig = plt.figure(figsize=(16, 10))
    gs = gridspec.GridSpec(2, 3, figure=fig, hspace=0.4, wspace=0.3)

    factor_names = ['Level', 'Skew', 'Curvature', 'PC4', 'PC5', 'PC6']
    K_mesh, T_mesh = np.meshgrid(k_grid, tau_grid)

    for i in range(min(n_components, 6)):
        ax = fig.add_subplot(gs[i // 3, i % 3], projection='3d')
        loading_surf = loadings_2d[i]
        ax.plot_surface(K_mesh, T_mesh * 12, loading_surf,
                        cmap='RdBu', alpha=0.85, edgecolor='none')
        ax.set_xlabel('k', fontsize=8)
        ax.set_ylabel('Months', fontsize=8)
        ax.set_zlabel(f'PC{i+1} loading', fontsize=8)
        ax.set_title(f'PC{i+1}: {factor_names[i]} ({ev_ratio[i]*100:.1f}%)', fontsize=10)

    plt.suptitle('PCA Factor Loadings (Eigensurfaces)', fontsize=14)
    plt.savefig('pca_loadings.png', dpi=150, bbox_inches='tight')

    # OU parameter estimation for each factor
    print("\nFactor mean-reversion (OU) parameters (daily, 252 trading days):")
    dt = 1/252
    for j in range(3):
        z = scores[:, j]
        # Regress z_{t+1} on z_t
        X_reg = z[:-1].reshape(-1, 1)
        y_reg = z[1:]
        from sklearn.linear_model import LinearRegression
        reg = LinearRegression().fit(X_reg, y_reg)
        phi = reg.coef_[0]  # AR(1) coefficient
        kappa_daily = -np.log(phi)
        kappa_ann = kappa_daily * 252
        half_life = np.log(2) / kappa_ann * 252  # in trading days
        print(f" PC{j+1}: kappa = {kappa_ann:.2f}/yr, half-life = {half_life:.1f} trading days")

    return pca, scores, loadings_2d


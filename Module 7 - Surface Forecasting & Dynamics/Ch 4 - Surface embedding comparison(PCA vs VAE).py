# VAE embedding
class VolSurfaceVAE(nn.Module):
    def __init__(self, input_dim, latent_dim=4, hidden=64):
        super().__init__()
        # Encoder
        self.encoder = nn.Sequential(
            nn.Linear(input_dim, hidden), nn.ReLU(),
            nn.Linear(hidden, hidden), nn.ReLU(),
        )
        self.mu_layer = nn.Linear(hidden, latent_dim)
        self.logvar_layer = nn.Linear(hidden, latent_dim)
        # Decoder
        self.decoder = nn.Sequential(
            nn.Linear(latent_dim, hidden), nn.ReLU(),
            nn.Linear(hidden, hidden), nn.ReLU(),
            nn.Linear(hidden, input_dim), nn.Softplus() # vols > 0
        )

    def encode(self, x):
        h = self.encoder(x)
        return self.mu_layer(h), self.logvar_layer(h)

    def reparameterise(self, mu, logvar):
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mu + eps * std

    def decode(self, z):
        return self.decoder(z)

    def forward(self, x):
        mu, logvar = self.encode(x)
        z = self.reparameterise(mu, logvar)
        return self.decode(z), mu, logvar

    def elbo_loss(self, x, recon, mu, logvar, beta=1.0):
        recon_loss = nn.functional.mse_loss(recon, x, reduction='mean')
        kl_loss = -0.5 * torch.mean(1 + logvar - mu.pow(2) - logvar.exp())
        return recon_loss + beta * kl_loss, recon_loss, kl_loss

# Training
X_tensor = torch.FloatTensor(X)
vae = VolSurfaceVAE(input_dim=X.shape[1], latent_dim=4)
optimizer = torch.optim.Adam(vae.parameters(), lr=1e-3)

for epoch in range(200):
    optimizer.zero_grad()
    recon, mu, logvar = vae(X_tensor)
    loss, rl, kl = vae.elbo_loss(X_tensor, recon, mu, logvar, beta=0.1)
    loss.backward()
    optimizer.step()
    if epoch % 50 == 0:
        print(f"Epoch {epoch}: Loss = {loss.item():.5f}, Recon = {rl.item():.5f}, KL = {kl.item():.5f}")

with torch.no_grad():
    mu_vae, _ = vae.encode(X_tensor)
    X_vae = mu_vae.numpy()


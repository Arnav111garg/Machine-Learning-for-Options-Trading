import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression
import matplotlib.pyplot as plt

def compute_spot_vol_dynamics(spot_ts, atm_vol_ts, skew_ts, window=20):
    """
    Analyse how ATM vol and skew respond to spot moves.

    Parameters:
    -----------
    spot_ts : pd.Series - daily spot prices
    atm_vol_ts : pd.Series - daily ATM implied vol (1m)
    skew_ts : pd.Series - daily skew (25-delta put vol - 25-delta call vol)
    window : int - rolling window for regression
    """
    # Compute log returns and vol changes
    spot_ret = np.log(spot_ts).diff().dropna()
    d_atm_vol = atm_vol_ts.diff().dropna()
    d_skew = skew_ts.diff().dropna()

    # Align
    df = pd.DataFrame({
        'spot_ret': spot_ret,
        'd_atm': d_atm_vol,
        'd_skew': d_skew
    }).dropna()

    # Global correlations
    corr_spot_atm = df['spot_ret'].corr(df['d_atm'])
    corr_spot_skew = df['spot_ret'].corr(df['d_skew'])
    print(f"Corr(spot_ret, d_ATM_vol) = {corr_spot_atm:.4f}")
    print(f"Corr(spot_ret, d_skew) = {corr_spot_skew:.4f}")

    # OLS: d_atm = beta_0 + beta_1 * spot_ret + epsilon
    # beta_1 is the 'vanna exposure' of the ATM vol
    X = df['spot_ret'].values.reshape(-1, 1)

    reg_atm = LinearRegression().fit(X, df['d_atm'])
    reg_skew = LinearRegression().fit(X, df['d_skew'])

    print(f"\nATM vol regression on spot:")
    print(f"beta = {reg_atm.coef_[0]:.4f} (1% down move => {-reg_atm.coef_[0]*0.01*100:.2f} bps ATM vol change)")

    print(f"\nSkew regression on spot:")
    print(f"beta = {reg_skew.coef_[0]:.4f} (1% down move => {-reg_skew.coef_[0]*0.01*100:.2f} bps skew change)")

    # Rolling regression for regime analysis
    rolling_beta_atm = (
        df['d_atm'].rolling(window).cov(df['spot_ret'])
        / df['spot_ret'].rolling(window).var()
    )

    return df, rolling_beta_atm

# Simulated data for demonstration
np.random.seed(42)
n = 500
spot_ret_sim = np.random.normal(0, 0.012, n) # daily returns

# ATM vol changes: negatively correlated with spot + noise
d_atm_sim = -2.5 * spot_ret_sim + np.random.normal(0, 0.005, n)

# Skew changes: also negatively correlated (deepens on selloffs)
d_skew_sim = -0.8 * spot_ret_sim + np.random.normal(0, 0.002, n)

spot_sim = pd.Series(100 * np.exp(np.cumsum(spot_ret_sim)))
atm_sim = pd.Series(0.20 + np.cumsum(d_atm_sim))
skew_sim = pd.Series(0.05 + np.cumsum(d_skew_sim))

df, rolling_beta = compute_spot_vol_dynamics(spot_sim, atm_sim, skew_sim)


import numpy as np
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D
from scipy.optimize import minimize
from scipy.stats import norm

# Black - Scholes IV solver
def bs_call(S, K, T, r, sigma):
    """Black - Scholes call price """
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)

def implied_vol(price, S, K, T, r, tol=1e-8, max_iter=100):
    """Newton - Raphson IV solver """
    sigma = 0.2 # initial guess
    for _ in range(max_iter):
        price_est = bs_call(S, K, T, r, sigma)
        d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
        vega = S * np.sqrt(T) * norm.pdf(d1)
        diff = price_est - price
        if abs(diff) < tol:
            break
        sigma -= diff / vega
    return max(sigma, 1e-6)

# SVI smile
def svi_total_var(k, a, b, rho, m, sigma_svi):
    """SVI total variance : w(k) = a + b[ rho(k-m) + sqrt ((k-m)^2 + sigma ^2)]"""
    return a + b * (rho * (k - m) + np.sqrt((k - m)**2 + sigma_svi**2))

def svi_implied_vol(k, tau, a, b, rho, m, sigma_svi):
    """SVI implied vol from total variance """
    w = svi_total_var(k, a, b, rho, m, sigma_svi)
    return np.sqrt(np.maximum(w / tau, 1e-8))

# Build a representative surface
# Typical SPX - like parameters per maturity
svi_params_by_tau = {
    1/12: dict(a=0.0020, b=0.15, rho=-0.80, m=0.01, sigma_svi=0.12),
    3/12: dict(a=0.0050, b=0.12, rho=-0.72, m=0.01, sigma_svi=0.14),
    6/12: dict(a=0.0100, b=0.10, rho=-0.65, m=0.01, sigma_svi=0.16),
    12/12: dict(a=0.0180, b=0.08, rho=-0.58, m=0.01, sigma_svi=0.18),
    24/12: dict(a=0.0280, b=0.06, rho=-0.50, m=0.01, sigma_svi=0.20),
}

k_grid = np.linspace(-0.5, 0.3, 80)
taus = list(svi_params_by_tau.keys())
K_mesh, T_mesh = np.meshgrid(k_grid, taus)
IV_mesh = np.zeros_like(K_mesh)

for i, tau in enumerate(taus):
    p = svi_params_by_tau[tau]
    IV_mesh[i, :] = svi_implied_vol(
        k_grid, tau, p['a'], p['b'], p['rho'], p['m'], p['sigma_svi']
    )

# Plot
fig = plt.figure(figsize=(14, 6))
ax1 = fig.add_subplot(121, projection='3d')
ax1.plot_surface(K_mesh, T_mesh * 12, IV_mesh * 100,
                 cmap='RdYlGn_r', alpha=0.85, edgecolor='none')
ax1.set_xlabel('Log - moneyness k')
ax1.set_ylabel('Maturity (months)')
ax1.set_zlabel('Implied Vol (%)')
ax1.set_title('SPX - like Vol Surface')

ax2 = fig.add_subplot(122)
colors = plt.cm.viridis(np.linspace(0, 1, len(taus)))
for i, (tau, color) in enumerate(zip(taus, colors)):
    p = svi_params_by_tau[tau]
    iv_smile = svi_implied_vol(k_grid, tau, **p)
    ax2.plot(k_grid, iv_smile * 100, color=color,
             label=f'{int(tau * 12)}M', linewidth=2)
ax2.set_xlabel('Log - moneyness k')
ax2.set_ylabel('Implied Volatility (%)')
ax2.set_title('Smile Slices by Maturity')
ax2.legend()
ax2.grid(alpha=0.3)
plt.tight_layout()
plt.savefig('vol_surface.png', dpi=150, bbox_inches='tight')
print("Surface plot saved.")


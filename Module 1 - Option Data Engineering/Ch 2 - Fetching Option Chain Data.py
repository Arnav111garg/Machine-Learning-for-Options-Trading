"""
Production-grade option chain fetcher with retry logic,
rate limiting, and validation.
"""
import time
import logging
import requests
import pandas as pd
import numpy as np
from datetime import date, datetime
from typing import Optional
from functools import wraps

logger = logging.getLogger(__name__)

# --- Rate-limiting decorator -----------------------------------------------
def rate_limited(max_calls: int, period: float):
    """Decorator: enforce max_calls per 'period' seconds."""
    min_interval = period / max_calls
    last_called = [0.0]

    def decorator(func):
        @wraps(func)
        def wrapper(*args, **kwargs):
            elapsed = time.time() - last_called[0]
            wait = min_interval - elapsed
            if wait > 0:
                time.sleep(wait)
            result = func(*args, **kwargs)
            last_called[0] = time.time()
            return result
        return wrapper
    return decorator

# --- Polygon.io chain fetcher ----------------------------------------------
class PolygonOptionChainFetcher:
    BASE_URL = "https://api.polygon.io/v3/snapshot/options"

    def __init__(self, api_key: str):
        self.api_key = api_key
        self.session = requests.Session()
        self.session.headers.update({'Authorization': f'Bearer {api_key}'})

    @rate_limited(max_calls=5, period=1.0)  # Polygon free tier: 5 req/sec
    def _get(self, url: str, params: dict) -> dict:
        resp = self.session.get(url, params=params, timeout=10)
        resp.raise_for_status()
        return resp.json()

    def fetch_chain(
        self,
        ticker: str,
        expiry_date: Optional[date] = None,
        strike_min: Optional[float] = None,
        strike_max: Optional[float] = None,
        option_type: Optional[str] = None,  # 'call' or 'put'
        limit: int = 250,
    ) -> pd.DataFrame:
        """Fetch the full option chain for a ticker."""
        url = f"{self.BASE_URL}/{ticker}"
        params = {
            'limit': limit,
            'apiKey': self.api_key,
        }
        if expiry_date:
            params['expiration_date'] = expiry_date.isoformat()
        if strike_min:
            params['strike_price.gte'] = strike_min
        if strike_max:
            params['strike_price.lte'] = strike_max
        if option_type:
            params['contract_type'] = option_type

        records = []
        cursor = None
        while True:
            if cursor:
                params['cursor'] = cursor
            data = self._get(url, params)

            for item in data.get('results', []):
                d = item.get('details', {})
                g = item.get('greeks', {}) or {}
                q = item.get('day', {}) or {}
                records.append({
                    'symbol': d.get('ticker'),
                    'underlying': ticker,
                    'expiry': d.get('expiration_date'),
                    'strike': d.get('strike_price'),
                    'option_type': d.get('contract_type'),
                    'bid': item.get('last_quote', {}).get('bid'),
                    'ask': item.get('last_quote', {}).get('ask'),
                    'volume': q.get('volume', 0),
                    'open_interest': item.get('open_interest', 0),
                    'iv': item.get('implied_volatility'),
                    'delta': g.get('delta'),
                    'gamma': g.get('gamma'),
                    'theta': g.get('theta'),
                    'vega': g.get('vega'),
                })

            # Pagination
            next_url = data.get('next_url')
            if not next_url:
                break
            cursor = next_url.split('cursor=')[-1]

        df = pd.DataFrame(records)
        df = self._post_process(df)
        return df

    def _post_process(self, df: pd.DataFrame) -> pd.DataFrame:
        if df.empty:
            return df
        df['expiry'] = pd.to_datetime(df['expiry']).dt.date
        df['mid'] = (df['bid'] + df['ask']) / 2
        df['spread'] = df['ask'] - df['bid']
        df['spread_pct'] = df['spread'] / df['mid'].replace(0, np.nan)
        # Flag wide spreads (> 20% of mid) as illiquid
        df['is_liquid'] = df['spread_pct'] < 0.20
        df = df.sort_values(['expiry', 'option_type', 'strike'])
        df = df.reset_index(drop=True)
        return df


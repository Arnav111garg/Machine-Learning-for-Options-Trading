import numpy as np
from scipy.interpolate import CubicSpline
from scipy.optimize import minimize
import pandas as pd

def impute_iv_surface(
    chain: pd.DataFrame,
    spot: float,
    rate: float,
    div_yield: float,
) -> pd.DataFrame:
    """
    Impute missing IVs in an option chain using cubic spline
    interpolation in log-moneyness space, per expiry.

    chain must have columns: expiry, strike, option_type, iv, tte_years
    Returns chain with 'iv_imputed' column.
    """
    chain = chain.copy()
    chain['iv_imputed'] = chain['iv']
    chain['imputed_flag'] = False

    for expiry, grp in chain.groupby('expiry'):
        tau = grp['tte_years'].iloc[0]
        F = spot * np.exp((rate - div_yield) * tau)

        # Work on each type separately, then combine
        for otype in ['call', 'put']:
            mask = (chain['expiry'] == expiry) & (chain['option_type'] == otype)
            sub = chain.loc[mask].copy()

            # Observed (non-missing) points
            obs = sub.dropna(subset=['iv'])
            if len(obs) < 3:
                continue  # Not enough points to spline

            log_m = np.log(obs['strike'] / F)
            ivs = obs['iv'].values

            # Sort by log-moneyness
            sort_idx = np.argsort(log_m)
            x_obs = log_m.values[sort_idx]
            y_obs = ivs[sort_idx]

            # Fit cubic spline
            cs = CubicSpline(x_obs, y_obs, bc_type='not-a-knot', extrapolate=True)

            # Impute missing rows
            miss_idx = sub[sub['iv'].isna()].index
            if len(miss_idx) == 0:
                continue

            miss_lm = np.log(chain.loc[miss_idx, 'strike'] / F)
            # Clamp to observed range (no wild extrapolation)
            miss_lm_clamped = np.clip(miss_lm, x_obs.min(), x_obs.max())
            imputed_iv = cs(miss_lm_clamped)

            # Enforce IV positivity
            imputed_iv = np.maximum(imputed_iv, 0.01)

            chain.loc[miss_idx, 'iv_imputed'] = imputed_iv
            chain.loc[miss_idx, 'imputed_flag'] = True

    return chain


"""
SVI Volatility Surface Calibration
Calibrates the 5-parameter SVI model per expiry slice.
"""
import numpy as np
import pandas as pd
from scipy.optimize import minimize, differential_evolution
from scipy.stats import norm
from dataclasses import dataclass
from typing import Optional

@dataclass
class SVIParams:
    a: float        # Level
    b: float        # Slope (wings)
    rho: float      # Skew asymmetry (-1, 1)
    m: float        # Minimum location
    sigma: float    # Curvature
    tau: float      # Time to expiry (for converting to IV)

    def total_variance(self, x: np.ndarray) -> np.ndarray:
        """Compute SVI total variance w(x)."""
        return self.a + self.b * (
            self.rho * (x - self.m) +
            np.sqrt((x - self.m)**2 + self.sigma**2)
        )

    def implied_vol(self, x: np.ndarray) -> np.ndarray:
        """Compute implied vol from total variance."""
        tv = self.total_variance(x)
        tv = np.maximum(tv, 1e-10)  # Numerical floor
        return np.sqrt(tv / self.tau)

    def check_butterfly_arbitrage(self, x: np.ndarray) -> np.ndarray:
        """
        Check Fukasawa's butterfly-free condition.
        Returns g(x) array; must be >= 0 everywhere.
        """
        w = self.total_variance(x)
        # Numerical derivatives
        h = 1e-5
        w_x = (self.total_variance(x + h) - self.total_variance(x - h)) / (2 * h)
        w_xx = (self.total_variance(x + h) - 2 * w + self.total_variance(x - h)) / h**2

        g = ((1 - x * w_x / (2 * w))**2
             - (w_x**2 / 4) * (1 / w + 0.25)
             + w_xx / 2)
        return g


def calibrate_svi_slice(
    log_moneyness: np.ndarray,
    market_total_var: np.ndarray,  # iv^2 * tau
    weights: Optional[np.ndarray] = None,
    tau: float = 1.0,
) -> SVIParams:
    """
    Calibrate SVI parameters to a single expiry slice.
    Uses differential evolution (global) then SLSQP (local) refinement.
    """
    if weights is None:
        weights = np.ones_like(log_moneyness)
    weights = weights / weights.sum()

    def svi_total_var(x, a, b, rho, m, sigma):
        return a + b * (rho * (x - m) + np.sqrt((x - m)**2 + sigma**2))

    def loss(params):
        a, b, rho, m, sigma = params
        if b < 0 or sigma <= 0 or abs(rho) >= 1:
            return 1e10
        # Check minimum variance positive
        if a + b * sigma * np.sqrt(1 - rho**2) < 0:
            return 1e10
        w_fit = svi_total_var(log_moneyness, a, b, rho, m, sigma)
        if np.any(w_fit < 0):
            return 1e10
        residuals = w_fit - market_total_var
        return float(np.sum(weights * residuals**2))

    # Bounds: a free, b >=0, rho in (-1, 1), m free, sigma >0
    bounds = [
        (-0.5, 0.5),      # a
        (0.001, 2.0),     # b
        (-0.999, 0.999),  # rho
        (-1.0, 1.0),      # m
        (0.001, 2.0),     # sigma
    ]

    # Global search
    de_result = differential_evolution(
        loss, bounds, seed=42, maxiter=500,
        tol=1e-8, polish=True, workers=1,
    )

    # Local refinement
    local_result = minimize(
        loss, de_result.x, method='SLSQP',
        bounds=bounds,
        options={'ftol': 1e-12, 'maxiter': 1000},
    )

    a, b, rho, m, sigma = local_result.x
    return SVIParams(a=a, b=b, rho=rho, m=m, sigma=sigma, tau=tau)


def build_full_surface(
    chain: pd.DataFrame,
    spot: float,
    rate: float = 0.05,
    div_yield: float = 0.0,
) -> dict[float, SVIParams]:
    """
    Build a full SVI surface: calibrate one slice per expiry.
    Returns dict mapping tau -> SVIParams.
    """
    surface = {}

    for expiry, grp in chain.groupby('expiry'):
        tau = grp['tte_years'].iloc[0]
        if tau < 1 / 365:  # Skip expired
            continue

        F = spot * np.exp((rate - div_yield) * tau)

        # Filter: liquid options only
        grp = grp[grp['iv'].notna() & (grp['iv'] > 0.01)]
        if len(grp) < 5:
            continue

        x = np.log(grp['strike'].values / F)
        tv = grp['iv'].values**2 * tau

        # Weight by inverse bid-ask spread
        spread = (grp['ask'] - grp['bid']).values
        mid = grp['mid'].values
        w = 1.0 / np.maximum(spread / np.maximum(mid, 1e-6), 0.01)

        try:
            params = calibrate_svi_slice(x, tv, weights=w, tau=tau)
            surface[tau] = params
        except Exception as e:
            print(f"SVI calibration failed for {expiry}: {e}")

    return surface


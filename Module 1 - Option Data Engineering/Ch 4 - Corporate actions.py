"""
Corporate actions adjustment engine for option chains.
Handles splits, dividends, and spin-offs.
"""
import pandas as pd
import numpy as np
from dataclasses import dataclass
from typing import Optional
from datetime import date

@dataclass
class SplitEvent:
    ex_date: date
    numerator: float  # e.g., 2 for a 2:1 split
    denominator: float  # e.g., 1 for a 2:1 split

@dataclass
class DividendEvent:
    ex_date: date
    amount: float  # Cash dividend per share
    currency: str = 'USD'

class CorporateActionsAdjuster:
    """
    Adjusts option chain data for corporate actions.
    All adjustments applied in reverse chronological order for history.
    """

    def __init__(
        self,
        splits: list[SplitEvent],
        dividends: list[DividendEvent],
    ):
        self.splits = sorted(splits, key=lambda x: x.ex_date)
        self.dividends = sorted(dividends, key=lambda x: x.ex_date)

    def adjust_chain(
        self,
        chain: pd.DataFrame,
        as_of: date,
    ) -> pd.DataFrame:
        """
        Adjust all strikes and OI in chain to reflect all corporate
        actions that occurred before or on 'as_of' date.

        chain must have: expiry, strike, option_type, bid, ask,
        mid, open_interest, volume
        """
        chain = chain.copy()

        for split in self.splits:
            if split.ex_date <= as_of:
                ratio = split.numerator / split.denominator

                # Adjust strikes (divide by ratio for forward split)
                chain['strike'] = chain['strike'] / ratio

                # Adjust prices (option prices scale with stock price)
                for col in ['bid', 'ask', 'mid', 'last']:
                    if col in chain.columns:
                        chain[col] = chain[col] / ratio

                # Adjust OI (more contracts post-split)
                chain['open_interest'] = (
                    chain['open_interest'] * ratio
                ).round().astype(int)

        return chain

    def compute_implied_dividend(
        self,
        chain: pd.DataFrame,
        spot: float,
        rate: float,
    ) -> pd.Series:
        """
        Compute implied dividend from put-call parity at each expiry.
        Uses ATM straddle (call - put = forward - strike * disc_factor).
        Returns a Series indexed by expiry.
        """
        results = {}

        for expiry, grp in chain.groupby('expiry'):
            tau = grp['tte_years'].iloc[0]
            disc = np.exp(-rate * tau)

            calls = grp[grp['option_type'] == 'call'].set_index('strike')
            puts = grp[grp['option_type'] == 'put'].set_index('strike')

            # Find common strikes
            common_K = calls.index.intersection(puts.index)
            if len(common_K) == 0:
                continue

            # Compute synthetic forward for each strike via PCP
            # F = (C - P)/ disc + K => D = S - F * disc
            C = calls.loc[common_K, 'mid']
            P = puts.loc[common_K, 'mid']
            K = common_K.values.astype(float)

            F_impl = (C.values - P.values) / disc + K
            D_impl = spot - F_impl * disc

            # Median across strikes (robust to noise)
            results[expiry] = np.nanmedian(D_impl)

        return pd.Series(results, name='implied_dividend')


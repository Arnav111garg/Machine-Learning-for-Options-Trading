from arcticdb import Arctic

# Initialize ArcticDB using a local disk-based backend (no MongoDB needed)
# This creates an 'arctic_db' directory in your Colab environment
store = Arctic('lmdb://arctic_db')

# Create or get a library
# In ArcticDB, libraries are created dynamically if they don't exist
lib = store.get_library('options_chains', create_if_missing=True)

# Generate dummy chain data for demonstration since chain_df is not in global scope

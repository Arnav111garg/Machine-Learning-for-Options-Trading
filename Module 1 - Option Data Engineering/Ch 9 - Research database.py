"""
Parquet-based research data lake with DuckDB querying.
Optimised for single-machine quant research workflows.
"""
import duckdb
import pandas as pd
import pyarrow as pa
import pyarrow.parquet as pq
from pathlib import Path
from datetime import date

class OptionDataLake:
    """
    Parquet-based options data lake.
    Partition layout:
    {base_dir}/{year}/{month}/{day}/{ticker}.parquet
    """

    def __init__(self, base_dir: str):
        self.base_dir = Path(base_dir)
        self.base_dir.mkdir(parents=True, exist_ok=True)
        self.con = duckdb.connect()

    def write_chain(
        self,
        chain: pd.DataFrame,
        ticker: str,
        snapshot_date: date,
    ) -> Path:
        """Write a single option chain snapshot to Parquet."""
        part_dir = (
            self.base_dir /
            f"year={snapshot_date.year}" /
            f"month={snapshot_date.month:02d}" /
            f"day={snapshot_date.day:02d}"
        )
        part_dir.mkdir(parents=True, exist_ok=True)
        path = part_dir / f"{ticker}.parquet"

        table = pa.Table.from_pandas(chain)
        pq.write_table(
            table,
            path,
            compression='snappy',  # Fast read / write
            row_group_size=10000,
            write_statistics=True,
            # Parquet column statistics enable predicate pushdown
        )
        return path

    def query(self, sql: str) -> pd.DataFrame:
        """Run an arbitrary SQL query against the data lake."""
        return self.con.execute(sql).df()

    def get_feature_snapshot(
        self,
        ticker: str,
        start_date: date,
        end_date: date,
    ) -> pd.DataFrame:
        """
        Pull all option chain data for a ticker over a date range.
        Uses DuckDB's Parquet scanner with predicate pushdown.
        """
        # Glob pattern for partition pruning
        pattern = str(
            self.base_dir / "year=*" / "month=*" / "day=*" /
            f"{ticker}.parquet"
        )
        sql = f"""
        SELECT *
        FROM parquet_scan('{pattern}', hive_partitioning=1)
        WHERE expiry BETWEEN DATE '{start_date}' AND DATE '{end_date}'
        ORDER BY ts, expiry, option_type, strike
        """
        return self.query(sql)

    def compute_daily_pcr(
        self,
        ticker: str,
        start_date: date,
        end_date: date,
    ) -> pd.DataFrame:
        """
        Compute daily put-call OI ratio from the raw chain data.
        This runs entirely inside DuckDB (no Python loop).
        """
        pattern = str(
            self.base_dir / "year=*" / "month=*" / "day=*" /
            f"{ticker}.parquet"
        )
        sql = f"""
        WITH daily_oi AS (
            SELECT
                CAST(ts AS DATE) AS trade_date,
                option_type,
                SUM(open_interest) AS total_oi
            FROM parquet_scan('{pattern}', hive_partitioning=1)
            WHERE
                ts >= TIMESTAMP '{start_date}'
                AND ts <= TIMESTAMP '{end_date}'
                AND iv BETWEEN 0.01 AND 5.0
                AND open_interest > 10
            GROUP BY 1, 2
        )
        SELECT
            trade_date,
            MAX(CASE WHEN option_type = 'call' THEN total_oi END) AS call_oi,
            MAX(CASE WHEN option_type = 'put' THEN total_oi END) AS put_oi,
            put_oi / NULLIF(call_oi, 0) AS pcr_oi
        FROM daily_oi
        GROUP BY trade_date
        ORDER BY trade_date
        """
        return self.query(sql)




import re
from dataclasses import dataclass
from datetime import date

@dataclass
class OsiSymbol:
    root: str
    expiry: date
    option_type: str  # 'C' or 'P'
    strike: float

def parse_osi(symbol: str) -> OsiSymbol:
    """
    Parse an OSI-format option symbol.
    Example: 'SPY251219C00450000' -> OsiSymbol(root='SPY', ...)
    """
    # Cleaned regex pattern to remove unwanted internal spaces
    pattern = r'^([A-Z]{1,6})(\d{6})([CP])(\d{8})$'
    m = re.match(pattern, symbol.strip())
    if not m:
        raise ValueError(f"Cannot parse OSI symbol: {symbol!r}")
    root = m.group(1).strip()
    expiry = date(2000 + int(m.group(2)[:2]),
                  int(m.group(2)[2:4]),
                  int(m.group(2)[4:6]))
    otype = m.group(3)
    strike = int(m.group(4)) / 1000.0
    return OsiSymbol(root=root, expiry=expiry, option_type=otype, strike=strike)

def build_osi(root: str, expiry: date, otype: str, strike: float) -> str:
    """Build OSI symbol from components."""
    yr = str(expiry.year)[-2:]
    mo = f"{expiry.month:02d}"
    dy = f"{expiry.day:02d}"
    k = f"{int(round(strike * 1000)):08d}"
    return f"{root:<6}{yr}{mo}{dy}{otype}{k}".replace(' ', '')


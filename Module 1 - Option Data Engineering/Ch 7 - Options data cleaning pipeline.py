"""
Production-grade options data cleaning pipeline.
Implements a multi-stage validation framework.
"""
import pandas as pd
import numpy as np
from typing import Tuple
import logging

logger = logging.getLogger(__name__)

class OptionsDataCleaner:
    """
    Multi-stage cleaning pipeline for options chain data.
    Each stage marks rows as valid / invalid with an error code.
    """

    def __init__(
        self,
        max_spread_pct: float = 0.30,          # 30% max spread / mid
        min_iv: float = 0.01,                  # 1% min IV
        max_iv: float = 5.00,                  # 500% max IV
        max_pcp_violation_usd: float = 0.10,   # PCP violation tolerance
        stale_quote_min: float = 30.0,         # Minutes before quote is stale
        min_oi: int = 10,                      # Min open interest to consider liquid
    ):
        self.max_spread_pct = max_spread_pct
        self.min_iv = min_iv
        self.max_iv = max_iv
        self.max_pcp_violation_usd = max_pcp_violation_usd
        self.stale_quote_min = stale_quote_min
        self.min_oi = min_oi

    def clean(
        self,
        chain: pd.DataFrame,
        spot: float,
        rate: float = 0.05,
        div_yield: float = 0.0,
    ) -> Tuple[pd.DataFrame, pd.DataFrame]:
        """
        Run full cleaning pipeline.
        Returns (clean_chain, error_log).
        """
        chain = chain.copy()
        chain['error_flags'] = ''
        chain['is_valid'] = True

        # Stage 1: Structural checks
        chain = self._check_structural(chain)

        # Stage 2: Bid-ask filter
        chain = self._filter_liquidity(chain)

        # Stage 3: IV range filter
        chain = self._filter_iv_range(chain)

        # Stage 4: Put-call parity check
        chain = self._check_pcp(chain, spot, rate, div_yield)

        # Stage 5: Greeks consistency
        chain = self._check_greeks(chain)

        # Separate clean and error records
        clean = chain[chain['is_valid']].copy()
        errors = chain[~chain['is_valid']].copy()

        n_total = len(chain)
        n_clean = len(clean)
        pct = 100 * n_clean / max(n_total, 1)
        logger.info(f"Cleaning: {n_clean}/{n_total} ({pct:.1f}%) records pass.")

        return clean.drop(columns=['error_flags', 'is_valid']), errors

    def _flag(self, chain: pd.DataFrame, mask: pd.Series, code: str) -> pd.DataFrame:
        """Flag rows matching mask with error code."""
        chain.loc[mask, 'error_flags'] += code + '|'
        chain.loc[mask, 'is_valid'] = False
        return chain

    def _check_structural(self, chain: pd.DataFrame) -> pd.DataFrame:
        # Inverted bid-ask
        bad = chain['bid'] > chain['ask']
        chain = self._flag(chain, bad, 'INVERTED_MARKET')

        # Negative prices
        bad = (chain['bid'] < 0) | (chain['ask'] < 0)
        chain = self._flag(chain, bad, 'NEGATIVE_PRICE')

        # Zero ask (no market)
        bad = chain['ask'] <= 0
        chain = self._flag(chain, bad, 'NO_OFFER')

        # Expired options
        if 'tte_years' in chain.columns:
            bad = chain['tte_years'] <= 0
            chain = self._flag(chain, bad, 'EXPIRED')

        return chain

    def _filter_liquidity(self, chain: pd.DataFrame) -> pd.DataFrame:
        mid = chain['mid']
        spread_pct = (chain['ask'] - chain['bid']) / mid.replace(0, np.nan)

        bad = spread_pct > self.max_spread_pct
        chain = self._flag(chain, bad, 'WIDE_SPREAD')

        if 'open_interest' in chain.columns:
            bad = chain['open_interest'] < self.min_oi
            chain = self._flag(chain, bad, 'LOW_OI')

        return chain

    def _filter_iv_range(self, chain: pd.DataFrame) -> pd.DataFrame:
        if 'iv' not in chain.columns:
            return chain
        bad_low = chain['iv'] < self.min_iv
        bad_high = chain['iv'] > self.max_iv
        bad_nan = chain['iv'].isna()
        chain = self._flag(chain, bad_low, 'IV_TOO_LOW')
        chain = self._flag(chain, bad_high, 'IV_TOO_HIGH')
        chain = self._flag(chain, bad_nan, 'IV_MISSING')
        return chain

    def _check_pcp(
        self,
        chain: pd.DataFrame,
        spot: float,
        rate: float,
        div_yield: float,
    ) -> pd.DataFrame:
        """Check put-call parity for matching pairs."""
        calls = chain[chain['option_type'] == 'call'].copy()
        puts = chain[chain['option_type'] == 'put'].copy()

        # Merge on (expiry, strike)
        merged = calls.merge(
            puts,
            on=['expiry', 'strike', 'tte_years'],
            suffixes=('_c', '_p'),
        )
        if merged.empty:
            return chain

        tau = merged['tte_years']
        disc = np.exp(-rate * tau)
        F = spot * np.exp((rate - div_yield) * tau)
        K = merged['strike']

        # PCP: C - P = disc * (F - K)
        C_mid = merged['mid_c']
        P_mid = merged['mid_p']
        pcp_lhs = C_mid - P_mid
        pcp_rhs = disc * (F - K)
        pcp_err = np.abs(pcp_lhs - pcp_rhs)

        bad_pairs = merged[pcp_err > self.max_pcp_violation_usd]
        if len(bad_pairs) > 0:
            bad_keys = set(
                zip(bad_pairs['expiry'], bad_pairs['strike'])
            )
            mask = chain.apply(
                lambda r: (r['expiry'], r['strike']) in bad_keys, axis=1
            )
            chain = self._flag(chain, mask, 'PCP_VIOLATION')

        return chain

    def _check_greeks(self, chain: pd.DataFrame) -> pd.DataFrame:
        if 'delta' not in chain.columns:
            return chain

        calls = chain[chain['option_type'] == 'call']
        puts = chain[chain['option_type'] == 'put']
        # Call delta in (0, 1), put delta in (-1, 0)
        bad_call = calls['delta'].notna() & (
            (calls['delta'] < -0.05) | (calls['delta'] > 1.05)
        )
        bad_put = puts['delta'].notna() & (
            (puts['delta'] < -1.05) | (puts['delta'] > 0.05)
        )
        chain = self._flag(chain, bad_call, 'BAD_DELTA_CALL')
        chain = self._flag(chain, bad_put, 'BAD_DELTA_PUT')
        return chain


"""
Feature computation engine for options sentiment signals.
Vectorised, production-ready implementation.
"""
import numpy as np
import pandas as pd
from scipy.stats import norm

def bs_greeks(
    S: np.ndarray,
    K: np.ndarray,
    T: np.ndarray,      # tte in years
    r: np.ndarray,
    q: np.ndarray,
    iv: np.ndarray,
    option_type: np.ndarray,  # 'call' or 'put'
) -> dict[str, np.ndarray]:
    """
    Vectorised Black-Scholes Greeks.
    Handles arrays of options simultaneously.
    """
    # Guard against zero time and zero vol
    T = np.maximum(T, 1e-10)
    iv = np.maximum(iv, 1e-10)
    sqT = np.sqrt(T)

    F = S * np.exp((r - q) * T)
    d1 = (np.log(S / K) + (r - q + 0.5 * iv**2) * T) / (iv * sqT)
    d2 = d1 - iv * sqT

    call_mask = (option_type == 'call') | (option_type == 'C')

    Nd1 = norm.cdf(d1)
    Nd1n = norm.cdf(-d1)
    Nd2 = norm.cdf(d2)
    Nd2n = norm.cdf(-d2)
    nd1 = norm.pdf(d1)  # Standard normal PDF

    disc = np.exp(-r * T)
    disc_q = np.exp(-q * T)

    # Delta
    delta = np.where(call_mask, disc_q * Nd1, -disc_q * Nd1n)

    # Gamma (same for calls and puts)
    gamma = (disc_q * nd1) / (S * iv * sqT)

    # Vega (per 1% = 0.01 move in vol)
    vega = S * disc_q * nd1 * sqT * 0.01

    # Theta (per calendar day)
    theta_call = (
        -S * disc_q * nd1 * iv / (2 * sqT)
        - r * K * disc * Nd2
        + q * S * disc_q * Nd1
    ) / 365.0
    theta_put = (
        -S * disc_q * nd1 * iv / (2 * sqT)
        + r * K * disc * Nd2n
        - q * S * disc_q * Nd1n
    ) / 365.0
    theta = np.where(call_mask, theta_call, theta_put)

    return {
        'delta': delta,
        'gamma': gamma,
        'vega': vega,
        'theta': theta
    }


def compute_gex_profile(
    chain: pd.DataFrame,
    spot: float,
    rate: float = 0.05,
    div_yield: float = 0.0,
    mm_convention: str = 'short_calls_long_puts',
) -> pd.DataFrame:
    """
    Compute the Gamma Exposure (GEX) profile across strikes.
    Returns a DataFrame with strike and net_gex columns.

    mm_convention:
    'short_calls_long_puts': standard assumption (MMs sell calls, buy puts from retail)
    """
    # Ensure greeks are computed
    if 'gamma' not in chain.columns:
        S = np.full(len(chain), spot)
        K = chain['strike'].values
        T = chain['tte_years'].values
        r = np.full(len(chain), rate)
        q = np.full(len(chain), div_yield)
        iv = chain['iv'].values
        ot = chain['option_type'].values
        greeks = bs_greeks(S, K, T, r, q, iv, ot)
        for g, v in greeks.items():
            chain = chain.copy()
            chain[g] = v

    # GEX per contract: gamma * OI * S^2 * multiplier
    chain = chain.copy()
    chain['gex_raw'] = (
        chain['gamma'] *
        chain['open_interest'] *
        spot**2 *
        100  # Standard US equity contract multiplier
    )

    if mm_convention == 'short_calls_long_puts':
        # Calls: MMs are short => destabilising (negative GEX sign convention)
        # Puts: MMs are long => stabilising (positive GEX)
        chain['gex_signed'] = np.where(
            chain['option_type'] == 'call',
            chain['gex_raw'],   # Positive: MMs short gamma
            -chain['gex_raw'],  # Negative: MMs long gamma
        )

    # Aggregate by strike
    gex_by_strike = (
        chain.groupby('strike')['gex_signed']
        .sum()
        .reset_index()
        .rename(columns={'gex_signed': 'net_gex'})
    )
    gex_by_strike['cumulative_gex'] = gex_by_strike['net_gex'].cumsum()

    return gex_by_strike


def compute_pcr(
    chain: pd.DataFrame,
    by: str = 'oi',  # 'oi' or 'volume'
    groupby_expiry: bool = True,
) -> pd.DataFrame:
    """
    Compute Put-Call Ratio (PCR) by OI or Volume.
    """
    col = 'open_interest' if by == 'oi' else 'volume'
    if col not in chain.columns:
        raise ValueError(f"Column '{col}' not found in chain.")

    calls = chain[chain['option_type'].isin(['call', 'C'])]
    puts = chain[chain['option_type'].isin(['put', 'P'])]

    if groupby_expiry:
        call_agg = calls.groupby('expiry')[col].sum().rename('call_val')
        put_agg = puts.groupby('expiry')[col].sum().rename('put_val')
        df = pd.concat([call_agg, put_agg], axis=1).fillna(0)
    else:
        df = pd.DataFrame({
            'call_val': [calls[col].sum()],
            'put_val': [puts[col].sum()],
        })

    df[f'pcr_{by}'] = df['put_val'] / df['call_val'].replace(0, np.nan)
    return df


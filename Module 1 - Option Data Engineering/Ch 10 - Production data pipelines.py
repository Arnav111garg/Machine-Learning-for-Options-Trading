class OptionsKafkaProducer:
    """
    Produces option quotes to a Kafka topic with schema validation,
    dead-letter queue, and delivery confirmation.
    """

    def __init__(
        self,
        bootstrap_servers: str,
        topic: str = 'options.raw.quotes',
        dlq_topic: str = 'options.dlq',
    ):
        self.topic = topic
        self.dlq_topic = dlq_topic
        self.producer = Producer({
            'bootstrap.servers': bootstrap_servers,
            'acks': 'all',  # Strongest durability
            'retries': 3,
            'retry.backoff.ms': 200,
            'compression.type': 'lz4',  # Fast compression for market data
            'linger.ms': 5,  # 5ms batching (latency vs throughput)
            'batch.size': 65536,
        })
        self._error_count = 0

    def _delivery_report(self, err, msg):
        if err is not None:
            self._error_count += 1
            logger.error(f"Delivery failed for {msg.key()}: {err}")
        else:
            pass  # Success - could log at DEBUG level

    def produce_quote(self, quote: dict) -> None:
        """
        Validate and produce a single option quote.
        Routes to DLQ if validation fails.
        """
        try:
            # Basic validation before producing
            assert quote.get('ask', 0) >= quote.get('bid', 0), "Inverted market"
            assert quote.get('strike', 0) > 0, "Non-positive strike"

            value = json.dumps(quote).encode('utf-8')
            key = f"{quote['underlying']}:{quote['symbol']}".encode()

            self.producer.produce(
                topic=self.topic,
                key=key,
                value=value,
                on_delivery=self._delivery_report,
            )
        except (AssertionError, KeyError) as e:
            # Route bad records to DLQ
            dlq_record = {
                'original': quote,
                'error': str(e),
                'ts': int(time.time() * 1000),
            }
            self.producer.produce(
                topic=self.dlq_topic,
                value=json.dumps(dlq_record).encode(),
            )

    def flush(self, timeout: float = 10.0) -> int:
        """Flush all pending messages. Returns undelivered count."""
        remaining = self.producer.flush(timeout=timeout)
        if remaining > 0:
            logger.warning(f"{remaining} messages not delivered in {timeout}s")
        return remaining



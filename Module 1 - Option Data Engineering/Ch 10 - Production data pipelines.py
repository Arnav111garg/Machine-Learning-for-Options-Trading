class InstrumentedCleaner:
    """
    Wraps OptionsDataCleaner with Prometheus instrumentation.
    """
    def __init__(self, cleaner, ticker: str):
        self.cleaner = cleaner
        self.ticker = ticker

    def clean(self, chain, spot, rate=0.05, div_yield=0.0):
        start = time.time()

        clean_df, error_df = self.cleaner.clean(
            chain, spot, rate, div_yield
        )

        elapsed = time.time() - start
        PROCESSING_TIME.observe(elapsed)

        # Record metrics
        RECORDS_PROCESSED.labels(
            ticker=self.ticker, status='clean'
        ).inc(len(clean_df))
        RECORDS_PROCESSED.labels(
            ticker=self.ticker, status='error'
        ).inc(len(error_df))

        return clean_df, error_df

"""
Backfill engine for options feature recomputation.
Supports parallel processing and incremental updates.
"""
import concurrent.futures
import logging
from datetime import date, timedelta
from typing import Callable
import pandas as pd

logger = logging.getLogger(__name__)

def backfill_features(
    tickers: list[str],
    start_date: date,
    end_date: date,
    feature_fn: Callable[[pd.DataFrame, date, str], pd.DataFrame],
    data_lake,        # OptionDataLake instance
    feature_store,    # Feature store write interface
    max_workers: int = 8,
    overwrite: bool = False,
) -> dict[str, int]:
    """
    Parallel backfill of features for multiple tickers over a date range.
    Returns dict: ticker -> number of days processed.
    """
    num_days = (end_date - start_date).days + 1
    all_dates = [start_date + timedelta(days=i) for i in range(num_days)]
    processed_counts = {ticker: 0 for ticker in tickers}

    def process_ticker_date(ticker: str, single_date: date) -> bool:
        try:
            # If incremental mode, skip existing dates in the feature store
            if not overwrite and hasattr(feature_store, 'exists') and feature_store.exists(ticker, single_date):
                return False

            # Retrieve raw options chain from Parquet data lake
            # We search options data lake for the requested ticker and date
            chain_data = data_lake.get_feature_snapshot(
                ticker=ticker,
                start_date=single_date,
                end_date=single_date
            )

            if chain_data.empty:
                return False

            # Compute analytical and market features
            features_df = feature_fn(chain_data, single_date, ticker)

            # Write output dataframe to feature store
            feature_store.write(ticker, single_date, features_df)
            return True
        except Exception as e:
            logger.error(f"Failed to backfill features for {ticker} on {single_date}: {e}")
            return False

    # Use ThreadPoolExecutor for I/O bound database and file-system lookups
    with concurrent.futures.ThreadPoolExecutor(max_workers=max_workers) as executor:
        future_to_task = {}
        for ticker in tickers:
            for single_date in all_dates:
                future = executor.submit(process_ticker_date, ticker, single_date)
                future_to_task[future] = (ticker, single_date)

        for future in concurrent.futures.as_completed(future_to_task):
            ticker, single_date = future_to_task[future]
            try:
                success = future.result()
                if success:
                    processed_counts[ticker] += 1
            except Exception as exc:
                logger.error(f"Task generated an exception: {ticker} on {single_date}: {exc}")

    return processed_counts
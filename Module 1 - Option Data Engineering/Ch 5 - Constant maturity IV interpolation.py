"""
Constant-maturity implied volatility constructor.
Handles expiry rolls and calendar spreads.
"""
import numpy as np
import pandas as pd
from scipy.interpolate import interp1d
from datetime import date, timedelta
import warnings

TRADING_DAYS_PER_YEAR = 252
CALENDAR_DAYS_PER_YEAR = 365.25

def compute_tte_years(as_of: date, expiry: date, use_calendar: bool = True) -> float:
    """Compute time-to-expiry in years."""
    if use_calendar:
        delta = (expiry - as_of).days
        return delta / CALENDAR_DAYS_PER_YEAR
    else:
        # Simple business day approximation
        bdays = np.busday_count(as_of.isoformat(), expiry.isoformat())
        return bdays / TRADING_DAYS_PER_YEAR

def constant_maturity_iv(
    term_structure: pd.DataFrame,  # columns: tte_years, iv_atm
    target_tte_years: float,
) -> float:
    """
    Interpolate (or extrapolate short end) to get constant-maturity ATM IV.
    Uses total-variance linear interpolation (no-calendar-arb preserving).

    term_structure: sorted by tte_years ascending, iv_atm in decimal
    target_tte_years: e.g., 30/365 for 30-day constant maturity
    """
    ts = term_structure.sort_values('tte_years').copy()
    ts = ts[ts['tte_years'] > 0]  # Remove expired

    if ts.empty:
        raise ValueError("No valid expiries in term structure.")

    # Total variance = iv^2 * tte
    ts['total_var'] = ts['iv_atm'] ** 2 * ts['tte_years']

    ttes = ts['tte_years'].values
    tvs = ts['total_var'].values

    # Interpolate total variance
    if target_tte_years < ttes[0]:
        # Short-end extrapolation: constant IV (forward-flat vol)
        warnings.warn(
            f"Target TTE {target_tte_years:.4f} shorter than "
            f"shortest expiry {ttes[0]:.4f}. Extrapolating flat."
        )
        total_var_target = tvs[0] * (target_tte_years / ttes[0])
    elif target_tte_years > ttes[-1]:
        # Long-end extrapolation: linear total variance
        warnings.warn(
            f"Target TTE {target_tte_years:.4f} longer than "
            f"longest expiry {ttes[-1]:.4f}. Extrapolating linear."
        )
        slope = (tvs[-1] - tvs[-2]) / (ttes[-1] - ttes[-2])
        total_var_target = tvs[-1] + slope * (target_tte_years - ttes[-1])
    else:
        # Normal interior interpolation
        interp_fn = interp1d(ttes, tvs, kind='linear', fill_value='extrapolate')
        total_var_target = float(interp_fn(target_tte_years))

    # Enforce non-negative total variance
    total_var_target = max(total_var_target, 1e-8)
    cm_iv = np.sqrt(total_var_target / target_tte_years)
    return cm_iv

def build_rolling_constant_maturity_series(
    daily_chains: dict[date, pd.DataFrame],  # date -> chain DataFrame
    target_days: list[int] = [7, 14, 30, 60, 90, 180],
) -> pd.DataFrame:
    """
    Build a daily time series of constant-maturity ATM IVs.
    Returns DataFrame with columns: date, cm_7d, cm_14d, ..., cm_180d
    """
    records = []
    for dt, chain in sorted(daily_chains.items()):
        row = {'date': dt}
        for d in target_days:
            target_tte = d / CALENDAR_DAYS_PER_YEAR
            try:
                # Build term structure from chain
                ts = (
                    chain[chain['option_type'] == 'call']
                    .groupby('expiry')['iv']
                    .agg(iv_atm='median')
                    .reset_index()
                )
                ts['tte_years'] = ts['expiry'].apply(
                    lambda e: compute_tte_years(dt, e)
                )
                ts = ts[ts['tte_years'] > 0].copy()
                cm = constant_maturity_iv(ts, target_tte)
                row[f'cm_{d}d'] = cm
            except Exception:
                row[f'cm_{d}d'] = np.nan
        records.append(row)

    df = pd.DataFrame(records).set_index('date')
    return df


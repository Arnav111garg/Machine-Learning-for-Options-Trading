import numpy as np
import pandas as pd
from sklearn.preprocessing import StandardScaler
from typing import List, Dict, Tuple

class OptionsFlowClassifier:
    """
    Classify and aggregate options flow for dealer positioning models.
    """

    def __init__(self, tick_data: pd.DataFrame):
        """
        Parameters
        ----------
        tick_data : DataFrame with columns:
            timestamp, strike, expiry, option_type, price, size,
            bid, ask, underlying_price, iv
        """
        self.ticks = tick_data.copy()
        self._classify_flow()

    def _classify_flow(self):
        """Lee-Ready classification."""
        df = self.ticks
        df['mid'] = (df['bid'] + df['ask']) / 2.0

        # Lee-Ready rules
        conditions = [
            df['price'] > df['mid'],  # Above mid = buy
            df['price'] < df['mid']   # Below mid = sell
        ]
        choices = [1, -1]
        df['lr_sign'] = np.select(conditions, choices, default=0)

        # Tick test for trades at mid
        df['price_diff'] = df['price'].diff()
        at_mid = df['lr_sign'] == 0
        df.loc[at_mid & (df['price_diff'] > 0), 'lr_sign'] = 1
        df.loc[at_mid & (df['price_diff'] < 0), 'lr_sign'] = -1
        df.loc[at_mid & (df['price_diff'] == 0), 'lr_sign'] = df['lr_sign'].shift().fillna(1)

        self.ticks = df

    def compute_greek_flows(self, window_minutes: int = 30) -> pd.DataFrame:
        """
        Compute signed Greek flows over rolling windows.
        """
        df = self.ticks.copy()

        # Dollar flows
        df['signed_delta_flow'] = df['lr_sign'] * df['delta'] * df['size'] * 100
        df['signed_gamma_flow'] = df['lr_sign'] * df['gamma'] * df['size'] * 100
        df['signed_vega_flow'] = df['lr_sign'] * df['vega'] * df['size'] * 100

        # Also compute notional (premium) flow
        df['signed_premium_flow'] = df['lr_sign'] * df['price'] * df['size'] * 100

        # Set timestamp as index for resampling
        df = df.set_index('timestamp').sort_index()

        freq = f'{window_minutes}T'
        flow_df = df.resample(freq).agg({
            'signed_delta_flow': 'sum',
            'signed_gamma_flow': 'sum',
            'signed_vega_flow': 'sum',
            'signed_premium_flow': 'sum',
            'size': 'sum',
            'underlying_price': 'last'
        }).rename(columns={'size': 'total_volume'})

        # Flow imbalance ratios
        for col in ['delta', 'gamma', 'vega', 'premium']:
            flow_col = f'signed_{col}_flow'
            flow_df[f'{col}_fir'] = (
                flow_df[flow_col].abs() /
                (flow_df[flow_col].abs().rolling(6).sum() + 1e-10)
            ) * np.sign(flow_df[flow_col])

        return flow_df

    def compute_vpin(self, bucket_size: int = 50) -> pd.Series:
        """
        Compute VPIN (Volume-Synchronized Probability of Informed Trading).
        """
        df = self.ticks.copy()
        df['vol_bucket'] = np.arange(len(df)) // bucket_size

        vpin_records = []
        for bucket, group in df.groupby('vol_bucket'):
            buy_vol = group.loc[group['lr_sign'] == 1, 'size'].sum()
            sell_vol = group.loc[group['lr_sign'] == -1, 'size'].sum()
            total_vol = buy_vol + sell_vol
            if total_vol > 0:
                vpin_records.append({
                    'bucket': bucket,
                    'timestamp': group['timestamp'].iloc[-1],
                    'vpin_bucket': abs(buy_vol - sell_vol) / total_vol
                })

        vpin_df = pd.DataFrame(vpin_records)
        # Rolling VPIN (50 buckets)
        vpin_df['vpin'] = vpin_df['vpin_bucket'].rolling(50).mean()
        return vpin_df.set_index('timestamp')['vpin']


class DealerFlowModel:
    """
    Model and predict dealer hedging flows from options positioning.
    """

    def __init__(self, gex_series: pd.Series, spot_series: pd.Series, market_volume: pd.Series):
        self.gex = gex_series
        self.spot = spot_series
        self.volume = market_volume
        self.aligned_data = pd.concat(
            [gex_series, spot_series, market_volume], axis=1
        ).dropna()
        self.aligned_data.columns = ['gex', 'spot', 'volume']

    def estimate_hedging_flow_fraction(self, vol_annualised: float = 0.20) -> pd.Series:
        """
        Estimate what fraction of today's volume is dealer gamma hedging.

        F_hedge = GEX * (daily_vol / spot) / ADV
        daily_vol = annualised_vol / sqrt(252)
        """
        daily_vol = vol_annualised / np.sqrt(252)
        spot = self.aligned_data['spot']
        gex = self.aligned_data['gex']
        adv = self.aligned_data['volume'].rolling(20).mean()

        # Expected hedging volume (absolute)
        expected_hedge_vol = abs(gex) * daily_vol / spot

        # As fraction of ADV
        hedge_fraction = expected_hedge_vol / (adv * spot + 1e-10)

        return hedge_fraction.clip(0, 1)

    def compute_flow_features(self) -> pd.DataFrame:
        """Build comprehensive flow feature matrix."""
        df = self.aligned_data.copy()

        # Daily spot returns
        df['ret_1d'] = df['spot'].pct_change()

        # Hedging flow estimates
        df['hedge_flow_frac'] = self.estimate_hedging_flow_fraction()

        # Flow direction from GEX sign (negative GEX -> pro-cyclical dealer flow)
        df['dealer_flow_direction'] = np.where(
            df['gex'] < 0,
            np.sign(df['ret_1d']),
            -np.sign(df['ret_1d'])
        )

        # Estimated dealer flow in $B
        df['dealer_flow_bn'] = (df['gex'] * df['ret_1d'] * -1 / 1e9)  # Dealers hedge: -GEX * dS

        # Cumulative flow pressure
        df['cumulative_dealer_flow'] = df['dealer_flow_bn'].cumsum()

        # Flow persistence (autocorrelation of dealer flow)
        df['flow_persistence'] = df['dealer_flow_bn'].rolling(5).corr(
            df['dealer_flow_bn'].shift(1)
        )

        # High volume + high GEX = strong mean-reversion force
        df['mr_force'] = (df['gex'] * df['volume']) / df['spot']

        return df

    def identify_flow_events(self, gex_threshold: float = 0.3, flow_threshold: float = 0.5) -> pd.DataFrame:
        """
        Flag dates with significant dealer flow events.
        """
        df = self.compute_flow_features()

        events = pd.DataFrame(index=df.index)
        events['gex_extreme'] = df['gex'].abs() > df['gex'].abs().quantile(gex_threshold)
        events['high_hedge_flow'] = df['hedge_flow_frac'] > flow_threshold
        events['vol_expansion'] = df['ret_1d'].abs() > df['ret_1d'].abs().rolling(20).mean() * 1.5
        events['dealer_flow_event'] = (
            events['gex_extreme'] & events['high_hedge_flow']
        ).astype(int)

        return events


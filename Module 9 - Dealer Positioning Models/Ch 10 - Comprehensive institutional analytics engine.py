import numpy as np
import pandas as pd
from scipy import stats
from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler
from typing import Dict, List, Optional, Tuple

class InstitutionalFlowAnalyzer:
    """
    Comprehensive institutional flow analysis for options markets.

    Identifies:
    1. Smart money positioning
    2. Skew / term structure regime
    3. Dark pool accumulation signals
    4. Risk reversal dynamics
    5. Unusual options activity (UOA)
    """

    INSTITUTION_THRESHOLDS = {
        'block_size_equity': 1000,
        'block_size_index': 500,
        'aggressiveness_threshold': 0.8,
        'size_ratio_threshold': 0.1,
        'sweep_venue_count': 2
    }

    def __init__(self, tick_data: pd.DataFrame, oi_data: pd.DataFrame, vol_surface: pd.DataFrame):
        """
        Parameters
        ----------
        tick_data : OPRA-level tick data with columns:
        timestamp, strike, expiry, option_type, price, size, bid, ask,
        venue, underlying_price, iv, delta, gamma, vega
        oi_data : Daily open interest data
        vol_surface : Vol surface data (strikes x expiries x metrics)
        """
        self.ticks = tick_data.copy()
        self.oi = oi_data.copy()
        self.surface = vol_surface.copy()
        self._preprocess()

    def _preprocess(self):
        """Tag trades with institutional characteristics."""
        df = self.ticks

        # Trade aggressiveness (how much did they pay above mid?)
        df['mid'] = (df['bid'] + df['ask']) / 2.0
        df['spread'] = df['ask'] - df['bid']
        df['aggressiveness'] = ((df['price'] - df['mid']) / (df['spread'] / 2.0 + 1e-6)).clip(-1, 1)

        # ADV for size ratio calculation
        adv_by_strike = df.groupby(['strike', 'expiry', 'option_type'])['size'].transform(
            lambda x: x.rolling(20, min_periods=5).mean()
        )
        df['size_ratio'] = df['size'] / (adv_by_strike + 1)

        # Block flag
        df['is_block'] = df['size'] >= self.INSTITUTION_THRESHOLDS['block_size_equity']

        # Directional sign (Lee-Ready)
        df['lr_sign'] = np.where(df['price'] > df['mid'], 1,
                                 np.where(df['price'] < df['mid'], -1, 0))

        self.ticks = df

    def detect_unusual_options_activity(self,
                                        volume_oi_ratio_threshold: float = 3.0,
                                        oi_change_threshold: float = 2.0) -> pd.DataFrame:
        """
        Detect Unusual Options Activity (UOA):
        High volume/OI ratio signals large directional bets.
        """
        daily_volume = self.ticks.groupby(
            [self.ticks['timestamp'].dt.date, 'strike', 'expiry', 'option_type']
        )['size'].sum().reset_index()
        daily_volume.columns = ['date', 'strike', 'expiry', 'option_type', 'volume']

        # Merge with OI
        merged = daily_volume.merge(
            self.oi[['date', 'strike', 'expiry', 'option_type', 'oi']],
            on=['date', 'strike', 'expiry', 'option_type'],
            how='left'
        )
        merged['vol_oi_ratio'] = merged['volume'] / (merged['oi'] + 1)

        # Rolling average for comparison
        merged['vol_oi_ratio_avg'] = merged.groupby(
            ['strike', 'expiry', 'option_type']
        )['vol_oi_ratio'].transform(lambda x: x.rolling(10, min_periods=3).mean())

        merged['vol_oi_zscore'] = (merged['vol_oi_ratio'] - merged['vol_oi_ratio_avg']) / \
                                  (merged.groupby(['strike', 'expiry', 'option_type'])
                                   ['vol_oi_ratio'].transform(lambda x: x.rolling(10, min_periods=3).std()) + 1e-6)

        # UOA flag
        uoa = merged[
            (merged['vol_oi_ratio'] > volume_oi_ratio_threshold) &
            (merged['vol_oi_zscore'] > 2.0)
        ].copy()

        # Add directional information
        flow_by_option = self.ticks.groupby(
            [self.ticks['timestamp'].dt.date, 'strike', 'expiry', 'option_type']
        ).apply(lambda x: (x['lr_sign'] * x['size']).sum() / x['size'].sum()).reset_index(name='net_flow_direction')

        uoa = uoa.merge(flow_by_option, on=['date', 'strike', 'expiry', 'option_type'], how='left')

        # Interpret direction
        uoa['signal'] = np.where(
            uoa['option_type'] == 'C',
            np.where(uoa['net_flow_direction'] > 0, 'BULLISH_UOA', 'BEARISH_UOA'),
            np.where(uoa['net_flow_direction'] > 0, 'BEARISH_UOA', 'BULLISH_UOA')
        )

        return uoa.sort_values('vol_oi_zscore', ascending=False)

    def compute_smart_money_index(self, window_days: int = 5) -> pd.Series:
        """
        Smart Money Index: ratio of institutional to total signed flow.
        """
        df = self.ticks.copy()
        df['date'] = df['timestamp'].dt.date

        df['delta_flow'] = df['lr_sign'] * df['delta'] * df['size'] * 100

        # Institutional flow: large, aggressive block trades
        inst_mask = (
            (df['is_block']) &
            (df['aggressiveness'].abs() > self.INSTITUTION_THRESHOLDS['aggressiveness_threshold'])
        )

        daily = df.groupby('date').agg(
            total_delta_flow=('delta_flow', 'sum'),
            inst_delta_flow=('delta_flow', lambda x: x[inst_mask.loc[x.index]].sum())
        )

        # SMI: institutional flow as fraction of total (adjusted)
        smi = daily['inst_delta_flow'] / (daily['total_delta_flow'].abs() + 1e-6)

        # Smooth
        smi_smooth = smi.rolling(window_days).mean()
        return smi_smooth

    def analyse_vol_surface_dynamics(self, spot: float) -> dict:
        """
        Analyse implied vol surface for institutional signals.
        """
        if self.surface.empty:
            return {}

        surface = self.surface

        # Risk reversal (25-delta)
        if all(col in surface.columns for col in ['iv_25dp', 'iv_25dc']):
            rr_25d = surface['iv_25dc'] - surface['iv_25dp']
            rr_zscore = (rr_25d - rr_25d.rolling(63).mean()) / rr_25d.rolling(63).std()
        else:
            rr_25d = pd.Series(dtype=float)
            rr_zscore = pd.Series(dtype=float)

        # Butterfly (25-delta: measures vol of vol / kurtosis)
        if all(col in surface.columns for col in ['iv_25dp', 'iv_25dc', 'iv_atm']):
            bf_25d = (surface['iv_25dp'] + surface['iv_25dc']) / 2 - surface['iv_atm']
            bf_zscore = (bf_25d - bf_25d.rolling(63).mean()) / bf_25d.rolling(63).std()
        else:
            bf_25d = pd.Series(dtype=float)
            bf_zscore = pd.Series(dtype=float)

        # Term structure slope (1M vs 3M)
        if 'iv_atm_1m' in surface.columns and 'iv_atm_3m' in surface.columns:
            ts_slope = surface['iv_atm_3m'] - surface['iv_atm_1m']
            ts_regime = pd.cut(ts_slope,
                               bins=[-np.inf, -0.02, -0.005, 0.005, 0.02, np.inf],
                               labels=['strong_backw', 'mild_backw', 'flat', 'mild_contango', 'strong_contango'])
        else:
            ts_slope = pd.Series(dtype=float)
            ts_regime = pd.Series(dtype='object')

        return {
            'risk_reversal_25d': rr_25d,
            'rr_zscore': rr_zscore,
            'butterfly_25d': bf_25d,
            'bf_zscore': bf_zscore,
            'ts_slope': ts_slope,
            'ts_regime': ts_regime,
            'extreme_fear': (rr_zscore < -2.0) if not rr_zscore.empty else pd.Series(),
            'extreme_complacency': (rr_zscore > 2.0) if not rr_zscore.empty else pd.Series()
        }

    def detect_institutional_accumulation(self, lookback_days: int = 20) -> pd.DataFrame:
        """
        Detect slow institutional accumulation via OI build with low volume.
        Signatures:
        - OI builds steadily over multiple days
        - Trades are spread out (not block sweeps)
        - Consistently on one side (buy or sell)
        """
        df = self.ticks.copy()
        df['date'] = df['timestamp'].dt.date

        # Daily net flow per option
        daily_flow = df.groupby(['date', 'strike', 'expiry', 'option_type']).apply(
            lambda x: pd.Series({
                'net_delta_flow': (x['lr_sign'] * x['delta'] * x['size']).sum(),
                'volume': x['size'].sum(),
                'avg_size': x['size'].mean(),
                'block_pct': x['is_block'].mean() if 'is_block' in x.columns else 0,
                'aggressiveness': x['aggressiveness'].mean()
            })
        ).reset_index()

        # Rolling accumulation signal
        daily_flow['flow_direction_consistency'] = daily_flow.groupby(
            ['strike', 'expiry', 'option_type']
        )['net_delta_flow'].transform(
            lambda x: x.rolling(lookback_days, min_periods=5).apply(
                lambda y: np.sign(y).mean()  # Consistent direction = high absolute value
            )
        )

        # Accumulation: consistent one-sided flow + small average size (gradual)
        daily_flow['is_accumulation'] = (
            (daily_flow['flow_direction_consistency'].abs() > 0.7) &  # 70%+ same direction
            (daily_flow['avg_size'] < 200) &  # Small average trade size (gradual)
            (daily_flow['block_pct'] < 0.3)  # Not dominated by blocks
        )

        # Summarize accumulation signals
        accumulation = daily_flow[daily_flow['is_accumulation']].copy()
        accumulation['direction'] = np.where(
            daily_flow.loc[daily_flow['is_accumulation'].index, 'flow_direction_consistency'] > 0,
            'LONG_ACCUMULATION', 'SHORT_ACCUMULATION'
        )

        return accumulation.sort_values('flow_direction_consistency', ascending=False, key=lambda x: x.abs())

    def generate_institutional_report(self, spot: float, date: Optional[str] = None) -> dict:
        """
        Generate comprehensive institutional analytics report.
        """
        report = {}

        # UOA
        try:
            uoa = self.detect_unusual_options_activity()
            report['uoa_bullish'] = uoa[uoa['signal'] == 'BULLISH_UOA'].head(5)
            report['uoa_bearish'] = uoa[uoa['signal'] == 'BEARISH_UOA'].head(5)
            report['n_uoa_events'] = len(uoa)
        except Exception as e:
            report['uoa_error'] = str(e)

        # Smart Money
        try:
            smi = self.compute_smart_money_index()
            report['smart_money_index'] = smi.iloc[-1] if not smi.empty else None
            report['smi_signal'] = 'BULLISH' if (smi.iloc[-1] > 0.5 if not smi.empty else False) else 'BEARISH'
        except Exception as e:
            report['smi_error'] = str(e)

        # Vol surface dynamics
        try:
            vol_dynamics = self.analyse_vol_surface_dynamics(spot)
            report['vol_surface'] = vol_dynamics
        except Exception as e:
            report['vol_surface_error'] = str(e)

        # Accumulation signals
        try:
            accum = self.detect_institutional_accumulation()
            report['accumulation_signals'] = accum.head(10)
        except Exception as e:
            report['accumulation_error'] = str(e)

        return report


class InstitutionalDashboard:
    """
    Real-time institutional analytics dashboard for options desks.
    Aggregates all institutional signals into a single trading view.
    """

    def __init__(self, analyzer: InstitutionalFlowAnalyzer, gex_calc, dex_calc, regime_classifier):
        self.analyzer = analyzer
        self.gex = gex_calc
        self.dex = dex_calc
        self.regime = regime_classifier

    def generate_morning_report(self, spot: float, date: str) -> str:
        """
        Generate text summary for morning stand-up.
        """
        gex_metrics = self.gex.compute_total_gex()
        dex_metrics = self.dex.compute_total_dex()

        lines = [
            f"=" * 60,
            f" DEALER POSITIONING MORNING REPORT {date}",
            f"=" * 60,
            f" Spot : {spot:.2f}",
            f"",
            f" --- GAMMA EXPOSURE (GEX) ---",
            f" Total GEX: ${gex_metrics['total_gex']/1e9:.2f}B",
            f" Gamma Flip : ${gex_metrics.get('gamma_flip', 'N/A')}",
            f" Distance : {gex_metrics.get('distance_to_flip', 0)*100:.2f}%",
            f" Regime : {'POSITIVE (Suppressed Vol)' if gex_metrics['total_gex'] > 0 else 'NEGATIVE (Explosive Vol)'}",
            f"",
            f" --- DELTA EXPOSURE (DEX) ---",
            f"Net DEX: ${dex_metrics['net_dex']/1e9:.2f}B",
            f" DPCR : {dex_metrics['dpcr']:.2f}",
            f" Charm Pressure : ${dex_metrics['charm_pressure']/1e6:.1f}M/day",
            f"",
            f" --- DEALER POSITIONING SIGNAL ---",
            f" Action : {'REDUCE VOL' if gex_metrics['total_gex'] > 0 else 'ADD VOL'}",
            f" Confidence : {'HIGH' if abs(gex_metrics['total_gex']) > 5e9 else 'MEDIUM'}",
            f"=" * 60
        ]

        return "\n".join(lines)


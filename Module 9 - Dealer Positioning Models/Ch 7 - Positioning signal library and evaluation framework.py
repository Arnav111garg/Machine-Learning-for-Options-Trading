import numpy as np
import pandas as pd
from scipy import stats
from typing import Dict, List, Optional, Callable

class PositioningSignalLibrary:
    """
    Library of positioning-based trading signals.
    All signals are z-score normalized to [-1, +1] range.
    """

    def __init__(self, data: pd.DataFrame):
        """
        data : DataFrame with columns:
        total_gex, net_dex, total_vex, total_vannex, spot,
        gamma_flip, iv_atm, pcr, dpcr, oi_max_strike,
        charm_flow, vix, ret_1d (forward return for evaluation)
        """
        self.data = data.copy().sort_index()
        self.signals = {}

    def _zscore(self, series: pd.Series, window: int = 63) -> pd.Series:
        """Rolling z-score normalisation."""
        mu = series.rolling(window).mean()
        sigma = series.rolling(window).std()
        return ((series - mu) / sigma).clip(-3, 3)

    def _rank_normalize(self, series: pd.Series, window: int = 252) -> pd.Series:
        """Rolling rank normalisation to [-0.5, 0.5]."""
        return series.rolling(window).rank(pct=True) - 0.5

    def gex_vol_signal(self, window: int = 21) -> pd.Series:
        """
        Signal: High positive GEX -> sell vol (expect suppressed RV).
        Goes long short-vol strategies when GEX is elevated.
        """
        sig = self._zscore(self.data['total_gex'], window)
        self.signals['gex_vol'] = sig
        return sig

    def gamma_flip_proximity_signal(self, decay_rate: float = 10.0) -> pd.Series:
        """
        Signal: Proximity to gamma flip determines regime.
        Far above flip: stable (sell vol).
        Near / below flip: unstable (buy vol).
        """
        dist = (self.data['spot'] - self.data['gamma_flip']) / self.data['spot']
        above = (self.data['spot'] > self.data['gamma_flip']).astype(float)

        # Signal: above flip = positive (stable = sell vol), below = negative
        sig = above * np.tanh(decay_rate * dist.abs()) - (1 - above)
        self.signals['flip_proximity'] = sig
        return sig

    def charm_momentum_signal(self, window: int = 5) -> pd.Series:
        """
        Signal: Charm flow predicts intraday directional pressure.
        Positive charm flow -> EOD buying pressure.
        """
        charm = self.data.get('charm_flow', pd.Series(0, index=self.data.index))
        sig = self._zscore(charm, window)
        self.signals['charm_momentum'] = sig
        return sig

    def vanna_squeeze_signal(self) -> pd.Series:
        """
        Signal: Large negative VannEx + rising IV = dealer equity selling.
        """
        vannex = self.data.get('total_vannex', pd.Series(0, index=self.data.index))
        iv = self.data['iv_atm']
        iv_change = iv.diff(3)

        # Squeeze: short VannEx & rising vol -> sell signal
        vanna_z = self._zscore(vannex)
        iv_z = self._zscore(iv_change)

        sig = -(vanna_z * iv_z).clip(-1, 1)  # Interaction signal
        self.signals['vanna_squeeze'] = sig
        return sig

    def dpcr_contrarian_signal(self, window: int = 63) -> pd.Series:
        """
        Contrarian put/call ratio signal (delta-adjusted).
        High DPCR (extreme bearishness) = contrarian bullish.
        """
        dpcr = self.data.get('dpcr', self.data.get('pcr', pd.Series(1, index=self.data.index)))
        sig = -self._rank_normalize(dpcr, window)  # Contrarian
        self.signals['dpcr_contrarian'] = sig
        return sig

    def pinning_signal(self, pin_threshold_pct: float = 0.02) -> pd.Series:
        """
        Signal: Near-expiry pinning to max OI strike.
        Returns long signal if spot is above pin strike (expect drift down to pin),
        short if below (expect drift up to pin).
        """
        spot = self.data['spot']
        pin = self.data.get('oi_max_strike', spot)
        dte = self.data.get('dte', pd.Series(30, index=self.data.index))

        dist_to_pin = (spot - pin) / spot
        near_pin = dist_to_pin.abs() < pin_threshold_pct

        # Pinning force strengthens as expiry approaches
        pin_force = np.exp(-dte / 5) * near_pin.astype(float)

        # Direction: above pin -> expect sell to pin; below -> buy to pin
        sig = -np.sign(dist_to_pin) * pin_force
        self.signals['pinning'] = sig
        return sig

    def dex_directional_signal(self, window: int = 10) -> pd.Series:
        """
        Signal: Dealer delta hedging pressure creates directional returns.
        Net positive DEX -> dealers need to sell -> bearish.
        """
        dex = self.data['net_dex']
        sig = -self._zscore(dex, window)  # Negative because dealers hedge against DEX
        self.signals['dex_directional'] = sig
        return sig

    def build_composite_signal(self,
                               signal_weights: Optional[Dict[str, float]] = None,
                               eval_forward_ret: str = 'ret_1d') -> pd.DataFrame:
        """
        Build composite signal from individual signals, evaluate IC.
        """
        if not self.signals:
            self.gex_vol_signal()
            self.gamma_flip_proximity_signal()
            self.charm_momentum_signal()
            self.vanna_squeeze_signal()
            self.dpcr_contrarian_signal()
            self.dex_directional_signal()

        signals_df = pd.DataFrame(self.signals, index=self.data.index)

        # Evaluate IC for each signal
        if eval_forward_ret in self.data.columns:
            fwd_ret = self.data[eval_forward_ret].shift(-1)
            ic_results = {}
            for sig_name in signals_df.columns:
                valid = (~signals_df[sig_name].isna() & ~fwd_ret.isna())
                ic = signals_df.loc[valid, sig_name].corr(fwd_ret[valid])
                ic_results[sig_name] = ic

            print("Signal IC (vs 1-day forward return):")
            for k, v in sorted(ic_results.items(), key=lambda x: -abs(x[1])):
                print(f" {k:30s}: {v:+.4f}")

        # Composite (equal weight if not specified)
        if signal_weights is None:
            signal_weights = {s: 1.0 / len(self.signals) for s in self.signals}

        composite = sum(signal_weights.get(s, 0) * signals_df[s] for s in signals_df.columns)
        composite = composite / composite.std()  # Normalise

        signals_df['composite'] = composite
        return signals_df


class SignalBacktester:
    """Quick signal backtest with transaction cost adjustment."""

    def __init__(self, signals: pd.DataFrame, returns: pd.Series, transaction_cost_bps: float = 5.0):
        self.signals = signals
        self.returns = returns
        self.tc = transaction_cost_bps / 10000

    def backtest_signal(self, signal_col: str = 'composite', top_pct: float = 0.3) -> Tuple[pd.DataFrame, dict]:
        """Long / short portfolio based on signal."""
        sig = self.signals[signal_col].fillna(0)
        ret = self.returns

        # Long top_pct, short bottom_pct
        threshold_long = sig.quantile(1 - top_pct)
        threshold_short = sig.quantile(top_pct)

        position = pd.Series(0.0, index=sig.index)
        position[sig >= threshold_long] = 1.0
        position[sig <= threshold_short] = -1.0

        # Transaction costs from daily rebalancing
        turnover = position.diff().abs()
        gross_ret = position.shift(1) * ret
        net_ret = gross_ret - turnover * self.tc

        # Performance metrics
        cum_ret = (1 + net_ret.fillna(0)).cumprod()
        sharpe = net_ret.mean() / net_ret.std() * np.sqrt(252)
        max_dd = (cum_ret / cum_ret.cummax() - 1).min()

        return pd.DataFrame({
            'gross_return': gross_ret,
            'net_return': net_ret,
            'cumulative': cum_ret,
            'position': position
        }), {
            'sharpe': sharpe,
            'annual_return': net_ret.mean() * 252,
            'max_drawdown': max_dd,
            'hit_rate': (gross_ret > 0).mean()
        }


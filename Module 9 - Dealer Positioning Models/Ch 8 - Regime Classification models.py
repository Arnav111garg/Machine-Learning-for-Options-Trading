import numpy as np
import pandas as pd
from hmmlearn.hmm import GaussianHMM
from sklearn.ensemble import RandomForestClassifier, GradientBoostingClassifier
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import TimeSeriesSplit
from sklearn.metrics import classification_report
from typing import Tuple

class DealerRegimeClassifier:
    """
    Classify dealer positioning regimes using HMM and supervised ML.
    """

    def __init__(self, n_regimes: int = 4):
        self.n_regimes = n_regimes
        self.hmm_model = None
        self.supervised_model = None
        self.scaler = StandardScaler()

    def _build_feature_matrix(self, data: pd.DataFrame) -> np.ndarray:
        """Build regime classification features."""
        features = pd.DataFrame(index=data.index)

        # GEX features
        gex = data['total_gex']
        gex_std = gex.rolling(252, min_periods=60).std()
        features['gex_norm'] = gex / (gex_std + 1e-10)
        features['gex_sign'] = np.sign(gex)
        features['gex_abs_norm'] = gex.abs() / (gex_std + 1e-10)

        # Positional
        if 'gamma_flip' in data.columns:
            features['dist_to_flip'] = (data['spot'] - data['gamma_flip']) / data['spot']
            features['above_flip'] = (data['spot'] > data['gamma_flip']).astype(float)

        # Volatility features
        if 'iv_atm' in data.columns:
            iv = data['iv_atm']
            features['iv_norm'] = (iv - iv.rolling(63).mean()) / iv.rolling(63).std()
        if 'rv_21d' in data.columns:
            features['vrp'] = iv - data['rv_21d']

        # Returns and autocorrelation
        if 'ret_1d' in data.columns:
            ret = data['ret_1d']
            features['ret_5d'] = ret.rolling(5).sum()
            features['ret_21d'] = ret.rolling(21).sum()
            features['realized_vol'] = ret.rolling(21).std() * np.sqrt(252)
            features['autocorr_5d'] = ret.rolling(10).apply(
                lambda x: x[:5].corr(x[5:]) if len(x) == 10 else 0
            )

        # Skew and flow
        if 'skew_25d' in data.columns:
            features['skew_norm'] = (data['skew_25d'] - data['skew_25d'].rolling(63).mean()) / \
                                    data['skew_25d'].rolling(63).std()

        if 'dpcr' in data.columns:
            features['dpcr_norm'] = (data['dpcr'] - data['dpcr'].rolling(63).mean()) / \
                                    data['dpcr'].rolling(63).std()

        return features.fillna(0)

    def _create_regime_labels(self, data: pd.DataFrame) -> pd.Series:
        """Create regime labels based on GEX quadrant."""
        gex = data['total_gex']
        gex_threshold = gex.abs().rolling(252, min_periods=60).quantile(0.5)

        labels = pd.Series(0, index=data.index)
        labels[((gex < 0) & (gex.abs() >= gex_threshold))] = 0  # Explosive vol
        labels[((gex > 0) & (gex.abs() >= gex_threshold))] = 1  # Suppressed vol
        labels[((gex < 0) & (gex.abs() < gex_threshold))] = 2   # Transition bearish
        labels[((gex > 0) & (gex.abs() < gex_threshold))] = 3   # Transition bullish

        return labels

    def fit_hmm(self, data: pd.DataFrame) -> dict:
        """Fit Gaussian HMM for unsupervised regime detection."""
        X = self._build_feature_matrix(data).values
        X_scaled = self.scaler.fit_transform(X)

        # Fit HMM
        self.hmm_model = GaussianHMM(
            n_components=self.n_regimes,
            covariance_type='full',
            n_iter=200,
            random_state=42
        )
        self.hmm_model.fit(X_scaled)

        # Decode most likely state sequence
        hidden_states = self.hmm_model.predict(X_scaled)
        state_probs = self.hmm_model.predict_proba(X_scaled)

        # Characterize each regime
        regime_stats = {}
        df_with_states = data.copy()
        df_with_states['hmm_regime'] = hidden_states

        for regime in range(self.n_regimes):
            mask = hidden_states == regime
            regime_data = df_with_states[mask]
            if 'ret_1d' in data.columns:
                ret = data.loc[mask, 'ret_1d']
                regime_stats[f'regime_{regime}'] = {
                    'mean_return': ret.mean() * 252,
                    'vol': ret.std() * np.sqrt(252),
                    'sharpe': ret.mean() / (ret.std() + 1e-10) * np.sqrt(252),
                    'mean_gex': data.loc[mask, 'total_gex'].mean(),
                    'count': mask.sum(),
                    'pct_time': mask.mean()
                }

        return {
            'hidden_states': pd.Series(hidden_states, index=data.index),
            'state_probs': pd.DataFrame(state_probs, index=data.index,
                                        columns=[f'prob_r{i}' for i in range(self.n_regimes)]),
            'transition_matrix': self.hmm_model.transmat_,
            'regime_stats': regime_stats,
            'log_likelihood': self.hmm_model.score(X_scaled)
        }

    def fit_supervised(self, data: pd.DataFrame) -> dict:
        """Fit supervised regime classifier using labelled data."""
        X = self._build_feature_matrix(data)
        y = self._create_regime_labels(data)

        # Walk-forward validation
        tscv = TimeSeriesSplit(n_splits=5)
        X_scaled = pd.DataFrame(
            self.scaler.fit_transform(X), index=X.index, columns=X.columns
        )

        # Gradient Boosting Classifier
        self.supervised_model = GradientBoostingClassifier(
            n_estimators=200,
            max_depth=3,
            learning_rate=0.1,
            subsample=0.8,
            random_state=42
        )

        oof_preds = np.zeros(len(X))
        cv_accuracies = []

        for fold, (train_idx, val_idx) in enumerate(tscv.split(X_scaled)):
            X_tr, X_val = X_scaled.iloc[train_idx], X_scaled.iloc[val_idx]
            y_tr, y_val = y.iloc[train_idx], y.iloc[val_idx]

            self.supervised_model.fit(X_tr, y_tr)
            preds = self.supervised_model.predict(X_val)
            oof_preds[val_idx] = preds
            acc = (preds == y_val.values).mean()
            cv_accuracies.append(acc)
            print(f"Fold {fold+1}: Accuracy = {acc:.4f}")

        # Final model
        self.supervised_model.fit(X_scaled, y)

        feature_importance = pd.Series(
            self.supervised_model.feature_importances_,
            index=X.columns
        ).sort_values(ascending=False)

        print(f"\nOOF Accuracy: {(oof_preds == y.values).mean():.4f}")
        print("\nTop Features:")
        print(feature_importance.head(10))

        return {
            'oof_predictions': pd.Series(oof_preds.astype(int), index=data.index),
            'cv_accuracies': cv_accuracies,
            'feature_importance': feature_importance
        }

    def predict_regime(self, data: pd.DataFrame) -> pd.DataFrame:
        """Predict current regime using both models."""
        X = self._build_feature_matrix(data)
        X_scaled = self.scaler.transform(X)

        results = pd.DataFrame(index=data.index)

        if self.supervised_model is not None:
            results['supervised_regime'] = self.supervised_model.predict(X_scaled)
            proba = self.supervised_model.predict_proba(X_scaled)
            for i in range(self.n_regimes):
                results[f'prob_r{i}'] = proba[:, i]
            results['regime_confidence'] = proba.max(axis=1)

        if self.hmm_model is not None:
            results['hmm_regime'] = self.hmm_model.predict(X_scaled)

        return results


class RegimeAwareStrategyRouter:
    """
    Route to different trading strategies based on detected regime.
    """

    STRATEGY_MAP = {
        0: {'name': 'Long Gamma / Long Vol', 'signal_sign': 1,
            'preferred_instruments': ['straddle', 'strangle', 'call spread']},
        1: {'name': 'Short Gamma / Short Vol', 'signal_sign': -1,
            'preferred_instruments': ['iron condor', 'butterfly', 'short straddle']},
        2: {'name': 'Defensive / Long Puts', 'signal_sign': 1,
            'preferred_instruments': ['put spread', 'risk reversal (put)', 'collar']},
        3: {'name': 'Breakout / Momentum', 'signal_sign': 1,
            'preferred_instruments': ['call spread', 'call backspread', 'ratio']},
    }

    def __init__(self, classifier: DealerRegimeClassifier):
        self.classifier = classifier

    def get_strategy(self, current_data: pd.DataFrame, confidence_threshold: float = 0.6) -> dict:
        """Get recommended strategy for current regime."""
        regime_df = self.classifier.predict_regime(current_data)
        latest = regime_df.iloc[-1]

        reg = int(latest.get('supervised_regime', latest.get('hmm_regime', 0)))
        confidence = latest.get('regime_confidence', 1.0)

        if confidence < confidence_threshold:
            return {
                'regime': reg,
                'strategy': 'Hold / Reduce Size (Low Confidence)',
                'confidence': confidence,
                'action': 'NEUTRAL'
            }

        strategy_info = self.STRATEGY_MAP[reg].copy()
        strategy_info['regime'] = reg
        strategy_info['confidence'] = confidence
        strategy_info['action'] = 'TRADE' if confidence > confidence_threshold else 'MONITOR'

        return strategy_info


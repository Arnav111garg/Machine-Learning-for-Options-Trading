import numpy as np
import pandas as pd
from scipy.stats import norm
from typing import Optional, Tuple
import warnings

# ================================================================
# Core Black - Scholes Greeks
# ================================================================

def bs_d1(S: float, K: float, r: float, sigma: float, T: float) -> float:
    """Compute d1 in Black-Scholes."""
    if T <= 0 or sigma <= 0:
        return np.nan
    return (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))

def bs_gamma(S: float, K: float, r: float, sigma: float, T: float, multiplier: float = 100) -> float:
    """
    Compute Black-Scholes gamma (per share, per contract).
    multiplier: standard equity options = 100 shares
    """
    if T <= 0 or sigma <= 0 or S <= 0:
        return 0.0
    d1 = bs_d1(S, K, r, sigma, T)
    gamma = norm.pdf(d1) / (S * sigma * np.sqrt(T))
    return gamma

def dollar_gamma(S: float, K: float, r: float, sigma: float, T: float) -> float:
    """Dollar gamma: P&L change for 1% move in S (per contract)."""
    g = bs_gamma(S, K, r, sigma, T)
    return g * (S ** 2) * 0.01 * 100  # *100 for contract multiplier

# ================================================================
# GEX Calculation Engine
# ================================================================

class GEXCalculator:
    """
    Gamma Exposure Calculator.

    Parameters
    ----------
    options_chain : pd.DataFrame
        Must contain : strike, expiry, option_type (C/P), oi (open interest),
        iv (implied volatility), bid, ask
    spot : float
        Current underlying price
    r : float
        Risk-free rate (annualised)
    dealer_sign_convention : str
        'standard' -> calls: customers buy; puts: customers buy (insurance)
        'net_flow' -> use signed_flow column if available
    """

    def __init__(self, options_chain: pd.DataFrame, spot: float, r: float = 0.05, dealer_sign_convention: str = 'standard'):
        self.chain = options_chain.copy()
        self.spot = spot
        self.r = r
        self.convention = dealer_sign_convention
        self._preprocess()

    def _preprocess(self):
        """Add time-to-expiry and compute gammas."""
        if 'dte' in self.chain.columns:
            self.chain['T'] = self.chain['dte'] / 365.0
        elif 'expiry' in self.chain.columns:
            today = pd.Timestamp.today().normalize()
            self.chain['T'] = (pd.to_datetime(self.chain['expiry']) - today).dt.days / 365.0
        else:
            raise ValueError("Need 'dte' or 'expiry' column")

        self.chain = self.chain[self.chain['T'] > 0].copy()

        # Compute gamma for each option
        self.chain['gamma'] = self.chain.apply(
            lambda row: bs_gamma(self.spot, row['strike'], self.r, row['iv'], row['T']),
            axis=1
        )

        # Dollar gamma per contract
        self.chain['dollar_gamma'] = self.chain.apply(
            lambda row: dollar_gamma(self.spot, row['strike'], self.r, row['iv'], row['T']),
            axis=1
        )

    def _compute_gex_sign(self, row) -> float:
        """Determine the sign of GEX for a given option contract."""
        if self.convention == 'standard':
            if row['option_type'].upper() == 'C':
                return -1.0
            else:
                return -1.0
        elif self.convention == 'net_flow':
            if 'signed_flow' in row.index:
                return -np.sign(row['signed_flow'])
            return -1.0
        elif self.convention == 'gex_standard':
            if row['option_type'].upper() == 'C':
                return -1.0
            else:
                return 1.0
        return -1.0

    def compute_gex_by_strike(self) -> pd.DataFrame:
        """Compute GEX aggregated by strike."""
        gex_records = []

        for (strike, expiry), group in self.chain.groupby(['strike', 'expiry']):
            for _, row in group.iterrows():
                sign = self._compute_gex_sign(row)
                gex = sign * row['gamma'] * row['oi'] * 100 * self.spot
                gex_records.append({
                    'strike': strike,
                    'expiry': expiry,
                    'dte': row['T'] * 365,
                    'option_type': row['option_type'],
                    'oi': row['oi'],
                    'gamma': row['gamma'],
                    'gex': gex
                })

        if not gex_records:
            return pd.DataFrame(columns=['strike', 'total_gex', 'call_gex', 'put_gex', 'total_oi'])

        gex_df = pd.DataFrame(gex_records)

        # Aggregate by strike
        gex_by_strike = gex_df.groupby('strike').agg(
            total_gex=('gex', 'sum'),
            call_gex=('gex', lambda x: x[gex_df.loc[x.index, 'option_type'] == 'C'].sum()),
            put_gex=('gex', lambda x: x[gex_df.loc[x.index, 'option_type'] == 'P'].sum()),
            total_oi=('oi', 'sum')
        ).reset_index()

        return gex_by_strike

    def compute_total_gex(self) -> dict:
        """Compute aggregate GEX metrics."""
        gex_by_strike = self.compute_gex_by_strike()
        if gex_by_strike.empty:
            return {
                'total_gex': 0.0, 'max_gex_strike': None, 'gamma_flip': None, 'gex_sign': 0.0,
                'call_gex': 0.0, 'put_gex': 0.0, 'gex_skew': 0.0, 'concentration': 0.0,
                'distance_to_wall': None, 'distance_to_flip': None
            }

        total_gex = gex_by_strike['total_gex'].sum()
        max_gex_idx = gex_by_strike['total_gex'].abs().idxmax()
        max_gex_strike = gex_by_strike.loc[max_gex_idx, 'strike']

        # Gamma flip
        sorted_gex = gex_by_strike.sort_values('strike')
        cumulative_gex = sorted_gex['total_gex'].cumsum()
        flip_candidates = sorted_gex[cumulative_gex.diff().apply(np.sign).diff() != 0]
        gamma_flip = flip_candidates['strike'].values[0] if len(flip_candidates) > 0 else None

        return {
            'total_gex': total_gex,
            'max_gex_strike': max_gex_strike,
            'gamma_flip': gamma_flip,
            'gex_sign': np.sign(total_gex),
            'call_gex': gex_by_strike['call_gex'].sum(),
            'put_gex': gex_by_strike['put_gex'].sum(),
            'gex_skew': gex_by_strike['call_gex'].sum() - gex_by_strike['put_gex'].sum(),
            'concentration': gex_by_strike['total_gex'].abs().max() / (gex_by_strike['total_gex'].abs().sum() + 1e-10),
            'distance_to_wall': (self.spot - max_gex_strike) / self.spot,
            'distance_to_flip': (self.spot - gamma_flip) / self.spot if gamma_flip else None
        }


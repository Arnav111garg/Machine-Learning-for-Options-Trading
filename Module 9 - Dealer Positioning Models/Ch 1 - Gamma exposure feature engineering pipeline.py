if __name__ == '__main__':
    # Simulate an options chain for SPX
    np.random.seed(42)
    spot = 5000.0

    strikes = np.arange(4500, 5500, 25)

    # Dynamically generate futures dates (e.g., 30, 60, and 90 days from today) to prevent expired dates
    today = pd.Timestamp.today().normalize()
    expiries = [(today + pd.Timedelta(days=d)).strftime('%Y-%m-%d') for d in [30, 60, 90]]

    rows = []

    for expiry in expiries:
        dte = (pd.to_datetime(expiry) - today).days
        for K in strikes:
            for opt_type in ['C', 'P']:
                moneyness = K / spot
                # Simulated IV with skew
                iv = 0.15 + 0.02 * (1 - moneyness) + 0.01 * np.random.randn()
                iv = max(0.05, iv)
                # OI decays with distance from ATM
                oi_base = 50000 * np.exp(-((K - spot) ** 2) / (2 * 200**2))
                oi = max(100, int(oi_base * (1 + 0.3 * np.random.randn())))
                rows.append({
                    'strike': K, 'expiry': expiry, 'option_type': opt_type,
                    'oi': oi, 'iv': iv, 'dte': dte,
                    'bid': 0, 'ask': 0
                })

    chain_df = pd.DataFrame(rows)
    calc = GEXCalculator(chain_df, spot=spot, r=0.05, dealer_sign_convention='gex_standard')
    gex_metrics = calc.compute_total_gex()

    print("=== GEX Metrics ===")
    for k, v in gex_metrics.items():
        if v is not None:
            print(f"{k:30s}: {v: >15.2f}" if isinstance(v, float) else f"{k}: {v}")


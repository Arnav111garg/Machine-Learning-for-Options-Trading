# GEX Feature Engineering for ML
# ================================================================

def build_gex_features(gex_history: pd.DataFrame) -> pd.DataFrame:
    """Build ML-ready feature matrix from time series of daily GEX metrics."""
    df = gex_history.sort_values('date').copy()
    spot = df['spot']

    # Level features
    df['gex_norm'] = df['total_gex'] / df['total_gex'].abs().rolling(252).mean()
    df['gex_zscore_21'] = (df['total_gex'] - df['total_gex'].rolling(21).mean()) / df['total_gex'].rolling(21).std()
    df['gex_zscore_63'] = (df['total_gex'] - df['total_gex'].rolling(63).mean()) / df['total_gex'].rolling(63).std()

    # Momentum features
    for lag in [1, 5, 21]:
        df[f'gex_mom_{lag}d'] = df['total_gex'].diff(lag)
        df[f'gex_pct_{lag}d'] = df['total_gex'].pct_change(lag)

    # Positional features
    df['dist_to_wall'] = (spot - df['max_gex_strike']) / spot
    df['dist_to_flip'] = (spot - df['gamma_flip']) / spot
    df['above_flip'] = (spot > df['gamma_flip']).astype(int)

    # Regime features
    df['gex_positive'] = (df['total_gex'] > 0).astype(int)
    df['gex_positive_streak'] = df['gex_positive'].groupby(
        (df['gex_positive'] != df['gex_positive'].shift()).cumsum()
    ).cumcount()

    # Rolling statistics
    df['gex_vol'] = df['total_gex'].rolling(21).std()
    df['gex_skew_21'] = df['total_gex'].rolling(21).skew()
    return df


import numpy as np
import pandas as pd
from scipy.stats import norm

class DEXCalculator:
    """
    Delta Exposure Calculator with term structure decomposition.
    """
    def __init__(self, options_chain: pd.DataFrame, spot: float, r: float = 0.05):
        self.chain = options_chain.copy()
        self.spot = spot
        self.r = r
        self._compute_deltas()

    def _compute_deltas(self):
        """Compute BS deltas for all options."""
        def bs_delta(row):
            S, K, r, sigma, T = (self.spot, row['strike'], self.r, row['iv'], row['T'])
            if T <= 0 or sigma <= 0:
                return 0.0
            d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
            if row['option_type'].upper() == 'C':
                return norm.cdf(d1)
            else:
                return norm.cdf(d1) - 1  # Negative for puts

        if 'T' not in self.chain.columns:
            self.chain['T'] = self.chain['dte'] / 365.0

        self.chain['delta'] = self.chain.apply(bs_delta, axis=1)
        # Dollar delta per contract (100 shares)
        self.chain['dollar_delta'] = (self.chain['delta'] * self.chain['oi'] * 100 * self.spot)

    def compute_dex_by_bucket(self) -> pd.DataFrame:
        """DEX decomposed by DTE bucket."""
        buckets = [(0, 7, '0-7d'), (7, 30, '7-30d'), (30, 60, '30-60d'), (60, 90, '60-90d'), (90, 365, '90-365d')]
        results = {}
        for low, high, label in buckets:
            mask = (self.chain['T'] * 365 > low) & (self.chain['T'] * 365 <= high)
            subset = self.chain[mask]
            if len(subset) == 0:
                results[label] = {'call_dex': 0, 'put_dex': 0, 'net_dex': 0}
                continue

            calls = subset[subset['option_type'] == 'C']
            puts = subset[subset['option_type'] == 'P']

            call_dex = calls['dollar_delta'].sum()
            put_dex = puts['dollar_delta'].sum()  # Already negative

            results[label] = {
                'call_dex': call_dex,
                'put_dex': put_dex,
                'net_dex': call_dex + put_dex,
                'abs_dex': abs(call_dex) + abs(put_dex)
            }
        return pd.DataFrame(results).T

    def compute_total_dex(self) -> dict:
        """Aggregate DEX metrics."""
        calls = self.chain[self.chain['option_type'] == 'C']
        puts = self.chain[self.chain['option_type'] == 'P']

        call_dex = calls['dollar_delta'].sum()
        put_dex = puts['dollar_delta'].sum()  # Negative
        net_dex = call_dex + put_dex

        # Delta-adjusted PCR
        dpcr = (puts['delta'].abs() * puts['oi']).sum() / \
               (calls['delta'] * calls['oi']).sum() if (calls['delta'] * calls['oi']).sum() > 0 else np.nan

        # Charm (dDelta/dT): how fast delta changes with time
        # This drives EOD dealer rebalancing pressure
        charm_pressure = self._estimate_charm_flow()

        return {
            'call_dex': call_dex,
            'put_dex': put_dex,
            'net_dex': net_dex,
            'dpcr': dpcr,
            'dex_ratio': call_dex / (abs(call_dex) + abs(put_dex) + 1e-10),
            'charm_pressure': charm_pressure,
            'hedging_demand': -net_dex / self.spot  # Shares to buy/sell
        }

    def _estimate_charm_flow(self) -> float:
        """
        Estimate daily charm (dDelta/dT) hedging pressure.
        Charm drives end-of-day re-hedging as time decays.
        """
        def bs_charm(row):
            S, K, r, sigma, T = (self.spot, row['strike'], self.r, row['iv'], row['T'])
            if T <= 0.001 or sigma <= 0:
                return 0.0
            d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
            d2 = d1 - sigma * np.sqrt(T)
            # Charm formula (rate of change of delta with time)
            charm = -norm.pdf(d1) * (2 * r * T - d2 * sigma * np.sqrt(T)) / (2 * T * sigma * np.sqrt(T))
            return charm

        self.chain['charm'] = self.chain.apply(bs_charm, axis=1)
        # Daily charm flow = charm * OI * 100 * S / 252 (per trading day)
        daily_charm_flow = (self.chain['charm'] * self.chain['oi'] * 100 * self.spot).sum() / 252
        return daily_charm_flow


def build_dex_features(dex_history: pd.DataFrame) -> pd.DataFrame:
    """
    Build comprehensive DEX feature set for ML models.
    """
    df = dex_history.sort_values('date').copy()
    # Z-score normalisation
    for window in [21, 63, 126]:
        df[f'net_dex_zscore_{window}d'] = (
            (df['net_dex'] - df['net_dex'].rolling(window).mean()) / df['net_dex'].rolling(window).std()
        )

    # DPCR features
    df['dpcr_ma21'] = df['dpcr'].rolling(21).mean()
    df['dpcr_deviation'] = df['dpcr'] - df['dpcr_ma21']
    df['dpcr_extreme_bearish'] = (df['dpcr'] > df['dpcr'].rolling(252).quantile(0.90)).astype(int)
    df['dpcr_extreme_bullish'] = (df['dpcr'] < df['dpcr'].rolling(252).quantile(0.10)).astype(int)

    # Charm pressure (predicts EOD squeeze potential)
    df['charm_norm'] = df['charm_pressure'] / df['spot']
    df['charm_positive'] = (df['charm_pressure'] > 0).astype(int)

    # DEX regime
    df['dex_bullish_regime'] = (df['net_dex'] > 0).astype(int)

    # Interaction features with GEX (if available)
    if 'total_gex' in df.columns:
        df['gex_dex_alignment'] = np.sign(df['total_gex']) * np.sign(df['net_dex'])
        df['gex_dex_ratio'] = df['total_gex'].abs() / (df['net_dex'].abs() + 1e-10)

    return df


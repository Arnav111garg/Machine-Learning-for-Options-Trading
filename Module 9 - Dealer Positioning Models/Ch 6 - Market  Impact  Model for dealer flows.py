import numpy as np
import pandas as pd
from scipy.optimize import curve_fit, minimize
from sklearn.linear_model import Ridge
from typing import Tuple, Optional

class DealerImpactModel:
    """
    Estimate and forecast market impact from dealer hedging flows.
    """

    def __init__(self):
        self.sqrt_impact_params = None
        self.kyle_lambda = None
        self.hawkes_params = None

    def estimate_sqrt_impact(self, trades_df: pd.DataFrame) -> dict:
        """
        Estimate square-root impact law from historical trades.

        Parameters
        ----------
        trades_df : DataFrame with: trade_size, daily_vol, adv, price_impact
        """
        # Normalise trade sizes
        Q_norm = trades_df['trade_size'].abs() / trades_df['adv']
        impact = trades_df['price_impact'].abs() / trades_df['daily_vol']

        # Fit: impact = eta * sqrt(Q_norm)
        def sqrt_law(Q, eta):
            return eta * np.sqrt(Q)

        popt, pcov = curve_fit(sqrt_law, Q_norm, impact, p0=[1.0])
        eta = popt[0]
        eta_std = np.sqrt(pcov[0, 0])

        self.sqrt_impact_params = {'eta': eta, 'eta_std': eta_std}

        # Also fit power law: impact = eta * Q^alpha
        def power_law(Q, eta, alpha):
            return eta * Q ** alpha

        popt2, _ = curve_fit(
            power_law, Q_norm, impact, p0=[1.0, 0.5],
            bounds=([0, 0.1], [10, 1.0])
        )

        return {
            'eta': eta,
            'eta_std': eta_std,
            'power_law_eta': popt2[0],
            'power_law_alpha': popt2[1],
            'r_squared_sqrt': 1 - np.var(impact - sqrt_law(Q_norm, eta)) / np.var(impact),
            'r_squared_power': 1 - np.var(impact - power_law(Q_norm, *popt2)) / np.var(impact)
        }

    def compute_gex_impact(self, gex: float, spot: float, daily_vol: float,
                           adv: float, eta: Optional[float] = None) -> float:
        """
        Compute estimated market impact from GEX-induced dealer flow.
        """
        if eta is None:
            eta = self.sqrt_impact_params['eta'] if self.sqrt_impact_params else 1.0

        # Dealer hedging volume = GEX * daily_move / spot
        daily_move = daily_vol  # As fraction of spot (annualised_vol / sqrt(252))
        hedge_vol_shares = abs(gex) * daily_move / (spot ** 2)
        Q_norm = hedge_vol_shares / adv

        # Convert to bps
        impact_bps = eta * np.sqrt(Q_norm) * daily_vol * 10000

        return impact_bps * np.sign(-gex)  # Negative GEX -> amplifies moves

    def estimate_kyle_lambda(self, order_flow: pd.Series, price_changes: pd.Series) -> float:
        """
        Estimate Kyle's lambda from options order flow data.
        """
        # OLS regression : dP = lambda * order_flow + epsilon
        X = order_flow.values.reshape(-1, 1)
        y = price_changes.values

        reg = Ridge(alpha=0.01).fit(X, y)
        self.kyle_lambda = reg.coef_[0]

        return self.kyle_lambda

    def fit_hawkes_process(self, trade_times: np.ndarray, T: float) -> dict:
        """
        Fit Hawkes process to dealer hedging trade arrival times.
        """
        def hawkes_log_likelihood(params):
            mu, alpha, beta = params
            if mu <= 0 or alpha <= 0 or beta <= 0 or alpha >= beta:
                return 1e10

            # Log-likelihood of Hawkes process
            ll = - mu * T
            lambda_t = np.zeros(len(trade_times))

            for i, t in enumerate(trade_times):
                # Intensity at time t
                if i > 0:
                    past_contrib = alpha * np.sum(
                        np.exp(- beta * (t - trade_times[:i]))
                    )
                    lambda_t[i] = mu + past_contrib
                else:
                    lambda_t[i] = mu

                ll += np.log(max(lambda_t[i], 1e-10))

            # Integral of intensity
            int_term = 0
            for i, t in enumerate(trade_times):
                int_term += (alpha / beta) * (1 - np.exp(- beta * (T - t)))

            ll -= int_term
            return - ll  # Minimise negative log-likelihood

        # Initial parameters
        n = len(trade_times)
        mu0 = n / T
        alpha0 = 0.5 * mu0
        beta0 = 2 * alpha0

        result = minimize(
            hawkes_log_likelihood,
            x0=[mu0, alpha0, beta0],
            method='Nelder-Mead',
            options={'maxiter': 5000, 'xatol': 1e-6}
        )

        mu, alpha, beta = result.x
        branching_ratio = alpha / beta

        self.hawkes_params = {
            'mu': mu, 'alpha': alpha, 'beta': beta,
            'branching_ratio': branching_ratio
        }

        return {
            'mu': mu,
            'alpha': alpha,
            'beta': beta,
            'branching_ratio': branching_ratio,
            'flash_crash_risk': branching_ratio > 0.8,
            'expected_duration': 1 / (beta - alpha) if beta > alpha else np.inf
        }


class ImpactAdjustedSignal:
    """
    Adjust trading signals for market impact from dealer flows.
    """

    def __init__(self, impact_model: DealerImpactModel):
        self.impact_model = impact_model

    def adjust_entry_price(self, signal_price: float, size: int,
                            gex: float, spot: float, daily_vol: float,
                            adv: float) -> dict:
        """
        Adjust entry price for expected impact from own trade + dealer hedging.
        """
        # Our own impact
        own_impact = self.impact_model.compute_gex_impact(
            gex=0, spot=spot, daily_vol=daily_vol, adv=adv
        )  # Baseline

        # GEX-implied dealer flow on the same direction
        dealer_impact = self.impact_model.compute_gex_impact(
            gex=gex, spot=spot, daily_vol=daily_vol, adv=adv
        )

        # Total adjusted entry price
        direction = 1 if signal_price > spot else -1
        total_impact_bps = (abs(own_impact) + abs(dealer_impact)) * direction

        adjusted_price = signal_price * (1 + total_impact_bps / 10000)

        return {
            'signal_price': signal_price,
            'adjusted_price': adjusted_price,
            'own_impact_bps': own_impact,
            'dealer_impact_bps': dealer_impact,
            'total_impact_bps': total_impact_bps,
            'breakeven_move_bps': total_impact_bps * 2  # Need 2x impact to profit
        }


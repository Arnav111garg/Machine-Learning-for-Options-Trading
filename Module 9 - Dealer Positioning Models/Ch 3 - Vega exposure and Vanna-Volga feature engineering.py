import numpy as np
import pandas as pd
from scipy.stats import norm

class VEXCalculator:
    """
    Vega Exposure Calculator with higher-order vol sensitivities.
    """

    def __init__(self, options_chain: pd.DataFrame, spot: float, r: float = 0.05):
        self.chain = options_chain.copy()
        self.spot = spot
        self.r = r
        self._compute_vol_greeks()

    def _bs_vanna(self, S, K, r, sigma, T) -> float:
        """dDelta / dSigma = dVega / dS"""
        if T <= 0 or sigma <= 0:
            return 0.0
        d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        return -norm.pdf(d1) * d2 / sigma

    def _bs_volga(self, S, K, r, sigma, T) -> float:
        """d2V / dSigma^2 = Vega * d1 * d2 / sigma"""
        if T <= 0 or sigma <= 0:
            return 0.0
        d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        vega = S * np.sqrt(T) * norm.pdf(d1)
        return vega * d1 * d2 / sigma

    def _bs_vega(self, S, K, r, sigma, T) -> float:
        if T <= 0 or sigma <= 0:
            return 0.0
        d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
        return S * np.sqrt(T) * norm.pdf(d1)

    def _compute_vol_greeks(self):
        if 'T' not in self.chain.columns:
            self.chain['T'] = self.chain['dte'] / 365.0

        args = [(self.spot, row['strike'], self.r, row['iv'], row['T'])
                for _, row in self.chain.iterrows()]

        self.chain['vega'] = [self._bs_vega(*a) for a in args]
        self.chain['vanna'] = [self._bs_vanna(*a) for a in args]
        self.chain['volga'] = [self._bs_volga(*a) for a in args]

        # Dollar vega: P&L per 1 vol point (0.01 move in IV)
        self.chain['dollar_vega'] = self.chain['vega'] * self.chain['oi'] * 100 * 0.01

    def compute_vex(self, dealer_short: bool = True) -> dict:
        """
        Compute VEX with higher-order sensitivities.
        dealer_short: if True, assume dealers are net short options
        """
        sign = -1 if dealer_short else 1

        total_vex = sign * (self.chain['vega'] * self.chain['oi'] * 100).sum()
        total_vannex = sign * (self.chain['vanna'] * self.chain['oi'] * 100).sum()
        total_volgex = sign * (self.chain['volga'] * self.chain['oi'] * 100).sum()

        # Skew VEX: OTM puts vs calls
        calls = self.chain[self.chain['option_type'] == 'C']
        puts = self.chain[self.chain['option_type'] == 'P']
        otm_calls = calls[calls['strike'] > self.spot]
        otm_puts = puts[puts['strike'] < self.spot]

        vex_otm_call = sign * (otm_calls['vega'] * otm_calls['oi'] * 100).sum()
        vex_otm_put = sign * (otm_puts['vega'] * otm_puts['oi'] * 100).sum()

        # Term structure VEX
        short_term = self.chain[self.chain['T'] * 365 <= 30]
        long_term = self.chain[self.chain['T'] * 365 > 30]
        vex_st = sign * (short_term['vega'] * short_term['oi'] * 100).sum()
        vex_lt = sign * (long_term['vega'] * long_term['oi'] * 100).sum()

        # Vol spike sensitivity
        vol_spike_pnl = total_vex * 0.05

        return {
            'total_vex': total_vex,
            'total_vannex': total_vannex,
            'total_volgex': total_volgex,
            'vex_otm_call': vex_otm_call,
            'vex_otm_put': vex_otm_put,
            'vex_skew': vex_otm_call - vex_otm_put,
            'vex_short_term': vex_st,
            'vex_long_term': vex_lt,
            'vex_term_ratio': vex_st / (vex_lt + 1e-10),
            'vol_spike_pnl_5pt': vol_spike_pnl,
            'vex_per_share': total_vex / (self.chain['oi'].sum() * 100 + 1)
        }

    def compute_vol_surface_features(self) -> dict:
        """
        Extract features related to dealer's vol surface exposure.
        """
        self.chain['moneyness'] = self.chain['strike'] / self.spot
        self.chain['moneyness_bucket'] = pd.cut(
            self.chain['moneyness'],
            bins=[0, 0.90, 0.95, 0.975, 1.025, 1.05, 1.10, 99],
            labels=['<90%', '90-95%', '95-97.5%', 'ATM', '102.5-105%', '105-110%', '>110%']
        )

        vanna_by_bucket = self.chain.groupby('moneyness_bucket', observed=False)['vanna'].sum()
        vega_by_bucket = self.chain.groupby('moneyness_bucket', observed=False)['vega'].sum()

        skew_sensitivity = self.chain['vanna'].corr(self.chain['moneyness'])

        return {
            'vanna_by_bucket': vanna_by_bucket.to_dict(),
            'vega_by_bucket': vega_by_bucket.to_dict(),
            'skew_sensitivity': skew_sensitivity,
            'weighted_avg_iv': (self.chain['iv'] * self.chain['vega'] * self.chain['oi']).sum() / \
                               ((self.chain['vega'] * self.chain['oi']).sum() + 1e-10)
        }


import numpy as np
import pandas as pd
import xgboost as xgb
from sklearn.model_selection import TimeSeriesSplit
from sklearn.metrics import (
    roc_auc_score,
    precision_recall_curve,
    average_precision_score,
    confusion_matrix
)
from sklearn.calibration import CalibratedClassifierCV
import matplotlib.pyplot as plt
import warnings
from typing import Tuple

warnings.filterwarnings('ignore')

class GammaFlipPredictor:
    """
    ML model to predict gamma flip events using options positioning data.

    Target: Will spot cross the gamma flip level within h days?
    """

    def __init__(self, horizon: int = 5, flip_threshold_pct: float = 0.005):
        """
        Parameters
        ----------
        horizon : int
            Prediction horizon in trading days
        flip_threshold_pct : float
            How close spot must get to flip level to count as a 'flip event'
            Default 0.5% of spot price
        """
        self.horizon = horizon
        self.threshold = flip_threshold_pct
        self.model = None
        self.feature_names = None

    def _create_features(self, data: pd.DataFrame) -> pd.DataFrame:
        """
        Engineering features for gamma flip prediction.

        data must contain : spot, gamma_flip, total_gex, iv_atm, skew,
        pcr, vix, vvix, gamma_flow, delta_flow
        """
        df = data.copy().sort_index()
        # Distance to flip (primary feature)
        df['dist_to_flip'] = (df['spot'] - df['gamma_flip']) / df['spot']
        df['abs_dist_to_flip'] = df['dist_to_flip'].abs()
        df['log_abs_dist'] = np.log(df['abs_dist_to_flip'] + 1e-4)
        df['above_flip'] = (df['spot'] > df['gamma_flip']).astype(int)

        # GEX features
        df['gex_norm'] = df['total_gex'] / df['total_gex'].rolling(252, min_periods=60).std()
        df['gex_sign'] = np.sign(df['total_gex'])
        df['gex_crossover_1d'] = (df['gex_sign'] != df['gex_sign'].shift(1)).astype(int)
        df['gex_velocity'] = df['total_gex'].diff(5) / (df['total_gex'].abs() + 1e-10)

        # GEX slope at flip (if available)
        if 'gex_slope_at_flip' in df.columns:
            df['flip_stability'] = df['gex_slope_at_flip'].abs()

        # Volatility features
        df['iv_zscore'] = (df['iv_atm'] - df['iv_atm'].rolling(21).mean()) / \
                           df['iv_atm'].rolling(21).std()
        df['vol_regime'] = (df['iv_atm'] > df['iv_atm'].rolling(63).quantile(0.75)).astype(int)
        df['vix_vvix_ratio'] = df['vix'] / (df['vvix'] + 1e-10)
        df['term_structure_slope'] = df.get('iv_30d', df['iv_atm']) - df.get('iv_7d', df['iv_atm'])

        # Flow features
        df['gamma_flow_norm'] = df.get('gamma_flow', 0) / \
                                (df.get('gamma_flow', pd.Series([1] * len(df), index=df.index)).rolling(21).std() + 1e-10)
        df['delta_flow_norm'] = df.get('delta_flow', 0) / \
                                (df.get('delta_flow', pd.Series([1] * len(df), index=df.index)).rolling(21).std() + 1e-10)

        # Momentum features
        for lag in [1, 3, 5, 10, 21]:
            df[f'ret_{lag}d'] = df['spot'].pct_change(lag)
            df[f'flip_dist_lag_{lag}d'] = df['dist_to_flip'].shift(lag)

        # PCR features
        df['pcr_ma5'] = df.get('pcr', 1.0).rolling(5).mean()
        df['pcr_extreme'] = (df.get('pcr', 1.0) > df.get('pcr', 1.0).rolling(63).quantile(0.9)).astype(int)

        # Interaction features
        df['dist_x_vol'] = df['abs_dist_to_flip'] * df['iv_atm']
        df['gex_x_momentum'] = df['gex_sign'] * df['ret_5d'] if 'ret_5d' in df.columns else 0

        # Calendar features
        df['day_of_week'] = df.index.dayofweek
        df['days_to_opex'] = df.get('days_to_opex', 30)  # Days to monthly expiry
        df['near_opex'] = (df['days_to_opex'] <= 5).astype(int)

        return df

    def _create_labels(self, data: pd.DataFrame) -> pd.Series:
        """
        Create binary labels: did spot cross flip level within h days?
        """
        flip = data['gamma_flip']
        spot = data['spot']

        labels = []
        for i in range(len(data)):
            future_window = spot.iloc[i + 1: i + 1 + self.horizon]
            future_flip = flip.iloc[i + 1: i + 1 + self.horizon]

            if len(future_window) == 0:
                labels.append(np.nan)
                continue

            # Check if spot crosses through flip level
            spot_minus_flip_now = spot.iloc[i] - flip.iloc[i]
            crossed = any(
                (spot_minus_flip_now > 0 and s < f) or
                (spot_minus_flip_now < 0 and s > f)
                for s, f in zip(future_window, future_flip)
            )
            labels.append(int(crossed))

        return pd.Series(labels, index=data.index)

    def build_feature_matrix(self, data: pd.DataFrame) -> Tuple[pd.DataFrame, pd.Series]:
        """Build X, y for model training."""
        features_df = self._create_features(data)
        labels = self._create_labels(data)
        # Select feature columns (exclude raw inputs and labels)
        exclude_cols = {
            'spot', 'gamma_flip', 'total_gex', 'iv_atm', 'skew',
            'pcr', 'vix', 'vvix', 'gamma_flow', 'delta_flow',
            'iv_30d', 'iv_7d', 'days_to_opex'
        }
        feature_cols = [c for c in features_df.columns if c not in exclude_cols]

        X = features_df[feature_cols]
        y = labels

        # Align and drop NaN
        mask = ~(X.isnull().any(axis=1) | y.isnull())
        return X[mask], y[mask]

    def train(self, data: pd.DataFrame, n_splits: int = 5) -> dict:
        """
        Train with walk-forward cross-validation.
        """
        X, y = self.build_feature_matrix(data)
        self.feature_names = X.columns.tolist()

        tscv = TimeSeriesSplit(n_splits=n_splits)

        xgb_params = {
            'n_estimators': 500,
            'max_depth': 4,
            'learning_rate': 0.05,
            'subsample': 0.8,
            'colsample_bytree': 0.8,
            'min_child_weight': 10,
            'gamma': 0.1,
            'scale_pos_weight': (y == 0).sum() / (y == 1).sum(),  # Handle imbalance
            'objective': 'binary:logistic',
            'eval_metric': 'auc',
            'random_state': 42,
            'n_jobs': -1,
            'early_stopping_rounds': 50
        }

        oof_probs = np.zeros(len(X))
        cv_aucs = []

        for fold, (train_idx, val_idx) in enumerate(tscv.split(X)):
            X_tr, X_val = X.iloc[train_idx], X.iloc[val_idx]
            y_tr, y_val = y.iloc[train_idx], y.iloc[val_idx]

            model = xgb.XGBClassifier(**xgb_params)
            model.fit(
                X_tr, y_tr,
                eval_set=[(X_val, y_val)],
                verbose=False
            )

            oof_probs[val_idx] = model.predict_proba(X_val)[:, 1]
            auc = roc_auc_score(y_val, oof_probs[val_idx])
            cv_aucs.append(auc)
            print(f"Fold {fold + 1}: AUC = {auc:.4f}")

        # Final model on all data
        self.model = xgb.XGBClassifier(**xgb_params)
        self.model.fit(X, y, eval_set=[(X, y)], verbose=False)

        # Feature importance
        importance = pd.Series(
            self.model.feature_importances_,
            index=self.feature_names
        ).sort_values(ascending=False)

        print(f"\nOOF AUC: {roc_auc_score(y, oof_probs):.4f}")
        print(f"CV AUC: {np.mean(cv_aucs):.4f} +/- {np.std(cv_aucs):.4f}")
        print("\nTop 10 Features:")
        print(importance.head(10))

        return {
            'oof_auc': roc_auc_score(y, oof_probs),
            'cv_aucs': cv_aucs,
            'feature_importance': importance,
            'oof_probs': oof_probs,
            'labels': y
        }

    def predict_proba(self, data: pd.DataFrame) -> np.ndarray:
        """Predict flip probability for new data."""
        X, _ = self.build_feature_matrix(data)
        return self.model.predict_proba(X)[:, 1]


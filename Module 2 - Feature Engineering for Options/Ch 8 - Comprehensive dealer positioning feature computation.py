# GEX and Dealer Positioning Features
import numpy as np
import pandas as pd
from scipy.stats import norm

def bs_greeks_fast(S, K, T, r, q, sigma, option_type):
    """Vectorized Black-Scholes greeks computation."""
    T = np.maximum(T, 1e-6)
    sigma = np.maximum(sigma, 1e-6)

    d1 = (np.log(S / K) + (r - q + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    nd1 = norm.pdf(d1)

    gamma = np.exp(-q * T) * nd1 / (S * sigma * np.sqrt(T))
    vanna = -np.exp(-q * T) * nd1 * d2 / sigma
    volga = gamma * S ** 2 * d1 * d2 / sigma
    charm = (-np.exp(-q * T) * nd1 * (2 * (r - q) * T - d2 * sigma * np.sqrt(T)) / (2 * T * sigma * np.sqrt(T)))

    return gamma, vanna, volga, charm

def compute_dealer_features(chain: pd.DataFrame, S: float, r: float = 0.05, q: float = 0.015) -> dict:
    """
    Compute all dealer positioning features.

    chain: DataFrame with:
    strike, expiry_years, iv, open_interest, option_type ('C'/'P')

    Sign convention:
    Calls: dealer SHORT (negative for dealer)
    Puts: dealer LONG (positive for dealer from put selling = customer puts)

    Actually for GEX:
    Calls OI: sign = +1 (short call = short gamma for dealer)
    Puts OI: dealer is SHORT puts => dealer is SHORT gamma from puts too

    STANDARD SPOTGAMMA convention:
    GEX from calls = +OI * Gamma * S^2 * 100
    GEX from puts = -OI * Gamma * S^2 * 100
    (Net GEX > 0 means dealers NET LONG gamma = stabilizing)
    """
    K = chain['strike'].values
    T = chain['expiry_years'].values
    iv = chain['iv'].values
    oi = chain['open_interest'].values
    otype = chain['option_type'].values

    gamma, vanna, volga, charm = bs_greeks_fast(S, K, T, r, q, iv, otype)

    # Dealer sign: +1 for calls, -1 for puts
    dealer_sign = np.where(otype == 'C', 1, -1)

    # GEX (per contract = 100 shares)
    gex_by_strike = dealer_sign * oi * gamma * S ** 2 * 100
    vex_by_strike = dealer_sign * oi * vanna * S * 100
    chex_by_strike = dealer_sign * oi * charm * S * 100

    feats = {
        # Aggregate exposures
        'gex_total': gex_by_strike.sum(),
        'vex_total': vex_by_strike.sum(),
        'chex_total': chex_by_strike.sum(),
        # Near-term vs far-term GEX (split at 45 days)
        'gex_near': gex_by_strike[T <= 45/252].sum(),
        'gex_far': gex_by_strike[T > 45/252].sum(),
        # Call vs put GEX
        'gex_calls': gex_by_strike[otype == 'C'].sum(),
        'gex_puts': gex_by_strike[otype == 'P'].sum(),
        # Gamma flip: spot where total GEX = 0
        'gex_sign': np.sign(gex_by_strike.sum()),
    }

    # GEX by strike for pinning / key level analysis
    strike_gex = pd.DataFrame({'strike': K, 'gex': gex_by_strike})
    strike_gex_agg = strike_gex.groupby('strike')['gex'].sum()

    # Max pain
    strikes_sorted = sorted(chain['strike'].unique())
    total_pain = []
    for k in strikes_sorted:
        pain = (chain[chain['option_type'] == 'C']
                .apply(lambda r: r['open_interest'] * max(k - r['strike'], 0), axis=1).sum()
                + chain[chain['option_type'] == 'P']
                .apply(lambda r: r['open_interest'] * max(r['strike'] - k, 0), axis=1).sum())
        total_pain.append(pain)

    max_pain_idx = np.argmin(total_pain)
    feats['max_pain_strike'] = strikes_sorted[max_pain_idx]
    feats['max_pain_distance'] = (strikes_sorted[max_pain_idx] - S) / S

    # Gamma flip level (approximate: find strike where cumulative GEX changes sign)
    cum_gex = strike_gex_agg.cumsum()
    if cum_gex.iloc[0] * cum_gex.iloc[-1] < 0:
        flip_idx = np.where(np.diff(np.sign(cum_gex.values)))[0]
        if len(flip_idx) > 0:
            feats['gamma_flip'] = strike_gex_agg.index[flip_idx[0]]
            feats['gamma_flip_dist'] = (feats['gamma_flip'] - S) / S

    return feats, strike_gex_agg


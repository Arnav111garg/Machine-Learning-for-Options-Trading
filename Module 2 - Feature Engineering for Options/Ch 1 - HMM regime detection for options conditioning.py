import numpy as np
import pandas as pd
from hmmlearn import hmm
from sklearn.preprocessing import StandardScaler

def compute_hmm_regime_features(
    returns: pd.Series,
    n_states: int = 3,
    n_iter: int = 1000
) -> pd.DataFrame:
    """
    Fit a Gaussian HMM to daily returns and extract regime probabilities.

    Returns:
    DataFrame with columns: regime_0_prob, regime_1_prob, regime_2_prob, most_likely_regime
    Used as conditioning variable for all options features.
    """
    X = returns.values.reshape(-1, 1)

    # Fit HMM
    model = hmm.GaussianHMM(
        n_components=n_states,
        covariance_type='full',
        n_iter=n_iter,
        random_state=42
    )
    model.fit(X)

    # Get smoothed state probabilities (forward-backward algorithm)
    # IMPORTANT: in live trading use FILTERED (forward only) probabilities
    # to avoid look-ahead bias
    log_probs, posteriors = model.score_samples(X)

    # Order states by volatility (low vol = state 0, high vol = state 2)
    vols = np.sqrt([model.covars_[k][0, 0] for k in range(n_states)])
    order = np.argsort(vols)
    posteriors = posteriors[:, order]  # re-order columns

    df_regimes = pd.DataFrame(
        posteriors,
        index=returns.index,
        columns=[f'regime_{k}_prob' for k in range(n_states)]
    )

    df_regimes['most_likely_regime'] = posteriors.argmax(axis=1)

    return df_regimes


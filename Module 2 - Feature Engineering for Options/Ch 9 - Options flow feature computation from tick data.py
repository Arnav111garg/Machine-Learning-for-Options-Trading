import numpy as np
import pandas as pd
from scipy.stats import norm

def compute_flow_features(trades_df: pd.DataFrame, quotes_df: pd.DataFrame, S: float, r: float, q: float) -> dict:
    """
    trades_df: options tick data with columns:
    timestamp, strike, expiry_years, option_type, price, quantity
    quotes_df: quotes (bid/ask) indexed by timestamp

    Returns dict of flow features.
    """

    def bs_delta_vega(S, K, T, r, q, sigma, otype):
        T = max(T, 1/252/8)  # floor at 1 hour
        d1 = (np.log(S / K) + (r - q + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
        if otype == 'C':
            delta = np.exp(-q * T) * norm.cdf(d1)
        else:
            delta = -np.exp(-q * T) * norm.cdf(-d1)
        vega = S * np.exp(-q * T) * norm.pdf(d1) * np.sqrt(T)
        return delta, vega

    # ---- Lee-Ready Trade Classification ----
    # Merge trades with prevailing quotes
    merged = pd.merge_asof(
        trades_df.sort_values('timestamp'),
        quotes_df[['timestamp', 'bid', 'ask']].sort_values('timestamp'),
        on='timestamp', direction='backward'
    )
    merged['midpoint'] = (merged['bid'] + merged['ask']) / 2

    def classify(row):
        if row['price'] > row['midpoint']:
            return 1  # buyer-initiated
        elif row['price'] < row['midpoint']:
            return -1  # seller-initiated
        else:
            return 0  # indeterminate (tick rule would go here)

    merged['direction'] = merged.apply(classify, axis=1)

    # Assume implied vol from price (simplified: use mid-market IV)
    merged['iv'] = 0.20  # placeholder

    # ---- Compute Delta and Vega for each trade ----
    deltas, vegas = [], []
    for _, row in merged.iterrows():
        d, v = bs_delta_vega(S, row['strike'], row['expiry_years'], r, q, row['iv'], row['option_type'])
        deltas.append(d)
        vegas.append(v)
    merged['delta'] = deltas
    merged['vega'] = vegas

    # ---- Aggregate Flow Features ----
    signed_delta = merged['direction'] * merged['delta'].abs() * merged['quantity'] * 100
    signed_vega = merged['direction'] * merged['vega'] * merged['quantity'] * 100

    # Split by option type
    calls = merged[merged['option_type'] == 'C']
    puts = merged[merged['option_type'] == 'P']

    call_vol = calls['quantity'].sum()
    put_vol = puts['quantity'].sum()

    features = {
        # Basic PCR
        'pcr_volume': put_vol / (call_vol + 1e-8),
        'pcr_z': None,  # requires historical normalization
        # Delta-adjusted PCR
        'call_delta_vol': (calls['delta'].abs() * calls['quantity']).sum(),
        'put_delta_vol': (puts['delta'].abs() * puts['quantity']).sum(),
        # Options Order Flow Imbalance
        'oofi': signed_delta.sum(),
        'oofi_calls': signed_delta[merged['option_type'] == 'C'].sum(),
        'oofi_puts': signed_delta[merged['option_type'] == 'P'].sum(),
        # Vega Flow
        'vega_flow': signed_vega.sum(),
        'vega_flow_calls': signed_vega[merged['option_type'] == 'C'].sum(),
        'vega_flow_puts': signed_vega[merged['option_type'] == 'P'].sum(),
        # Unusual activity
        'max_voir': None,  # requires OI data from prior day
        'total_volume': merged['quantity'].sum(),
        'n_large_trades': (merged['quantity'] >= 100).sum(),
        # Trade size distribution (small = retail, large = institutional)
        'large_trade_fraction': merged[merged['quantity'] >= 100]['quantity'].sum() / (merged['quantity'].sum() + 1e-8),
    }

    # Delta-adjusted PCR
    features['dpcr'] = features['put_delta_vol'] / (features['call_delta_vol'] + 1e-8)

    return features


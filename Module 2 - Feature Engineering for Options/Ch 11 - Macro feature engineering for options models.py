import numpy as np
import pandas as pd
from fredapi import Fred  # pip install fredapi

def build_macro_features(fred_api_key: str, start_date: str = '2000-01-01') -> pd.DataFrame:
    """
    Build comprehensive macro feature set using FRED data.
    All features are available in real-time (no revision look-ahead).

    Key macro series used:
    GS10 : 10-year Treasury yield
    GS2: 2-year Treasury yield
    GS5: 5-year Treasury yield
    T10YIE : 10-year breakeven inflation
    DTB3 : 3-month T-bill
    DGS10 : Daily 10-year
    TEDRATE : TED spread
    DCOILWTICO : WTI crude oil
    DEXUSEU : USD/EUR exchange rate
    """
    fred = Fred(api_key=fred_api_key)

    series = {
        'y10': fred.get_series('GS10', start_date),
        'y2': fred.get_series('GS2', start_date),
        'y5': fred.get_series('GS5', start_date),
        'be10': fred.get_series('T10YIE', start_date),
        'ted': fred.get_series('TEDRATE', start_date),
        'oil': fred.get_series('DCOILWTICO', start_date),
    }

    df = pd.DataFrame(series).ffill()
    feat = pd.DataFrame(index=df.index)

    # ---- Yield Curve Features ----
    feat['yc_slope'] = df['y10'] - df['y2']  # 10Y-2Y slope
    feat['yc_curvature'] = 2 * df['y5'] - df['y2'] - df['y10']
    feat['yc_level'] = (df['y2'] + df['y5'] + df['y10']) / 3
    feat['real_rate_10y'] = df['y10'] - df['be10']

    # ---- Recession Signals ----
    # Yield curve inversion flag
    feat['yc_inverted'] = (feat['yc_slope'] < 0).astype(int)

    # Duration of inversion
    feat['inv_duration'] = feat['yc_inverted'].groupby(
        (feat['yc_inverted'] != feat['yc_inverted'].shift()).cumsum()
    ).cumsum()

    # ---- Funding Stress ----
    feat['ted_spread'] = df['ted']
    feat['ted_z'] = ((df['ted'] - df['ted'].rolling(252).mean()) / df['ted'].rolling(252).std())

    # ---- Commodity Vol Proxy ----
    # Oil realized vol as commodity uncertainty proxy
    oil_ret = np.log(df['oil']).diff()
    feat['oil_rv_21d'] = oil_ret.rolling(21).std() * np.sqrt(252)

    # ---- Cross-asset macro stress composite ----
    def z252(x):
        return (x - x.rolling(252).mean()) / x.rolling(252).std()

    # Flip sign so all components positive = stress
    feat['macro_stress'] = (
        z252(-feat['yc_slope']) * 0.3 +       # inverted curve = stress
        z252(feat['ted_spread']) * 0.3 +      # high TED = stress
        z252(feat['oil_rv_21d']) * 0.2 +      # oil vol spike = stress
        z252(-feat['real_rate_10y']) * 0.2     # very negative real rates = stress
    )

    return feat.dropna(how='all')

def create_macro_regime_dummies(macro_features: pd.DataFrame) -> pd.DataFrame:
    """
    Create regime dummies for conditioning options strategies.
    """
    df = macro_features.copy()
    regimes = pd.DataFrame(index=df.index)

    # Crisis regime : macro stress in top quartile
    stress_q75 = df['macro_stress'].quantile(0.75)
    regimes['crisis_regime'] = (df['macro_stress'] > stress_q75).astype(int)

    # Rate regime : rising vs. falling rates
    regimes['rising_rates'] = (df['yc_level'].diff(63) > 0).astype(int)

    # Curve regime
    regimes['curve_inverted'] = (df['yc_slope'] < 0).astype(int)
    regimes['curve_steep'] = (df['yc_slope'] > 1.5).astype(int)

    # Composite regime (3-state : bull / neutral / bear macro)
    regimes['macro_regime'] = pd.cut(
        df['macro_stress'],
        bins=[-np.inf, -0.5, 0.5, np.inf],
        labels=['bull_macro', 'neutral_macro', 'bear_macro']
    )

    return regimes
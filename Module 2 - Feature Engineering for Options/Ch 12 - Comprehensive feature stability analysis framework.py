import numpy as np
import pandas as pd
from scipy import stats
from statsmodels.tsa.stattools import adfuller, kpss
from statsmodels.stats.stattools import durbin_watson
import warnings
warnings.filterwarnings('ignore')

def feature_stability_report(feature: pd.Series,
                             target: pd.Series,
                             horizons: list = [1, 5, 21],
                             regime_col: pd.Series = None,
                             feature_name: str = 'Feature') -> dict:
    """
    Comprehensive feature stability analysis.

    Args:
        feature: pandas Series of feature values (time-indexed)
        target: pandas Series of target returns (time-indexed)
        horizons: list of prediction horizons in days
        regime_col: optional Series of regime labels (same index)
        feature_name: name for reporting

    Returns:
        dict with all stability statistics
    """
    report = {}

    # ---- 1. Stationarity Tests ----
    feat_clean = feature.dropna()

    # ADF test
    adf_result = adfuller(feat_clean, autolag='AIC')
    report['adf_stat'] = adf_result[0]
    report['adf_pvalue'] = adf_result[1]
    report['adf_stationary'] = adf_result[1] < 0.05

    # KPSS test
    kpss_result = kpss(feat_clean, regression='c', nlags='auto')
    report['kpss_stat'] = kpss_result[0]
    report['kpss_pvalue'] = kpss_result[1]
    report['kpss_stationary'] = kpss_result[1] > 0.05  # H0 = stationary

    # Combined verdict
    if report['adf_stationary'] and report['kpss_stationary']:
        report['stationarity'] = 'STATIONARY'
    elif not report['adf_stationary'] and not report['kpss_stationary']:
        report['stationarity'] = 'UNIT_ROOT'
    else:
        report['stationarity'] = 'AMBIGUOUS'

    # ---- 2. Information Coefficient at Multiple Horizons ----
    ic_by_horizon = {}
    for h in horizons:
        target_h = target.shift(-h)  # h-day ahead return
        aligned = pd.concat([feature, target_h], axis=1).dropna()
        if len(aligned) < 30:
            continue
        ic, pval = stats.spearmanr(aligned.iloc[:, 0], aligned.iloc[:, 1])
        tstat = ic * np.sqrt((len(aligned) - 2) / (1 - ic ** 2))
        ic_by_horizon[h] = {'ic': ic, 'pvalue': pval, 'tstat': tstat, 'n': len(aligned)}
    report['ic_by_horizon'] = ic_by_horizon

    # ---- 3. Rolling IC (Stability over Time) ----
    h = horizons[0]  # use shortest horizon for rolling
    roll_window = 252
    target_h = target.shift(-h)
    aligned = pd.concat([feature, target_h], axis=1).dropna()

    rolling_ic = []
    dates = []
    for i in range(roll_window, len(aligned)):
        window = aligned.iloc[i - roll_window: i]
        ic, _ = stats.spearmanr(window.iloc[:, 0], window.iloc[:, 1])
        rolling_ic.append(ic)
        dates.append(aligned.index[i])

    rolling_ic = pd.Series(rolling_ic, index=dates)
    report['rolling_ic_mean'] = rolling_ic.mean()
    report['rolling_ic_std'] = rolling_ic.std()
    report['rolling_ic_min'] = rolling_ic.min()
    report['rolling_ic_pct_positive'] = (rolling_ic > 0).mean()
    report['rolling_ic_sharpe'] = rolling_ic.mean() / (rolling_ic.std() + 1e-8)

    # ---- 4. Out-of-Sample R-squared ----
    # Split: first half train, second half test
    n = len(aligned)
    train = aligned.iloc[: n // 2]
    test = aligned.iloc[n // 2:]

    from sklearn.linear_model import LinearRegression
    reg = LinearRegression().fit(train.iloc[:, [0]], train.iloc[:, [1]])
    pred = reg.predict(test.iloc[:, [0]])
    ss_res = ((test.iloc[:, 1].values - pred.flatten()) ** 2).sum()
    ss_tot = ((test.iloc[:, 1].values - test.iloc[:, 1].mean()) ** 2).sum()
    report['oos_r2'] = 1 - ss_res / ss_tot

    # ---- 5. Regime-Conditional IC ----
    if regime_col is not None:
        regime_ics = {}
        for regime in regime_col.unique():
            mask = regime_col == regime
            aligned_reg = pd.concat([feature[mask], target_h[mask]], axis=1).dropna()
            if len(aligned_reg) >= 20:
                ic_r, pval_r = stats.spearmanr(aligned_reg.iloc[:, 0], aligned_reg.iloc[:, 1])
                regime_ics[regime] = {'ic': ic_r, 'pvalue': pval_r, 'n': len(aligned_reg)}
        report['regime_ics'] = regime_ics

        # Kruskal-Wallis test for regime differences
        groups = [
            aligned[regime_col.reindex(aligned.index) == r].iloc[:, 0].dropna().values
            for r in regime_col.unique() if r in regime_col.values
        ]
        groups = [g for g in groups if len(g) >= 5]
        if len(groups) >= 2:
            kw_stat, kw_pval = stats.kruskal(*groups)
            report['regime_kw_stat'] = kw_stat
            report['regime_kw_pval'] = kw_pval
            report['regime_stable'] = kw_pval > 0.05

    # ---- 6. Autocorrelation of Feature ----
    acf_1 = feature.autocorr(lag=1)
    acf_5 = feature.autocorr(lag=5)
    acf_21 = feature.autocorr(lag=21)
    report['autocorr_1d'] = acf_1
    report['autocorr_5d'] = acf_5
    report['autocorr_21d'] = acf_21

    # ---- 7. Summary Score ----
    score = 0
    if report['stationarity'] == 'STATIONARY':
        score += 20
    if report.get('rolling_ic_pct_positive', 0) > 0.60:
        score += 20
    if report.get('rolling_ic_sharpe', 0) > 0.5:
        score += 20
    if report.get('oos_r2', -np.inf) > 0:
        score += 20
    if ic_by_horizon.get(1, {}).get('pvalue', 1) < 0.05:
        score += 20

    report['stability_score'] = score
    report['grade'] = ('A' if score >= 80 else 'B' if score >= 60 else 'C' if score >= 40 else 'D')

    print(f"\n{'='*60}")
    print(f" FEATURE STABILITY REPORT : {feature_name}")
    print(f"{'='*60}")
    print(f" Stationarity : {report['stationarity']}")
    print(f"ADF p-value : {report['adf_pvalue']:.4f}")
    print(f" KPSS p-value : {report['kpss_pvalue']:.4f}")
    print(f"\nIC Summary (horizon={horizons[0]}d):")
    print(f" Rolling IC Mean : {report['rolling_ic_mean']:.4f}")
    print(f" Rolling IC Std: {report['rolling_ic_std']:.4f}")
    print(f" % Positive : {report['rolling_ic_pct_positive']:.1%}")
    print(f" IC Sharpe : {report['rolling_ic_sharpe']:.2f}")
    print(f"\nOOS R-squared : {report['oos_r2']:.4f}")
    print(f"\nStability Score : {score}/100 (Grade : {report['grade']})")
    print(f"{'='*60}\n")

    return report


def feature_correlation_analysis(features_df: pd.DataFrame) -> dict:
    """
    Analyze the feature set for multicollinearity and redundancy.
    """
    # Pearson and Spearman correlation matrices
    pearson_corr = features_df.corr(method='pearson')
    spearman_corr = features_df.corr(method='spearman')

    # VIF for each feature
    from sklearn.linear_model import LinearRegression
    vifs = {}
    cols = features_df.columns.tolist()
    for i, col in enumerate(cols):
        y = features_df[col].values
        X = features_df.drop(columns=[col]).values
        mask = ~(np.isnan(y) | np.isnan(X).any(axis=1))
        if mask.sum() < 10:
            vifs[col] = np.nan
            continue
        reg = LinearRegression().fit(X[mask], y[mask])
        r2 = reg.score(X[mask], y[mask])
        vifs[col] = 1 / (1 - r2) if r2 < 1 else np.inf

    # Condition number of feature covariance matrix
    cov_matrix = features_df.cov()
    eigenvalues = np.linalg.eigvalsh(cov_matrix.values)
    eigenvalues = eigenvalues[eigenvalues > 0]
    condition_number = eigenvalues.max() / eigenvalues.min()

    # Cluster features by correlation (agglomerative)
    from scipy.cluster.hierarchy import linkage, fcluster
    from scipy.spatial.distance import squareform

    dist_matrix = 1 - np.abs(spearman_corr.values)
    np.fill_diagonal(dist_matrix, 0)
    linkage_matrix = linkage(squareform(dist_matrix), method='ward')
    clusters = fcluster(linkage_matrix, t=0.3, criterion='distance')

    return {
        'pearson_corr': pearson_corr,
        'spearman_corr': spearman_corr,
        'vifs': pd.Series(vifs),
        'condition_number': condition_number,
        'feature_clusters': pd.Series(clusters, index=cols),
        'high_vif_features': [k for k, v in vifs.items() if v > 10],
        'high_corr_pairs': [
            (pearson_corr.columns[i], pearson_corr.columns[j])
            for i in range(len(cols))
            for j in range(i + 1, len(cols))
            if abs(pearson_corr.iloc[i, j]) > 0.80
        ]
    }


import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression

def compute_har_rv_features(rv_daily: pd.Series) -> pd.DataFrame:
    """
    Compute HAR-RV components and VRP proxy.

    Input: rv_daily Series of daily realized volatility (annualized %)
    """
    feat = pd.DataFrame(index=rv_daily.index)

    # HAR components (variance domain: more Gaussian)
    rv_var = rv_daily ** 2  # realized variance

    feat['rv_d'] = rv_var  # daily
    feat['rv_w'] = rv_var.rolling(5).mean()  # weekly
    feat['rv_m'] = rv_var.rolling(22).mean()  # monthly

    # HAR-RV one-step-ahead forecast (expanding window OLS)
    # In production: use rolling window or pre-fit coefficients
    har_forecast = pd.Series(index=rv_daily.index, dtype=float)

    min_train = 252  # at least 1 year of training data
    X_cols = ['rv_d', 'rv_w', 'rv_m']

    for t in range(min_train, len(feat)):
        X_train = feat[X_cols].iloc[:t].dropna()
        y_train = rv_var.shift(-1).iloc[:t].reindex(X_train.index)
        mask = y_train.notna() & X_train.notna().all(axis=1)
        if mask.sum() < 50:
            continue
        reg = LinearRegression().fit(X_train[mask], y_train[mask])
        x_cur = feat[X_cols].iloc[t:t+1].dropna()
        if len(x_cur) > 0:
            har_forecast.iloc[t] = reg.predict(x_cur)[0]

    feat['har_rv_forecast'] = np.sqrt(har_forecast.clip(lower=0))

    return feat

def compute_vrp(iv_30d: pd.Series, rv_realized: pd.Series) -> pd.Series:
    """
    Variance Risk Premium = IV^2 - RV^2
    Both should be annualized volatilities (in %, e.g., 0.20 for 20%)

    Positive VRP = IV > RV = investors paying for variance insurance
    (the normal state: VRP is negative on average for the buyer of var)
    """
    vrp = iv_30d ** 2 - rv_realized ** 2
    return vrp

# Interpretation guide:
# VRP > 0: market charging a premium for variance insurance -> normal
# VRP < 0 (backwardation): rare, signals crisis or extreme fear
# VRP z-score > 2: very cheap IV relative to RV -> potential IV-buying opportunity
# VRP z-score < -2: very expensive IV -> variance selling opportunity


import numpy as np
from scipy.optimize import minimize
import pandas as pd

def svi_total_variance(x: np.ndarray, a: float, b: float, rho: float, m: float, s: float) -> np.ndarray:
    """SVI total variance function w(x) = sigma_iv^2 * T"""
    return a + b * (rho * (x - m) + np.sqrt((x - m)**2 + s**2))

def fit_svi_slice(log_moneyness: np.ndarray, total_var: np.ndarray, weights: np.ndarray = None) -> dict:
    """
    Fit SVI parameters to a single maturity slice.

    Args:
        log_moneyness : array of log(K/F) values
        total_var : array of sigma_iv^2 * T values
        weights : optional array of vega weights for fitting

    Returns:
        dict with SVI params and fit quality metrics
    """
    if weights is None:
        weights = np.ones_like(total_var)

    def objective(params):
        a_val, b_val, rho_val, m_val, s_val = params
        pred = svi_total_variance(log_moneyness, a_val, b_val, rho_val, m_val, s_val)
        residuals = (pred - total_var) * weights
        return np.sum(residuals**2)

    # Multiple starting points to avoid local minima
    best_result = None
    best_val = np.inf

    atm_var = np.interp(0.0, log_moneyness, total_var)  # ATM total var

    for rho_init in [-0.5, 0.0, 0.5]:
        p0 = [atm_var * 0.8, 0.1, rho_init, 0.0, 0.1]
        bounds = [
            (1e-5, None),      # a >= 0
            (1e-5, None),      # b >= 0
            (-0.999, 0.999),   # rho in (-1, 1)
            (-1.0, 1.0),       # m
            (1e-5, None),      # s > 0
        ]
        try:
            result = minimize(
                objective, p0, method='L-BFGS-B',
                bounds=bounds,
                options={'maxiter': 2000, 'ftol': 1e-12}
            )
            if result.fun < best_val and result.success:
                best_val = result.fun
                best_result = result
        except Exception:
            continue

    if best_result is None:
        return {}

    a, b, rho, m, s = best_result.x

    # Compute derived features
    atm_total_var_fitted = svi_total_variance(np.array([0.0]), a, b, rho, m, s)[0]

    return {
        'svi_a': a, 'svi_b': b, 'svi_rho': rho, 'svi_m': m, 'svi_s': s,
        'svi_atm_var': atm_total_var_fitted,
        'svi_wing_slope': b,       # controls wing steepness
        'svi_skew': rho * b,       # approximate skew
        'svi_curvature': b * s,    # approximate curvature
        'fit_rmse': np.sqrt(best_val / len(total_var))
    }

def extract_surface_features(all_slices: dict) -> pd.DataFrame:
    """
    all_slices : {T_i: {'log_money': array, 'total_var': array}}
    Returns DataFrame of surface features indexed by maturity.
    """
    records = []
    for T, data in sorted(all_slices.items()):
        params = fit_svi_slice(data['log_money'], data['total_var'])
        if params:
            params['maturity'] = T
            records.append(params)
    return pd.DataFrame(records).set_index('maturity') if records else pd.DataFrame()

# IV Surface PCA
import numpy as np
import pandas as pd
from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler

def surface_pca_features(
    iv_panel: pd.DataFrame,
    n_components: int = 5,
    min_periods: int = 252
) -> pd.DataFrame:
    """
    iv_panel : DataFrame, index=dates, columns=(strike, maturity) tuples,
               values=implied volatilities (annualized, decimal)

    Returns : DataFrame of PCA scores + rolling PCA scores
    """
    # Drop columns with too many NaNs
    iv_clean = iv_panel.dropna(axis=1, thresh=int(0.8 * len(iv_panel)))
    iv_clean = iv_clean.ffill().bfill()

    # Daily changes in IV surface
    delta_iv = iv_clean.diff().dropna()

    # ---- STATIC PCA (fit on first 2 years, apply to rest ) ----
    # In production: use expanding window PCA with re-estimation
    train = delta_iv.iloc[:min_periods]

    scaler = StandardScaler()
    train_scaled = scaler.fit_transform(train)

    pca = PCA(n_components=n_components)
    pca.fit(train_scaled)

    # Apply to full sample
    all_scaled = scaler.transform(delta_iv)
    scores = pca.transform(all_scaled)

    score_df = pd.DataFrame(
        scores,
        index=delta_iv.index,
        columns=[f'iv_pc{k+1}' for k in range(n_components)]
    )

    # Explained variance
    evr = pca.explained_variance_ratio_
    print(f"Explained variance: {evr.cumsum()}")

    # ---- Loadings : interpret each PC ----
    loadings = pd.DataFrame(
        pca.components_,
        columns=iv_clean.columns,
        index=[f'PC{k+1}' for k in range(n_components)]
    )

    # ---- Rolling Z-scores of PCA scores ----
    for k in range(n_components):
        col = f'iv_pc{k+1}'
        mu = score_df[col].rolling(63).mean()
        sd = score_df[col].rolling(63).std()
        score_df[f'{col}_z63'] = (score_df[col] - mu) / sd

    # ---- Cumulative PCA scores (level, not change) ----
    for k in range(n_components):
        score_df[f'iv_pc{k+1}_level'] = score_df[f'iv_pc{k+1}'].cumsum()

    return score_df, loadings, pca.explained_variance_ratio_


import numpy as np
import pandas as pd
from scipy.optimize import curve_fit

def nelson_siegel(T, L, S, C, lam):
    """Nelson-Siegel term structure model."""
    e = np.exp(-lam * T)
    factor1 = (1 - e) / (lam * T)
    return L + S * factor1 + C * (factor1 - e)

def fit_nelson_siegel(maturities: np.ndarray, atm_vols: np.ndarray) -> dict:
    """Fit NS model and return factors as features."""
    try:
        p0 = [atm_vols.mean(), 0.0, 0.0, 1.0]
        bounds = ([0, -1, -1, 0.01], [2, 1, 1, 10])
        popt, _ = curve_fit(nelson_siegel, maturities, atm_vols, p0=p0, bounds=bounds, maxfev=5000)
        L, S, C, lam = popt
        fitted = nelson_siegel(maturities, *popt)
        rmse = np.sqrt(np.mean((fitted - atm_vols) ** 2))
        return {
            'ns_level': L,
            'ns_slope': S,
            'ns_curve': C,
            'ns_lambda': lam,
            'ns_rmse': rmse
        }
    except RuntimeError:
        return {}

def compute_ts_features(atm_vol_ts: dict) -> dict:
    """
    atm_vol_ts : { maturity_years : atm_vol } e.g. {1/12: 0.18, 3/12: 0.19, ...}
    """
    T = np.array(sorted(atm_vol_ts.keys()))
    v = np.array([atm_vol_ts[t] for t in T])

    feat = {}

    # ---- Level, Slope, Curvature ----
    T1m, T3m, T6m, T12m = 1/12, 3/12, 6/12, 1.0
    v1m = np.interp(T1m, T, v)
    v3m = np.interp(T3m, T, v)
    v6m = np.interp(T6m, T, v)
    v12m = np.interp(T12m, T, v)

    feat['ts_level_6m'] = v6m
    feat['ts_slope'] = v1m - v12m  # + = backwardation
    feat['ts_curvature'] = v1m + v12m - 2 * v6m
    feat['ts_1m_3m'] = v1m - v3m  # very short end
    feat['ts_3m_12m'] = v3m - v12m  # long end
    feat['ts_vix_vxv'] = v1m / v3m  # VIX/VXV ratio

    # ---- Forward variances ----
    w1m = v1m ** 2 * T1m
    w3m = v3m ** 2 * T3m
    w6m = v6m ** 2 * T6m
    w12m = v12m ** 2 * T12m

    feat['fwd_vol_1m_3m'] = np.sqrt(max((w3m - w1m) / (T3m - T1m), 1e-8))
    feat['fwd_vol_3m_6m'] = np.sqrt(max((w6m - w3m) / (T6m - T3m), 1e-8))
    feat['fwd_vol_6m_12m'] = np.sqrt(max((w12m - w6m) / (T12m - T6m), 1e-8))

    # ---- Forward variance spreads ----
    feat['fvs_1m_3m'] = feat['fwd_vol_1m_3m'] - v1m  # calendar premium
    feat['fvs_3m_6m'] = feat['fwd_vol_3m_6m'] - v3m

    # ---- Nelson-Siegel Fit ----
    ns_params = fit_nelson_siegel(T, v)
    feat.update(ns_params)

    return feat


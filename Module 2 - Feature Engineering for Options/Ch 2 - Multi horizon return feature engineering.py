import numpy as np
import pandas as pd
from scipy import stats

def compute_return_features(df_ohlcv: pd.DataFrame) -> pd.DataFrame:
    """
    Input: df_ohlcv with columns ['Open', 'High', 'Low', 'Close', 'Volume']
    Output: DataFrame of return-based features

    All features are point-in-time (no look-ahead bias):
    at time t, we use data up to and including t.
    """
    df = df_ohlcv.copy()
    feat = pd.DataFrame(index=df.index)

    # Log returns
    log_ret = np.log(df['Close']).diff()

    # ---- Multi-horizon returns ----
    for h in [1, 5, 21, 63, 252]:
        feat[f'ret_{h}d'] = np.log(df['Close'] / df['Close'].shift(h))

    # ---- 12-1 Momentum ----
    feat['mom_12_1'] = feat['ret_252d'] - feat['ret_21d']

    # ---- Short-term reversal ----
    feat['reversal_1m'] = -feat['ret_21d']

    # ---- Rolling realized volatility (annualized) ----
    for n in [5, 21, 63]:
        feat[f'rv_{n}d'] = log_ret.rolling(n).std() * np.sqrt(252)

    # ---- Parkinson High-Low Volatility ----
    log_hl = np.log(df['High'] / df['Low'])
    feat['vol_park_21d'] = np.sqrt(
        (log_hl**2 / (4 * np.log(2))).rolling(21).mean() * 252
    )

    # ---- Garman-Klass Estimator ----
    log_hl2 = 0.5 * np.log(df['High'] / df['Low'])**2
    log_co2 = (2 * np.log(2) - 1) * np.log(df['Close'] / df['Open'])**2
    gk_daily = log_hl2 - log_co2
    feat['vol_gk_21d'] = np.sqrt(gk_daily.rolling(21).mean() * 252)

    # ---- Overnight Gap ----
    feat['gap_ret'] = np.log(df['Open'] / df['Close'].shift(1))

    # ---- Rolling Skewness and Kurtosis ----
    def rolling_skew_kurt(series, window):
        sk = series.rolling(window).apply(stats.skew, raw=True)
        ku = series.rolling(window).apply(stats.kurtosis, raw=True)
        return sk, ku

    feat['skew_21d'], feat['kurt_21d'] = rolling_skew_kurt(log_ret, 21)
    feat['skew_63d'], feat['kurt_63d'] = rolling_skew_kurt(log_ret, 63)

    # ---- Bipower Variation (Jump Detection) ----
    def bpv(r, n=21):
        """Realized bipower variation over rolling window n"""
        absret = r.abs()
        bv = (np.pi / 2) * (n / (n - 1)) * (absret * absret.shift(1)).rolling(n).sum()
        rv = (r**2).rolling(n).sum()
        return bv, rv

    bv_21, rv_21 = bpv(log_ret, 21)
    feat['jump_ratio_21d'] = ((rv_21 - bv_21).clip(lower=0) / rv_21).fillna(0)

    return feat.dropna(how='all')


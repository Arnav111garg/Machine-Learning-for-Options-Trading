import numpy as np
from scipy.stats import norm
import pandas as pd

def bs_greeks(S, K, T, r, q, sigma, option_type='C'):
    """
    Compute all Black-Scholes Greeks for a European option.

    Parameters:
    S: spot price
    K: strike
    T: time to expiry (years)
    r: risk-free rate (continuous, decimal)
    q: dividend yield (continuous, decimal)
    sigma: implied volatility (decimal, e.g. 0.20)
    option_type: 'C' or 'P'

    Returns:
    dict with: price, delta, gamma, theta, vega, rho, vanna, volga, charm
    """
    # Guard against near-zero T
    T = max(T, 1e-8)
    sigma = max(sigma, 1e-8)

    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)

    Nd1 = norm.cdf(d1)
    Nd2 = norm.cdf(d2)
    nd1 = norm.pdf(d1)

    phi = 1 if option_type == 'C' else -1  # call = 1, put = -1

    # Price
    price = phi * (S * np.exp(-q * T) * norm.cdf(phi * d1) - K * np.exp(-r * T) * norm.cdf(phi * d2))

    # First-order Greeks
    delta = phi * np.exp(-q * T) * norm.cdf(phi * d1)
    gamma = np.exp(-q * T) * nd1 / (S * sigma * np.sqrt(T))
    vega = S * np.exp(-q * T) * nd1 * np.sqrt(T)  # per unit of sigma
    theta = (-S * np.exp(-q * T) * nd1 * sigma / (2 * np.sqrt(T)) \
             - phi * r * K * np.exp(-r * T) * norm.cdf(phi * d2) \
             + phi * q * S * np.exp(-q * T) * norm.cdf(phi * d1)) / 252  # per calendar day
    rho = phi * K * T * np.exp(-r * T) * norm.cdf(phi * d2)

    # Second-order Greeks
    vanna = -np.exp(-q * T) * nd1 * d2 / sigma  # dDelta / dSigma
    volga = vega * d1 * d2 / sigma  # dVega / dSigma
    charm = (-np.exp(-q * T) * nd1 * (2 * (r - q) * T - d2 * sigma * np.sqrt(T)) / (2 * T * sigma * np.sqrt(T)))  # dDelta / dT

    return {
        'price': price, 'delta': delta, 'gamma': gamma,
        'theta': theta, 'vega': vega, 'rho': rho,
        'vanna': vanna, 'volga': volga, 'charm': charm,
        'd1': d1, 'd2': d2
    }

def compute_gex(options_chain: pd.DataFrame, S: float) -> float:
    """
    Compute aggregate Gamma Exposure (GEX) from an options chain.

    options_chain: DataFrame with columns:
    strike, expiry_years, iv, open_interest, option_type, r, q

    Convention: dealers are SHORT calls and LONG puts (they sold them to clients).
    So call gamma enters positively, put gamma enters negatively for dealer.
    """
    gex_total = 0.0
    for _, row in options_chain.iterrows():
        g = bs_greeks(
            S, row['strike'], row['expiry_years'],
            row['r'], row['q'], row['iv'],
            row['option_type']
        )
        sign = 1 if row['option_type'] == 'C' else -1
        gex_total += sign * row['open_interest'] * g['gamma'] * (S**2) * 100
    return gex_total

# GEX interpretation:
# GEX > 0: dealers long gamma, suppress volatility (buy dips, sell rips)
# GEX < 0: dealers short gamma, amplify volatility (feedback loops)
# GEX = 0: "gamma flip" level, critical technical level


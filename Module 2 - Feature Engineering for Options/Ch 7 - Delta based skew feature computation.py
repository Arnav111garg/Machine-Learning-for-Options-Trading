import numpy as np
import pandas as pd
from scipy.interpolate import interp1d

def find_delta_strike(S, T, r, q, sigma_curve_func, target_delta: float, option_type='C', tol=1e-6) -> float:
    """
    Find the strike K such that delta(K) = target_delta.
    Uses bisection on K for fixed maturity.
    """
    from scipy.optimize import brentq

    def delta_diff(K):
        sigma = sigma_curve_func(np.log(K / (S * np.exp((r - q) * T))))
        d1 = (np.log(S / K) + (r - q + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
        if option_type == 'C':
            return np.exp(-q * T) * norm_cdf(d1) - target_delta
        else:
            return -np.exp(-q * T) * norm_cdf(-d1) - target_delta

    from scipy.stats import norm
    norm_cdf = norm.cdf
    K_lo, K_hi = S * 0.5, S * 2.0
    try:
        return brentq(delta_diff, K_lo, K_hi, xtol=tol)
    except ValueError:
        return np.nan

def compute_skew_features(chain_df: pd.DataFrame, S: float, r: float, q: float) -> dict:
    """
    chain_df: options chain with columns: strike, maturity, iv, option_type
    S: current spot
    r, q: rates

    Returns: dict of skew features for each maturity
    """
    skew_features = {}

    for T, group in chain_df.groupby('maturity'):
        # Separate calls and puts
        calls = group[group['option_type'] == 'C'].sort_values('strike')
        puts = group[group['option_type'] == 'P'].sort_values('strike')

        # Build smile interpolator (log-moneyness domain)
        all_opts = pd.concat([calls, puts]).drop_duplicates('strike')
        all_opts['log_money'] = np.log(all_opts['strike'] / (S * np.exp((r - q) * T)))
        all_opts = all_opts.sort_values('log_money')

        if len(all_opts) < 5:
            continue

        smile_interp = interp1d(
            all_opts['log_money'],
            all_opts['iv'],
            kind='cubic',
            fill_value='extrapolate',
            bounds_error=False
        )

        # ATM vol (log-moneyness = 0)
        v_atm = float(smile_interp(0.0))

        # Vol at standard log-moneyness strikes
        v_m10 = float(smile_interp(-0.10))  # 10% OTM put
        v_m05 = float(smile_interp(-0.05))
        v_p05 = float(smile_interp(+0.05))
        v_p10 = float(smile_interp(+0.10))  # 10% OTM call

        prefix = f'T{int(T * 12):02d}m'

        skew_features[f'{prefix}_atm_vol'] = v_atm
        skew_features[f'{prefix}_skew_10pct'] = v_m10 - v_atm  # put skew
        skew_features[f'{prefix}_skew_05pct'] = v_m05 - v_atm
        skew_features[f'{prefix}_rr_10pct'] = v_m10 - v_p10    # risk reversal
        skew_features[f'{prefix}_bf_10pct'] = (v_m10 + v_p10) / 2 - v_atm  # butterfly
        skew_features[f'{prefix}_norm_skew'] = (v_m10 - v_atm) / v_atm

        # Slope of the smile (derivative at ATM)
        slope = (v_m05 - v_p05) / 0.10
        skew_features[f'{prefix}_smile_slope'] = slope

        # Curvature (second derivative at ATM)
        curvature = (v_m10 + v_p10 - 2 * v_atm) / (0.10 ** 2)
        skew_features[f'{prefix}_smile_curv'] = curvature

    # Skew term structure: slope of RR across maturities
    rr_cols = {k: v for k, v in skew_features.items() if 'rr_10pct' in k}
    if len(rr_cols) >= 2:
        mats = sorted([float(k.split('T')[1].split('m')[0]) / 12 for k in rr_cols.keys()])
        rrs = [rr_cols[f'T{int(m * 12):02d}m_rr_10pct'] for m in mats]
        skew_features['skew_ts_slope'] = np.polyfit(mats, rrs, 1)[0]

    return skew_features


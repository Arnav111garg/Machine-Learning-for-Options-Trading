import numpy as np
import pandas as pd

def compute_cross_asset_features(data: dict) -> pd.DataFrame:
    """
    data : dict of time series DataFrames , all aligned to same dates:
    'vix': VIX level
    'vxv': VXV (93-day VIX)
    'vvix': VVIX (vol of vol)
    'move': MOVE index
    'cdx_ig': CDX.IG spread
    'cdx_hy': CDX.HY spread
    'eurusd_atm_1m': EUR/USD 1-month ATM vol
    'tnx': 10-year treasury yield
    'spx_atm_1m': SPX ATM 1-month IV
    """
    df = pd.DataFrame(data)
    feat = pd.DataFrame(index=df.index)

    # ---- Vol Ratios and Spreads ----
    feat['vix_vxv_ratio'] = df['vix'] / df['vxv']  # TS slope
    feat['vvix_vix_ratio'] = df['vvix'] / df['vix']  # vol-of-vol normalized
    feat['move_vix_ratio'] = df['move'] / df['vix']  # rates vs equity vol

    # ---- Z-score standardized spreads (252-day) ----
    def z_score(series, window=252):
        mu = series.rolling(window).mean()
        sd = series.rolling(window).std()
        return (series - mu) / sd

    feat['vix_z'] = z_score(df['vix'])
    feat['move_z'] = z_score(df['move'])
    feat['cdx_ig_z'] = z_score(df['cdx_ig'])
    feat['fxvol_z'] = z_score(df['eurusd_atm_1m'])

    # Credit - equity divergence
    feat['credit_eq_div'] = feat['cdx_ig_z'] - feat['vix_z']

    # FX - equity vol divergence
    feat['fx_eq_div'] = feat['fxvol_z'] - feat['vix_z']

    # Rates - equity vol divergence
    feat['rates_eq_div'] = feat['move_z'] - feat['vix_z']

    # ---- Vol Regime Features ----
    # VIX absolute level buckets
    feat['vix_regime'] = pd.cut(
        df['vix'],
        bins=[0, 12, 16, 20, 25, 30, 50, 100],
        labels=['ultra_low', 'low', 'normal', 'elevated', 'high', 'crisis', 'panic']
    )

    # VIX term structure regime
    feat['ts_contango'] = (df['vxv'] > df['vix']).astype(int)
    feat['ts_slope_pct'] = (df['vxv'] - df['vix']) / df['vix']

    # ---- Macro stress composite ----
    # Simple average of z-scores (robust to any one market misbehaving)
    stress_components = ['cdx_ig_z', 'move_z', 'vix_z', 'fxvol_z']
    feat['macro_stress'] = feat[stress_components].mean(axis=1)

    # ---- VIX vs Realized Vol spread ----
    if 'spx_rv_1m' in df.columns:
        feat['vrp'] = df['spx_atm_1m']**2 - df['spx_rv_1m']**2
        feat['vrp_z'] = z_score(feat['vrp'])

    # ---- VVIX as near-term vol spike predictor ----
    feat['vvix_z'] = z_score(df['vvix'])
    feat['vvix_above_30'] = (df['vvix'] > 30).astype(int)  # alarm threshold

    # ---- Rolling correlations between markets ----
    feat['spx_rates_corr'] = (
        df['vix'].pct_change()
        .rolling(21)
        .corr(df['tnx'].diff())
    )
    return feat


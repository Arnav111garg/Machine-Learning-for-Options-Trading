import numpy as np
import pandas as pd
from itertools import product
from scipy import stats
from typing import Dict, List, Callable, Optional
import warnings

class RobustnessTester:
    """
    Institutional robustness testing for ML-based options strategies.

    Tests:
    1. Parameter sensitivity
    2. Monte Carlo permutation
    3. Regime analysis
    4. Sensitivity to specific periods
    """

    def __init__(self, backtest_fn: Callable, base_params: dict):
        """
        Parameters
        ----------
        backtest_fn : Function that takes **params and returns
                      {'sharpe': float, 'returns': pd.Series, ...}
        base_params : Dictionary of base parameter values
        """
        self.backtest_fn = backtest_fn
        self.base_params = base_params

    # 1. Parameter Sensitivity
    def parameter_sensitivity(self, param_grid: Dict[str, List], metric: str = 'sharpe') -> pd.DataFrame:
        """
        Sweep parameters and record performance metric.

        Usage:
        ------
        param_grid = {
            'lookback_window': [10, 20, 30, 40, 50, 60],
            'vol_threshold': [0.10, 0.15, 0.20, 0.25, 0.30]
        }
        results = tester.parameter_sensitivity(param_grid)
        """
        param_names = list(param_grid.keys())
        param_values = list(param_grid.values())

        results = []
        for combo in product(*param_values):
            params = {**self.base_params, **dict(zip(param_names, combo))}
            try:
                result = self.backtest_fn(**params)
                row = dict(zip(param_names, combo))
                row[metric] = result.get(metric, np.nan)
                row['n_trades'] = result.get('n_trades', np.nan)
                results.append(row)
            except Exception as e:
                warnings.warn(f"Failed for params {combo}: {e}")

        df = pd.DataFrame(results)
        df['rank'] = df[metric].rank(ascending=False)
        return df

    def parameter_stability_score(self, sensitivity_df: pd.DataFrame, metric: str = 'sharpe') -> dict:
        """
        Score parameter stability from sensitivity analysis.

        A score close to 1.0 indicates a flat landscape (robust).
        A score close to 0.0 indicates a spike (fragile / overfitted).

        Score = 1 - CV(metric) in top quartile vs all params
        """
        all_vals = sensitivity_df[metric].dropna()
        top_q_vals = all_vals.nlargest(len(all_vals) // 4)

        cv_top = top_q_vals.std() / (top_q_vals.mean() + 1e-8)
        cv_all = all_vals.std() / (all_vals.mean() + 1e-8)

        # Flatness score: high when top quartile is compact AND metric is high
        positive_pct = (all_vals > 0).mean()
        flatness = 1 - cv_top

        return {
            'flatness_score': flatness,
            'positive_pct': positive_pct,
            'best_metric': all_vals.max(),
            'mean_metric': all_vals.mean(),
            'median_metric': all_vals.median(),
            'stability_grade': 'A' if flatness > 0.7 and positive_pct > 0.6
                               else 'B' if flatness > 0.5 and positive_pct > 0.4
                               else 'C' if positive_pct > 0.3
                               else 'D'
        }

    # 2. Monte Carlo Permutation
    def monte_carlo_permutation(self, strategy_returns: pd.Series, n_simulations: int = 10000, metric: str = 'sharpe') -> dict:
        """
        Monte Carlo permutation test:
        Shuffle the strategy returns and recompute performance.

        Under the null hypothesis that strategy returns are IID random noise,
        the shuffled returns have the same marginal distribution but no sequential structure.

        If the observed Sharpe exceeds the 95th percentile of shuffled Sharpes,
        the strategy has statistically significant sequential structure.

        This tests the NULL HYPOTHESIS that there is NO predictable structure
        in the strategy's signals.

        """
        observed_metric = self._compute_metric(strategy_returns, metric)

        null_distribution = []
        for _ in range(n_simulations):
            shuffled = strategy_returns.sample(frac=1, replace=False).values
            null_metric = self._compute_metric(pd.Series(shuffled), metric)
            null_distribution.append(null_metric)

        null_distribution = np.array(null_distribution)
        pvalue = (null_distribution >= observed_metric).mean()

        return {
            'observed_metric': observed_metric,
            'null_mean': null_distribution.mean(),
            'null_std': null_distribution.std(),
            'null_95th_pct': np.percentile(null_distribution, 95),
            'p_value': pvalue,
            'is_significant_5pct': pvalue < 0.05,
            'null_distribution': null_distribution,
            'z_score': (observed_metric - null_distribution.mean()) / (null_distribution.std() + 1e-8)
        }

    def _compute_metric(self, returns: pd.Series, metric: str) -> float:
        if metric == 'sharpe':
            return returns.mean() / (returns.std() + 1e-8) * np.sqrt(252)
        elif metric == 'cagr':
            return (1 + returns).prod() ** (252 / len(returns)) - 1
        elif metric == 'calmar':
            cagr = self._compute_metric(returns, 'cagr')
            peak = (1 + returns).cumprod().expanding().max()
            dd = ((1 + returns).cumprod() - peak) / peak
            mdd = dd.min()
            return cagr / (abs(mdd) + 1e-8)
        return np.nan

    # 3. Regime Analysis
    def regime_analysis(self, strategy_returns: pd.Series, vix_data: Optional[pd.Series] = None, market_returns: Optional[pd.Series] = None) -> pd.DataFrame:
        """
        Decompose performance by market regime.

        Regimes defined by VIX level (if available) or return rolling vol:
        - Low vol regime: VIX < 15 (or bottom tercile)
        - Normal vol regime: 15 <= VIX < 25
        - High vol regime: VIX >= 25 (or top tercile)

        Also separates bull / bear market periods if market_returns provided.
        """
        results = {}

        if vix_data is not None:
            # Align
            aligned = pd.DataFrame({
                'strategy': strategy_returns,
                'vix': vix_data
            }).dropna()

            for regime, mask in [
                ('Low Vol (VIX <15)', aligned['vix'] < 15),
                ('Normal Vol (15-25)', (aligned['vix'] >= 15) & (aligned['vix'] < 25)),
                ('High Vol (VIX 25-35)', (aligned['vix'] >= 25) & (aligned['vix'] < 35)),
                ('Crisis (VIX >35)', aligned['vix'] >= 35)
            ]:
                if mask.sum() < 20:
                    continue
                regime_rets = aligned.loc[mask, 'strategy']
                results[regime] = {
                    'n_days': len(regime_rets),
                    'annl_ret': regime_rets.mean() * 252 * 100,
                    'annl_vol': regime_rets.std() * np.sqrt(252) * 100,
                    'sharpe': regime_rets.mean() / (regime_rets.std() + 1e-8) * np.sqrt(252),
                    'win_rate': (regime_rets > 0).mean() * 100
                }

        if market_returns is not None:
            aligned_mkt = pd.DataFrame({
                'strategy': strategy_returns,
                'market': market_returns
            }).dropna()

            # Bull: market up 12m rolling, Bear: market down 12m rolling
            rolling_mkt = aligned_mkt['market'].rolling(252).mean()

            for regime, mask in [
                ('Bull Market', rolling_mkt > 0),
                ('Bear Market', rolling_mkt <= 0)
            ]:
                if mask.sum() < 30:
                    continue
                regime_rets = aligned_mkt.loc[mask, 'strategy']
                results[regime] = {
                    'n_days': len(regime_rets),
                    'annl_ret': regime_rets.mean() * 252 * 100,
                    'annl_vol': regime_rets.std() * np.sqrt(252) * 100,
                    'sharpe': regime_rets.mean() / (regime_rets.std() + 1e-8) * np.sqrt(252),
                    'win_rate': (regime_rets > 0).mean() * 100
                }

        return pd.DataFrame(results).T

    # 4. Sensitivity to Training Data Length
    def sensitivity_to_history_length(self, X: pd.DataFrame, y: pd.Series, model, min_train_years: int = 1, max_train_years: int = 10) -> pd.DataFrame:
        """
        Test: does performance degrade with less training data?

        A robust strategy should show reasonable performance even when trained on shorter historical windows.
        If performance collapses without very long training history, the model is capturing a regime rather than a signal.
        """
        from sklearn.base import clone
        from scipy.stats import spearmanr

        results = []
        for n_years in range(min_train_years, max_train_years + 1):
            n_obs = n_years * 252
            if n_obs >= len(X) - 252:
                break

            X_train = X.iloc[-n_obs - 252 : -252]  # n_years before last year
            y_train = y.iloc[-n_obs - 252 : -252]
            X_test = X.iloc[-252:]  # Last year as test
            y_test = y.iloc[-252:]

            m = clone(model)
            m.fit(X_train, y_train)
            preds = m.predict(X_test)

            ic, _ = spearmanr(preds, y_test)
            da = (np.sign(preds) == np.sign(y_test)).mean()

            results.append({
                'train_years': n_years,
                'oos_ic': ic,
                'oos_da': da
            })

        return pd.DataFrame(results)

    # 5. White's Reality Check
    def whites_reality_check(self, all_strategy_returns: pd.DataFrame, best_strategy_returns: pd.Series, n_bootstrap: int = 5000) -> dict:
        """
        White's (2000) Reality Check Bootstrap.

        Tests the null hypothesis that the BEST strategy out of a pool has zero expected return, accounting for data snooping.
        Significance at 5% means: even after testing many strategies, the best one is genuinely above zero.
        """
        # Observed best statistic: mean excess return of best strategy
        best_mean = best_strategy_returns.mean()

        null_dist = []
        n = len(best_strategy_returns)

        for _ in range(n_bootstrap):
            # Resample with replacement (block bootstrap for temporal dependence)
            block_size = int(np.sqrt(n))
            n_blocks = n // block_size + 1
            indices = []
            for _ in range(n_blocks):
                start = np.random.randint(0, n - block_size)
                indices.extend(range(start, start + block_size))
            indices = indices[:n]

            # Maximum mean return across all strategies in this bootstrap sample
            boot_returns = all_strategy_returns.iloc[indices]
            max_mean = boot_returns.mean(axis=0).max()
            null_dist.append(max_mean)

        null_dist = np.array(null_dist)
        pvalue = (null_dist >= best_mean).mean()

        return {
            'best_strategy_mean': best_mean,
            'rc_p_value': pvalue,
            'rc_95pct_critical': np.percentile(null_dist, 95),
            'is_significant_5pct': pvalue < 0.05,
            'null_distribution': null_dist
        }


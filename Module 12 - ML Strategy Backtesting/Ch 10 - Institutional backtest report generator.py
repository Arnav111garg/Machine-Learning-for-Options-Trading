from __future__ import annotations
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.gridspec as gridspec
from matplotlib.backends.backend_pdf import PdfPages
from typing import Optional, Dict

class InstitutionalReportGenerator:
    def __init__(self, strategy_name: str,
                 returns: pd.Series,
                 benchmark: Optional[pd.Series] = None,
                 metadata: Optional[Dict] = None):
        self.name = strategy_name
        self.returns = returns.dropna()
        self.benchmark = benchmark
        self.metadata = metadata or {}

    def generate_tearsheet(self, save_path: Optional[str] = None):
        """Generate the full multi-page tearsheet."""
        fig = plt.figure(figsize=(16, 20))
        fig.patch.set_facecolor('#0d1117')

        gs = gridspec.GridSpec(4, 3, figure=fig, hspace=0.4, wspace=0.35)

        # 1. Equity Curve
        ax1 = fig.add_subplot(gs[0, :])
        ax1.set_facecolor('#1a1f2e')

        cum_returns = (1 + self.returns).cumprod()
        rolling_max = cum_returns.expanding().max()
        drawdown = (cum_returns - rolling_max) / rolling_max * 100

        ax1.plot(cum_returns.index, cum_returns.values, color='#00d4ff', lw=1.5, label=f'{self.name}')

        if self.benchmark is not None:
            cum_bench = (1 + self.benchmark.reindex(self.returns.index).fillna(0)).cumprod()
            ax1.plot(cum_bench.index, cum_bench.values, color='#888888', lw=1.0, alpha=0.7, label='Benchmark', linestyle='--')

        ax2 = ax1.twinx()
        ax2.fill_between(drawdown.index, drawdown.values, 0, color='#ff4444', alpha=0.3, label='Drawdown')
        ax2.set_ylabel('Drawdown (%)', color='#ff4444')
        ax2.tick_params(colors='#ff4444')
        ax2.set_ylim(-100, 10)

        ax1.set_title(f'{self.name} Equity Curve & Drawdown', color='white', fontsize=14, fontweight='bold')
        ax1.set_ylabel('Portfolio Value', color='white')
        ax1.tick_params(colors='white')
        ax1.legend(loc='upper left')
        ax1.grid(color='#333344', alpha=0.5)

        # 2. Monthly Return Heatmap
        ax3 = fig.add_subplot(gs[1, :])
        ax3.set_facecolor('#1a1f2e')

        monthly = self.returns.resample('ME').apply(lambda x: (1 + x).prod() - 1) * 100

        try:
            monthly_table = monthly.groupby([
                monthly.index.year, monthly.index.month
            ]).first().unstack()
            monthly_table.columns = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']

            vmax = max(abs(monthly_table.values.flatten()[np.isfinite(monthly_table.values.flatten())]).max(), 1)

            im = ax3.imshow(monthly_table.values, cmap='RdYlGn', vmin=-vmax, vmax=vmax, aspect='auto')

            for i in range(len(monthly_table.index)):
                for j in range(len(monthly_table.columns)):
                    val = monthly_table.values[i, j]
                    if np.isfinite(val):
                        text_color = 'black' if abs(val) < vmax * 0.6 else 'white'
                        ax3.text(j, i, f'{val:.1f}%', ha='center', va='center', color=text_color, fontsize=8)

            ax3.set_xticks(range(12))
            ax3.set_xticklabels(['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'], color='white', fontsize=9)
            ax3.set_yticks(range(len(monthly_table.index)))
            ax3.set_yticklabels(monthly_table.index, color='white', fontsize=9)
            ax3.set_title('Monthly Returns Heatmap (%)', color='white', fontsize=12, fontweight='bold')
            plt.colorbar(im, ax=ax3, shrink=0.8)
        except Exception as e:
            ax3.text(0.5, 0.5, f'Monthly heatmap unavailable: {e}', transform=ax3.transAxes, ha='center', color='white')

        # 3. Return Distribution
        ax4 = fig.add_subplot(gs[2, 0])
        ax4.set_facecolor('#1a1f2e')
        ax4.hist(self.returns * 100, bins=60, color='#00d4ff', alpha=0.7, edgecolor='none', density=True)

        x = np.linspace(self.returns.min() * 100, self.returns.max() * 100, 200)
        from scipy.stats import norm
        mu_n = self.returns.mean() * 100
        s_n = self.returns.std() * 100
        ax4.plot(x, norm.pdf(x, mu_n, s_n), 'r--', lw=2, label='Normal')

        ax4.axvline(self.returns.quantile(0.05) * 100, color='orange', lw=1.5, linestyle='--', label='5% VaR')
        ax4.set_title('Daily Return Distribution', color='white', fontsize=11)
        ax4.tick_params(colors='white')
        ax4.set_xlabel('Daily Return (%)', color='white')
        ax4.legend(fontsize=8)
        ax4.grid(color='#333344', alpha=0.5)

        # 4. Rolling Sharpe
        ax5 = fig.add_subplot(gs[2, 1])
        ax5.set_facecolor('#1a1f2e')

        rolling_sharpe = (self.returns.rolling(252).mean() / self.returns.rolling(252).std() * np.sqrt(252))
        ax5.plot(rolling_sharpe.index, rolling_sharpe.values, color='#00ff88', lw=1.2)
        ax5.axhline(0, color='white', lw=0.5, alpha=0.5)
        ax5.fill_between(rolling_sharpe.index, rolling_sharpe.values, 0, where=rolling_sharpe > 0, color='#00ff88', alpha=0.2)
        ax5.fill_between(rolling_sharpe.index, rolling_sharpe.values, 0, where=rolling_sharpe <= 0, color='#ff4444', alpha=0.2)
        ax5.set_title('Rolling 252-Day Sharpe Ratio', color='white', fontsize=11)
        ax5.tick_params(colors='white')
        ax5.grid(color='#333344', alpha=0.5)

        # 5. Summary Statistics Table
        ax6 = fig.add_subplot(gs[2, 2])
        ax6.set_facecolor('#1a1f2e')
        ax6.axis('off')

        try:
            perf = PerformanceAttributor(self.returns)
            sr = perf.sharpe_ratio()
            cagr = perf._cagr()
            mdd = perf.max_drawdown()['max_drawdown']
            sortino = perf.sortino_ratio()
        except NameError:
            # Fallback metrics if PerformanceAttributor is not defined yet
            sr = self.returns.mean() / self.returns.std() * np.sqrt(252) if self.returns.std() != 0 else 0
            cagr = (1 + self.returns).prod() ** (252 / len(self.returns)) - 1 if len(self.returns) > 0 else 0
            mdd = drawdown.min() / 100
            sortino = 0

        vol = self.returns.std() * np.sqrt(252)
        skew = self.returns.skew()
        kurt = self.returns.kurt()
        var95 = self.returns.quantile(0.05)

        table_data = [
            ['Metric', 'Value'],
            ['CAGR', f'{cagr * 100:.2f}%'],
            ['Ann. Vol', f'{vol * 100:.2f}%'],
            ['Sharpe', f'{sr:.3f}'],
            ['Sortino', f'{sortino:.3f}'],
            ['Max DD', f'{mdd * 100:.2f}%'],
            ['Skewness', f'{skew:.3f}'],
            ['Kurt (excess)', f'{kurt:.3f}'],
            ['95% VaR (d)', f'{var95 * 100:.3f}%'],
        ]

        table = ax6.table(cellText=table_data[1:], colLabels=table_data[0], cellLoc='center', loc='center', bbox=[0, 0, 1, 1])
        table.auto_set_font_size(False)
        table.set_fontsize(9)

        for (i, j), cell in table.get_celld().items():
            cell.set_facecolor('#2a2f3e' if i % 2 == 0 else '#1a1f2e')
            cell.set_text_props(color='white')
            cell.set_edgecolor('#555566')

        ax6.set_title('Performance Summary', color='white', fontsize=11)

        # 6. Trade-Level Analysis
        ax7 = fig.add_subplot(gs[3, :])
        ax7.set_facecolor('#1a1f2e')

        # Rolling 63-day performance
        rolling_ret = self.returns.rolling(63).apply(lambda x: (1 + x).prod() - 1)
        ax7.bar(rolling_ret.index, rolling_ret.values * 100, color=np.where(rolling_ret.values > 0, '#00d4ff', '#ff4444'), alpha=0.8, width=1)
        ax7.axhline(0, color='white', lw=0.5)
        ax7.set_title('Rolling 63-Day Quarterly Return (%)', color='white', fontsize=11, fontweight='bold')
        ax7.tick_params(colors='white')
        ax7.grid(color='#333344', alpha=0.5, axis='y')

        plt.suptitle(f'INSTITUTIONAL PERFORMANCE TEARSHEET: {self.name}', color='white', fontsize=16, fontweight='bold', y=0.98)

        if save_path:
            plt.savefig(save_path, dpi=150, bbox_inches='tight', facecolor='#0d1117')

        return fig


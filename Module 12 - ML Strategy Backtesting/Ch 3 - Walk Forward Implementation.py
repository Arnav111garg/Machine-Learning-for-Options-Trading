from sklearn.base import BaseEstimator, clone
from sklearn.preprocessing import StandardScaler
import numpy as np
import pandas as pd
from scipy import stats
from typing import Callable, List, Tuple, Optional

class WalkForwardOptimiser:
    """
    Production-grade Walk-Forward Testing for options ML strategies.

    Design principles:
    1. Strict temporal causality: test data never contaminates train
    2. Feature standardisation fitted on train, applied to test
    3. Hyperparameter optimisation inside each training window
    4. Aggregated OOS performance is the TRUE performance estimate
    """

    def __init__(
        self,
        model: BaseEstimator,
        train_size: int,
        test_size: int,
        step_size: Optional[int] = None,
        expanding: bool = True,
        n_jobs: int = 1
    ):
        """
        Parameters
        ----------
        model : sklearn-compatible estimator
        train_size : Number of observations in training window
        test_size : Number of observations in testing window
        step_size : Advance step (defaults to test_size)
        expanding : If True, use expanding window; else rolling
        """
        self.model = model
        self.train_size = train_size
        self.test_size = test_size
        self.step_size = step_size or test_size
        self.expanding = expanding
        self.n_jobs = n_jobs

    def split(self, X: pd.DataFrame) -> List[Tuple]:
        """
        Generate (train_idx, test_idx) pairs.

        Key design choice: indices, not slices, to support
        non-contiguous data (e.g., data with gaps).
        """
        n = len(X)
        splits = []

        start = 0
        test_start = self.train_size

        while test_start + self.test_size <= n:
            train_start = 0 if self.expanding else test_start - self.train_size
            train_idx = np.arange(train_start, test_start)
            test_idx = np.arange(test_start, test_start + self.test_size)
            splits.append((train_idx, test_idx))
            test_start += self.step_size

        return splits

    def fit_predict(
        self,
        X: pd.DataFrame,
        y: pd.Series,
        param_grid: Optional[dict] = None,
        cv_metric: str = 'sharpe'
    ) -> dict:
        """
        Execute the full walk-forward procedure.

        Returns OOS predictions and performance metrics per fold.

        Parameters
        ----------
        X : Feature matrix (must be temporally ordered)
        y : Target (forward returns, aligned with X)
        param_grid : If provided, perform grid search in each fold
        cv_metric : Metric for hyperparameter selection in inner CV
        """
        splits = self.split(X)
        n_folds = len(splits)

        all_oos_predictions = []
        all_oos_targets = []
        all_oos_timestamps = []
        fold_results = []

        print(f"Walk-Forward Testing: {n_folds} folds")
        print(f"Mode: {'Expanding' if self.expanding else 'Rolling'}")
        print(f"Train={self.train_size}, Test={self.test_size}")
        print("-" * 50)

        for fold_idx, (train_idx, test_idx) in enumerate(splits):
            # Extract train/test sets
            X_train = X.iloc[train_idx]
            y_train = y.iloc[train_idx]
            X_test = X.iloc[test_idx]
            y_test = y.iloc[test_idx]

            # CRITICAL: Fit scaler ONLY on training data
            scaler = StandardScaler()
            X_train_scaled = scaler.fit_transform(X_train)
            X_test_scaled = scaler.transform(X_test)  # Apply (not fit) to test!

            # Hyperparameter selection (inner CV on training data only)
            if param_grid:
                best_model = self._inner_cv_search(
                    X_train_scaled, y_train, param_grid, cv_metric
                )
            else:
                best_model = clone(self.model)

            # Train on full training window
            best_model.fit(X_train_scaled, y_train)

            # Predict on OOS test window
            if hasattr(best_model, 'predict_proba'):
                preds = best_model.predict_proba(X_test_scaled)[:, 1]
            else:
                preds = best_model.predict(X_test_scaled)

            # Compute fold OOS metrics
            oos_ic, _ = stats.spearmanr(preds, y_test)
            da = (np.sign(preds) == np.sign(y_test)).mean()

            fold_result = {
                'fold': fold_idx + 1,
                'train_start': X.index[train_idx[0]],
                'train_end': X.index[train_idx[-1]],
                'test_start': X.index[test_idx[0]],
                'test_end': X.index[test_idx[-1]],
                'n_train': len(train_idx),
                'n_test': len(test_idx),
                'oos_ic': oos_ic,
                'oos_da': da,
                'model_params': best_model.get_params() if hasattr(best_model, 'get_params') else {}
            }
            fold_results.append(fold_result)

            print(
                f"Fold {fold_idx + 1:2d}: "
                f"Train [{fold_result['train_start'].date()} - {fold_result['train_end'].date()}] | "
                f"Test [{fold_result['test_start'].date()} - {fold_result['test_end'].date()}] | "
                f"OOS IC={oos_ic:.3f} | DA={da:.2%}"
            )

            all_oos_predictions.extend(preds)
            all_oos_targets.extend(y_test.values)
            all_oos_timestamps.extend(X.index[test_idx])

        # Aggregate OOS statistics
        oos_df = pd.DataFrame({
            'timestamp': all_oos_timestamps,
            'prediction': all_oos_predictions,
            'actual': all_oos_targets
        }).set_index('timestamp')

        agg_ic, _ = stats.spearmanr(oos_df['prediction'], oos_df['actual'])
        agg_da = (np.sign(oos_df['prediction']) == np.sign(oos_df['actual'])).mean()

        return {
            'oos_predictions': oos_df,
            'fold_results': pd.DataFrame(fold_results),
            'aggregate_oos_ic': agg_ic,
            'aggregate_oos_da': agg_da,
            'n_folds': n_folds,
            'parameter_stability': self._compute_parameter_stability(fold_results)
        }

    def _inner_cv_search(self, X_train, y_train, param_grid, metric):
        """Inner CV for hyperparameter search uses only training data."""
        from sklearn.model_selection import TimeSeriesSplit, GridSearchCV

        inner_cv = TimeSeriesSplit(n_splits=3)

        if metric == 'sharpe':
            # Custom Sharpe scorer
            from sklearn.metrics import make_scorer
            def sharpe_scorer(estimator, X, y):
                preds = estimator.predict(X)
                strategy_returns = np.sign(preds) * y
                if strategy_returns.std() == 0:
                    return 0
                return (strategy_returns.mean() / strategy_returns.std() * np.sqrt(252))
            scorer = make_scorer(sharpe_scorer)
        else:
            scorer = metric

        gs = GridSearchCV(
            clone(self.model), param_grid, cv=inner_cv,
            scoring=scorer, n_jobs=self.n_jobs, refit=True
        )
        gs.fit(X_train, y_train)
        return gs.best_estimator_

    def _compute_parameter_stability(self, fold_results: List[dict]) -> dict:
        """
        Measure parameter stability across folds.
        High stability = model is robust, not overfitting to noise.
        """
        if not fold_results or not fold_results[0].get('model_params'):
            return {}

        params = fold_results[0]['model_params'].keys()
        stability = {}
        for p in params:
            values = [
                f['model_params'].get(p)
                for f in fold_results
                if f['model_params'].get(p) is not None
            ]
            if values and all(isinstance(v, (int, float)) for v in values):
                stability[p] = {
                    'mean': np.mean(values),
                    'std': np.std(values),
                    'cv': np.std(values) / (np.mean(values) + 1e-10)
                }
        return stability

# Practical Usage
def walk_forward_demo():
    """Demonstration of WFO for an options ML strategy."""
    from sklearn.ensemble import GradientBoostingRegressor

    np.random.seed(42)
    n = 1000
    dates = pd.date_range('2018-01-01', periods=n, freq='B')

    # Synthetic features: IV spread, skew, momentum, etc.
    features = pd.DataFrame({
        'iv_spread': np.random.randn(n) * 0.05,
        'put_call_skew': np.random.randn(n) * 0.02,
        'realized_vol': np.abs(np.random.randn(n)) * 0.15 + 0.10,
        'momentum_5d': np.random.randn(n) * 0.02,
        'vix_level': 20 + np.random.randn(n) * 5
    }, index=dates)

    # True signal with noise
    true_signal = (
        0.3 * features['iv_spread']
        - 0.2 * features['put_call_skew']
        + 0.1 * features['momentum_5d']
    )
    target = true_signal.shift(-5) + np.random.randn(n) * 0.02  # 5-day ahead
    target = target.dropna()
    features = features.loc[target.index]

    wfo = WalkForwardOptimiser(
        model=GradientBoostingRegressor(n_estimators=100),
        train_size=252,  # 1 year training
        test_size=63,    # 1 quarter testing
        expanding=True
    )
    results = wfo.fit_predict(features, target)
    print(f"\nAggregate OOS IC = {results['aggregate_oos_ic']:.4f}")
    print(f"Aggregate OOS DA = {results['aggregate_oos_da']:.2%}")
    return results

# Execute Demo
demo_results = walk_forward_demo()


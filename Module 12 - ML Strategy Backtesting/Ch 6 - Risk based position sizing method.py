import numpy as np
import pandas as pd
from scipy.optimize import minimize
from typing import Optional, Tuple

class PositionSizer:
    """
    Implements multiple position sizing methodologies for options strategies.

    Methods: Kelly, Fixed Fractional, Volatility Targeting,
    Risk Parity, Max Drawdown Constraint.
    """

    def __init__(self, portfolio_value: float,
                 max_drawdown_limit: float = 0.20,
                 vol_target: float = 0.15):
        self.portfolio_value = portfolio_value
        self.max_drawdown_limit = max_drawdown_limit
        self.vol_target = vol_target

    # Kelly Criterion

    def kelly_fraction(self, returns: pd.Series,
                       half_kelly: bool = True) -> float:
        """
        Full or Half-Kelly fraction from historical return moments.

        Parameters
        ----------
        returns : Historical OOS returns of the strategy
        half_kelly : If True, scale by 0.5 (recommended for live trading)
        """
        if len(returns) < 30:
            raise ValueError("Need at least 30 return observations for Kelly")

        mu = returns.mean()
        sigma = returns.std()

        if sigma < 1e-10:
            return 0.0

        kelly = mu / (sigma ** 2)

        # Clip to [-3, 3] extreme Kelly values indicate estimation noise
        kelly = np.clip(kelly, -3, 3)

        return kelly * (0.5 if half_kelly else 1.0)

    def portfolio_kelly(self, returns: pd.DataFrame,
                        half_kelly: bool = True) -> pd.Series:
        """
        Multi-asset portfolio Kelly via mean-variance optimisation.

        f* = Sigma^{-1} * mu (risk-adjusted weights)
        """
        mu = returns.mean()
        Sigma = returns.cov()

        try:
            # Regularised inverse (ridge regularisation)
            n = len(mu)
            lambda_reg = 1e-4 # regularisation
            Sigma_reg = Sigma + lambda_reg * np.eye(n)
            weights = np.linalg.solve(Sigma_reg, mu)
        except np.linalg.LinAlgError:
            weights = np.zeros(len(mu))

        weights = pd.Series(weights, index=returns.columns)

        if half_kelly:
            weights *= 0.5

        return weights

    # Volatility Targeting

    def volatility_targeted_size(self, forecast_vol: float,
                                 signal_strength: float = 1.0) -> float:
        """
        Size position to target a constant portfolio volatility.

        Intuition: when markets are calm (low vol), you can take
        larger positions to maintain constant risk exposure.
        When markets are turbulent, reduce size.

        This is a core technique at AHL, Man Investments, and
        similar systematic funds.

        position_size = (vol_target / forecast_vol) * signal_strength * capital
        """
        if forecast_vol < 1e-6:
            return 0.0

        vol_scalar = self.vol_target / forecast_vol
        dollar_size = vol_scalar * signal_strength * self.portfolio_value

        # Safety cap: never exceed 3x portfolio in single position
        max_size = 3.0 * self.portfolio_value
        return np.clip(dollar_size, -max_size, max_size)

    # Options Vega Position Sizing

    def options_vega_targeting(self, target_vega_pct: float,
                               option_vega: float,
                               spot_price: float,
                               n_contracts_multiplier: int = 100) -> int:
        """
        Size an options position by targeting a percentage of portfolio
        allocated to vega exposure.

        target_vega_dollar = target_vega_pct * portfolio_value
        n_contracts = target_vega_dollar / (vega_per_contract)

        where vega_per_contract = option_vega * spot * multiplier

        Parameters
        ----------
        target_vega_pct : Desired vega / portfolio value (e.g., 0.01 = 1%)
        option_vega : Vega of 1 option contract (per 1% vol move)
        spot_price : Current underlying price
        n_contracts_multiplier : Standard options multiplier (100 for equity options)

        Returns
        -------
        Number of contracts (integer, signed: positive = long vol, negative = short)
        """
        target_vega_dollar = target_vega_pct * self.portfolio_value
        vega_per_contract = option_vega * spot_price * n_contracts_multiplier / 100

        if abs(vega_per_contract) < 1e-6:
            return 0

        n_contracts = int(target_vega_dollar / vega_per_contract)
        return n_contracts

    # Fixed Fractional (Fixed - Risk)

    def fixed_fractional(self, risk_per_trade: float,
                         stop_loss_distance: float) -> float:
        """
        Risk a fixed fraction of portfolio per trade.

        n = (f * W) / stop_distance

        Parameters
        ----------
        risk_per_trade : Fraction of portfolio to risk (e.g., 0.01 = 1%)
        stop_loss_distance : Dollar distance to stop loss
        """
        dollar_risk = risk_per_trade * self.portfolio_value
        position_size = dollar_risk / (stop_loss_distance + 1e-8)

        return position_size

    # Maximum Drawdown Constraint

    def drawdown_constrained_size(self, proposed_size: float,
                                  current_drawdown: float,
                                  max_drawdown_budget: float = None) -> float:
        """
        Scale down position size when in drawdown.

        Common professional practice: reduce risk as drawdown grows.
        At 50% of max DD budget: reduce to 75% of normal size.
        At 100% of max DD budget: reduce to 25% of normal size.

        This is a form of "gearing with the tide" used by many
        successful systematic funds.
        """
        if max_drawdown_budget is None:
            max_drawdown_budget = self.max_drawdown_limit

        dd_fraction = current_drawdown / max_drawdown_budget

        if dd_fraction <= 0:
            scale = 1.0
        elif dd_fraction <= 0.5:
            scale = 1.0 - 0.5 * dd_fraction
        elif dd_fraction <= 1.0:
            scale = 0.75 - 0.5 * (dd_fraction - 0.5)
        else:
            scale = 0.0  # Stop trading completely at max drawdown

        return proposed_size * max(0.0, scale)

    # Integrated Sizing Engine

    def compute_position(self, signal: float,
                         forecast_vol: float,
                         option_vega: float,
                         spot_price: float,
                         current_drawdown: float = 0.0,
                         returns_history: Optional[pd.Series] = None) -> dict:
        """
        Integrated position computation combining multiple methodologies.

        Final size = vol_targeted_size
        * kelly_fraction (if returns_history provided)
        * drawdown_scalar
        """
        # Step 1: Volatility-targeted base size (% of capital)
        base_size = self.volatility_targeted_size(forecast_vol, signal)

        # Step 2: Kelly adjustment (if we have historical OOS returns)
        kelly_adj = 1.0
        if returns_history is not None and len(returns_history) >= 30:
            kelly = self.kelly_fraction(returns_history, half_kelly=True)
            kelly_adj = np.clip(kelly, 0.0, 2.0)  # Cap at 2x

        # Step 3: Drawdown scalar
        dd_scalar = self.drawdown_constrained_size(1.0, current_drawdown)

        # Final notional size
        final_notional = base_size * kelly_adj * dd_scalar

        # Translate to options contracts (if vega targeting applicable)
        n_contracts = int(final_notional / (option_vega * spot_price * 100 + 1e-8))

        return {
            'signal': signal,
            'base_size': base_size,
            'kelly_adjustment': kelly_adj,
            'dd_scalar': dd_scalar,
            'final_notional': final_notional,
            'n_contracts': n_contracts,
            'forecast_vol': forecast_vol
        }


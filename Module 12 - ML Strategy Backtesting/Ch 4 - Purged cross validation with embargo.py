import numpy as np
import pandas as pd
from sklearn.model_selection import KFold

class PurgedKFoldCV:
    """
    Purged K-Fold Cross-Validation for financial time series.

    Reference: Lopez de Prado, M. (2018). "Advances in Financial Machine Learning." Wiley.

    This is THE correct CV scheme when observations have overlapping
    labels (e.g., multi-day forward returns).

    Without purging, in-sample performance is severely overstated
    because the model trains on data whose labels overlap with test data.
    """

    def __init__(self, n_splits: int = 5, embargo_pct: float = 0.01):
        """
        Parameters
        ----------
        n_splits : Number of CV folds (typically 5-10)
        embargo_pct : Fraction of total observations to embargo
                      after each test fold. 0.01 = 1% embargo.
        """
        self.n_splits = n_splits
        self.embargo_pct = embargo_pct

    def split(self, X: pd.DataFrame, label_end_times: pd.Series, groups=None):
        """
        Generate (train_idx, test_idx) pairs with purging and embargo.

        Parameters
        ----------
        X : Feature matrix
        label_end_times : Series mapping each observation time t
                          to its label end time t+h.
                          Index = observation start time,
                          Values = label end time

        Yields
        ------
        (train_indices, test_indices) both are index arrays
        """
        n = X.shape[0]

        # Compute embargo size
        embargo_size = int(n * self.embargo_pct)

        # Base fold split (sequential, not random!)
        indices = np.arange(n)
        kf = KFold(n_splits=self.n_splits, shuffle=False)

        test_ranges = [(t[0], t[-1]) for _, t in kf.split(X)]

        for i, (test_start, test_end) in enumerate(test_ranges):
            test_idx = indices[test_start : test_end + 1]
            test_times = X.index[test_idx]

            # Test window : [test_t0, test_tN]
            test_t0 = test_times[0]
            test_tN = test_times[-1]

            # Purge : remove observations whose labels overlap test window
            train_mask = np.ones(n, dtype=bool)
            train_mask[test_start : test_end + 1] = False  # Remove test observations

            # For each potential train observation, check if its label
            # end time falls within the test window
            for j in range(n):
                if j >= test_start and j <= test_end:
                    continue  # Already excluded (test set)
                obs_time = X.index[j]
                obs_label_end = label_end_times.iloc[j]

                # Purge if label overlaps with test window
                if obs_label_end >= test_t0:
                    train_mask[j] = False

            # Embargo : remove 'embargo_size' observations before test
            embargo_start = max(0, test_start - embargo_size)
            train_mask[embargo_start : test_start] = False

            train_idx = indices[train_mask]

            if len(train_idx) == 0:
                continue  # Skip if no training data

            yield train_idx, test_idx

    def get_train_test_times(self, X: pd.DataFrame, test_fold_idx: int, label_end_times: pd.Series) -> dict:
        """Diagnostic : show what's in each fold."""
        splits = list(self.split(X, label_end_times))
        if test_fold_idx >= len(splits):
            raise IndexError(f"Fold {test_fold_idx} doesn't exist")

        train_idx, test_idx = splits[test_fold_idx]
        return {
            'train_period': (X.index[train_idx[0]], X.index[train_idx[-1]]),
            'test_period': (X.index[test_idx[0]], X.index[test_idx[-1]]),
            'n_train': len(train_idx),
            'n_test': len(test_idx),
            'purged_obs': len(X) - len(train_idx) - len(test_idx)
        }

# Combinatorial Purged CV (CPCV)
class CombinatorialPurgedCV:
    """
    Combinatorial Purged Cross-Validation (Lopez de Prado, 2018).
    Generates multiple test paths by choosing test folds combinatorially.

    This produces many more OOS paths than standard WFO, allowing
    a better distribution of OOS performance to be estimated.

    Key insight : instead of 1 OOS path of length T, we get C(k, t) OOS paths,
    each of length T * t / k, where k = n_splits, t = n_test_splits.
    """

    def __init__(self, n_splits: int = 10, n_test_splits: int = 2, embargo_pct: float = 0.01):
        from itertools import combinations
        self.n_splits = n_splits
        self.n_test_splits = n_test_splits
        self.embargo_pct = embargo_pct
        self._combinations = list(combinations(range(n_splits), n_test_splits))

    @property
    def n_paths(self) -> int:
        """Number of OOS paths generated."""
        from math import comb
        return comb(self.n_splits, self.n_test_splits)

    def split(self, X: pd.DataFrame, label_end_times: pd.Series):
        """Generate all combinatorial splits."""
        n = len(X)
        fold_size = n // self.n_splits
        embargo = int(n * self.embargo_pct)

        for test_combo in self._combinations:
            test_idx_list = []
            for fold_i in test_combo:
                start = fold_i * fold_size
                end = start + fold_size if fold_i < self.n_splits - 1 else n
                test_idx_list.extend(range(start, end))

            test_idx = np.array(test_idx_list)

            # Purge train
            test_times = X.index[test_idx]
            t0, tN = test_times.min(), test_times.max()

            train_mask = np.ones(n, dtype=bool)
            train_mask[test_idx] = False

            for j in np.where(train_mask)[0]:
                label_end = label_end_times.iloc[j]
                if label_end >= t0:
                    train_mask[j] = False

            train_idx = np.where(train_mask)[0]
            yield train_idx, test_idx


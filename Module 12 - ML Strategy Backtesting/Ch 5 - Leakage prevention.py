# Type I: Direct Look-Ahead Bias

# WRONG Uses next day's close to compute today's signal
def bad_moving_average_signal(prices: pd.Series, window: int = 20):
    # If prices.shift(-1) appears anywhere, that's look-ahead
    return prices.rolling(window).mean() # Seems OK ...

# But if prices itself was already shifted forward, it's leakage!
# Check your data pipeline carefully.

# CORRECT
def correct_moving_average_signal(prices: pd.Series, window: int = 20):
    """
    Signal at time t uses only prices[t-window+1 : t].
    pandas rolling().mean() IS look-ahead free IF the data is not pre-shifted.

    HOWEVER: when applied to daily OHLCV data, ensure 'close' means
    the close price of day t, not the open of day t+1.
    """
    # Add min_periods to avoid signals from insufficient data
    signal = prices.rolling(window=window, min_periods=window).mean()

    # Shift by 1 to avoid using today's close to trade today's close
    # (we trade the next day's open)
    return signal.shift(1) # Can only trade on the NEXT bar

# Type II: Feature Engineering Leakage
class LeakageSafeFeatureEngineer:
    """
    Feature engineering that is GUARANTEED look-ahead free.

    Every feature f_t must satisfy: f_t(data[0:t])
    i.e., f_t is measurable with respect to information up to t.
    """

    @staticmethod
    def safe_zscore(series: pd.Series, window: int = 252) -> pd.Series:
        """
        Rolling z-score: CORRECT implementation.

        Common mistake: using series.mean() and series.std()
        which use the FULL dataset (future included).
        """
        rolling_mean = series.rolling(window=window, min_periods=window//2).mean()
        rolling_std = series.rolling(window=window, min_periods=window//2).std()
        return (series - rolling_mean) / (rolling_std + 1e-8)

    @staticmethod
    def safe_realized_vol(returns: pd.Series, window: int = 21) -> pd.Series:
        """
        Realised vol: annualised, look-ahead free.

        rv_t = std(r_{t-window+1}, ..., r_t) * sqrt(252)

        Note: rv_t uses r_t (today's return), which is KNOWN at close of day t.
        This IS valid for computing features AT THE CLOSE.
        But you CANNOT use rv_t to enter a trade at OPEN of day t.
        """
        return returns.rolling(window=window, min_periods=5).std() * np.sqrt(252)

    @staticmethod
    def safe_iv_zscore(iv_series: pd.Series, window: int = 252) -> pd.Series:
        """
        IV z-score: normalise current IV relative to historical distribution.
        Uses only past data.
        """
        rolling_mean = iv_series.shift(1).rolling(window=window, min_periods=60).mean()
        rolling_std = iv_series.shift(1).rolling(window=window, min_periods=60).std()
        # shift(1) ensures we don't use today's IV in today's normalisation
        return (iv_series - rolling_mean) / (rolling_std + 1e-8)

    @staticmethod
    def safe_label_encoding(categorical: pd.Series, freq_threshold: float = 0.01) -> pd.Series:
        """
        Categorical encoding without leakage.

        Standard error: fit LabelEncoder on full dataset (including future).
        Safe approach: use ONLY historical frequency up to each point.
        """
        encoded = pd.Series(index=categorical.index, dtype=float)
        for i in range(1, len(categorical)):
            historical = categorical.iloc[:i]
            freq_map = historical.value_counts(normalize=True)
            current_val = categorical.iloc[i]
            encoded.iloc[i] = freq_map.get(current_val, freq_threshold)
        return encoded

    @staticmethod
    def check_for_leakage(features: pd.DataFrame, target: pd.Series, threshold: float = 0.3) -> dict:
        """
        Leakage detection heuristic.

        If a feature has an unusually high correlation with the TARGET
        (not a lagged version), it may be directly derived from future info.

        Note: this is a heuristic, not a guarantee. Manual code review is irreplaceable.
        """
        leakage_report = {}
        for col in features.columns:
            # Correlation with target (contemporaneous)
            corr_now = features[col].corr(target)
            # Correlation with 1-period lagged target
            corr_lag1 = features[col].corr(target.shift(1))
            # Correlation with 1-period ahead target (look-ahead)
            corr_fwd = features[col].corr(target.shift(-1))

            # Flag if correlation with forward target is suspiciously high
            leakage_report[col] = {
                'corr_contemporaneous': corr_now,
                'corr_lag1': corr_lag1,
                'corr_forward': corr_fwd,
                'suspected_leakage': abs(corr_fwd) > threshold and abs(corr_fwd) > abs(corr_lag1) * 1.5
            }

        suspected = {k: v for k, v in leakage_report.items() if v['suspected_leakage']}
        if suspected:
            print(f"POTENTIAL LEAKAGE DETECTED in features: {list(suspected.keys())}")
        else:
            print("No obvious leakage detected (manual review still required)")

        return leakage_report


# Type III: Preprocessing Leakage

# THE WRONG WAY (leakage via global preprocessing)
def WRONG_preprocessing(X_train, X_test, n_components=10):
    """
    NEVER do this: scaler and PCA are fit on combined train + test data!
    This leaks information from test to train.
    """
    X_all = np.vstack([X_train, X_test])

    # WRONG: scaler sees all data including test
    scaler = StandardScaler()
    X_all_scaled = scaler.fit_transform(X_all) # BUG!

    # WRONG: PCA computed on full dataset
    pca = PCA(n_components=n_components)
    X_all_pca = pca.fit_transform(X_all_scaled) # BUG!

    n_train = len(X_train)
    return X_all_pca[:n_train], X_all_pca[n_train:]

# THE CORRECT WAY (leakage-free sklearn Pipeline)
def CORRECT_preprocessing_pipeline():
    """
    sklearn Pipeline ensures fit() is called ONLY on train data.
    transform() is then applied to test data using train statistics.

    This is the correct pattern for ML in finance.
    """
    pipeline = Pipeline([
        ('scaler', StandardScaler()), # fit on train only
        ('pca', PCA(n_components=10)), # fit on train only
    ])
    return pipeline

# Usage in WFO context:
def correct_wfo_with_pipeline(X: pd.DataFrame, y: pd.Series, model, train_idx, test_idx):
    X_train, X_test = X.iloc[train_idx], X.iloc[test_idx]
    y_train = y.iloc[train_idx]
    pipe = Pipeline([
        ('scaler', StandardScaler()),
        ('model', model)
    ])
    pipe.fit(X_train, y_train) # Pipeline fit ONLY on train
    return pipe.predict(X_test) # Pipeline transform + predict on test


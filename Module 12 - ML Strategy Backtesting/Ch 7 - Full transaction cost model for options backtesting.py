from dataclasses import dataclass
from typing import Optional
import numpy as np

@dataclass
class TransactionCostModel:
    """
    Production transaction cost model for options backtesting.

    Calibrate these parameters against your actual broker data.
    Defaults below are based on IBKR tiered pricing for
    equity options (SPX, SPY, QQQ) circa 2023.
    """

    # Commission parameters
    commission_per_contract: float = 0.65  # USD per contract
    commission_floor: float = 1.00        # Minimum per trade
    commission_cap: float = 0.30          # % of premium max

    # Bid-ask parameters (fraction of mid price)
    spread_normal: float = 0.02           # 2% for liquid ATM options
    spread_illiquid: float = 0.10         # 10% for deep OTM / far expiry

    # Market impact
    impact_coefficient: float = 0.25      # in Almgren-Chriss model

    # Short selling / borrowing
    borrow_rate_annual: float = 0.005     # 0.5% annual for liquid ETFs

    # Financing
    margin_rate_annual: float = 0.055      # Prime + 1.5%

    def commission(self, n_contracts: int, option_premium: float) -> float:
        """Compute commission for a trade."""
        per_contract = self.commission_per_contract * abs(n_contracts)
        floor_charge = max(per_contract, self.commission_floor)
        cap_charge = min(
            floor_charge,
            self.commission_cap * abs(n_contracts) * option_premium * 100
        )
        return cap_charge

    def bid_ask_cost(self, n_contracts: int, bid: float, ask: float,
                     order_type: str = 'market') -> float:
        """
        Cost from crossing the bid-ask spread.
        Market orders always cross full spread.
        Limit orders cross half spread on average.
        """
        spread = ask - bid
        mid = (ask + bid) / 2

        if order_type == 'market':
            # Pay full spread for market orders
            cost_per_contract = spread * 100
        elif order_type == 'limit':
            # Pay half spread on average (50% fill at limit)
            cost_per_contract = spread * 0.5 * 100
        else:
            cost_per_contract = 0

        return cost_per_contract * abs(n_contracts)

    def market_impact(self, n_contracts: int,
                      option_mid_price: float,
                      option_adv_contracts: float,
                      option_vol_daily: float) -> float:
        """
        Market impact using square-root law.

        For options, we measure impact in terms of IV shift,
        which then maps to price impact via vega.

        Here simplified: dollar impact as function of size /ADV.
        """
        if option_adv_contracts < 1:
            # Extremely illiquid don't trade
            return float('inf')

        participation_rate = abs(n_contracts) / option_adv_contracts

        # Price impact as fraction of mid
        price_impact_pct = (
            self.impact_coefficient *
            option_vol_daily *
            np.sqrt(participation_rate)
        )

        dollar_impact = price_impact_pct * option_mid_price * 100 * abs(n_contracts)
        return dollar_impact

    def total_round_trip_cost(self, n_contracts: int,
                              bid: float, ask: float,
                              option_adv_contracts: float = 1000,
                              option_vol_daily: float = 0.02,
                              holding_days: int = 1) -> dict:
        """
        Full round-trip transaction cost (entry + exit).
        Includes commissions, spread, impact, and holding costs.
        """
        mid = (bid + ask) / 2

        # Entry costs
        entry_commission = self.commission(n_contracts, mid)
        entry_spread = self.bid_ask_cost(n_contracts, bid, ask, 'market')
        entry_impact = self.market_impact(n_contracts, mid,
                                          option_adv_contracts,
                                          option_vol_daily)

        # Exit costs (assume same conditions)
        exit_commission = entry_commission
        exit_spread = entry_spread
        exit_impact = entry_impact

        # Holding cost (financing the position)
        notional = mid * abs(n_contracts) * 100
        holding_cost = notional * (self.margin_rate_annual / 252) * holding_days

        # Totals
        total_entry = entry_commission + entry_spread + entry_impact
        total_exit = exit_commission + exit_spread + exit_impact
        total = total_entry + total_exit + holding_cost

        # Cost as % of notional
        cost_pct = total / (notional + 1e-10) * 100

        return {
            'entry_commission': entry_commission,
            'entry_spread': entry_spread,
            'entry_impact': entry_impact,
            'exit_commission': exit_commission,
            'exit_spread': exit_spread,
            'exit_impact': exit_impact,
            'holding_cost': holding_cost,
            'total_entry': total_entry,
            'total_exit': total_exit,
            'total_round_trip': total,
            'cost_pct_of_notional': cost_pct,
            'n_contracts': n_contracts,
            'mid_price': mid
        }

    def cost_adjusted_pnl(self, gross_pnl: float,
                          trade_records: list) -> dict:
        """
        Adjust gross PnL for all transaction costs.
        Returns net PnL and cost breakdown.
        """
        total_costs = sum(
            self.total_round_trip_cost(**trade)['total_round_trip']
            for trade in trade_records
        )
        net_pnl = gross_pnl - total_costs
        return {
            'gross_pnl': gross_pnl,
            'total_costs': total_costs,
            'net_pnl': net_pnl,
            'cost_drag': total_costs / (abs(gross_pnl) + 1e-10)
        }

# Break-Even Analysis
def compute_breakeven_ic(cost_model: TransactionCostModel,
                        vol_forecast: float,
                        sigma_iv: float,
                        portfolio_value: float = 1e6) -> dict:
    """
    What IC is needed to overcome transaction costs?

    Key insight for volatility trading:
    The strategy must predict RV - IV with sufficient accuracy
    to generate gross PnL > transaction costs.

    If IC_required > 0.05 (which is considered very good in finance),
    the strategy is likely unprofitable after costs.
    """
    # Assume trading ATM straddle (simplified)
    # Approximate ATM vega as % of S
    atm_vega_pct = 0.40 * np.sqrt(30/365)

    # Expected gross return from vol mis-pricing
    expected_gross_return_pct = (vol_forecast - sigma_iv) * atm_vega_pct

    # Typical cost as % of notional
    # (simplified: assume 2% spread + 0.1% commission on 30-day ATM)
    cost_pct = 0.021 # Combined entry + exit

    # Required IC = minimum correlation to generate expected_gross > cost
    # Simplified: sharpe_breakeven = cost / expected_return_std
    required_edge = cost_pct / (abs(expected_gross_return_pct) + 1e-8)

    return {
        'expected_gross_return_pct': expected_gross_return_pct * 100,
        'cost_pct': cost_pct * 100,
        'net_return_pct': (expected_gross_return_pct - cost_pct) * 100,
        'profitable_after_costs': expected_gross_return_pct > cost_pct,
        'required_edge_ratio': required_edge
    }


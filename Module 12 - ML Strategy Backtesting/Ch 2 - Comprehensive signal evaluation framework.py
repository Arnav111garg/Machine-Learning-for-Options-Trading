import numpy as np
import pandas as pd
from scipy import stats
from sklearn.metrics import (
    roc_auc_score,
    average_precision_score,
    precision_recall_curve
)
import matplotlib.pyplot as plt
import warnings

class SignalEvaluator:
    """
    Rigorous signal evaluation for quantitative strategies.

    Implements IC analysis, directional accuracy, Brier scores,
    and quintile return analysis the standard toolkit used
    at quantitative hedge funds for alpha signal research.
    """

    def __init__(self, signal: pd.Series, forward_returns: pd.Series, signal_name: str = "Signal"):
        """
        Parameters
        ----------
        signal : pd.Series, index = timestamp
        forward_returns : pd.Series, r_{t+h}, aligned with signal
        signal_name : str, for plot labelling
        """
        # Align and drop NaNs
        aligned = pd.DataFrame({'signal': signal, 'returns': forward_returns}).dropna()
        self.signal = aligned['signal']
        self.returns = aligned['returns']
        self.name = signal_name
        self.T = len(aligned)

    # Information Coefficient

    def information_coefficient(self, method: str = 'spearman') -> dict:
        """
        Compute IC and its statistics.
        Spearman IC is preferred (robust to outliers).
        Pearson IC useful for continuous predictions.
        """
        if method == 'spearman':
            ic, pvalue = stats.spearmanr(self.signal, self.returns)
        elif method == 'pearson':
            ic, pvalue = stats.pearsonr(self.signal, self.returns)
        else:
            raise ValueError("method must be 'spearman' or 'pearson'")

        # Rolling IC (monthly)
        rolling_ic = self._rolling_ic(window=21, method=method)

        return {
            'ic': ic,
            'ic_pvalue': pvalue,
            'ic_mean': rolling_ic.mean(),
            'ic_std': rolling_ic.std(),
            'ir': rolling_ic.mean() / rolling_ic.std(),
            'ic_positive_pct': (rolling_ic > 0).mean(),
            'rolling_ic': rolling_ic
        }

    def _rolling_ic(self, window: int = 21, method: str = 'spearman') -> pd.Series:
        """Compute rolling IC over specified window."""
        ic_values = []
        timestamps = []
        for i in range(window, self.T):
            s = self.signal.iloc[i - window : i]
            r = self.returns.iloc[i - window : i]
            if method == 'spearman':
                ic_val, _ = stats.spearmanr(s, r)
            else:
                ic_val, _ = stats.pearsonr(s, r)
            ic_values.append(ic_val)
            timestamps.append(self.signal.index[i])
        return pd.Series(ic_values, index=timestamps)

    # Directional Accuracy

    def directional_accuracy(self) -> dict:
        """
        Hit rate: fraction of times signal correctly predicts direction.

        Critical: separate DA by volatility regime (low/mid/high vol)
        as signal behaviour is regime-dependent.
        """
        signal_dir = np.sign(self.signal)
        returns_dir = np.sign(self.returns)

        da = (signal_dir == returns_dir).mean()

        # Binomial test: is DA significantly > 0.5?
        n_correct = (signal_dir == returns_dir).sum()
        binom_result = stats.binomtest(n_correct, self.T, p=0.5, alternative='greater')

        return {
            'directional_accuracy': da,
            'da_pvalue': binom_result.pvalue,
            'da_significant_at_5pct': binom_result.pvalue < 0.05
        }

    # Quintile Analysis

    def quintile_analysis(self, n_quantiles: int = 5) -> pd.DataFrame:
        """
        Stratify signal into quantiles and examine return distributions.

        Monotonically increasing mean returns across quantiles
        is the gold standard for signal validity.
        """
        df = pd.DataFrame({'signal': self.signal, 'returns': self.returns})
        df['quantile'] = pd.qcut(df['signal'], q=n_quantiles, labels=False)

        stats_df = df.groupby('quantile')['returns'].agg([
            'mean', 'std', 'median',
            lambda x: stats.ttest_1samp(x, 0)[1],  # p-value vs 0
            'count'
        ])
        stats_df.columns = ['mean_return', 'std_return', 'median_return', 'pvalue', 'count']
        stats_df['sharpe'] = (stats_df['mean_return'] / stats_df['std_return'] * np.sqrt(252))
        stats_df['spread'] = (stats_df.loc[n_quantiles - 1, 'mean_return'] - stats_df.loc[0, 'mean_return'])
        return stats_df

    # Decay Analysis

    def signal_decay(self, max_horizon: int = 20) -> pd.DataFrame:
        """
        Measure how IC decays with prediction horizon.
        Essential for calibrating holding period.
        """
        horizons = range(1, max_horizon + 1)
        decay = []
        for h in horizons:
            fwd_ret = self.returns.shift(-h + 1)  # h-period return
            aligned = pd.DataFrame({'s': self.signal, 'r': fwd_ret}).dropna()
            if len(aligned) < 30:
                break
            ic, pval = stats.spearmanr(aligned['s'], aligned['r'])
            decay.append({'horizon': h, 'ic': ic, 'pvalue': pval})
        return pd.DataFrame(decay).set_index('horizon')

    # AUC-ROC for Binary Signals

    def roc_analysis(self, threshold: float = 0.0) -> dict:
        """
        ROC-AUC for the signal's ability to classify positive vs negative returns.
        Threshold defines "positive" return.
        """
        y_true = (self.returns > threshold).astype(int)
        y_score = self.signal

        try:
            auc = roc_auc_score(y_true, y_score)
            ap = average_precision_score(y_true, y_score)
        except ValueError:
            return {'auc': np.nan, 'average_precision': np.nan}

        return {
            'auc': auc,
            'average_precision': ap,
            'base_rate': y_true.mean()
        }

    # Full Report

    def full_report(self) -> dict:
        """Generate complete signal evaluation report."""
        report = {}
        report['ic_stats'] = self.information_coefficient()
        report['directional_accuracy'] = self.directional_accuracy()
        report['quintile_analysis'] = self.quintile_analysis()
        report['signal_decay'] = self.signal_decay()
        report['roc_analysis'] = self.roc_analysis()
        return report

    def plot_signal_diagnostics(self, figsize=(16, 12)):
        """Comprehensive signal diagnostic plots."""
        fig, axes = plt.subplots(2, 3, figsize=figsize)
        fig.suptitle(f'Signal Diagnostics: {self.name}', fontsize=14, fontweight='bold')

        # 1. Rolling IC
        ic_stats = self.information_coefficient()
        rolling_ic = ic_stats['rolling_ic']
        axes[0, 0].plot(rolling_ic.index, rolling_ic.values, color='steelblue', alpha=0.8)
        axes[0, 0].axhline(0, color='black', lw=0.5)
        axes[0, 0].axhline(ic_stats['ic_mean'], color='red', linestyle='--', label=f"Mean IC={ic_stats['ic_mean']:.3f}")
        axes[0, 0].fill_between(rolling_ic.index, rolling_ic.values, 0, alpha=0.3, color='steelblue')
        axes[0, 0].set_title('Rolling 21-Day IC')
        axes[0, 0].legend()

        # 2. Quintile Returns
        q_stats = self.quintile_analysis()
        q_stats['mean_return'].plot(kind='bar', ax=axes[0, 1], color=['red'] * 2 + ['gray'] + ['green'] * 2)
        axes[0, 1].set_title('Quintile Mean Returns')
        axes[0, 1].set_xlabel('Quintile')
        axes[0, 1].axhline(0, color='black', lw=0.5)

        # 3. Signal Decay
        decay = self.signal_decay()
        axes[0, 2].plot(decay.index, decay['ic'], 'o-', color='purple')
        axes[0, 2].axhline(0, color='black', lw=0.5)
        axes[0, 2].set_title('IC Decay by Horizon')
        axes[0, 2].set_xlabel('Days Forward')
        axes[0, 2].set_ylabel('IC')

        # 4. Signal vs Return Scatter
        axes[1, 0].scatter(self.signal, self.returns, alpha=0.2, s=2, color='steelblue')
        z = np.polyfit(self.signal, self.returns, 1)
        p = np.poly1d(z)
        x_line = np.linspace(self.signal.min(), self.signal.max(), 100)
        axes[1, 0].plot(x_line, p(x_line), 'r-', lw=2)
        axes[1, 0].set_title('Signal vs Forward Returns')
        axes[1, 0].set_xlabel('Signal')
        axes[1, 0].set_ylabel('Forward Return')

        # 5. IC Distribution
        rolling_ic.hist(bins=40, ax=axes[1, 1], color='steelblue', edgecolor='white')
        axes[1, 1].axvline(0, color='black', lw=1)
        axes[1, 1].axvline(ic_stats['ic_mean'], color='red', linestyle='--', lw=2)
        axes[1, 1].set_title('IC Distribution')

        # 6. Cumulative IC
        cum_ic = rolling_ic.cumsum()
        axes[1, 2].plot(cum_ic.index, cum_ic.values, color='darkgreen')
        axes[1, 2].set_title('Cumulative IC')
        axes[1, 2].axhline(0, color='black', lw=0.5)

        plt.tight_layout()
        return fig

# Deflated Sharpe Ratio Implementation
from scipy.special import ndtri  # Inverse normal CDF

def deflated_sharpe_ratio(observed_sr: float, T: int, n_trials: int, skewness: float = 0.0, kurtosis: float = 3.0, alpha: float = 0.05) -> dict:
    """
    Compute the Deflated Sharpe Ratio (Lopez de Prado & Bailey, 2014).

    This is THE standard for evaluating whether a backtest SR
    is statistically significant given the number of strategies tested.

    Parameters
    ----------
    observed_sr : Annualised Sharpe Ratio from best strategy found
    T : Number of return observations
    n_trials : Number of strategies tested (critical input!)
    skewness : Skewness of strategy returns
    kurtosis : Excess kurtosis (0 for normal)
    alpha : Significance level

    Returns
    -------
    dict with DSR, p-value, and minimum required SR
    """
    # SR of benchmark: E[max(SR)] under null hypothesis of no skill
    # (using closed-form approximation from Extreme Value Theory)
    from scipy.stats import norm

    # Expected maximum SR among n_trials iid standard normal SR values
    gamma_euler = 0.5772156649  # Euler-Mascheroni constant
    sr_benchmark = (
        (1 - gamma_euler) * ndtri(1 - 1.0 / n_trials)
        + gamma_euler * ndtri(1 - 1.0 / (n_trials * np.e))
    )

    # SR standard error (accounting for non-normality)
    sr_std = np.sqrt(
        (1 - skewness * observed_sr + ((kurtosis - 1) / 4) * observed_sr ** 2)
        / (T - 1)
    )

    # Probability that observed SR > SR_benchmark (null: no skill)
    psr = norm.cdf((observed_sr - sr_benchmark) / sr_std)

    # Minimum SR to reject null at confidence level 1 - alpha
    min_sr = sr_benchmark + sr_std * ndtri(1 - alpha)

    return {
        'deflated_sr': psr,
        'sr_benchmark': sr_benchmark,
        'min_sr_required': min_sr,
        'observed_sr': observed_sr,
        'is_significant': psr > (1 - alpha),
        'n_trials': n_trials,
        'interpretation': (
            f"With {n_trials} strategies tested, observed SR={observed_sr:.2f} "
            f"{'IS' if psr > 1 - alpha else 'IS NOT'} significant. "
            f"Required SR > {min_sr:.2f}."
        )
    }

# Example
result = deflated_sharpe_ratio(
    observed_sr=1.5,
    T=252 * 3,
    n_trials=100,
    skewness=-0.5,
    kurtosis=5.0
)
print(result['interpretation'])


import numpy as np
import pandas as pd
from scipy import stats
import matplotlib.pyplot as plt
from typing import Optional

class PerformanceAttributor:
    """
    Institutional-grade performance attribution for options ML strategies.

    Implements:
    1. Standard risk-adjusted metrics
    2. Greeks-based P&L decomposition
    3. Factor-based attribution (delta, vega, theta components)
    4. Drawdown analysis
    5. Rolling regime analysis
    """

    def __init__(self, returns: pd.Series,
                 benchmark_returns: Optional[pd.Series] = None,
                 risk_free_rate: float = 0.045):
        """
        Parameters
        ----------
        returns : Daily net returns (net of all costs)
        benchmark_returns : Benchmark daily returns (e.g., SPX)
        risk_free_rate : Annual risk-free rate
        """
        self.returns = returns.dropna()
        self.benchmark = benchmark_returns
        self.rf_daily = risk_free_rate / 252
        self.excess_ret = self.returns - self.rf_daily

    # Core Metrics
    def sharpe_ratio(self) -> float:
        return self.excess_ret.mean() / self.excess_ret.std() * np.sqrt(252)

    def sortino_ratio(self) -> float:
        downside = self.excess_ret[self.excess_ret < 0]
        downside_vol = np.sqrt((downside ** 2).mean()) * np.sqrt(252)
        return self.excess_ret.mean() * 252 / (downside_vol + 1e-8)

    def calmar_ratio(self) -> float:
        cagr = self._cagr()
        mdd = self.max_drawdown()['max_drawdown']
        return cagr / (abs(mdd) + 1e-8)

    def omega_ratio(self, threshold: float = 0.0) -> float:
        """Omega = E[max(r - L, 0)] / E[max(L - r, 0)]"""
        excess = self.returns - threshold / 252
        gains = excess[excess > 0].sum()
        losses = (-excess[excess < 0]).sum()
        return gains / (losses + 1e-8)

    def _cagr(self) -> float:
        n_years = len(self.returns) / 252
        total = (1 + self.returns).prod()
        return total ** (1 / n_years) - 1

    # Drawdown Analysis
    def max_drawdown(self) -> dict:
        """Compute maximum drawdown, duration, and recovery time."""
        cumulative = (1 + self.returns).cumprod()
        rolling_max = cumulative.expanding().max()
        drawdown = (cumulative - rolling_max) / rolling_max

        mdd = drawdown.min()
        mdd_date = drawdown.idxmin()

        # Find start of this drawdown
        peak_idx = cumulative.loc[:mdd_date].idxmax()

        # Find recovery date (if it exists)
        post_peak = cumulative.loc[mdd_date:]
        recovery_vals = post_peak[post_peak >= cumulative.loc[peak_idx]]

        recovery_date = recovery_vals.index[0] if len(recovery_vals) > 0 else None
        dd_days = (mdd_date - peak_idx).days
        rec_days = (recovery_date - mdd_date).days if recovery_date else None

        return {
            'max_drawdown': mdd,
            'max_drawdown_pct': mdd * 100,
            'peak_date': peak_idx,
            'trough_date': mdd_date,
            'recovery_date': recovery_date,
            'drawdown_days': dd_days,
            'recovery_days': rec_days,
            'drawdown_series': drawdown
        }

    # Greeks P&L Attribution
    def greeks_pnl_attribution(self, portfolio_history: pd.DataFrame) -> pd.DataFrame:
        """
        Decompose daily P&L into Greek components.

        portfolio_history must contain columns:
        ['delta', 'gamma', 'theta', 'vega', 'underlying_move', 'vol_move', 'daily_pnl']

        Attribution:
        - Delta P&L = delta * dS
        - Gamma P&L = 0.5 * gamma * dS^2
        - Theta P&L = theta * dt
        - Vega P&L = vega * dIV
        - Residual = Total - sum(above)
        """
        hist = portfolio_history.copy()

        hist['delta_pnl'] = hist['delta'] * hist['underlying_move']
        hist['gamma_pnl'] = 0.5 * hist['gamma'] * (hist['underlying_move'] ** 2)
        hist['theta_pnl'] = hist['theta'] * (1 / 252)
        hist['vega_pnl'] = hist['vega'] * hist.get('vol_move', 0)

        hist['explained_pnl'] = (
            hist['delta_pnl'] +
            hist['gamma_pnl'] +
            hist['theta_pnl'] +
            hist['vega_pnl']
        )
        hist['residual_pnl'] = hist['daily_pnl'] - hist['explained_pnl']
        hist['r2_attribution'] = 1 - (hist['residual_pnl'].var() / hist['daily_pnl'].var())

        attribution = pd.DataFrame({
            'total_pnl': hist['daily_pnl'].sum(),
            'delta_pnl': hist['delta_pnl'].sum(),
            'gamma_pnl': hist['gamma_pnl'].sum(),
            'theta_pnl': hist['theta_pnl'].sum(),
            'vega_pnl': hist['vega_pnl'].sum(),
            'residual_pnl': hist['residual_pnl'].sum(),
            'avg_r2': hist['r2_attribution'].mean()
        }, index=[0])

        return attribution

    # Full Summary Report
    def full_report(self) -> dict:
        """Generate comprehensive performance report."""
        dd_stats = self.max_drawdown()

        # Tail statistics
        var_95 = self.returns.quantile(0.05)
        cvar_95 = self.returns[self.returns <= var_95].mean()
        skewness = self.returns.skew()
        kurtosis = self.returns.kurt()

        # Monthly aggregation
        monthly = self.returns.resample('ME').apply(lambda x: (1 + x).prod() - 1)

        # Win/loss statistics
        winning_days = (self.returns > 0).mean()
        avg_win = self.returns[self.returns > 0].mean()
        avg_loss = self.returns[self.returns < 0].mean()
        profit_factor = -avg_win * winning_days / (avg_loss * (1 - winning_days) + 1e-8)

        report = {
            'Return Metrics': {
                'CAGR': f"{self._cagr() * 100:.2f}%",
                'Annualised Return': f"{self.returns.mean() * 252 * 100:.2f}%",
                'Annualised Vol': f"{self.returns.std() * np.sqrt(252) * 100:.2f}%",
                'Monthly Sharpe': f"{monthly.mean() / monthly.std() * np.sqrt(12):.3f}",
            },
            'Risk-Adjusted Metrics': {
                'Sharpe Ratio': f"{self.sharpe_ratio():.3f}",
                'Sortino Ratio': f"{self.sortino_ratio():.3f}",
                'Calmar Ratio': f"{self.calmar_ratio():.3f}",
                'Omega Ratio': f"{self.omega_ratio():.3f}",
            },
            'Drawdown': {
                'Max Drawdown': f"{dd_stats['max_drawdown_pct']:.2f}%",
                'Drawdown Duration': f"{dd_stats['drawdown_days']} days",
                'Recovery Time': f"{dd_stats['recovery_days']} days",
            },
            'Tail Risk': {
                '95% VaR (daily)': f"{var_95 * 100:.3f}%",
                '95% CVaR (daily)': f"{cvar_95 * 100:.3f}%",
                'Skewness': f"{skewness:.3f}",
                'Excess Kurtosis': f"{kurtosis:.3f}",
            },
            'Trade Statistics': {
                'Winning Days': f"{winning_days * 100:.1f}%",
                'Avg Win': f"{avg_win * 100:.3f}%",
                'Avg Loss': f"{avg_loss * 100:.3f}%",
                'Profit Factor': f"{profit_factor:.2f}",
            }
        }
        return report

    def print_report(self):
        """Pretty-print the performance report."""
        report = self.full_report()
        print("=" * 60)
        print(" STRATEGY PERFORMANCE REPORT ")
        print("=" * 60)
        for section, metrics in report.items():
            print(f"\n{section}")
            print("-" * 40)
            for name, value in metrics.items():
                print(f"  {name:<28} {value:>12}")
        print("=" * 60)


from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from enum import Enum
from typing import Optional, Dict, List, Deque
from collections import deque
import pandas as pd
import numpy as np
from datetime import datetime

# Event Definitions

class EventType(Enum):
    MARKET = "MARKET"
    SIGNAL = "SIGNAL"
    ORDER = "ORDER"
    FILL = "FILL"

class OrderType(Enum):
    MARKET = "MARKET"
    LIMIT = "LIMIT"
    MOC = "MOC"  # Market-on-Close

class Direction(Enum):
    LONG = 1
    SHORT = -1
    EXIT = 0

@dataclass
class Event:
    event_type: EventType
    timestamp: datetime

@dataclass
class MarketEvent(Event):
    """
    Fired once per bar for every instrument.
    Contains the full options chain snapshot.
    """
    symbol: str
    spot_price: float
    option_chain: pd.DataFrame  # Columns: strike, expiry, type, bid, ask, iv, delta, gamma, theta, vega

    def __post_init__(self):
        self.event_type = EventType.MARKET

@dataclass
class SignalEvent(Event):
    """
    Carries a directional signal with strength metadata.
    """
    strategy_id: str
    symbol: str
    signal_type: Direction
    strength: float  # [-1, 1] normalised
    metadata: dict = field(default_factory=dict)

    def __post_init__(self):
        self.event_type = EventType.SIGNAL

@dataclass
class OrderEvent(Event):
    """
    A concrete trading instruction.
    """
    symbol: str
    order_type: OrderType
    quantity: int  # Negative = short
    direction: Direction
    limit_price: Optional[float] = None

    def __post_init__(self):
        self.event_type = EventType.ORDER

@dataclass
class FillEvent(Event):
    """
    Represents a completed order execution with realistic costs.
    """
    symbol: str
    exchange: str
    quantity: int
    direction: Direction
    fill_price: float
    commission: float
    slippage: float

    @property
    def total_cost(self) -> float:
        """All-in cost including commissions and slippage."""
        return (self.fill_price * abs(self.quantity) * 100  # Options: 100 multiplier
                + self.commission + self.slippage)

    def __post_init__(self):
        self.event_type = EventType.FILL

# Data Handler

class DataHandler(ABC):
    """Abstract interface for market data streaming."""

    @abstractmethod
    def get_latest_bar(self, symbol: str) -> pd.Series:
        raise NotImplementedError

    @abstractmethod
    def update_bars(self, events: Deque) -> bool:
        """Push next bar to queue. Returns False when data exhausted."""
        raise NotImplementedError

class HistoricalOptionsDataHandler(DataHandler):
    """
    Streams historical options data bar-by-bar.

    Critical design decision: data is buffered and we NEVER allow
    the strategy to access data beyond the current bar index.
    This enforces strict temporal causality.
    """

    def __init__(self, spot_data: pd.DataFrame, options_data: pd.DataFrame, symbol: str):
        self.spot_data = spot_data.copy()
        self.options_data = options_data.copy()
        self.symbol = symbol
        self._bar_index = 0
        self._latest_bars: Dict[str, pd.DataFrame] = {}
        self._max_bars = len(spot_data)

    def get_latest_bar(self, symbol: str) -> Optional[pd.Series]:
        """Returns the CURRENT bar (no future data accessible)."""
        if symbol not in self._latest_bars:
            return None
        return self._latest_bars[symbol].iloc[-1]

    def get_latest_bars(self, symbol: str, N: int = 1) -> pd.DataFrame:
        """Returns last N bars. Enforces data availability constraint."""
        if symbol not in self._latest_bars:
            return pd.DataFrame()
        bars = self._latest_bars[symbol]
        return bars.iloc[-N:] if len(bars) >= N else bars

    def update_bars(self, events: Deque) -> bool:
        """Advance one bar and emit MarketEvent."""
        if self._bar_index >= self._max_bars:
            return False  # Backtest complete

        # Get current bar data
        current_date = self.spot_data.index[self._bar_index]
        spot_row = self.spot_data.iloc[self._bar_index]
        options_slice = self.options_data[
            self.options_data.index.get_level_values('date') == current_date
        ]

        # Buffer current bar (all historical bars up to now are accessible)
        if self.symbol not in self._latest_bars:
            self._latest_bars[self.symbol] = pd.DataFrame()

        new_row = pd.DataFrame([spot_row], index=[current_date])
        self._latest_bars[self.symbol] = pd.concat(
            [self._latest_bars[self.symbol], new_row]
        )

        # Emit market event
        event = MarketEvent(
            event_type=EventType.MARKET,
            timestamp=current_date,
            symbol=self.symbol,
            spot_price=spot_row['close'],
            option_chain=options_slice
        )
        events.append(event)
        self._bar_index += 1
        return True

# Execution Handler

class SimulatedExecutionHandler:
    """
    Simulates order execution with realistic market microstructure.

    Key realism assumptions:
    1. Options trade at mid + half-spread (bid-ask friction)
    2. Slippage scales with order size relative to ADV
    3. Commission structure matches IBKR tiered pricing
    """

    def __init__(self, commission_per_contract: float = 0.65, slippage_multiplier: float = 0.1):
        self.commission_per_contract = commission_per_contract
        self.slippage_mult = slippage_multiplier

    def execute_order(self, event: OrderEvent, market_data: MarketEvent, events: Deque) -> None:
        """Convert OrderEvent to FillEvent with realistic pricing."""
        if event.event_type != EventType.ORDER:
            return

        # Find the relevant option in the chain
        chain = market_data.option_chain

        # Simulate fill price: mid-price with half-spread slippage
        bid = chain['bid'].mean() if len(chain) > 0 else 0
        ask = chain['ask'].mean() if len(chain) > 0 else 0
        mid = (bid + ask) / 2
        spread = ask - bid

        # Aggressive fills take more spread (market orders vs limit)
        if event.order_type == OrderType.MARKET:
            fill_price = ask if event.direction == Direction.LONG else bid
        else:
            fill_price = mid  # Limit order gets mid

        # Slippage: proportional to order size (simplified)
        slippage = self.slippage_mult * spread * abs(event.quantity)
        commission = self.commission_per_contract * abs(event.quantity)

        fill = FillEvent(
            event_type=EventType.FILL,
            timestamp=event.timestamp,
            symbol=event.symbol,
            exchange="CBOE",
            quantity=event.quantity,
            direction=event.direction,
            fill_price=fill_price,
            commission=commission,
            slippage=slippage
        )
        events.append(fill)

# Main Backtesting Engine

class EventDrivenBacktester:
    """
    Orchestrates the full event loop.

    Loop invariant: at each iteration, only past data is visible.
    This is the core temporal causality guarantee.
    """

    def __init__(self, data_handler: DataHandler, strategy, portfolio, execution_handler):
        self.data = data_handler
        self.strategy = strategy
        self.portfolio = portfolio
        self.execution = execution_handler
        self.events: Deque = deque()

    def _process_event(self, event: Event) -> None:
        """Route event to correct handler."""
        if event.event_type == EventType.MARKET:
            self.strategy.calculate_signals(event, self.events)
            self.portfolio.update_timeindex(event)

        elif event.event_type == EventType.SIGNAL:
            self.portfolio.update_signal(event, self.events)

        elif event.event_type == EventType.ORDER:
            # Retrieve current market data for realistic fills
            latest = self.data.get_latest_bar(event.symbol)
            self.execution.execute_order(event, latest, self.events)

        elif event.event_type == EventType.FILL:
            self.portfolio.update_fill(event)

    def run(self) -> Dict:
        """Execute the full backtest loop."""
        while True:
            # Advance one bar (emits MarketEvent)
            has_data = self.data.update_bars(self.events)
            if not has_data:
                break

            # Drain the event queue
            while self.events:
                event = self.events.popleft()
                self._process_event(event)

        # Compute and return performance metrics
        return self.portfolio.output_summary_stats()

# Options Chain Management in Backtest

class OptionsChainSelector:
    """
    Selects the appropriate option contracts for trading at each bar.
    Design principle: mimic how a real trader selects contracts.
    """

    def __init__(self, target_dte: int = 30, target_delta: float = 0.30, dte_tolerance: int = 5):
        self.target_dte = target_dte
        self.target_delta = target_delta
        self.dte_tol = dte_tolerance

    def select_contract(self, chain: pd.DataFrame, current_date: pd.Timestamp, option_type: str = 'P') -> Optional[pd.Series]:
        """
        Select contract closest to target DTE and delta.
        Returns None if no suitable contract exists (critical for handling weekend/holiday gaps and liquidity gaps).
        """
        if chain.empty:
            return None

        # Filter by option type
        chain = chain[chain['option_type'] == option_type].copy()

        # Compute DTE
        chain['dte'] = (pd.to_datetime(chain['expiry']) - current_date).dt.days

        # Filter to DTE window
        mask = (chain['dte'] >= self.target_dte - self.dte_tol) & (chain['dte'] <= self.target_dte + self.dte_tol)
        chain = chain[mask]

        if chain.empty:
            return None

        # Among valid expiries, find closest expiry first
        chain = chain.sort_values('dte')
        target_expiry_chain = chain[
            chain['dte'] == chain['dte'].min()
        ]

        # Then find closest delta within that expiry
        target_expiry_chain = target_expiry_chain.copy()
        target_expiry_chain['delta_dist'] = (
            (target_expiry_chain['delta'].abs() - self.target_delta).abs()
        )

        return target_expiry_chain.nsmallest(1, 'delta_dist').iloc[0]

    def handle_roll(self, position: pd.Series, chain: pd.DataFrame, current_date: pd.Timestamp, roll_dte_threshold: int = 7) -> Optional[pd.Series]:
        """
        Determine if a position needs to be rolled and return new contract.
        Roll rule: exit when DTE < roll_dte_threshold, enter new position at target_dte.
        """
        dte = (pd.to_datetime(position['expiry']) - current_date).days

        if dte < roll_dte_threshold:
            # Close old, open new
            new_contract = self.select_contract(
                chain, current_date, position['option_type']
            )
            return new_contract  # None means skip bar

        return position  # No roll needed

# Greeks-Aware Portfolio Tracker

class OptionsPortfolio:
    """
    Tracks positions, PnL, and Greeks in real-time during backtest.
    """

    def __init__(self, initial_capital: float = 1_000_000.0):
        self.initial_capital = initial_capital
        self.current_capital = initial_capital
        self.positions: Dict[str, dict] = {}  # symbol -> position info
        self.all_holdings_history = []
        self.current_holdings = self._construct_holdings_snapshot()

    def _construct_holdings_snapshot(self) -> dict:
        return {
            'cash': self.current_capital,
            'total': self.current_capital,
            'portfolio_delta': 0.0,
            'portfolio_gamma': 0.0,
            'portfolio_theta': 0.0,
            'portfolio_vega': 0.0,
            'positions': {}
        }

    def update_fill(self, fill: FillEvent) -> None:
        """Update portfolio state after a fill."""
        contract_value = fill.fill_price * abs(fill.quantity) * 100
        total_cost = contract_value + fill.commission + fill.slippage

        if fill.direction == Direction.LONG:
            self.current_capital -= total_cost
            self.positions[fill.symbol] = {
                'quantity': fill.quantity,
                'avg_price': fill.fill_price,
                'cost_basis': total_cost
            }
        elif fill.direction == Direction.SHORT:
            self.current_capital += (contract_value - fill.commission - fill.slippage)
            self.positions[fill.symbol] = {
                'quantity': -fill.quantity,
                'avg_price': fill.fill_price,
                'cost_basis': total_cost
            }

    def update_timeindex(self, event: MarketEvent) -> None:
        """
        Mark-to-market all positions at current market prices.
        This is called ONCE per bar, AFTER all events for that bar.
        """
        chain = event.option_chain
        snapshot = self._construct_holdings_snapshot()

        mtm_value = self.current_capital
        total_delta = 0.0
        total_gamma = 0.0
        total_theta = 0.0
        total_vega = 0.0

        for symbol, pos in self.positions.items():
            # Find current market price of position
            symbol_chain = chain[chain['symbol'] == symbol]
            if symbol_chain.empty:
                # Option may have expired or been delisted
                continue

            current_price = symbol_chain.iloc[0]['mid']
            pos_value = current_price * abs(pos['quantity']) * 100

            # Accumulate Greeks
            if 'delta' in symbol_chain.columns:
                total_delta += symbol_chain.iloc[0]['delta'] * pos['quantity'] * 100
                total_gamma += symbol_chain.iloc[0]['gamma'] * pos['quantity'] * 100
                total_theta += symbol_chain.iloc[0]['theta'] * pos['quantity'] * 100
                total_vega += symbol_chain.iloc[0]['vega'] * pos['quantity'] * 100

            mtm_value += pos_value
            snapshot['positions'][symbol] = {
                **pos, 'current_price': current_price,
                'mtm_value': pos_value
            }

        snapshot.update({
            'cash': self.current_capital,
            'total': mtm_value,
            'portfolio_delta': total_delta,
            'portfolio_gamma': total_gamma,
            'portfolio_theta': total_theta,
            'portfolio_vega': total_vega,
            'timestamp': event.timestamp
        })

        self.all_holdings_history.append(snapshot)


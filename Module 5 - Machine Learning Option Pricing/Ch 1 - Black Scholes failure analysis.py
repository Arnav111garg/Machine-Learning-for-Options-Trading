import numpy as np
import scipy.stats as ss
from scipy.optimize import brentq
import matplotlib.pyplot as plt

# Core BS functions
def bs_price(S, K, r, sigma, T, option_type='call'):
    """Black-Scholes closed-form price."""
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    if option_type == 'call':
        return S * ss.norm.cdf(d1) - K * np.exp(-r * T) * ss.norm.cdf(d2)
    else:
        return K * np.exp(-r * T) * ss.norm.cdf(-d2) - S * ss.norm.cdf(-d1)

def bs_vega(S, K, r, sigma, T):
    """BS vega: dC/d(sigma)."""
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    return S * ss.norm.pdf(d1) * np.sqrt(T)

def implied_vol(C_mkt, S, K, r, T, option_type='call', tol=1e-8):
    """
    Newton-Raphson implied volatility solver.
    More stable than bisection for near-ATM options.
    """
    # Initial guess via Brenner-Subrahmanyam approximation
    sigma = np.sqrt(2 * np.pi / T) * C_mkt / S
    sigma = max(sigma, 1e-4) # floor

    for iteration in range(100):
        price = bs_price(S, K, r, sigma, T, option_type)
        vega = bs_vega(S, K, r, sigma, T)
        diff = price - C_mkt
        if abs(diff) < tol:
            return sigma
        if vega < 1e-12:
            # Fallback to bisection
            return brentq(
                lambda s: bs_price(S, K, r, s, T, option_type) - C_mkt,
                1e-4, 10.0, xtol=tol
            )
        sigma -= diff / vega
        sigma = max(sigma, 1e-4) # keep positive
    return sigma

# Risk-neutral density via Breeden-Litzenberger
def risk_neutral_density(S, K_grid, r, T, C_func, dK=0.5):
    """
    Numerical second derivative of call prices w.r.t. strike.
    C_func : callable (K) -> call price
    """
    C_plus = np.array([C_func(K + dK) for K in K_grid])
    C_minus = np.array([C_func(K - dK) for K in K_grid])
    C_center = np.array([C_func(K) for K in K_grid])

    # Second derivative
    d2C_dK2 = (C_plus - 2 * C_center + C_minus) / dK**2

    # Risk-neutral density
    q = np.exp(r * T) * d2C_dK2
    q = np.maximum(q, 0) # enforce non-negativity
    return q

# Simulate the volatility smile
def simulate_smile_from_mixture():
    """
    Generate realistic call prices from a mixture of log-normals
    (captures skew and kurtosis), then compute implied vols.
    """
    S, r, T = 100.0, 0.02, 0.25
    K_grid = np.linspace(70, 140, 200)
    log_m = np.log(K_grid / (S * np.exp(r * T))) # log-moneyness

    # Two-component mixture (crash + normal regime)
    sig1, mu1, w1 = 0.30, np.log(0.92), 0.15 # crash component
    sig2, mu2, w2 = 0.15, np.log(1.00), 0.85 # normal component

    def mixture_call(K):
        def price_component(mu, sig, weight):
            F = S * np.exp((r + mu) * T) # displaced forward
            return weight * bs_price(F, K, 0, sig, T)
        return price_component(mu1, sig1, w1) + price_component(mu2, sig2, w2)

    # Market prices from mixture
    C_mkt = np.array([mixture_call(K) for K in K_grid])

    # Implied vols
    IV_smile = []
    for i, K in enumerate(K_grid):
        try:
            if C_mkt[i] > 1e-8: # filter deep OTM
                iv = implied_vol(C_mkt[i], S, K, r, T)
                IV_smile.append(iv if 0.01 < iv < 5.0 else np.nan)
            else:
                IV_smile.append(np.nan)
        except:
            IV_smile.append(np.nan)

    return K_grid, np.array(IV_smile), C_mkt, S, r, T

K_grid, IV_smile, C_mkt, S, r, T = simulate_smile_from_mixture()

# BS mispricing at flat 20% vol
C_bs_flat = np.array([bs_price(S, K, r, 0.20, T) for K in K_grid])
pricing_error = C_mkt - C_bs_flat


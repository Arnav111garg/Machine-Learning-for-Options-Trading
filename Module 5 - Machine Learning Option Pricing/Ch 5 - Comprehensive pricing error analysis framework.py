import numpy as np
import pandas as pd
from scipy import stats

class PricingErrorAnalyzer:
    """
    Comprehensive pricing error analysis for option models.
    Produces institutional-grade diagnostics used on real desks.
    """

    def __init__(self, C_pred, C_true, features_df):
        """
        Parameters
        ----------
        C_pred : predicted prices (array)
        C_true : market prices (array)
        features_df : DataFrame with columns:
        [S, K, T, IV_atm, vega_bs, delta_bs,
        bid_ask_spread, volume, log_money]
        """
        self.C_pred = np.asarray(C_pred)
        self.C_true = np.asarray(C_true)
        self.df = features_df.copy()
        self.errors = self.C_pred - self.C_true
        self.abs_err = np.abs(self.errors)

        # Compute IV errors via linearisation
        vega = self.df['vega_bs'].values + 1e-8
        self.iv_errors = self.errors / vega
        # Normalise by spot
        S = self.df['S'].values
        self.norm_err = self.errors / S * 10000  # in bps

    def summary_metrics(self):
        """All global metrics in one dict."""
        e, iv_e, n_e = self.errors, self.iv_errors, self.norm_err

        metrics = {
            # Price space
            'RMSE_$': np.sqrt(np.mean(e**2)),
            'MAE_$': np.mean(np.abs(e)),
            'Bias_$': np.mean(e),
            'MaxErr_$': np.max(np.abs(e)),
            'P95Err_$': np.percentile(np.abs(e), 95),

            # IV space
            'RMSE_IV': np.sqrt(np.mean(iv_e**2)),
            'MAE_IV': np.mean(np.abs(iv_e)),
            'Bias_IV': np.mean(iv_e),
            'MaxErr_IV': np.max(np.abs(iv_e)),

            # Normalised (bps of spot)
            'RMSE_bps': np.sqrt(np.mean(n_e**2)),
            'Bias_bps': np.mean(n_e),

            # R-squared
            'R2_price': 1 - np.sum(e**2) / np.sum((self.C_true - self.C_true.mean())**2),
            'R2_IV': 1 - np.sum(iv_e**2) / (np.sum((self.iv_errors - self.iv_errors.mean())**2) + 1e-16),

            # Distribution of errors
            'Skewness': stats.skew(e),
            'Kurtosis': stats.kurtosis(e),
            'Normality_p': stats.normaltest(e).pvalue,
        }
        return metrics

    def by_moneyness(self, bins=None):
        """Error breakdown by moneyness bucket."""
        if bins is None:
            bins = [-3, -1.5, -0.5, 0.5, 1.5, 3]
        labels = ['Deep OTM Put', 'OTM Put', 'ATM', 'OTM Call', 'Deep OTM Call']

        lm = self.df['log_money'].values
        bucket = pd.cut(lm, bins=bins, labels=labels)

        results = []
        for label in labels:
            mask = (bucket == label).values
            if mask.sum() == 0:
                continue
            e = self.errors[mask]
            iv_e = self.iv_errors[mask]
            results.append({
                'Bucket': label,
                'N': mask.sum(),
                'RMSE_$': np.sqrt(np.mean(e**2)),
                'Bias_$': np.mean(e),
                'RMSE_IV': np.sqrt(np.mean(iv_e**2)),
                'Bias_IV': np.mean(iv_e),
                'MaxErr_$': np.max(np.abs(e)),
            })
        return pd.DataFrame(results).set_index('Bucket')

    def by_maturity(self):
        """Error breakdown by maturity bucket."""
        T = self.df['T'].values * 252  # in days
        bins = [0, 14, 30, 60, 90, 180, 365, 730]
        labels = ['<2w', '2w-1m', '1-2m', '2-3m', '3-6m', '6-12m', '>12m']

        bucket = pd.cut(T, bins=bins, labels=labels)
        results = []

        for label in labels:
            mask = (bucket == label).values
            if mask.sum() < 5:
                continue
            e = self.errors[mask]
            iv_e = self.iv_errors[mask]
            results.append({
                'Maturity': label,
                'N': mask.sum(),
                'RMSE_$': np.sqrt(np.mean(e**2)),
                'Bias_$': np.mean(e),
                'RMSE_IV': np.sqrt(np.mean(iv_e**2)),
                'Bias_IV': np.mean(iv_e),
            })
        return pd.DataFrame(results).set_index('Maturity')

    def by_vol_regime(self):
        """Error breakdown by VIX / IV regime."""
        iv_atm = self.df['IV_atm'].values * 100  # in %
        bins = [0, 12, 20, 30, 50, 200]
        labels = ['Very Low <12%', 'Low 12-20%', 'Normal 20-30%', 'High 30-50%', 'Crisis >50%']

        bucket = pd.cut(iv_atm, bins=bins, labels=labels)
        results = []

        for label in labels:
            mask = (bucket == label).values
            if mask.sum() < 5:
                continue
            e = self.errors[mask]
            iv_e = self.iv_errors[mask]
            results.append({
                'Regime': label,
                'N': mask.sum(),
                'RMSE_$': np.sqrt(np.mean(e**2)),
                'Bias_$': np.mean(e),
                'RMSE_IV': np.sqrt(np.mean(iv_e**2)),
            })
        return pd.DataFrame(results).set_index('Regime')

    def by_liquidity(self, n_quantiles=4):
        """Error breakdown by bid-ask spread (liquidity proxy)."""
        spread = self.df['bid_ask_spread'].values
        quantile_bins = np.percentile(spread, np.linspace(0, 100, n_quantiles + 1))
        labels = [f'Q{i+1} (tightest)' if i == 0 else f'Q{i+1} (widest)' if i == n_quantiles - 1 else f'Q{i+1}' for i in range(n_quantiles)]

        bucket = pd.cut(spread, bins=quantile_bins, labels=labels, include_lowest=True)
        results = []

        for label in labels:
            mask = (bucket == label).values
            if mask.sum() < 5:
                continue
            e = self.errors[mask]
            results.append({
                'Liquidity': label,
                'N': mask.sum(),
                'Avg Spread': spread[mask].mean(),
                'RMSE_$': np.sqrt(np.mean(e**2)),
                'Bias_$': np.mean(e),
            })
        return pd.DataFrame(results).set_index('Liquidity')

    def error_heatmap_data(self):
        """
        Returns RMSE_IV heatmap data by (moneyness x maturity).
        Used to identify systematic blind spots.
        """
        lm = self.df['log_money'].values
        T = self.df['T'].values * 252

        money_bins = [-np.inf, -1.5, -0.5, 0.5, 1.5, np.inf]
        mat_bins = [0, 30, 60, 90, 180, np.inf]

        money_labels = ['Deep OTM P', 'OTM P', 'ATM', 'OTM C', 'Deep OTM C']
        mat_labels = ['<1m', '1-2m', '2-3m', '3-6m', '>6m']

        heatmap = np.full((len(money_labels), len(mat_labels)), np.nan)

        for i, (ml, mr) in enumerate(zip(money_bins[:-1], money_bins[1:])):
            for j, (tl, tr) in enumerate(zip(mat_bins[:-1], mat_bins[1:])):
                mask = (lm >= ml) & (lm < mr) & (T >= tl) & (T < tr)
                if mask.sum() >= 3:
                    iv_e = self.iv_errors[mask]
                    heatmap[i, j] = np.sqrt(np.mean(iv_e**2))

        return heatmap, money_labels, mat_labels

    def full_report(self):
        """Generate complete diagnostic report."""
        print("=" * 65)
        print(" PRICING ERROR ANALYSIS REPORT ")
        print("=" * 65)

        print("\n [1] GLOBAL METRICS ")
        metrics = self.summary_metrics()
        for k, v in metrics.items():
            if isinstance(v, float):
                print(f" {k : <20}: {v :.6f}")

        print("\n [2] BY MONEYNESS ")
        print(self.by_moneyness().to_string())
        print("\n [3] BY MATURITY ")
        print(self.by_maturity().to_string())

        print("\n [4] BY VOLATILITY REGIME ")
        print(self.by_vol_regime().to_string())

        print("\n [5] BY LIQUIDITY ")
        print(self.by_liquidity().to_string())

        heatmap, ml, tl = self.error_heatmap_data()
        print("\n [6] ERROR HEATMAP (RMSE_IV by Moneyness x Maturity)")
        df_heatmap = pd.DataFrame(heatmap, index=ml, columns=tl)
        print(df_heatmap.round(4).to_string())
        print("=" * 65)


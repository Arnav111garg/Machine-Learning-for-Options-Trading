import numpy as np
import pandas as pd
from scipy.stats import norm
from sklearn.preprocessing import StandardScaler

def engineer_option_features(df: pd.DataFrame) -> pd.DataFrame:
    """
    Comprehensive feature engineering for option pricing ML.
    Parameters
    ----------
    df : DataFrame with columns:
    [S, K, r, q, T, C_mid, IV_atm, skew_25d, bf_25d,
    rv_5d, rv_21d, rv_63d, vix, open_interest, volume]

    Returns
    -------
    DataFrame with engineered features
    """
    d = df.copy()

    # Core normalised variables
    d['forward'] = d['S'] * np.exp((d['r'] - d['q']) * d['T'])
    d['log_money'] = np.log(d['K'] / d['forward'])  # ln(K/F)
    d['std_money'] = d['log_money'] / (d['IV_atm'] * np.sqrt(d['T']))

    # Delta-equivalent (Black-76 approximation using ATM vol)
    d1 = -d['std_money'] + 0.5 * d['IV_atm'] * np.sqrt(d['T'])
    d['delta_approx'] = norm.cdf(d1)

    # Normalised price features
    d['C_over_S'] = d['C_mid'] / d['S']
    d['intrinsic'] = np.maximum(d['S'] - d['K'] * np.exp(-d['r'] * d['T']), 0) / d['S']
    d['time_value'] = d['C_over_S'] - d['intrinsic']

    # Volatility features
    d['VRP_21d'] = d['IV_atm']**2 - d['rv_21d']**2  # variance risk premium
    d['vol_ratio'] = d['IV_atm'] / (d['rv_21d'] + 1e-8)  # IV/RV ratio
    d['term_slope'] = (d['rv_5d'] - d['rv_63d']) / (d['rv_63d'] + 1e-8)

    # Normalised surface parameters
    d['skew_norm'] = d['skew_25d'] / (d['IV_atm'] + 1e-8)
    d['bf_norm'] = d['bf_25d'] / (d['IV_atm'] + 1e-8)

    # Time features
    d['sqrt_T'] = np.sqrt(d['T'])
    d['log_T'] = np.log(d['T'] + 1e-8)
    d['T_sq'] = d['T']**2

    # Market regime features
    d['vix_norm'] = d['vix'] / 100.0
    d['vix_rv_ratio'] = d['vix'] / (d['rv_21d'] * 100 + 1e-8)

    # Liquidity proxies
    d['log_oi'] = np.log1p(d['open_interest'])
    d['log_vol'] = np.log1p(d['volume'])

    # Select and order features
    feature_cols = [
        'log_money', 'std_money', 'delta_approx',  # moneyness
        'T', 'sqrt_T', 'log_T',  # maturity
        'IV_atm', 'skew_25d', 'bf_25d',  # surface
        'skew_norm', 'bf_norm',  # normalised surface
        'rv_5d', 'rv_21d', 'rv_63d',  # realised vol
        'VRP_21d', 'vol_ratio', 'term_slope',  # vol dynamics
        'r', 'q',  # rates
        'vix_norm', 'vix_rv_ratio',  # regime
        'log_oi', 'log_vol',  # liquidity
    ]

    return d, feature_cols

def temporal_train_val_test_split(df, date_col='date', train_pct=0.70, val_pct=0.15):
    """
    Time-aware split that prevents look-ahead bias.
    """
    dates = df[date_col].sort_values().unique()
    n = len(dates)

    train_end = dates[int(n * train_pct)]
    val_end = dates[int(n * (train_pct + val_pct))]

    train = df[df[date_col] <= train_end]
    val = df[(df[date_col] > train_end) & (df[date_col] <= val_end)]
    test = df[df[date_col] > val_end]

    print(f"Train: {len(train):,} obs | {train[date_col].min()} - {train[date_col].max()}")
    print(f"Val: {len(val):,} obs | {val[date_col].min()} - {val[date_col].max()}")
    print(f"Test: {len(test):,} obs | {test[date_col].min()} - {test[date_col].max()}")

    return train, val, test

def evaluate_pricing_model(C_pred, C_actual, S, option_type='call'):
    """
    Comprehensive pricing error metrics used by institutional desks.
    """
    errors = C_pred - C_actual

    metrics = {
        'RMSE': np.sqrt(np.mean(errors**2)),
        'MAE': np.mean(np.abs(errors)),
        'MAPE': np.mean(np.abs(errors / (C_actual + 1e-8))) * 100,
        'R2': 1 - np.sum(errors**2) / np.sum((C_actual - C_actual.mean())**2),
        # Normalised by spot (institutionally preferred)
        'RMSE/S': np.sqrt(np.mean((errors / S)**2)) * 10000,  # in bps
        'Bias': np.mean(errors),
        'MaxError': np.max(np.abs(errors)),
    }
    return metrics


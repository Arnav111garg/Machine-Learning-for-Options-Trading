import numpy as np
import torch
import time
import logging
import threading
from dataclasses import dataclass, field
from typing import Optional, Dict, List
from collections import deque

logger = logging.getLogger('prod_pricer')

# Data classes
@dataclass
class PricingRequest:
    option_id: str
    S: float
    K: float
    T: float  # maturity in years
    r: float
    q: float
    option_type: str  # 'call' or 'put'
    market_state: np.ndarray  # pre-computed state features

@dataclass
class PricingResponse:
    option_id: str
    price: float
    delta: float
    gamma: float
    vega: float
    theta: float
    iv: float
    latency_us: float  # latency in microseconds
    model_used: str  # 'primary' or 'fallback'
    arb_free: bool

# Production Pricer
class ProductionOptionPricer:
    """
    Production-grade option pricer with:
    - ONNX / TorchScript primary model
    - BS fallback
    - Real-time arbitrage checking
    - Performance monitoring
    - Thread-safe inference
    """

    def __init__(self, model_path: str,
                 latency_budget_ms: float = 5.0,
                 max_iv_error_threshold: float = 0.05):
        self.latency_budget_ms = latency_budget_ms
        self.max_iv_error_threshold = max_iv_error_threshold

        # Load models
        self.primary_model = self._load_model(model_path)
        self.fallback_active = False

        # Thread lock for model access
        self._lock = threading.RLock()

        # Performance monitoring
        self.latency_history = deque(maxlen=10000)
        self.error_history = deque(maxlen=10000)
        self.arb_viol_history = deque(maxlen=1000)
        self.model_errors = deque(maxlen=1000)

        # Arbitrage thresholds
        self.arb_tol = {'butterfly': -1e-3, 'calendar': -1e-4}

        logger.info(f"ProductionOptionPricer initialised | latency budget: {latency_budget_ms}ms")

    def _load_model(self, path: str):
        """Load TorchScript model for C++-compatible inference."""
        try:
            model = torch.jit.load(path)
            model.eval()
            # Warm up
            dummy = torch.zeros(1, 24)  # adjust to feature dim
            with torch.no_grad():
                _ = model(dummy)
            logger.info(f"Primary model loaded from {path}")
            return model
        except Exception as e:
            logger.error(f"Failed to load primary model: {e}")
            return None

    def price_single(self, req: PricingRequest) -> PricingResponse:
        """
        Price a single option. Thread-safe, latency-bounded.
        Falls back to Black-Scholes if ML model fails or is slow.
        """
        t0 = time.perf_counter()

        try:
            with self._lock:
                if self.primary_model is not None and not self.fallback_active:
                    price, greeks = self._ml_price(req)
                    model_used = 'primary'
                else:
                    price, greeks = self._bs_price(req)
                    model_used = 'fallback'
        except Exception as e:
            logger.warning(f"Pricing error: {e}. Using BS fallback.")
            price, greeks = self._bs_price(req)
            model_used = 'fallback'

        latency_us = (time.perf_counter() - t0) * 1e6

        # Check latency budget
        if latency_us > self.latency_budget_ms * 1000:
            logger.warning(f"Latency exceeded budget: {latency_us:.0f}us")
        self.latency_history.append(latency_us)

        # Arbitrage check (lightweight)
        arb_free = self._quick_arb_check(req, price, greeks)
        if not arb_free:
            self.arb_viol_history.append({
                'option_id': req.option_id,
                'time': time.time(),
                'price': price
            })
            # Correct to BS if arbitrage detected
            price, greeks = self._bs_price(req)
            model_used = 'fallback_arb'

        return PricingResponse(
            option_id=req.option_id,
            price=price,
            delta=greeks['delta'],
            gamma=greeks['gamma'],
            vega=greeks['vega'],
            theta=greeks['theta'],
            iv=greeks.get('iv', np.nan),
            latency_us=latency_us,
            model_used=model_used,
            arb_free=arb_free,
        )

    def price_batch(self, requests: List[PricingRequest]) -> List[PricingResponse]:
        """
        Batch pricing much more efficient than single calls.
        Uses vectorised tensor operations.
        """
        t0 = time.perf_counter()

        # Stack features
        states = np.stack([r.market_state for r in requests])
        X_tensor = torch.FloatTensor(states)

        with torch.no_grad():
            X_for_greeks = X_tensor.requires_grad_(True)
            prices = self.primary_model(X_for_greeks)

        # Batch Greeks via autograd
        grads = torch.autograd.grad(prices.sum(), X_for_greeks)[0]

        prices_np = prices.detach().numpy()
        grads_np = grads.detach().numpy()

        latency_ms = (time.perf_counter() - t0) * 1000
        logger.debug(f"Batch price: {len(requests)} options in {latency_ms:.2 f}ms")

        responses = []
        for i, req in enumerate(requests):
            resp = PricingResponse(
                option_id=req.option_id,
                price=float(max(prices_np[i], 0)),
                delta=float(grads_np[i, 0]),  # S feature
                gamma=float(0.0),             # requires 2nd order
                vega=float(grads_np[i, 3]),   # sigma feature
                theta=float(-grads_np[i, 2]),  # T feature
                iv=float(np.nan),
                latency_us=latency_ms * 1000 / len(requests),
                model_used='primary_batch',
                arb_free=True,
            )
            responses.append(resp)

        return responses

    def _ml_price(self, req: PricingRequest):
        """Run ML model inference for a single option."""
        x = torch.FloatTensor(req.market_state).unsqueeze(0)
        x.requires_grad_(True)

        with torch.enable_grad():
            C = self.primary_model(x)
            grad = torch.autograd.grad(C, x, create_graph=False)[0]

        price = float(C.item())
        greeks = {
            'delta': float(grad[0, 0].item()),
            'vega': float(grad[0, 3].item()),
            'theta': float(-grad[0, 2].item()),
            'gamma': 0.0,  # compute separately if needed
        }
        return price, greeks

    def _bs_price(self, req: PricingRequest):
        """Black-Scholes fallback pricing."""
        from scipy.stats import norm
        S, K, r, T, q = req.S, req.K, req.r, req.T, req.q
        sigma = 0.20  # default; should use ATM IV from last known surface

        d1 = (np.log(S/K) + (r - q + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)

        if req.option_type == 'call':
            price = S * np.exp(-q * T) * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
            delta = np.exp(-q * T) * norm.cdf(d1)
        else:
            price = K * np.exp(-r * T) * norm.cdf(-d2) - S * np.exp(-q * T) * norm.cdf(-d1)
            delta = -np.exp(-q * T) * norm.cdf(-d1)

        vega = S * np.exp(-q * T) * norm.pdf(d1) * np.sqrt(T)
        gamma = np.exp(-q * T) * norm.pdf(d1) / (S * sigma * np.sqrt(T))
        theta = (-(S * np.exp(-q * T) * norm.pdf(d1) * sigma / (2 * np.sqrt(T))) - r * K * np.exp(-r * T) * norm.cdf(d2)) / 252

        return price, {
            'delta': delta,
            'gamma': gamma,
            'vega': vega,
            'theta': theta,
            'iv': sigma
        }

    def _quick_arb_check(self, req, price, greeks):
        """
        Lightweight arbitrage check: intrinsic value and delta bounds.
        Full butterfly / calendar checks run asynchronously.
        """
        S, K, r, T = req.S, req.K, req.r, req.T

        # Intrinsic value
        intrinsic = max(S * np.exp(-req.q * T) - K * np.exp(-r * T), 0)
        if price < intrinsic - 1e-4:
            return False

        # Delta bounds for calls
        if req.option_type == 'call':
            if not (0.0 <= greeks.get('delta', 0.5) <= 1.0):
                return False

        return True

    def get_performance_stats(self) -> Dict:
        """Real-time performance statistics."""
        if not self.latency_history:
            return {}

        lats = np.array(self.latency_history)
        return {
            'latency_mean_us': lats.mean(),
            'latency_p50_us': np.percentile(lats, 50),
            'latency_p95_us': np.percentile(lats, 95),
            'latency_p99_us': np.percentile(lats, 99),
            'latency_max_us': lats.max(),
            'n_priced': len(lats),
            'n_arb_violations': len(self.arb_viol_history),
            'fallback_active': self.fallback_active,
        }


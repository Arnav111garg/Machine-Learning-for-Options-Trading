# Polynomial Ridge Regression
class PolynomialRidgePricer:
    """
    Polynomial feature expansion + Ridge regression.
    Strong baseline before moving to more complex models.
    """
    def __init__(self, degree=3, alpha=1.0):
        self.degree = degree
        self.alpha = alpha
        self.pipe = Pipeline([
            ('poly', PolynomialFeatures(degree=degree, include_bias=True)),
            ('scaler', StandardScaler()),
            ('ridge', Ridge(alpha=alpha, fit_intercept=True)),
        ])

    def fit(self, X, y):
        self.pipe.fit(X, y)
        n_params = len(self.pipe.named_steps['ridge'].coef_)
        print(f"Polynomial Ridge: {n_params} parameters, degree={self.degree}")
        return self

    def predict(self, X):
        return np.maximum(self.pipe.predict(X), 0)  # enforce non-negativity

    def predict_iv(self, X, S, K, r, T):
        """Convert price predictions back to implied vol."""
        prices = self.predict(X)
        ivs = []
        for i, (price, s, k, t) in enumerate(zip(prices, S, K, T)):
            try:
                iv = implied_vol(price, s, k, r[i], t)
                ivs.append(iv)
            except:
                ivs.append(np.nan)
        return np.array(ivs)

# Gaussian Process Regressor with financial kernels
class GPOptionPricer:
    """
    Gaussian Process option pricer with calibrated kernel.
    Provides uncertainty estimates for risk management.
    """
    def __init__(self, n_restarts=10):
        # Composite kernel: amplitude * (Matern + noise)
        self.kernel = (
            ConstantKernel(1.0, (1e-2, 1e3)) *
            Matern(
                length_scale=np.ones(5),  # per-dimension ARD
                length_scale_bounds=[(1e-3, 1e2)] * 5,
                nu=2.5  # twice differentiable
            ) +
            WhiteKernel(noise_level=1e-3, noise_level_bounds=(1e-6, 1e0))
        )
        self.gpr = GaussianProcessRegressor(
            kernel=self.kernel,
            alpha=0.0,  # noise handled by WhiteKernel
            normalize_y=True,
            n_restarts_optimizer=n_restarts,
            random_state=42,
        )
        self.scaler_X = StandardScaler()
        self.scaler_y = StandardScaler()

    def fit(self, X, y):
        X_scaled = self.scaler_X.fit_transform(X)
        y_scaled = self.scaler_y.fit_transform(y.reshape(-1, 1)).ravel()
        self.gpr.fit(X_scaled, y_scaled)
        print(f"GP fitted | kernel: {self.gpr.kernel_}")
        print(f"Log marginal likelihood: {self.gpr.log_marginal_likelihood():.4f}")
        return self

    def predict(self, X, return_std=True):
        X_scaled = self.scaler_X.transform(X)
        if return_std:
            mu_s, std_s = self.gpr.predict(X_scaled, return_std=True)
            mu = self.scaler_y.inverse_transform(mu_s.reshape(-1, 1)).ravel()
            std = std_s * self.scaler_y.scale_[0]
            return np.maximum(mu, 0), std
        else:
            mu_s = self.gpr.predict(X_scaled, return_std=False)
            mu = self.scaler_y.inverse_transform(mu_s.reshape(-1, 1)).ravel()
            return np.maximum(mu, 0)

    def predict_with_band(self, X, confidence=0.95):
        """Return prediction interval at given confidence."""
        mu, std = self.predict(X)
        z = ss.norm.ppf(0.5 + confidence / 2)
        return mu, mu - z * std, mu + z * std

    def analytic_delta(self, X, dX=1e-4):
        """
        Finite-difference delta from GP mean.
        For Matern kernel, can also use analytic gradient.
        """
        X_up = X.copy()
        X_up[:, 0] += dX  # perturb S
        X_down = X.copy()
        X_down[:, 0] -= dX
        C_up = self.predict(X_up, return_std=False)
        C_down = self.predict(X_down, return_std=False)
        return (C_up - C_down) / (2 * dX)

# IV-Weighted Loss for direct IV regression
class IVWeightedLoss(nn.Module):
    """
    Vega-normalised loss: equivalent to fitting in IV space.
    Ensures uniform accuracy across all strikes.
    """
    def __init__(self, eps=1e-6):
        super().__init__()
        self.eps = eps

    def forward(self, C_pred, C_true, vega):
        """
        Parameters
        ----------
        C_pred : predicted prices (batch)
        C_true : true market prices (batch)
        vega : BS vega at each option (batch)
        """
        # IV error approximation via first-order Taylor expansion
        iv_error = (C_pred - C_true) / (vega + self.eps)
        return torch.mean(iv_error ** 2)

# Example training loop skeleton
def train_ridge_model(X_train, C_train, X_val, C_val):
    """Fit and select optimal ridge alpha via validation."""
    alphas = np.logspace(-3, 3, 50)
    best_mse = np.inf
    best_alpha = None

    for alpha in alphas:
        model = PolynomialRidgePricer(degree=3, alpha=alpha)
        model.fit(X_train, C_train)
        C_val_pred = model.predict(X_val)
        mse = np.mean((C_val_pred - C_val) ** 2)
        if mse < best_mse:
            best_mse = mse
            best_alpha = alpha

    print(f"Best alpha={best_alpha:.4f} | Val RMSE={np.sqrt(best_mse):.6f}")
    final_model = PolynomialRidgePricer(degree=3, alpha=best_alpha)
    final_model.fit(X_train, C_train)
    return final_model


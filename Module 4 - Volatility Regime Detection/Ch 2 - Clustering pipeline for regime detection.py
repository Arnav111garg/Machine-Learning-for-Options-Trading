import numpy as np
import pandas as pd
from sklearn.preprocessing import StandardScaler
from sklearn.mixture import GaussianMixture
from sklearn.cluster import KMeans, SpectralClustering, DBSCAN
from sklearn.metrics import silhouette_score, calinski_harabasz_score
from sklearn.decomposition import PCA
import matplotlib.pyplot as plt
from scipy.stats import norm
from typing import Tuple, List, Optional

class RegimeClusteringPipeline:
    """
    Multi-method clustering pipeline for volatility regime detection.
    Supports KMeans, GMM, Spectral, and DBSCAN.
    """

    def __init__(self, n_regimes: int = 3):
        self.n_regimes = n_regimes
        self.scaler = StandardScaler()
        self.pca = None
        self.models = {}

    def build_features(self, returns: np.ndarray,
                       iv: Optional[np.ndarray] = None,
                       windows: List[int] = [5, 21, 63]) -> pd.DataFrame:
        """
        Build feature matrix from returns (and optionally IV).

        Parameters
        ----------
        returns : array of daily log-returns
        iv : optional ATM implied volatility time series
        windows : rolling window sizes in days
        """
        df = pd.DataFrame({'ret': returns})

        for w in windows:
            # Realised volatility (close-to-close)
            df[f'rv_{w}d'] = (
                df['ret'].rolling(w).std() * np.sqrt(252)
            )
            # Skewness
            df[f'skew_{w}d'] = df['ret'].rolling(w).skew()
            # Kurtosis
            df[f'kurt_{w}d'] = df['ret'].rolling(w).kurt()
            # Downside realised vol
            df[f'down_rv_{w}d'] = (
                df['ret'].clip(upper=0).rolling(w).std() * np.sqrt(252)
            )

        # Absolute return momentum
        df['abs_ret_5d'] = df['ret'].abs().rolling(5).mean()
        # Directional vol ratio (down/up vol ratio)
        df['vol_ratio_21'] = df['down_rv_21d'] / df['rv_21d']

        # IV features (if provided)
        if iv is not None:
            df['iv'] = iv
            df['vix_level'] = iv
            df['vix_change'] = pd.Series(np.log(iv)).diff().values
            df['vrp_21d'] = iv - df['rv_21d'] # Volatility risk premium

        # Drop rows with NaNs (window burn-in)
        df = df.dropna()
        return df

    def fit_optimal_k(self, X_scaled: np.ndarray, k_range: range = range(2, 7)) -> dict:
        """Select optimal K via BIC (GMM) and silhouette."""
        results = {}
        for k in k_range:
            gmm = GaussianMixture(
                n_components=k,
                covariance_type='full',
                random_state=42,
                n_init=10
            )
            gmm.fit(X_scaled)
            labels = gmm.predict(X_scaled)
            results[k] = {
                'bic': gmm.bic(X_scaled),
                'aic': gmm.aic(X_scaled),
                'silhouette': silhouette_score(X_scaled, labels) if k > 1 else 0,
                'calinski': calinski_harabasz_score(X_scaled, labels) if k > 1 else 0,
                'model': gmm,
            }
        return results

    def fit(self, returns: np.ndarray, iv: Optional[np.ndarray] = None,
            pca_components: int = 5) -> 'RegimeClusteringPipeline':
        """Fit all clustering models."""
        # Feature construction
        self.feature_df_ = self.build_features(returns, iv)
        X = self.feature_df_.values

        # Standardise
        X_scaled = self.scaler.fit_transform(X)

        # PCA for dimensionality reduction (retain 90% variance)
        self.pca = PCA(n_components=pca_components, random_state=42)
        X_pca = self.pca.fit_transform(X_scaled)
        print(f"PCA: {pca_components} components explain "
              f"{self.pca.explained_variance_ratio_.sum():.1%} variance")

        # 1) K-Means
        self.models['kmeans'] = KMeans(
            n_clusters=self.n_regimes,
            n_init=50,
            random_state=42
        ).fit(X_pca)

        # 2) GMM (full covariance)
        self.models['gmm'] = GaussianMixture(
            n_components=self.n_regimes,
            covariance_type='full',
            n_init=20,
            random_state=42
        ).fit(X_pca)

        # 3) Spectral Clustering
        self.models['spectral'] = SpectralClustering(
            n_clusters=self.n_regimes,
            affinity='rbf',
            random_state=42
        ).fit(X_pca)

        # 4) DBSCAN (for anomaly detection)
        self.models['dbscan'] = DBSCAN(
            eps=0.5,
            min_samples=10
        ).fit(X_pca)

        self.X_pca_ = X_pca
        self.X_scaled_ = X_scaled

        # Optimal K selection
        self.k_selection_ = self.fit_optimal_k(X_pca)
        optimal_k = min(self.k_selection_, key=lambda k: self.k_selection_[k]['bic'])
        print(f"BIC-optimal K = {optimal_k}")

        return self

    def regime_labels(self, method: str = 'gmm') -> np.ndarray:
        """Get regime labels from specified method."""
        if method == 'gmm':
            return self.models['gmm'].predict(self.X_pca_)
        elif method == 'kmeans':
            return self.models['kmeans'].labels_
        elif method == 'spectral':
            return self.models['spectral'].labels_
        elif method == 'dbscan':
            return self.models['dbscan'].labels_ # -1 = noise
        else:
            raise ValueError(f"Unknown method: {method}")

    def regime_probabilities(self) -> np.ndarray:
        """Soft regime assignment probabilities (GMM only)."""
        return self.models['gmm'].predict_proba(self.X_pca_)

    def characterise_regimes(self, method: str = 'gmm') -> pd.DataFrame:
        """
        Compute descriptive statistics for each regime.
        Returns a DataFrame with per-regime statistics.
        """
        labels = self.regime_labels(method)
        rows = []
        unique_labels = sorted(set(labels))
        for k in unique_labels:
            mask = labels == k
            rv_col = self.feature_df_['rv_21d'].values
            rows.append({
                'Regime': k,
                'N_obs': mask.sum(),
                'Freq': mask.mean(),
                'Mean_RV': rv_col[mask].mean(),
                'Median_RV': np.median(rv_col[mask]),
                'Std_RV': rv_col[mask].std(),
            })
        return pd.DataFrame(rows).set_index('Regime')

# --- Example Usage ---
rng = np.random.RandomState(42)
T = 3000

# Synthetic 3-regime data
regimes_true = np.random.choice(3, T, p=[0.6, 0.3, 0.1])
returns_syn = np.where(regimes_true == 0,
                       rng.normal(0.0004, 0.008, T),
                       np.where(regimes_true == 1,
                                rng.normal(-0.0002, 0.018, T),
                                rng.normal(-0.002, 0.035, T)))
iv_syn = (
    0.15 * (regimes_true == 0) +
    0.28 * (regimes_true == 1) +
    0.50 * (regimes_true == 2) +
    rng.normal(0, 0.02, T)
).clip(0.05)

pipeline = RegimeClusteringPipeline(n_regimes=3)
pipeline.fit(returns_syn, iv_syn)
print(pipeline.characterise_regimes('gmm'))


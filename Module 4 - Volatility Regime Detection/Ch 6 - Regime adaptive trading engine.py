import numpy as np
import pandas as pd
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple
from scipy.stats import norm

# Helper placeholder for OnlineRegimeFilter to make code run
class OnlineRegimeFilter:
    def __init__(self, transition_matrix, emission_means, emission_stds):
        self.transition_matrix = transition_matrix
        self.emission_means = emission_means
        self.emission_stds = emission_stds

    def update(self, observation):
        # Return a dummy probability vector for demonstration
        K = len(self.emission_means)
        probs = np.ones(K) / K
        return probs

@dataclass
class OptionPosition:
    """ Represents a single options position. """
    strike: float
    maturity: float  # Time to expiry in years
    option_type: str  # 'call' or 'put'
    quantity: float  # Positive = long, negative = short
    spot_at_entry: float
    iv_at_entry: float

@dataclass
class RegimeAdaptiveEngine:
    """
    Regime-adaptive options trading engine.

    Core responsibilities:
    - Maintain real-time regime probability estimates
    - Compute regime-adjusted Greeks
    - Execute regime-driven rebalancing
    - Enforce regime-dependent risk limits
    """
    # Model parameters (from fitted HMM)
    regime_means: np.ndarray = field(default_factory=lambda: np.array([0.0003, -0.001]))
    regime_vols: np.ndarray = field(default_factory=lambda: np.array([0.01, 0.025]))
    transition_matrix: np.ndarray = field(default_factory=lambda: np.array([[0.97, 0.03], [0.10, 0.90]]))

    # Risk limits per regime [low_vol, high_vol]
    max_vega_per_regime: np.ndarray = field(default_factory=lambda: np.array([-50000, 25000]))  # Negative = short vega allowed
    max_gamma_per_regime: np.ndarray = field(default_factory=lambda: np.array([5000, 20000]))
    max_delta_per_regime: np.ndarray = field(default_factory=lambda: np.array([10000, 5000]))

    def __post_init__(self):
        self.K = len(self.regime_means)
        self.p_filtered = np.ones(self.K) / self.K
        self.positions: List[OptionPosition] = []
        self.filter = OnlineRegimeFilter(
            transition_matrix=self.transition_matrix,
            emission_means=self.regime_means,
            emission_stds=self.regime_vols,
        )

    @staticmethod
    def bs_greeks(S: float, K: float, T: float, r: float, sigma: float, option_type: str = 'call') -> dict:
        """Black-Scholes Greeks for a single option."""
        if T <= 0:
            return {'price': max(S - K, 0) if option_type == 'call' else max(K - S, 0),
                    'delta': 0, 'gamma': 0, 'vega': 0, 'theta': 0}

        d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)

        phi_d1 = norm.pdf(d1)

        if option_type == 'call':
            price = S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
            delta = norm.cdf(d1)
        else:
            price = K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)
            delta = norm.cdf(d1) - 1

        gamma = phi_d1 / (S * sigma * np.sqrt(T))
        vega = S * phi_d1 * np.sqrt(T)  # Per unit vol change
        theta = (-(S * phi_d1 * sigma) / (2 * np.sqrt(T)) - r * K * np.exp(-r * T) * norm.cdf(d2)) / 252

        return {'price': price, 'delta': delta, 'gamma': gamma, 'vega': vega, 'theta': theta}

    def regime_adjusted_greeks(self, S: float, K: float, T: float, r: float, option_type: str) -> dict:
        """
        Compute Greeks averaged over regime posterior probabilities.
        Returns both individual regime Greeks and weighted average.
        """
        regime_greeks = []
        for k in range(self.K):
            greeks_k = self.bs_greeks(S, K, T, r, self.regime_vols[k], option_type)
            regime_greeks.append(greeks_k)

        # Weighted average (regime-posterior-weighted)
        avg_greeks = {}
        for key in ['price', 'delta', 'gamma', 'vega', 'theta']:
            avg_greeks[key] = sum(
                self.p_filtered[k] * regime_greeks[k][key]
                for k in range(self.K)
            )

        avg_greeks['regime_greeks'] = regime_greeks
        avg_greeks['regime_probs'] = self.p_filtered.copy()

        return avg_greeks

    def update_regime(self, observation: float) -> np.ndarray:
        """ Update regime probabilities with new market observation. """
        self.p_filtered = self.filter.update(observation)
        return self.p_filtered

    def compute_portfolio_greeks(self, S: float, r: float) -> dict:
        """ Compute aggregate portfolio Greeks across all positions. """
        total_delta = total_gamma = total_vega = total_theta = 0.0

        for pos in self.positions:
            greeks = self.regime_adjusted_greeks(
                S, pos.strike, pos.maturity, r, pos.option_type
            )
            total_delta += greeks['delta'] * pos.quantity
            total_gamma += greeks['gamma'] * pos.quantity
            total_vega += greeks['vega'] * pos.quantity
            total_theta += greeks['theta'] * pos.quantity

        return {
            'delta': total_delta,
            'gamma': total_gamma,
            'vega': total_vega,
            'theta': total_theta,
        }

    def compute_regime_risk_limits(self) -> dict:
        """
        Compute current risk limits as regime-probability-weighted
        average of per-regime limits.
        """
        max_vega = sum(
            self.p_filtered[k] * self.max_vega_per_regime[k]
            for k in range(self.K)
        )
        max_gamma = sum(
            self.p_filtered[k] * self.max_gamma_per_regime[k]
            for k in range(self.K)
        )
        max_delta = sum(
            self.p_filtered[k] * self.max_delta_per_regime[k]
            for k in range(self.K)
        )
        return {'max_vega': max_vega, 'max_gamma': max_gamma, 'max_delta': max_delta}

    def delta_hedge_size(self, S: float, r: float) -> float:
        """
        Compute the shares of underlying needed to delta-neutralise
        the portfolio, using regime-adjusted deltas.
        """
        port_greeks = self.compute_portfolio_greeks(S, r)
        # Hedge = -delta (buy underlying to offset short delta from options)
        return -port_greeks['delta']

    def regime_signal(self) -> str:
        """
        Generate human-readable regime trading signal.
        Returns actionable signal for the trading desk.
        """
        k = np.argmax(self.p_filtered)
        p_max = self.p_filtered[k]

        if p_max < 0.6:
            return "UNCERTAIN: Regime probability below 60%, reduce position size"

        if k == 0:  # Low-vol regime
            return (f"LOW-VOL REGIME ({p_max:.0%} confidence): "
                    f"Short vol strategies, sell straddles / strangles, "
                    f"target negative vega. Regime vol: {self.regime_vols[0]*np.sqrt(252):.1%}")
        else:  # High-vol regime
            return (f"HIGH-VOL REGIME ({p_max:.0%} confidence): "
                    f"Long vol / tail hedges, buy puts, reduce short gamma. "
                    f"Regime vol: {self.regime_vols[1]*np.sqrt(252):.1%}")

    @property
    def current_regime_vol(self) -> float:
        """Regime-weighted vol estimate for the current market state."""
        return float(self.p_filtered @ self.regime_vols)

# Example usage
engine = RegimeAdaptiveEngine(
    regime_means=np.array([0.0003, -0.0012]),
    regime_vols=np.array([0.008, 0.024]),
    transition_matrix=np.array([[0.97, 0.03], [0.10, 0.90]])
)

# Add some positions
engine.positions = [
    OptionPosition(100, 0.25, 'put', -10, 100, 0.15),
    OptionPosition(105, 0.25, 'call', -10, 100, 0.15),
]

# Simulate market update
for ret in np.random.normal(0, 0.008, 50):
    probs = engine.update_regime(ret)

print(engine.regime_signal())
print(f"Regime-weighted vol: {engine.current_regime_vol * np.sqrt(252):.2%}")
print(f"Risk limits: {engine.compute_regime_risk_limits()}")


class BaseRegimeModel(ABC):
    """Abstract base class for all regime detection models."""

    @abstractmethod
    def fit(self, data: pd.DataFrame) -> 'BaseRegimeModel':
        pass

    @abstractmethod
    def predict_proba(self, snapshot: MarketSnapshot) -> np.ndarray:
        """Return regime probability vector."""
        pass

    @abstractmethod
    def update(self, snapshot: MarketSnapshot) -> np.ndarray:
        """Real-time Bayesian update with new observation."""
        pass

    @property
    @abstractmethod
    def n_regimes(self) -> int:
        pass

class HMMRegimeModel(BaseRegimeModel):
    """HMM-based regime model (wraps GaussianHMM)."""

    def __init__(self, n_states: int = 3):
        self._n_regimes = n_states
        self.hmm = None
        self.online_filter = None
        self.feature_scaler = StandardScaler()

    @property
    def n_regimes(self) -> int:
        return self._n_regimes

    def fit(self, data: pd.DataFrame) -> 'HMMRegimeModel':
        X = self.feature_scaler.fit_transform(data.values)
        # Fit on single most discriminating feature (returns)
        self.hmm = GaussianHMM(n_states=self._n_regimes)
        self.hmm.fit(data['return'].values)

        self.online_filter = OnlineRegimeFilter(
            transition_matrix=self.hmm.A,
            emission_means=self.hmm.mu,
            emission_stds=self.hmm.sigma,
        )
        return self

    def predict_proba(self, snapshot: MarketSnapshot) -> np.ndarray:
        return self.online_filter.p_filtered.copy()

    def update(self, snapshot: MarketSnapshot) -> np.ndarray:
        return self.online_filter.update(snapshot.spx_return)


@dataclass
class MarketSnapshot:
    """Real-time market snapshot for regime computation."""
    timestamp: datetime
    spx_return: float
    vix: float
    vix_3m: float          # 3-month VIX (VXV)
    ig_spread: float       # IG credit spread (OAS)
    hy_spread: float       # HY credit spread (OAS)
    ted_spread: float      # LIBOR-T-Bill spread
    equity_bond_corr: float # 63-day rolling SPX-TLT corr
    spx_rv_21d: float      # 21-day realized vol (ann.)
    skew_index: float      # Put-call skew (CBOE SKEW)
    vvix: float            # VIX of VIX
    put_call_ratio: float  # Equity PCR

    @property
    def vrp(self) -> float:
        """Volatility risk premium."""
        return self.vix - self.spx_rv_21d * 100

    @property
    def vix_term_struct(self) -> float:
        """VIX term structure ratio (spot/3m)."""
        return self.vix / (self.vix_3m + 1e-8)

    def to_feature_vector(self) -> np.ndarray:
        """Convert to standardised feature vector for model input."""
        return np.array([
            self.spx_return,
            self.vix,
            self.vix_3m,
            self.vix_term_struct,  # Derived feature
            self.ig_spread,
            self.hy_spread,
            self.ted_spread,
            self.equity_bond_corr,
            self.spx_rv_21d,
            self.vrp,              # Derived feature
            self.skew_index,
            self.vvix,
            self.put_call_ratio,
        ])


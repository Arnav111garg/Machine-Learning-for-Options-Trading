class EnsembleRegimeSystem:
    """
    Ensemble of multiple regime models.
    Combines HMM, ML classifier, and stress detector
    into a single regime signal.
    """

    def __init__(self, models: Dict[str, BaseRegimeModel], weights: Optional[Dict[str, float]] = None):
        self.models = models
        self.weights = weights or {k: 1.0 / len(models) for k in models}
        self.regime_history: List[np.ndarray] = []
        self.last_snapshot: Optional[MarketSnapshot] = None

    def update_all(self, snapshot: MarketSnapshot) -> np.ndarray:
        """
        Update all models with new observation.
        Returns ensemble regime probability vector.
        """
        individual_probs = {}
        for name, model in self.models.items():
            try:
                probs = model.update(snapshot)
                individual_probs[name] = probs
            except Exception as e:
                logger.warning(f"Model {name} failed: {e}; skipping.")

        if not individual_probs:
            # Fallback: uniform distribution
            n = list(self.models.values())[0].n_regimes
            return np.ones(n) / n

        # Weighted average
        ensemble_probs = np.zeros_like(list(individual_probs.values())[0])
        total_weight = 0.0
        for name, probs in individual_probs.items():
            w = self.weights.get(name, 1.0)
            ensemble_probs += w * probs
            total_weight += w

        ensemble_probs /= total_weight
        self.regime_history.append(ensemble_probs.copy())
        self.last_snapshot = snapshot
        return ensemble_probs

    def current_regime_signal(self) -> dict:
        """
        Generate structured regime signal for trading desk.
        """
        if not self.regime_history:
            return {'regime': 'UNKNOWN', 'confidence': 0.0}

        p = self.regime_history[-1]
        k = int(np.argmax(p))
        confidence = float(p[k])

        regime_names = ['LOW_VOL', 'NORMAL', 'STRESS', 'CRISIS']
        regime_name = regime_names[k] if k < len(regime_names) else f'REGIME_{k}'

        return {
            'regime': regime_name,
            'confidence': confidence,
            'probs': dict(zip(regime_names[:len(p)], p.tolist())),
            'entropy': float(-np.sum(p * np.log(np.clip(p, 1e-10, None)))),
            'timestamp': self.last_snapshot.timestamp if self.last_snapshot else None,
        }

    def risk_multiplier(self, base_risk: float = 1.0) -> float:
        """
        Compute regime-appropriate risk multiplier for position sizing.

        Low-vol: 1.2x risk (can lever up in calm markets)
        Normal: 1.0x risk (base case)
        Stress: 0.6x risk (reduce exposure)
        Crisis: 0.2x risk (emergency de-risk)
        """
        risk_factors = np.array([1.2, 1.0, 0.6, 0.2])
        if not self.regime_history:
            return base_risk
        p = self.regime_history[-1]
        # Weighted risk factor
        n = min(len(p), len(risk_factors))
        multiplier = float(p[:n] @ risk_factors[:n])
        return base_risk * multiplier

    def generate_trading_brief(self) -> str:
        """
        Generate morning brief for the trading desk.
        Format used at tier-1 quant funds.
        """
        signal = self.current_regime_signal()
        risk_mult = self.risk_multiplier()

        brief = f"""
REGIME DETECTION BRIEF
======================
Timestamp : {signal.get('timestamp', 'N/A')}
Current Regime : {signal['regime']}
Confidence : {signal['confidence']:.1%}
Entropy : {signal['entropy']:.3f} (0= certain, {np.log(4):.2f}= max uncertain)

REGIME PROBABILITIES :
{chr(10).join(f' {k}: {v:.1%}' for k, v in signal['probs'].items())}

RISK POSTURE :
Risk Multiplier : {risk_mult:.2f}x base
Action : {'NORMAL TRADING' if risk_mult > 0.8 else 'REDUCE EXPOSURE' if risk_mult > 0.4 else 'EMERGENCY DE-RISK'}

OPTIONS DESK GUIDANCE :
Target Vega : {'SHORT (sell vol)' if signal['regime'] == 'LOW_VOL' else 'FLAT (neutral)' if signal['regime'] == 'NORMAL' else 'LONG (buy vol)'}
Delta Hedging : Use regime-adjusted delta (see Vol Report)
Preferred Structures : {'Iron Condors / Short Strangles' if signal['regime'] == 'LOW_VOL' else 'Long Puts / Put Spreads' if signal['regime'] in ('STRESS', 'CRISIS') else 'Balanced / Butterflies'}
"""
        return brief


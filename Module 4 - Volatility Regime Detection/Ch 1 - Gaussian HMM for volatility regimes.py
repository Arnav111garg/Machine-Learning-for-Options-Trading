def generate_synthetic_spx(T: int = 2000, seed: int = 42) -> Tuple[np.ndarray, np.ndarray]:
    """Generate synthetic 2-regime SPX daily returns."""
    rng = np.random.RandomState(seed)
    # True parameters
    A_true = np.array([[0.97, 0.03], [0.10, 0.90]])
    mu_true = [0.0005, -0.001]
    sig_true = [0.008, 0.025]
    pi_true = [0.75, 0.25]

    # Simulate Markov chain
    states = np.zeros(T, dtype=int)
    states[0] = rng.choice(2, p=pi_true)
    for t in range(1, T):
        states[t] = rng.choice(2, p=A_true[states[t - 1]])

    # Simulate returns
    returns = np.array([
        rng.normal(mu_true[s], sig_true[s]) for s in states
    ])
    return returns, states

# Fit HMM
returns, true_states = generate_synthetic_spx(T=2000)
hmm = GaussianHMM(n_states=2, n_iter=500, tol=1e-8)
hmm.fit(returns)


import numpy as np
from scipy.stats import norm
from scipy.special import logsumexp
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches
from typing import Tuple, List, Optional
import warnings

class GaussianHMM:
    """
    Gaussian HMM for Volatility Regime Detection.

    Implements Baum-Welch (EM), Forward-Backward, and Viterbi
    with log-scaling to prevent numerical underflow.

    Parameters
    ----------
    n_states : int
        Number of hidden states (regimes).
    n_iter : int
        Maximum EM iterations.
    tol : float
        Convergence tolerance on log-likelihood.
    """

    def __init__(self, n_states: int = 2, n_iter: int = 200,
                 tol: float = 1e-6, random_state: int = 42):
        self.n_states = n_states
        self.n_iter = n_iter
        self.tol = tol
        self.rng = np.random.RandomState(random_state)

    def _init_params(self, X: np.ndarray) -> None:
        """K-means initialisation for means; uniform for transition."""
        K = self.n_states
        # Transition matrix: slight self-persistence
        self.A = np.full((K, K), (1 - 0.9) / (K - 1))
        np.fill_diagonal(self.A, 0.9)
        # Initial distribution
        self.pi0 = np.ones(K) / K
        # Emission parameters: partition data into K quantiles
        quantiles = np.linspace(0, 100, K + 1)
        self.mu = np.array([
            np.percentile(X, (quantiles[i] + quantiles[i + 1]) / 2)
            for i in range(K)
        ])
        self.sigma = np.full(K, np.std(X))

    def _log_emission(self, X: np.ndarray) -> np.ndarray:
        """Log emission probabilities: shape (T, K)."""
        T = len(X)
        log_b = np.zeros((T, self.n_states))
        for k in range(self.n_states):
            log_b[:, k] = norm.logpdf(X, loc=self.mu[k], scale=self.sigma[k])
        return log_b

    def _forward_log(self, log_b: np.ndarray) -> Tuple[np.ndarray, float]:
        """
        Log-scaled forward algorithm.
        Returns log_alpha (T, K) and log-likelihood.
        """
        T, K = log_b.shape
        log_alpha = np.zeros((T, K))
        log_A = np.log(self.A + 1e-300)
        log_pi0 = np.log(self.pi0 + 1e-300)

        # Initialization
        log_alpha[0] = log_pi0 + log_b[0]

        # Recursion
        for t in range(1, T):
            for j in range(K):
                log_alpha[t, j] = logsumexp(
                    log_alpha[t - 1] + log_A[:, j]
                ) + log_b[t, j]

        log_likelihood = logsumexp(log_alpha[-1])
        return log_alpha, log_likelihood

    def _backward_log(self, log_b: np.ndarray) -> np.ndarray:
        """Log-scaled backward algorithm. Returns log_beta (T, K)."""
        T, K = log_b.shape
        log_beta = np.zeros((T, K))
        log_A = np.log(self.A + 1e-300)
        # Initialization
        log_beta[-1] = 0.0 # log(1) = 0

        # Recursion
        for t in range(T - 2, -1, -1):
            for i in range(K):
                log_beta[t, i] = logsumexp(
                    log_A[i, :] + log_b[t + 1, :] + log_beta[t + 1, :]
                )
        return log_beta

    def _e_step(self, X: np.ndarray) -> Tuple[np.ndarray, np.ndarray, float]:
        """E-Step: compute gamma (smoothed) and xi (joint) posteriors."""
        T = len(X)
        K = self.n_states
        log_b = self._log_emission(X)
        log_alpha, log_lik = self._forward_log(log_b)
        log_beta = self._backward_log(log_b)
        log_A = np.log(self.A + 1e-300)

        # Smoothed state probabilities gamma_t (k)
        log_gamma = log_alpha + log_beta
        log_gamma -= logsumexp(log_gamma, axis=1, keepdims=True)
        gamma = np.exp(log_gamma)

        # Joint transition probabilities xi_t (i,j)
        log_xi = np.zeros((T - 1, K, K))
        for t in range(T - 1):
            for i in range(K):
                for j in range(K):
                    log_xi[t, i, j] = (
                        log_alpha[t, i] + log_A[i, j] +
                        log_b[t + 1, j] + log_beta[t + 1, j]
                    )
            log_xi[t] -= logsumexp(log_xi[t].flatten())
        xi = np.exp(log_xi)

        return gamma, xi, log_lik

    def _m_step(self, X: np.ndarray, gamma: np.ndarray,
                xi: np.ndarray) -> None:
        """M-Step: update all parameters."""
        # Initial distribution
        self.pi0 = gamma[0] / gamma[0].sum()

        # Transition matrix
        self.A = xi.sum(axis=0)
        self.A /= self.A.sum(axis=1, keepdims=True)

        # Emission parameters
        for k in range(self.n_states):
            w = gamma[:, k]
            self.mu[k] = np.dot(w, X) / w.sum()
            self.sigma[k] = np.sqrt(
                np.dot(w, (X - self.mu[k]) ** 2) / w.sum()
            )

    def fit(self, X: np.ndarray) -> 'GaussianHMM':
        """Fit HMM via Baum-Welch EM algorithm."""
        self._init_params(X)
        log_lik_prev = -np.inf
        self.log_likelihoods_ = []

        for iteration in range(self.n_iter):
            gamma, xi, log_lik = self._e_step(X)
            self._m_step(X, gamma, xi)
            self.log_likelihoods_.append(log_lik)

            if abs(log_lik - log_lik_prev) < self.tol:
                print(f"Converged at iteration {iteration + 1}")
                break
            log_lik_prev = log_lik

        # Sort states by sigma (low vol = state 0, high vol = state 1)
        order = np.argsort(self.sigma)
        self.mu = self.mu[order]
        self.sigma = self.sigma[order]
        self.A = self.A[np.ix_(order, order)]
        self.pi0 = self.pi0[order]

        # Final smoothed probabilities and regime labels
        self.gamma_, _, self.log_likelihood_ = self._e_step(X)
        self.regime_labels_ = np.argmax(self.gamma_, axis=1)
        return self

    def viterbi(self, X: np.ndarray) -> np.ndarray:
        """Viterbi algorithm: most likely state sequence."""
        T = len(X)
        K = self.n_states
        log_b = self._log_emission(X)
        log_A = np.log(self.A + 1e-300)
        log_pi0 = np.log(self.pi0 + 1e-300)

        log_delta = np.zeros((T, K))
        psi = np.zeros((T, K), dtype=int)

        log_delta[0] = log_pi0 + log_b[0]

        for t in range(1, T):
            for j in range(K):
                candidates = log_delta[t - 1] + log_A[:, j]
                psi[t, j] = np.argmax(candidates)
                log_delta[t, j] = candidates[psi[t, j]] + log_b[t, j]

        # Backtrack
        states = np.zeros(T, dtype=int)
        states[-1] = np.argmax(log_delta[-1])
        for t in range(T - 2, -1, -1):
            states[t] = psi[t + 1, states[t + 1]]
        return states

    def predict_proba(self, X: np.ndarray) -> np.ndarray:
        """Real-time filtered probabilities (causal, no lookahead)."""
        T = len(X)
        K = self.n_states
        log_b = self._log_emission(X)
        log_alpha, _ = self._forward_log(log_b)
        # Normalise to get filtered probabilities
        log_filter = log_alpha - logsumexp(log_alpha, axis=1, keepdims=True)
        return np.exp(log_filter)

    def bic(self, X: np.ndarray) -> float:
        """Bayesian Information Criterion."""
        K = self.n_states
        n_params = K ** 2 + K # transitions + means + variances
        _, log_lik = self._forward_log(self._log_emission(X))
        return -2 * log_lik + n_params * np.log(len(X))

    @property
    def regime_durations_(self) -> dict:
        """Expected duration in each regime."""
        return {k: 1 / (1 - self.A[k, k]) for k in range(self.n_states)}

    @property
    def stationary_dist_(self) -> np.ndarray:
        """Stationary distribution of the Markov chain."""
        eigvals, eigvecs = np.linalg.eig(self.A.T)
        idx = np.argmin(np.abs(eigvals - 1.0))
        pi = np.real(eigvecs[:, idx])
        return pi / pi.sum()


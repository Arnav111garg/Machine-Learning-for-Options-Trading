import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier, GradientBoostingClassifier
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import TimeSeriesSplit, cross_val_score
from sklearn.metrics import classification_report, roc_auc_score
from sklearn.calibration import CalibratedClassifierCV
import xgboost as xgb
from typing import Dict, List, Tuple, Optional

class MarketStressDetector:
    """
    Multi-signal market stress detection system.

    Combines fundamental stress indicators with ML classification
    to generate regime-aware stress probability scores.

    Stress levels:
    0 = Normal (VIX < 20)
    1 = Elevated (VIX 20-30)
    2 = High Stress (VIX 30-40)
    3 = Crisis (VIX > 40)
    """
    def __init__(self, n_stress_levels: int = 4, model_type: str = 'xgboost'):
        self.n_stress_levels = n_stress_levels
        self.model_type = model_type
        self.scaler = StandardScaler()
        self.model = None
        self.feature_names = None

    def create_stress_labels(self, vix: np.ndarray, thresholds: List[float] = [20, 30, 40]) -> np.ndarray:
        """Create stress level labels from VIX."""
        labels = np.zeros(len(vix), dtype=int)
        for i, thresh in enumerate(thresholds):
            labels[vix >= thresh] = i + 1
        return labels

    def build_stress_features(self,
                              vix: np.ndarray,
                              returns: np.ndarray,
                              credit_spread: Optional[np.ndarray] = None,
                              ted_spread: Optional[np.ndarray] = None) -> pd.DataFrame:
        """
        Construct comprehensive stress feature matrix.
        """
        n = len(vix)
        df = pd.DataFrame(index=range(n))

        # VIX-based features
        df['vix'] = vix
        df['vix_ma5'] = pd.Series(vix).rolling(5).mean()
        df['vix_ma21'] = pd.Series(vix).rolling(21).mean()
        df['vix_zscore_63'] = ((pd.Series(vix) - pd.Series(vix).rolling(63).mean()) / pd.Series(vix).rolling(63).std())
        df['vix_pct_change_1d'] = pd.Series(vix).pct_change(1)
        df['vix_pct_change_5d'] = pd.Series(vix).pct_change(5)

        # VIX term structure proxy (VIX level vs 6M average)
        df['vix_term_struct'] = vix / (pd.Series(vix).rolling(126).mean())

        # Return-based features
        df['rv_5d'] = (pd.Series(returns).rolling(5).std() * np.sqrt(252))
        df['rv_21d'] = (pd.Series(returns).rolling(21).std() * np.sqrt(252))
        df['rv_63d'] = (pd.Series(returns).rolling(63).std() * np.sqrt(252))
        df['ret_skew_21d'] = pd.Series(returns).rolling(21).skew()
        df['ret_kurt_21d'] = pd.Series(returns).rolling(21).kurt()
        df['max_drawdown_21d'] = pd.Series(returns).rolling(21).apply(
            lambda x: (x.cumsum() - x.cumsum().cummax()).min(),
            raw=False
        )

        # VRP: VIX vs realized vol spread
        df['vrp_21d'] = vix - df['rv_21d']

        # Regime indicators
        df['vix_above_20'] = (vix > 20).astype(int)
        df['vix_above_30'] = (vix > 30).astype(int)
        df['rv_spike'] = (df['rv_5d'] > 2 * df['rv_63d']).astype(int)

        # Credit spread features (if available)
        if credit_spread is not None:
            df['credit_spread'] = credit_spread
            df['credit_spread_chg'] = pd.Series(credit_spread).diff(5)
            df['credit_spread_zscore'] = (
                (pd.Series(credit_spread) - pd.Series(credit_spread).rolling(126).mean())
                / pd.Series(credit_spread).rolling(126).std()
            )

        # TED spread (funding stress)
        if ted_spread is not None:
            df['ted_spread'] = ted_spread
            df['ted_spread_chg'] = pd.Series(ted_spread).diff(1)

        return df.dropna()

    def fit(self, X: pd.DataFrame, y: np.ndarray, n_splits: int = 5) -> 'MarketStressDetector':
        """
        Fit stress detection model with time-series cross-validation.
        """
        self.feature_names = list(X.columns)
        X_arr = X.values

        # Scale features
        X_scaled = self.scaler.fit_transform(X_arr)

        if self.model_type == 'xgboost':
            base_model = xgb.XGBClassifier(
                n_estimators=300,
                max_depth=4,
                learning_rate=0.05,
                subsample=0.8,
                colsample_bytree=0.8,
                objective='multi:softprob',
                num_class=self.n_stress_levels,
                use_label_encoder=False,
                eval_metric='mlogloss',
                random_state=42
            )
        elif self.model_type == 'random_forest':
            base_model = RandomForestClassifier(
                n_estimators=500,
                max_depth=6,
                min_samples_leaf=20,
                class_weight='balanced',
                random_state=42
            )
        else:
            raise ValueError(f"Unknown model_type: {self.model_type}")

        # Calibrate probabilities (Platt scaling)
        self.model = CalibratedClassifierCV(
            base_model, method='isotonic', cv=3
        )

        # Time-series cross-validation
        tscv = TimeSeriesSplit(n_splits=n_splits)
        cv_aucs = []
        for train_idx, val_idx in tscv.split(X_scaled):
            X_train, X_val = X_scaled[train_idx], X_scaled[val_idx]
            y_train, y_val = y[train_idx], y[val_idx]
            self.model.fit(X_train, y_train)
            proba = self.model.predict_proba(X_val)
            # One-vs-Rest AUC
            try:
                auc = roc_auc_score(y_val, proba, multi_class='ovr')
                cv_aucs.append(auc)
            except Exception:
                pass

        print(f"Cross-validated OVR AUC: {np.mean(cv_aucs):.4f} +/- {np.std(cv_aucs):.4f}")

        # Final fit on all data
        self.model.fit(X_scaled, y)

        # Feature importances
        if hasattr(self.model.estimator, 'feature_importances_'):
            self.feature_importances_ = self.model.estimator.feature_importances_
        return self

    def predict_stress_proba(self, X: pd.DataFrame) -> np.ndarray:
        """Returns probability of each stress level."""
        X_scaled = self.scaler.transform(X.values)
        return self.model.predict_proba(X_scaled)

    def stress_score(self, X: pd.DataFrame) -> np.ndarray:
        """
        Scalar stress score in [0, 1].
        Weighted sum of stress-level probabilities.
        """
        proba = self.predict_stress_proba(X)
        weights = np.arange(self.n_stress_levels) / (self.n_stress_levels - 1)
        return proba @ weights

    def top_stress_features(self, n: int = 10) -> pd.Series:
        """Return top N most important features for stress detection."""
        return (
            pd.Series(self.feature_importances_, index=self.feature_names)
            .sort_values(ascending=False)
            .head(n)
        )


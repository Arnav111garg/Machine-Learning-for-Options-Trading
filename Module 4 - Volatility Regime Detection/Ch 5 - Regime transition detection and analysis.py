import numpy as np
import pandas as pd
from scipy.stats import weibull_min, lognorm, expon
from lifelines import WeibullFitter, KaplanMeierFitter, CoxPHFitter
from typing import List, Dict, Optional

class RegimeTransitionAnalyzer:
    """
    Analyzes regime transitions, fits duration distributions,
    and computes time-varying transition probabilities.
    """
    def __init__(self, n_regimes: int = 2):
        self.n_regimes = n_regimes

    def extract_regime_episodes(self,
                                labels: np.ndarray,
                                dates: Optional[pd.DatetimeIndex] = None) -> pd.DataFrame:
        """
        Extract regime episodes (start, end, duration, from_regime, to_regime).
        """
        episodes = []
        T = len(labels)
        t = 0

        while t < T:
            current_regime = labels[t]
            start = t

            while t < T and labels[t] == current_regime:
                t += 1

            end = t - 1
            duration = end - start + 1
            to_regime = labels[t] if t < T else None

            episode = {
                'start_idx': start,
                'end_idx': end,
                'duration': duration,
                'regime': current_regime,
                'to_regime': to_regime,
                'censored': (t >= T),  # Last episode may be censored
            }

            if dates is not None:
                episode['start_date'] = dates[start]
                episode['end_date'] = dates[end]

            episodes.append(episode)

        return pd.DataFrame(episodes)

    def fit_duration_distributions(self, episodes: pd.DataFrame) -> Dict[int, dict]:
        """
        Fit duration distributions for each regime.
        Compares Exponential, Weibull, and Log-normal.
        """
        results = {}

        for regime in range(self.n_regimes):
            mask = episodes['regime'] == regime
            durations = episodes.loc[mask, 'duration'].values
            censored = episodes.loc[mask, 'censored'].values

            if len(durations) < 5:
                continue

            regime_results = {}

            # Weibull fit via MLE
            c_arr = 1 - censored.astype(int)  # 1=observed, 0=censored

            # Kaplan-Meier
            kmf = KaplanMeierFitter()
            kmf.fit(durations, event_observed=c_arr, label=f'Regime {regime}')
            regime_results['kaplan_meier'] = kmf

            # Weibull
            wf = WeibullFitter()
            wf.fit(durations, event_observed=c_arr)
            regime_results['weibull'] = {
                'lambda': wf.lambda_,
                'rho': wf.rho_,
                'median': wf.median_survival_time_,
                'aic': wf.AIC_,
            }

            # Test for memorylessness (Weibull rho ~ 1 => exponential)
            regime_results['is_memoryless'] = abs(wf.rho_ - 1.0) < 0.2

            # Empirical statistics
            regime_results['empirical'] = {
                'mean': durations.mean(),
                'median': np.median(durations),
                'std': durations.std(),
                'min': durations.min(),
                'max': durations.max(),
                'n_episodes': len(durations),
            }

            results[regime] = regime_results

        return results

    def compute_transition_matrix(self,
                                  labels: np.ndarray,
                                  time_varying: bool = False,
                                  covariates: Optional[np.ndarray] = None) -> np.ndarray:
        """
        Estimate transition matrix from label sequence.
        If time_varying and covariates provided, estimates
        a logistic regression transition model.
        """
        K = self.n_regimes

        if not time_varying:
            # Count transitions
            counts = np.zeros((K, K))
            for t in range(len(labels) - 1):
                counts[labels[t], labels[t + 1]] += 1
            # Row-normalise
            row_sums = counts.sum(axis=1, keepdims=True)
            A = counts / np.where(row_sums == 0, 1, row_sums)
            return A
        else:
            # Time-varying: logistic regression on covariates
            from sklearn.linear_model import LogisticRegression

            # Fit one binary model per (i,j) pair
            A_models = {}
            for i in range(K):
                mask_from_i = (labels[:-1] == i)
                X_i = covariates[:-1][mask_from_i]
                y_i = labels[1:][mask_from_i]

                if len(y_i) < 10:
                    continue

                lr = LogisticRegression(multi_class='multinomial', max_iter=1000)
                lr.fit(X_i, y_i)
                A_models[i] = lr

            return A_models

    def transition_risk_score(self,
                              current_regime: int,
                              days_in_regime: int,
                              features: np.ndarray,
                              A_models: dict) -> Dict[int, float]:
        """
        Compute probability of transitioning to each other regime
        given current state and predictive features.
        """
        if current_regime not in A_models:
            K = self.n_regimes
            return {k: 1.0 / K for k in range(K)}

        model = A_models[current_regime]
        proba = model.predict_proba(features.reshape(1, -1))[0]
        return dict(zip(model.classes_, proba))

    def plot_regime_timeline(self,
                             labels: np.ndarray,
                             dates: Optional[pd.DatetimeIndex] = None,
                             vix: Optional[np.ndarray] = None):
        """Plot regime labels over time with VIX overlay."""
        import matplotlib.pyplot as plt
        import matplotlib.patches as mpatches

        colors = ['#2ecc71', '#f39c12', '#e74c3c', '#8e44ad']
        fig, axes = plt.subplots(2, 1, figsize=(14, 7), sharex=True)

        T = len(labels)
        x = np.arange(T) if dates is None else dates

        # Regime shading
        ax1 = axes[0]
        for t in range(T - 1):
            ax1.axvspan(t, t + 1, alpha=0.3, color=colors[labels[t] % len(colors)])

        if vix is not None:
            ax1.plot(x[:len(vix)], vix, 'k-', lw=0.8, label='VIX')
            ax1.set_ylabel('VIX')

        # Regime probability or label
        ax2 = axes[1]
        unique_regimes = sorted(set(labels))
        for k in unique_regimes:
            ax2.fill_between(range(T), (labels == k).astype(float), alpha=0.7, color=colors[k % len(colors)], label=f'Regime {k}')
        ax2.set_ylabel('Regime')
        ax2.legend(loc='upper right')

        plt.tight_layout()
        return fig


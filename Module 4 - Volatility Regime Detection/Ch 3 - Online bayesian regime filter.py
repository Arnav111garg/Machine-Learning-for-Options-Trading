# Bayesian Online Change-Point Detection (BOCPD)
# =============================================================
class BOCPD:
    """
    Bayesian Online Change-Point Detection with Normal-Inverse-Gamma prior.
    Adams & MacKay (2007).

    Emission: Normal with unknown mean and variance.
    Prior: Normal-Inverse-Gamma (conjugate).
    Hazard: Constant (geometric run-lengths).
    """

    def __init__(self, hazard_lambda: float = 1/100,
                 mu0: float = 0.0, kappa0: float = 1.0,
                 alpha0: float = 1.0, beta0: float = 0.01):
        self.lam = hazard_lambda
        self.mu0 = mu0
        self.kappa0 = kappa0
        self.alpha0 = alpha0
        self.beta0 = beta0

        # Run-length distribution: dict {run_length: log_prob}
        self.R = {0: 0.0} # log p(r_0 = 0) = 0 (certain start)
        # Sufficient statistics per run-length
        self.params = {0: (mu0, kappa0, alpha0, beta0)}
        self.changepoint_probs = []

    def _log_student_t(self, x: float, mu: float, sigma_sq: float, nu: float) -> float:
        """Log PDF of Student-t predictive distribution."""
        return (
            gammaln((nu + 1) / 2) - gammaln(nu / 2)
            - 0.5 * np.log(np.pi * nu * sigma_sq)
            - ((nu + 1) / 2) * np.log(1 + (x - mu)**2 / (nu * sigma_sq))
        )

    def _predictive_log_prob(self, x: float, params: Tuple) -> float:
        """Predictive log-likelihood under Normal-Inverse-Gamma."""
        mu_n, kappa_n, alpha_n, beta_n = params
        # Predictive: Student-t with 2*alpha degrees of freedom
        nu = 2 * alpha_n
        sigma_sq_pred = beta_n * (kappa_n + 1) / (kappa_n * alpha_n)
        return self._log_student_t(x, mu_n, sigma_sq_pred, nu)

    def _update_params(self, x: float, params: Tuple) -> Tuple:
        """Bayesian update of Normal-Inverse-Gamma params with new data x."""
        mu_n, kappa_n, alpha_n, beta_n = params
        kappa_np1 = kappa_n + 1
        mu_np1 = (kappa_n * mu_n + x) / kappa_np1
        alpha_np1 = alpha_n + 0.5
        beta_np1 = beta_n + 0.5 * kappa_n / kappa_np1 * (x - mu_n)**2
        return (mu_np1, kappa_np1, alpha_np1, beta_np1)

    def update(self, x: float) -> Tuple[float, dict]:
        """
        Update with new observation x.
        Returns (prob of change-point at t, run-length distribution).
        """
        new_R = {}
        new_params = {}

        # Compute log-predictive probs for each run-length
        log_pred = {
            r: self._predictive_log_prob(x, self.params[r])
            for r in self.R
        }

        # Change-point probability (r_t = 0)
        log_cp_prob = np.log(self.lam) + np.logaddexp.reduce([
            self.R[r] + log_pred[r] for r in self.R
        ])
        new_R[0] = log_cp_prob
        new_params[0] = (self.mu0, self.kappa0, self.alpha0, self.beta0)

        # Run-length growth (r_t = r_{t-1} + 1)
        for r in self.R:
            new_r = r + 1
            new_R[new_r] = (
                self.R[r] + log_pred[r] + np.log(1 - self.lam)
            )
            new_params[new_r] = self._update_params(x, self.params[r])

        # Normalise
        log_total = np.logaddexp.reduce(list(new_R.values()))
        self.R = {r: v - log_total for r, v in new_R.items()}
        self.params = new_params

        cp_prob = np.exp(self.R[0])
        self.changepoint_probs.append(cp_prob)
        return cp_prob, {r: np.exp(v) for r, v in self.R.items()}

# Example: Detect regime changes in synthetic VIX series
vix_changes = np.concatenate([
    np.random.normal(0.0, 0.05, 200),  # calm
    np.random.normal(0.5, 0.20, 50),   # crisis onset
    np.random.normal(0.0, 0.15, 150),  # elevated
    np.random.normal(-0.2, 0.08, 100), # recovery
])

bocpd = BOCPD(hazard_lambda=1/50, mu0=0, kappa0=1, alpha0=2, beta0=0.05)
for v in vix_changes:
    bocpd.update(v)

print(f"Max change-point probability: {max(bocpd.changepoint_probs):.4f}")


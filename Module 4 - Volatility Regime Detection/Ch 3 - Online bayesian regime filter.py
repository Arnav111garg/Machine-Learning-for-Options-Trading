import numpy as np
from scipy.stats import norm, t as student_t
from scipy.special import gammaln
from typing import Tuple, Optional

class OnlineRegimeFilter:
    """
    Real-time Bayesian regime filter for options trading.
    Updates regime probabilities with each new observation.

    Suitable for intraday or end-of-day signal generation.
    """

    def __init__(self, transition_matrix: np.ndarray,
                 emission_means: np.ndarray,
                 emission_stds: np.ndarray,
                 initial_probs: Optional[np.ndarray] = None):
        self.A = transition_matrix # (K, K)
        self.mu = emission_means # (K,)
        self.sigma = emission_stds # (K,)
        self.K = len(emission_means)
        if initial_probs is None:
            self.p_filtered = np.ones(self.K) / self.K
        else:
            self.p_filtered = initial_probs.copy()

        self.history = []

    def update(self, observation: float) -> np.ndarray:
        """
        Update filtered probabilities with new observation.
        Returns regime probability vector p(s_t | y_{1:t}).

        Complexity: O(K^2) per step.
        """
        # Prediction step: p(s_t | y_{1:t-1})
        p_pred = self.A.T @ self.p_filtered

        # Emission probabilities
        b = np.array([
            norm.pdf(observation, loc=self.mu[k], scale=self.sigma[k])
            for k in range(self.K)
        ])

        # Update step (Bayes rule)
        p_unnorm = b * p_pred
        normaliser = p_unnorm.sum()

        if normaliser < 1e-300:
            # Numerical issue: return prediction
            self.p_filtered = p_pred
        else:
            self.p_filtered = p_unnorm / normaliser

        # Store history
        self.history.append({
            'filtered_probs': self.p_filtered.copy(),
            'observation': observation,
            'normaliser': normaliser,
        })

        return self.p_filtered

    @property
    def current_regime(self) -> int:
        """Most likely current regime (MAP estimate)."""
        return int(np.argmax(self.p_filtered))

    @property
    def regime_certainty(self) -> float:
        """Certainty = max probability. High = confident regime signal."""
        return float(np.max(self.p_filtered))

    @property
    def regime_entropy(self) -> float:
        """Shannon entropy of filtered probabilities. Low = certain."""
        p = np.clip(self.p_filtered, 1e-300, None)
        return float(-np.sum(p * np.log(p)))

    def compute_log_likelihood(self, observations: np.ndarray) -> float:
        """Compute total log-likelihood of observation sequence."""
        log_lik = 0.0
        for obs in observations:
            p_pred = self.A.T @ self.p_filtered
            b = np.array([
                norm.pdf(obs, self.mu[k], self.sigma[k])
                for k in range(self.K)
            ])
            lik = (b * p_pred).sum()
            log_lik += np.log(lik + 1e-300)
            self.p_filtered = (b * p_pred) / (lik + 1e-300)
        return log_lik


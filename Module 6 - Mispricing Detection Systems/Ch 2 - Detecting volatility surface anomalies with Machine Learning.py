import numpy as np
from scipy.optimize import minimize
from scipy.interpolate import RectBivariateSpline
import warnings
from sklearn.gaussian_process import GaussianProcessRegressor
from sklearn.gaussian_process.kernels import RBF, WhiteKernel, Matern

class SVISurface:
    """
    SVI (Stochastic Volatility Inspired) surface fitting.
    Used for smooth surface representation and anomaly detection.
    """

    def __init__(self):
        self.params_per_slice = {} # {T: [a, b, rho, m, sigma]}
        self.fitted_surfaces = {}

    @staticmethod
    def svi_total_var(k, a, b, rho, m, sigma):
        """SVI total variance: w(k) = a + b[rho(k-m) + sqrt((k-m)^2 + sigma^2)]"""
        term = rho * (k - m) + np.sqrt((k - m)**2 + sigma**2)
        return a + b * term

    @staticmethod
    def svi_vol(k, a, b, rho, m, sigma, T):
        """SVI implied vol: sigma_iv = sqrt(w(k) / T)"""
        w = SVISurface.svi_total_var(k, a, b, rho, m, sigma)
        return np.sqrt(np.maximum(w / T, 1e-10))

    def fit_slice(self, k_arr: np.ndarray, iv_arr: np.ndarray, T: float, weights: np.ndarray = None) -> dict:
        """
        Fit SVI to a single expiry slice.

        k_arr: log-moneyness array
        iv_arr: market implied vol array
        T: time to expiry (in years)
        """
        if weights is None:
            weights = np.ones(len(k_arr))

        w_mkt = iv_arr**2 * T  # Market total variance

        def objective(params):
            a, b, rho, m, sigma = params
            w_fit = self.svi_total_var(k_arr, a, b, rho, m, sigma)
            return np.sum(weights * (w_fit - w_mkt)**2)

        # No-arbitrage constraints
        def constr_positivity(params):
            a, b, rho, m, sigma = params
            return a + b * sigma * np.sqrt(1 - rho**2)  # >= 0

        constraints = [{'type': 'ineq', 'fun': constr_positivity}]
        bounds = [
            (0, 1.0),       # a: ATM total var
            (0, 2.0),       # b: vol-of-vol
            (-0.999, 0.999), # rho: correlation
            (-0.5, 0.5),    # m: ATM shift
            (0.001, 1.0),   # sigma: smoothness
        ]

        # Multi-start optimization
        best_result = None
        best_val = np.inf

        for _ in range(10):
            x0 = [
                np.mean(w_mkt),
                0.1 + 0.1 * np.random.rand(),
                -0.5 + 0.3 * np.random.randn(),
                0.01 * np.random.randn(),
                0.1 + 0.05 * np.random.rand()
            ]
            result = minimize(objective, x0, method='SLSQP', bounds=bounds, constraints=constraints, options={'ftol': 1e-10, 'maxiter': 1000})
            if result.success and result.fun < best_val:
                best_val = result.fun
                best_result = result

        if best_result is None:
            warnings.warn(f"SVI fit failed for T={T:.2f}")
            return None

        a, b, rho, m, sigma = best_result.x
        self.params_per_slice[T] = best_result.x

        return {
            'params': {'a': a, 'b': b, 'rho': rho, 'm': m, 'sigma': sigma},
            'rmse': np.sqrt(best_val / len(k_arr)),
            'residuals': self.svi_total_var(k_arr, a, b, rho, m, sigma) - w_mkt
        }

    def detect_anomalies(self, k_arr: np.ndarray, iv_arr: np.ndarray, T: float, threshold_vols: float = 0.5) -> dict:
        """
        Detect surface anomalies after SVI fitting.
        Returns contracts with |residual| > threshold_vols (in vol points).
        """
        if T not in self.params_per_slice:
            self.fit_slice(k_arr, iv_arr, T)

        params = self.params_per_slice[T]
        iv_fit = self.svi_vol(k_arr, *params, T)
        residuals_vol = (iv_arr - iv_fit) * 100  # In vol points (%)

        anomalies = {
            'k': k_arr[np.abs(residuals_vol) > threshold_vols],
            'iv_mkt': iv_arr[np.abs(residuals_vol) > threshold_vols],
            'iv_fit': iv_fit[np.abs(residuals_vol) > threshold_vols],
            'residuals': residuals_vol[np.abs(residuals_vol) > threshold_vols],
            'type': np.where(residuals_vol[np.abs(residuals_vol) > threshold_vols] > 0, 'Rich', 'Cheap')
        }
        return anomalies

    def check_calendar_arbitrage(self, T1: float, T2: float, k_grid: np.ndarray) -> dict:
        """
        Check for calendar arbitrage between two expiry slices.
        Calendar arb iff w(k, T1) > w(k, T2) for any k (T2 > T1).
        """
        assert T2 > T1, "T2 must be greater than T1"
        assert T1 in self.params_per_slice and T2 in self.params_per_slice

        w1 = self.svi_total_var(k_grid, *self.params_per_slice[T1])
        w2 = self.svi_total_var(k_grid, *self.params_per_slice[T2])

        violations = k_grid[w1 > w2]
        severity = (w1 - w2)[w1 > w2]

        return {
            'has_calendar_arb': len(violations) > 0,
            'violation_strikes': violations,
            'severity': severity,
            'max_violation_vol': np.sqrt(max(severity.max(), 0) / T1) if len(severity) > 0 else 0
        }

class GPVolSurface:
    """
    Gaussian Process for IV surface: provides uncertainty estimates
    that flag potential anomalies (high uncertainty = anomalous region).
    """

    def __init__(self):
        # Kernel: smooth Matern (5/2) + white noise for residuals
        self.kernel = Matern(length_scale=[0.1, 0.5], nu=2.5) + WhiteKernel(noise_level=1e-4)
        self.gp = GaussianProcessRegressor(
            kernel=self.kernel, alpha=1e-6,
            n_restarts_optimizer=5, normalize_y=True
        )

    def fit(self, k_arr, T_arr, iv_arr):
        """Fit GP to observed IV surface points."""
        X = np.column_stack([k_arr, T_arr])
        self.gp.fit(X, iv_arr)
        return self

    def predict_with_uncertainty(self, k_arr, T_arr):
        """Predict IV + 2-sigma confidence interval."""
        X = np.column_stack([k_arr, T_arr])
        iv_pred, iv_std = self.gp.predict(X, return_std=True)
        return iv_pred, iv_std

    def flag_anomalies(self, k_new, T_new, iv_new, n_sigma=2.0):
        """Flag points outside n_sigma confidence band as anomalies."""
        iv_pred, iv_std = self.predict_with_uncertainty(k_new, T_new)
        deviation = np.abs(iv_new - iv_pred)
        anomaly_mask = deviation > n_sigma * iv_std
        return {
            'anomaly_idx': np.where(anomaly_mask)[0],
            'deviations_sigma': deviation / iv_std,
            'predicted_iv': iv_pred,
            'uncertainty_1sigma': iv_std
        }


import numpy as np
import pandas as pd
from sklearn.linear_model import Ridge
from statsmodels.tsa.stattools import adfuller, coint
from statsmodels.tsa.arima.model import ARIMA

class OptionsStatArbEngine:
    """
    Comprehensive statistical arbitrage signal generator for options markets.
    Combines multiple signals: VRP, skew mean reversion, cross-sectional IV,
    put-call parity, and cointegration-based spreads.
    """

    def __init__(self):
        self.signals = {}

    # Signal 1: VRP
    def vrp_signal(self, iv_history: pd.Series, rv_history: pd.Series, lookback: int = 60) -> float:
        """
        Variance Risk Premium signal.
        Returns z-score: positive = short var, negative = long var.
        """
        vrp = iv_history**2 - rv_history**2
        z = (vrp.iloc[-1] - vrp.rolling(lookback).mean().iloc[-1]) / vrp.rolling(lookback).std().iloc[-1]
        return float(z)

    # Signal 2: Skew Mean Reversion
    def skew_mr_signal(self, skew_history: pd.Series, lookback: int = 60) -> dict:
        """
        OU mean reversion signal for volatility skew (25d RR).
        Fits AR(1) to estimate OU parameters.
        """
        # Estimate OU via AR(1)
        skew = skew_history.dropna()
        skew_lag = skew.shift(1).dropna()
        skew_curr = skew.iloc[1:]

        # OLS: skew_t = alpha + beta * skew_{t - 1}
        beta = np.cov(skew_curr, skew_lag)[0, 1] / np.var(skew_lag)
        alpha = skew_curr.mean() - beta * skew_lag.mean()

        theta = alpha / (1 - beta)  # Long-run mean
        kappa = -np.log(beta) * 252  # Mean reversion speed (annualized)
        resid = skew_curr - (alpha + beta * skew_lag)
        sigma_ou = resid.std() * np.sqrt(252)

        # Current z-score
        current_skew = skew.iloc[-1]
        equilibrium_std = sigma_ou / np.sqrt(2 * kappa)
        z = (current_skew - theta) / (equilibrium_std + 1e-8)

        # ADF test for stationarity
        adf_stat, adf_pval, *_ = adfuller(skew.dropna())

        if z > 1.5:
            trade = 'Short RR (buy puts vs calls)'
            signal_val = -np.sign(z)
        elif z < -1.5:
            trade = 'Long RR (sell puts vs calls)'
            signal_val = -np.sign(z)
        else:
            trade = 'Flat'
            signal_val = 0

        return {
            'z_score': float(z),
            'theta_mean': float(theta),
            'kappa': float(kappa),
            'half_life_days': float(np.log(2) / kappa * 252) if kappa > 0 else np.inf,
            'equilibrium_std': float(equilibrium_std),
            'adf_pvalue': float(adf_pval),
            'is_stationary': adf_pval < 0.05,
            'signal': signal_val,
            'trade': trade
        }

    # Signal 3: Cross-Sectional IV
    def cross_sectional_iv_signal(self, iv_panel: pd.DataFrame, factor_matrix: pd.DataFrame, lookback: int = 60) -> pd.Series:
        """
        Cross-sectional IV factor-neutral residuals.
        iv_panel: (T x N) DataFrame of implied vols
        factor_matrix: (T x K) DataFrame of factor exposures
        Returns: (N,) Series of current z-scores per stock
        """
        # Rolling OLS to get factor-neutral IVs
        current_iv = iv_panel.iloc[-1]
        hist_iv = iv_panel.iloc[-lookback:]
        hist_factors = factor_matrix.iloc[-lookback:]

        # Fit cross-sectional regression
        model = Ridge(alpha=0.01)

        # For each time step, regress IV cross-section on factors
        all_residuals = []
        for t in range(len(hist_iv)):
            y = hist_iv.iloc[t].values
            X = hist_factors.iloc[t].values.reshape(1, -1).repeat(len(y), axis=0)
            # Simple: regress out market vol
            beta = np.cov(y, X[:, 0])[0, 1] / (np.var(X[:, 0]) + 1e-8)
            residuals = y - beta * X[:, 0] - np.mean(y - beta * X[:, 0])
            all_residuals.append(residuals)

        residual_matrix = np.array(all_residuals)
        res_mean = residual_matrix.mean(axis=0)
        res_std = residual_matrix.std(axis=0)

        # Current residual
        y_cur = current_iv.values
        X_cur = factor_matrix.iloc[-1].values[0]
        beta_cur = np.cov(y_cur, np.full(len(y_cur), X_cur))[0, 1] / (np.var(X_cur) + 1e-8)
        res_cur = y_cur - beta_cur * X_cur - np.mean(y_cur - beta_cur * X_cur)

        z_scores = (res_cur - res_mean) / (res_std + 1e-8)
        return pd.Series(z_scores, index=iv_panel.columns)

    # Signal 4: Put-Call Parity
    def put_call_parity_signal(self, strikes: np.ndarray, calls: np.ndarray, puts: np.ndarray, S: float, r: float, T: float, q: float = 0.0, borrow_rate: float = 0.0) -> dict:
        """
        Detect put-call parity violations.
        Returns mispricing per strike in dollar terms.
        """
        # Theoretical: C - P = S*e^{-(q+borrow)*T} - K*e^{-rT}
        theo_cp_diff = S * np.exp(-(q + borrow_rate) * T) - strikes * np.exp(-r * T)
        market_cp_diff = calls - puts

        violations = market_cp_diff - theo_cp_diff

        # Significant violations (adjust for bid-ask)
        significant = np.abs(violations) > 0.05 * S * 0.01  # > 1 bp of spot

        trades = []
        for i, (K, v, sig) in enumerate(zip(strikes, violations, significant)):
            if sig:
                if v > 0:  # Calls too expensive vs. puts
                    trades.append({
                        'strike': K,
                        'violation': v,
                        'trade': f'Sell call K={K}, Buy put K={K}, Long stock',
                        'type': 'Reverse conversion'
                    })
                else:  # Puts too expensive vs. calls
                    trades.append({
                        'strike': K,
                        'violation': v,
                        'trade': f'Buy call K={K}, Sell put K={K}, Short stock',
                        'type': 'Conversion'
                    })

        return {
            'violations_dollar': violations,
            'violations_pct': violations / S * 100,
            'significant_trades': trades,
            'max_violation': float(np.max(np.abs(violations)))
        }

    # Aggregate Signal
    def aggregate_signals(self, signal_dict: dict, weights: dict = None) -> float:
        """
        Combine multiple signals into a single composite score [-1, 1].
        signal_dict: { signal_name : z_score }
        """
        if weights is None:
            weights = {k: 1.0 / len(signal_dict) for k in signal_dict}

        # Normalize individual signals to [-1, 1]
        normalized = {k: np.tanh(v / 2) for k, v in signal_dict.items()}

        # Weighted average
        composite = sum(
            weights.get(k, 0) * v for k, v in normalized.items()
        )

        return np.clip(composite, -1, 1)


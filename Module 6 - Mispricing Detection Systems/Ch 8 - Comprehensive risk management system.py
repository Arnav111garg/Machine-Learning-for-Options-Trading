import numpy as np
import pandas as pd
from scipy.stats import norm, t as student_t
from scipy.optimize import minimize
from dataclasses import dataclass
from typing import List, Dict, Optional, Tuple

@dataclass
class Position:
    """A single options position with full Greeks."""
    ticker: str
    strike: float
    expiry: float
    option_type: str
    quantity: float  # Positive = long, negative = short
    iv: float
    delta: float
    gamma: float
    vega: float
    theta: float
    vanna: float = 0.0
    volga: float = 0.0
    cost_basis: float = 0.0

class RiskManagementSystem:
    """
    Portfolio risk management for options mispricing strategies.

    Features:
    - Greeks aggregation and limits monitoring
    - Historical and parametric VaR/ES
    - Stress testing
    - Dynamic hedging recommendations
    - P&L attribution
    """

    def __init__(self, risk_limits: dict):
        """
        risk_limits: {
            'max_delta': 50000,   # $ per 1% spot move
            'max_vega': 100000,   # $ per 1% vol move
            'max_gamma': 5000,    # $ per 1% spot move squared
            'max_theta': 10000,   # $ per day
            'var_95': 500000,     # 1-day 95% VaR
            'stop_loss': 1000000  # Daily stop
        }
        """
        self.limits = risk_limits
        self.positions = []
        self.pnl_history = []

    def add_position(self, pos: Position):
        self.positions.append(pos)

    def aggregate_greeks(self, S: float) -> dict:
        """Compute portfolio-level Greeks."""
        greeks = {'delta': 0.0, 'gamma': 0.0, 'vega': 0.0, 'theta': 0.0, 'vanna': 0.0, 'volga': 0.0}

        for pos in self.positions:
            qty = pos.quantity
            greeks['delta'] += qty * pos.delta * S
            greeks['gamma'] += qty * pos.gamma * (S ** 2) / 100
            greeks['vega'] += qty * pos.vega
            greeks['theta'] += qty * pos.theta
            greeks['vanna'] += qty * pos.vanna
            greeks['volga'] += qty * pos.volga

        return greeks

    def check_limits(self, S: float) -> dict:
        """Check current Greeks against risk limits. Return breaches."""
        greeks = self.aggregate_greeks(S)
        breaches = {}
        limit_map = {
            'delta': ('max_delta', greeks['delta']),
            'vega': ('max_vega', greeks['vega']),
            'gamma': ('max_gamma', greeks['gamma']),
            'theta': ('max_theta', greeks['theta'])
        }

        for greek, (limit_name, value) in limit_map.items():
            if limit_name in self.limits:
                limit = self.limits[limit_name]
                if abs(value) > limit:
                    breaches[greek] = {
                        'current': value,
                        'limit': limit,
                        'excess': abs(value) - limit,
                        'utilization': abs(value) / limit
                    }

        return {
            'greeks': greeks,
            'breaches': breaches,
            'all_within_limits': len(breaches) == 0
        }

    def historical_var(self, returns: np.ndarray, confidence: float = 0.99) -> Tuple[float, float]:
        """
        Historical simulation VaR and ES.

        returns: (T,) array of portfolio returns
        Returns: (VaR, ES) at given confidence level
        """
        n = len(returns)
        sorted_returns = np.sort(returns)
        var_idx = int((1 - confidence) * n)
        var = -sorted_returns[var_idx]
        es = -sorted_returns[:var_idx].mean()
        return var, es

    def parametric_var(self, greeks: dict, S: float, sigma_S: float, sigma_vol: float, rho_svol: float = -0.7, confidence: float = 0.99) -> dict:
        """
        Parametric VaR using Greeks expansion.
        Assumes: Delta S ~ N(0, S* sigma_S * sqrt(T))
                 Delta sigma ~ N(0, sigma_vol * sqrt(T))
        """
        delta = greeks['delta'] / S
        gamma = greeks['gamma']
        vega = greeks['vega']
        vanna = greeks['vanna']

        T = 1 / 252
        var_dS = (S * sigma_S) ** 2 * T
        var_dsig = sigma_vol ** 2 * T
        cov_dSsig = rho_svol * S * sigma_S * sigma_vol * T

        var_delta_pnl = (greeks['delta']) ** 2 * var_dS / (S ** 2)
        var_vega_pnl = (vega) ** 2 * var_dsig
        var_gamma_pnl = 0.5 * (gamma * (S ** 2)) ** 2 * 2 * (var_dS ** 2) / (S ** 4)
        var_vanna_pnl = 2 * vanna * greeks['delta'] * cov_dSsig

        total_var = var_delta_pnl + var_vega_pnl + var_gamma_pnl + var_vanna_pnl
        total_std = np.sqrt(max(total_var, 0))

        z_conf = norm.ppf(confidence)
        var_normal = z_conf * total_std
        es_normal = total_std * norm.pdf(z_conf) / (1 - confidence)

        skew = -1.0
        kurt = 3.0
        z_cf = z_conf + (z_conf ** 2 - 1) * skew / 6 + (z_conf ** 3 - 3 * z_conf) * kurt / 24
        var_cf = z_cf * total_std

        return {
            'var_99_normal': var_normal,
            'es_99_normal': es_normal,
            'var_99_cf': var_cf,
            'std_daily_pnl': total_std,
            'breakdown': {
                'delta_risk': np.sqrt(var_delta_pnl),
                'vega_risk': np.sqrt(var_vega_pnl),
                'gamma_risk': np.sqrt(var_gamma_pnl),
                'vanna_risk': np.sqrt(abs(var_vanna_pnl))
            }
        }

    def stress_test(self, greeks: dict, S: float) -> pd.DataFrame:
        """
        Run standardized stress scenarios.
        Returns P&L impact for each scenario.
        """
        scenarios = {
            'Vol Spike (+15%)': {'dS': 0.0, 'dvol': 0.15},
            'Vol Collapse (-8%)': {'dS': 0.0, 'dvol': -0.08},
            'Crash -10%, vol +20%': {'dS': -0.10 * S, 'dvol': 0.20},
            'Melt-up +8%, vol -5%': {'dS': 0.08 * S, 'dvol': -0.05},
            'Gap -20%, vol +40%': {'dS': -0.20 * S, 'dvol': 0.40},
            'Crisis -30%, vol +60%': {'dS': -0.30 * S, 'dvol': 0.60},
            'Vol-of-vol spike': {'dS': 0.0, 'dvol': 0.30},
            'Skew inversion': {'dS': -0.05 * S, 'dvol': 0.10}
        }

        results = []
        for name, params in scenarios.items():
            dS = params['dS']
            dvol = params['dvol']

            pnl = (
                greeks['delta'] * dS / S +
                0.5 * greeks['gamma'] * ((dS / S) ** 2) * 100 +
                greeks['vega'] * dvol * 100 +
                greeks['vanna'] * (dS / S) * dvol +
                0.5 * greeks['volga'] * (dvol ** 2)
            )

            results.append({
                'Scenario': name,
                'Spot Move': f"{params['dS'] / S * 100:.1f}%",
                'Vol Move': f"{params['dvol'] * 100:.1f}%",
                'P&L ($)': f"{pnl:,.0f}",
                'P&L (Severity)': 'CRITICAL' if abs(pnl) > self.limits.get('stop_loss', 1e8) \
                                 else 'HIGH' if abs(pnl) > 0.5 * self.limits.get('stop_loss', 1e8) \
                                 else 'MODERATE'
            })

        return pd.DataFrame(results)

    def dynamic_hedging_recommendations(self, greeks: dict, S: float, limit_utilization_threshold: float = 0.80) -> List[dict]:
        """Recommend hedging trades to bring Greeks within limits."""
        recommendations = []

        # Delta hedge
        if abs(greeks['delta']) > self.limits.get('max_delta', np.inf) * limit_utilization_threshold:
            shares_needed = -greeks['delta'] / S
            recommendations.append({
                'type': 'Delta Hedge',
                'action': f"{'Buy' if shares_needed > 0 else 'Sell'} {abs(shares_needed):.1f} shares",
                'instrument': 'Underlying (spot / futures)',
                'urgency': 'High' if abs(greeks['delta']) > self.limits.get('max_delta', np.inf) else 'Medium',
                'greek_relief': f"Delta: {greeks['delta']:.0f} -> ~0"
            })

        # Vega hedge
        if abs(greeks['vega']) > self.limits.get('max_vega', np.inf) * limit_utilization_threshold:
            var_swap_notional = -greeks['vega'] / (2 * 0.20 * 10000 / 100)
            recommendations.append({
                'type': 'Vega Hedge',
                'action': f"{'Enter long' if var_swap_notional > 0 else 'Enter short'} variance swap, notional ${abs(var_swap_notional):,.0f}",
                'instrument': 'ATM straddle or variance swap',
                'urgency': 'High' if abs(greeks['vega']) > self.limits.get('max_vega', np.inf) else 'Medium',
                'greek_relief': f"Vega: {greeks['vega']:.0f} -> ~0"
            })

        # Gamma management
        if abs(greeks['gamma']) > self.limits.get('max_gamma', np.inf) * limit_utilization_threshold:
            recommendations.append({
                'type': 'Gamma Management',
                'action': f"Reduce gamma via {'OTM long options' if greeks['gamma'] < 0 else 'short straddle'}",
                'instrument': 'OTM options',
                'urgency': 'Medium',
                'greek_relief': f"Gamma: {greeks['gamma']:.1f} -> target 0"
            })

        return recommendations

    def compute_pnl_attribution(self, S_prev: float, S_curr: float, sigma_prev: float, sigma_curr: float, T_prev: float, T_curr: float, greeks: dict) -> dict:
        """Decompose realized P&L into Greek components."""
        dS = S_curr - S_prev
        dsig = sigma_curr - sigma_prev
        dt = T_prev - T_curr

        pnl_delta = greeks['delta'] * dS / S_prev
        pnl_gamma = 0.5 * greeks['gamma'] * ((dS / S_prev) ** 2) * 100
        pnl_vega = greeks['vega'] * dsig * 100
        pnl_theta = greeks['theta'] * dt * 252
        pnl_vanna = greeks.get('vanna', 0.0) * (dS / S_prev) * dsig
        pnl_volga = 0.5 * greeks.get('volga', 0.0) * (dsig ** 2)
        pnl_total = pnl_delta + pnl_gamma + pnl_vega + pnl_theta + pnl_vanna + pnl_volga

        return {
            'delta_pnl': pnl_delta,
            'gamma_pnl': pnl_gamma,
            'vega_pnl': pnl_vega,
            'theta_pnl': pnl_theta,
            'vanna_pnl': pnl_vanna,
            'volga_pnl': pnl_volga,
            'total_pnl': pnl_total,
            'explained_ratio': abs(pnl_total) / (abs(pnl_delta) + abs(pnl_gamma) + abs(pnl_vega) + 1e-8)
        }


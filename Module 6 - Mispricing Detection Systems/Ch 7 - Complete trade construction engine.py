import numpy as np
from scipy.stats import norm
from scipy.optimize import minimize
from dataclasses import dataclass
from typing import List, Dict, Optional

@dataclass
class OptionsContract:
    """ Represents an options contract. """
    strike: float
    expiry: float       # In years
    option_type: str    # 'call' or 'put'
    iv: float           # Current implied vol
    delta: float
    gamma: float
    vega: float
    theta: float
    price: float
    bid: float
    ask: float

    @property
    def mid(self):
        return (self.bid + self.ask) / 2

    @property
    def effective_spread(self):
        return (self.ask - self.bid) / self.mid


class TradeConstructor:
    """
    Constructs optimal option trades given a mispricing signal.
    Handles delta, gamma, and vega neutralization.
    """

    def __init__(self, S: float, r: float = 0.05, q: float = 0.015):
        self.S = S
        self.r = r
        self.q = q

    def bs_greeks(self, K: float, T: float, sigma: float, option_type: str = 'call') -> dict:
        """Black-Scholes Greeks."""
        d1 = (np.log(self.S / K) + (self.r - self.q + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)

        F = self.S * np.exp((self.r - self.q) * T)

        if option_type == 'call':
            delta = np.exp(-self.q * T) * norm.cdf(d1)
            price = np.exp(-self.q * T) * self.S * norm.cdf(d1) - np.exp(-self.r * T) * K * norm.cdf(d2)
        else:
            delta = -np.exp(-self.q * T) * norm.cdf(-d1)
            price = np.exp(-self.r * T) * K * norm.cdf(-d2) - np.exp(-self.q * T) * self.S * norm.cdf(-d1)

        gamma = np.exp(-self.q * T) * norm.pdf(d1) / (self.S * sigma * np.sqrt(T))
        vega = self.S * np.exp(-self.q * T) * norm.pdf(d1) * np.sqrt(T) / 100  # Per 1% change
        theta = -(self.S * norm.pdf(d1) * sigma * np.exp(-self.q * T)) / (2 * np.sqrt(T)) \
                + (self.q * self.S * delta * np.exp(-self.q * T) \
                - (self.r if option_type == 'call' else -self.r) * np.exp(-self.r * T) * K * norm.cdf(d2 if option_type == 'call' else -d2)) / 252

        return {
            'price': price, 'delta': delta, 'gamma': gamma,
            'vega': vega, 'theta': theta
        }

    def construct_rv_trade(self, target_contract: OptionsContract, hedge_contracts: List[OptionsContract], signal_z: float, max_vega: float = 10000, target_delta: float = 0.0, target_vega: float = 0.0) -> dict:
        """
        Construct a mispricing trade:
        - Target: the mispriced contract
        - Hedges: list of fairly-priced contracts to neutralize exposures

        signal_z > 0: sell target (rich)
        signal_z < 0: buy target (cheap)

        Returns optimal trade weights.
        """
        # Direction
        direction = -np.sign(signal_z)  # Short if rich, long if cheap

        # Size target position
        signal_strength = min(abs(signal_z) / 3.0, 1.0)
        target_size = direction * signal_strength * max_vega / abs(target_contract.vega)

        # Portfolio: [target, hedge1, hedge2, ...]
        all_contracts = [target_contract] + hedge_contracts
        n = len(all_contracts)

        # Greeks matrix: (n_contracts, n_greeks)
        deltas = np.array([c.delta for c in all_contracts])
        vegas = np.array([c.vega for c in all_contracts])
        gammas = np.array([c.gamma for c in all_contracts])

        # Objective: minimize gamma exposure (sign of signal preserved)
        def objective(w_hedge):
            w = np.concatenate([[target_size], w_hedge])
            total_gamma = np.dot(w, gammas)
            return total_gamma ** 2  # Minimize net gamma

        # Constraints: delta-neutral and vega-neutral
        def delta_neutral(w_hedge):
            w = np.concatenate([[target_size], w_hedge])
            return np.dot(w, deltas) - target_delta * max_vega

        def vega_neutral(w_hedge):
            w = np.concatenate([[target_size], w_hedge])
            return np.dot(w, vegas) - target_vega * max_vega

        w0 = np.zeros(n - 1)
        constraints = [
            {'type': 'eq', 'fun': delta_neutral},
            {'type': 'eq', 'fun': vega_neutral}
        ]
        bounds = [(-max_vega, max_vega)] * (n - 1)

        result = minimize(objective, w0, method='SLSQP', bounds=bounds, constraints=constraints)

        w_hedge = result.x if result.success else w0
        w_total = np.concatenate([[target_size], w_hedge])

        # P&L attribution
        net_delta = np.dot(w_total, deltas)
        net_vega = np.dot(w_total, vegas)
        net_gamma = np.dot(w_total, gammas)
        net_theta = np.dot(w_total, [c.theta for c in all_contracts])

        # Estimate trade cost (crossing bid-ask)
        trade_cost = sum(
            abs(w) * c.effective_spread * c.mid * self.S / 100
            for w, c in zip(w_total, all_contracts)
        )

        return {
            'weights': dict(zip(
                [f"{c.option_type}_{c.strike}_{c.expiry:.3f}" for c in all_contracts],
                w_total
            )),
            'net_greeks': {
                'delta': net_delta,
                'vega': net_vega,
                'gamma': net_gamma,
                'theta': net_theta
            },
            'estimated_edge': abs(signal_z) * abs(target_contract.vega) * 0.01,
            'estimated_cost': trade_cost,
            'net_edge': abs(signal_z) * abs(target_contract.vega) * 0.01 - trade_cost,
            'optimization_success': result.success
        }

    def size_position(self, edge_dollar: float, volatility_edge: float, risk_budget_dollar: float, sharpe_target: float = 2.0) -> float:
        """
        Kelly-based position sizing.
        Kelly fraction: f* = mu / sigma^2 (for continuous time)
        Practical: use fractional Kelly (1/2 or 1/4 Kelly).
        """
        # Estimate return and volatility of the trade
        mu = edge_dollar  # Expected P&L
        sigma = risk_budget_dollar / sharpe_target  # Target vol of position

        # Kelly sizing
        kelly_full = mu / (sigma ** 2) if sigma > 0 else 0
        kelly_half = kelly_full / 2  # Conservative: 1/2 Kelly

        # Cap at risk budget
        position_size = min(kelly_half, risk_budget_dollar / sigma)
        return max(position_size, 0)

    def variance_swap_replication(self, strikes: np.ndarray, call_prices: np.ndarray, put_prices: np.ndarray, T: float) -> float:
        """
        Replicate variance swap fair value (Neuberger formula).
        K_var = (2/T) * sum_i (e^{rT}/K_i^2) * Option(K_i) * dK_i
        """
        F = self.S * np.exp((self.r - self.q) * T)
        # Split at ATM: puts below, calls above
        atm_idx = np.argmin(np.abs(strikes - F))

        K_var = 0.0
        dk = np.diff(strikes)

        for i in range(len(strikes)):
            if i == 0:
                dK_i = dk[0]
            elif i == len(strikes) - 1:
                dK_i = dk[-1]
            else:
                dK_i = (dk[i] + dk[i - 1]) / 2

            if strikes[i] <= F:
                price = put_prices[i]
            else:
                price = call_prices[i]

            K_var += np.exp(self.r * T) * price / strikes[i]**2 * dK_i

        K_var *= 2 / T
        return np.sqrt(K_var) * 100  # Convert to vol units (%)


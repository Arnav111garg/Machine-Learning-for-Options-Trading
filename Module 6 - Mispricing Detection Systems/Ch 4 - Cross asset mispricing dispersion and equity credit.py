class DispersionTradeEngine:
    """
    Constructs and monitors volatility dispersion trades.
    Detects when index vol is rich vs. component vols.
    """

    def __init__(self, weights: dict):
        """
        weights: { ticker : weight } must sum to 1.0
        """
        self.weights = weights
        self.tickers = list(weights.keys())
        self.w_arr = np.array(list(weights.values()))

    def compute_implied_correlation(self, index_iv: float, component_ivs: dict) -> float:
        """
        Extract implied average pairwise correlation from index IV and component IVs.
        Using: sigma_idx^2 = rho * sigma_bar^2 (approximation for uniform rho)
        """
        # Weighted average component variance
        component_var_weighted = sum(
            self.weights[t]**2 * component_ivs[t]**2
            for t in self.tickers
        )

        # Cross terms with implied correlation rho
        cross_term_coeff = sum(
            2 * self.weights[self.tickers[i]] * self.weights[self.tickers[j]]
            * component_ivs[self.tickers[i]] * component_ivs[self.tickers[j]]
            for i in range(len(self.tickers))
            for j in range(i + 1, len(self.tickers))
        )

        # Solve for rho: index_iv^2 = comp_var_weighted + rho * cross_term_coeff
        rho_implied = (index_iv**2 - component_var_weighted) / cross_term_coeff
        return np.clip(rho_implied, -1, 1)

    def compute_fair_index_vol(self, component_ivs: dict, realized_corr: float) -> float:
        """
        Compute fair index vol given component IVs and expected correlation.
        """
        var_diagonal = sum(
            self.weights[t]**2 * component_ivs[t]**2
            for t in self.tickers
        )
        var_cross = realized_corr * sum(
            2 * self.weights[self.tickers[i]] * self.weights[self.tickers[j]]
            * component_ivs[self.tickers[i]] * component_ivs[self.tickers[j]]
            for i in range(len(self.tickers))
            for j in range(i + 1, len(self.tickers))
        )
        return np.sqrt(var_diagonal + var_cross)

    def dispersion_signal(self, index_iv: float, component_ivs: dict, hist_rho_mean: float = 0.55, hist_rho_std: float = 0.10) -> dict:
        """
        Generate the dispersion trading signal.
        Returns signal strength and trade direction.
        """
        implied_rho = self.compute_implied_correlation(index_iv, component_ivs)
        fair_index_vol = self.compute_fair_index_vol(component_ivs, hist_rho_mean)

        # Dispersion = index IV - fair (using historical avg correlation)
        dispersion = (index_iv - fair_index_vol) * 100  # In vol points

        # Z-score of implied correlation
        rho_z = (implied_rho - hist_rho_mean) / hist_rho_std

        # Signal
        if rho_z > 1.5:
            trade = "Short index vol, Long component vols"
            direction = -1
        elif rho_z < -1.5:
            trade = "Long index vol, Short component vols"
            direction = 1
        else:
            trade = "No trade"
            direction = 0

        return {
            'implied_correlation': implied_rho,
            'hist_avg_correlation': hist_rho_mean,
            'correlation_z_score': rho_z,
            'dispersion_vol_pts': dispersion,
            'fair_index_vol': fair_index_vol * 100,
            'market_index_vol': index_iv * 100,
            'trade': trade,
            'direction': direction,
            'signal_strength': min(abs(rho_z) / 3.0, 1.0)
        }

    def compute_hedge_ratios(self, index_notional: float, index_iv: float, component_ivs: dict, component_prices: dict) -> dict:
        """
        Compute variance-swap notionals for each leg.
        For a variance swap: PnL = N * (sigma_realized^2 - sigma_strike^2)
        Vega-neutral at inception requires: vega_index = vega_components (weighted)
        """
        # Index vega (per unit notional): 2 * sigma * N
        index_vega_per_notional = 2 * index_iv

        # Component notionals for vega neutrality
        component_notionals = {}
        for t in self.tickers:
            # Vega contribution of component i: w_i^2 * 2 * sigma_i * N_i
            # For delta-hedged options: notional scaled by weight and vol
            component_notionals[t] = (
                index_notional * self.weights[t] *
                (index_iv / component_ivs[t])  # Vol-ratio adjustment
            )

        return component_notionals


class MertonCrossAssetArb:
    """
    Detects cross-asset mispricing between equity options and credit (CDS).
    Based on Merton's structural model.
    """

    @staticmethod
    def merton_credit_spread(equity_vol: float, equity_price: float, debt: float, maturity: float, risk_free_rate: float) -> float:
        """
        Compute theoretical CDS spread from Merton model.
        equity_vol: annualized implied volatility
        equity_price: current stock price
        debt: face value of total debt (per share)
        maturity: CDS maturity in years
        """
        # Solve for asset value V and asset vol sigma_V
        # Equity = max(V - D, 0) = call option on assets
        # Two equations: E = V*Phi(d1) - D*e^{-rT}*Phi(d2)
        # sigma_E = Phi(d1) * V/E * sigma_V

        def equations(params):
            V, sigma_V = params
            if V <= 0 or sigma_V <= 0:
                return [1e6, 1e6]

            d1 = (np.log(V / debt) + (risk_free_rate + 0.5 * sigma_V ** 2) * maturity) / (sigma_V * np.sqrt(maturity))
            d2 = d1 - sigma_V * np.sqrt(maturity)

            E_model = V * norm.cdf(d1) - debt * np.exp(-risk_free_rate * maturity) * norm.cdf(d2)
            sigma_E_model = norm.cdf(d1) * V / equity_price * sigma_V

            return [E_model - equity_price, sigma_E_model - equity_vol]

        # Solve numerically
        try:
            from scipy.optimize import fsolve
            V0 = equity_price + debt
            sol = fsolve(equations, [V0, equity_vol * equity_price / V0], full_output=True)
            V_star, sigma_V_star = sol[0]

            # Credit spread from distance-to-default
            d2 = (np.log(V_star / debt) + (risk_free_rate - 0.5 * sigma_V_star ** 2) * maturity) / (sigma_V_star * np.sqrt(maturity))

            # Default probability (risk-neutral)
            pd_rn = norm.cdf(-d2)

            # CDS spread (assuming 40% recovery)
            recovery = 0.40
            cds_spread = (1 - recovery) * pd_rn / (maturity * (1 - pd_rn * (1 - recovery)))

            return cds_spread * 10000  # In basis points
        except Exception:
            return np.nan

    def equity_credit_signal(self, equity_iv: float, equity_price: float, debt_per_share: float, cds_spread_bps: float, maturity: float = 5.0, r: float = 0.05) -> dict:
        """
        Compare market CDS spread to Merton-implied theoretical spread.
        Signal = market spread - theoretical spread.
        """
        theo_spread = self.merton_credit_spread(equity_iv, equity_price, debt_per_share, maturity, r)

        if np.isnan(theo_spread):
            return {'valid': False}

        spread_diff = cds_spread_bps - theo_spread

        if spread_diff > 50:  # CDS wide vs. equity vol
            trade = "Buy equity puts / Buy CDS protection hedge reversed: Equity options cheap vs. credit"
            direction = "Long Equity Vol / Short CDS"
        elif spread_diff < -50:  # CDS tight vs. equity vol
            trade = "Sell equity puts / Sell CDS: equity options rich vs credit"
            direction = "Short Equity Vol / Long CDS"
        else:
            trade = "No significant cross-asset mispricing"
            direction = "Neutral"

        return {
            'valid': True,
            'market_cds_bps': cds_spread_bps,
            'merton_implied_cds_bps': theo_spread,
            'spread_difference_bps': spread_diff,
            'trade': trade,
            'direction': direction
        }


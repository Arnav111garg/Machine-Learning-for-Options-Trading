import numpy as np
import pandas as pd
from scipy.stats import norm

class VarianceRiskPremiumSignal:
    """
    Tracks and signals on the Variance Risk Premium (VRP).
    VRP = IV^2 - Realized Vol^2
    Persistently positive VRP -> short variance trade profitable.
    """

    def __init__(self, rv_window=21, vrp_lookback=252, entry_z=0.5):
        self.rv_window = rv_window  # Days for realized vol estimate
        self.vrp_lookback = vrp_lookback  # For z-score normalization
        self.entry_z = entry_z

    def compute_realized_vol(self, returns: np.ndarray) -> float:
        """
        Yang-Zhang realized volatility estimator (open-high-low-close).
        """
        return np.std(returns) * np.sqrt(252)

    def compute_vrp(self, iv_t: float, rv_realized: float) -> float:
        """
        VRP = IV^2 - RV^2 (in variance units).
        """
        return iv_t**2 - rv_realized**2

    def vrp_signal(self, vrp_history: pd.Series, vrp_current: float) -> dict:
        """
        Generate signal based on current VRP vs. history.
        High VRP -> sell variance (short straddle, variance swap).
        """
        mu = vrp_history.mean()
        sigma = vrp_history.std()
        z = (vrp_current - mu) / sigma

        if z > self.entry_z:
            trade = 'Short variance (sell ATM straddle / strangle)'
            signal_val = -1
        elif z < -self.entry_z:
            trade = 'Long variance (buy variance swap)'
            signal_val = 1
        else:
            trade = 'Flat'
            signal_val = 0

        return {
            'vrp_current': vrp_current * 10000,  # In vol-squared * 1e4
            'vrp_mean': mu * 10000,
            'vrp_z_score': z,
            'signal': signal_val,
            'trade': trade
        }

    def variance_swap_pnl(self, sigma_strike: float, sigma_realized: float, notional: float = 1e6) -> float:
        """
        Variance swap P&L:
        PnL = N * (sigma_realized^2 - sigma_strike^2) * 10000
        (Long variance swap profits when realized > strike)
        """
        return notional * (sigma_realized**2 - sigma_strike**2) * 10000


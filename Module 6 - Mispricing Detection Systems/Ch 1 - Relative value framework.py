if __name__ == "__main__":
    np.random.seed(42)

    # Simulate IV surface: T = 252 days, N = 20 contracts (5 strikes x 4 expiries)
    T, N = 252, 20

    # Generate correlated IV changes (3-factor model)
    loadings = np.random.randn(3, N) * 0.5
    loadings[0] = 0.01 + 0.001 * np.random.randn(N)  # PC1: level
    loadings[1] = np.linspace(-0.005, 0.005, N)       # PC2: skew
    loadings[2] = np.abs(np.linspace(-0.003, 0.003, N)) - 0.001  # PC3: curve

    factor_returns = np.random.randn(T, 3) * np.array([2.0, 0.8, 0.3])
    iv_changes = factor_returns @ loadings + 0.001 * np.random.randn(T, N)
    iv_levels = 0.20 + np.cumsum(iv_changes, axis=0)  # Starting at 20% vol

    # Fit RV framework
    rv = RelativeValueFramework(n_factors=3, lookback_days=60)
    rv.fit(iv_levels)

    # Compute residuals over time
    iv_mean = iv_levels[:60].mean(axis=0)  # Use first 60 days as baseline
    residuals = np.array([rv.compute_residuals(iv_levels[t], iv_mean) for t in range(60, T)])

    residuals_df = pd.DataFrame(residuals, columns=[f"Contract_{i}" for i in range(N)])

    # Generate signals
    zscores = rv.rolling_zscore(residuals_df)
    signals = rv.generate_signals(zscores.dropna())

    print("\nSignal statistics:")
    print(f" Long signals : {(signals == 1).sum().sum()}")
    print(f" Short signals: {(signals == -1).sum().sum()}")
    print(f" Avg signal magnitude: {signals.abs().mean().mean():.3f}")


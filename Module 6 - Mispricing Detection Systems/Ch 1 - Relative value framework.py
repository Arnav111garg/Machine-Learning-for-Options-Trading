import numpy as np
import pandas as pd
from sklearn.decomposition import PCA
from scipy import stats

class RelativeValueFramework:
    """
    Relative value framework for implied volatility surfaces.
    Uses PCA to decompose surface dynamics and build RV signals.
    """

    def __init__(self, n_factors=3, lookback_days=60, z_entry=1.5, z_exit=0.5):
        self.n_factors = n_factors
        self.lookback = lookback_days
        self.z_entry = z_entry
        self.z_exit = z_exit
        self.pca = PCA(n_components=n_factors)

    def fit(self, iv_matrix: np.ndarray):
        """
        Fit PCA to IV changes.
        iv_matrix: (T, N) array T time steps, N contracts
        """
        # Compute IV changes
        div_matrix = np.diff(iv_matrix, axis=0)

        # Fit PCA
        self.pca.fit(div_matrix)
        self.factor_loadings_ = self.pca.components_  # (n_factors, N)
        self.explained_variance_ratio_ = self.pca.explained_variance_ratio_

        print(f"Variance explained by {self.n_factors} factors:")
        for i, var in enumerate(self.explained_variance_ratio_):
            print(f" PC{i+1}: {var:.1%}")
        print(f" Total: {self.explained_variance_ratio_.sum():.1%}")

        return self

    def compute_residuals(self, iv_vector: np.ndarray, iv_mean: np.ndarray) -> np.ndarray:
        """
        Compute factor-neutral residuals for a given IV snapshot.

        iv_vector: (N,) current IV snapshot
        iv_mean: (N,) mean IV vector (baseline)
        Returns: (N,) residuals
        """
        # Demean
        iv_dev = iv_vector - iv_mean

        # Project onto factor space and compute residual
        factor_scores = self.factor_loadings_ @ iv_dev  # (n_factors,)
        iv_hat = iv_mean + self.factor_loadings_.T @ factor_scores  # (N,)
        residuals = iv_vector - iv_hat

        return residuals

    def rolling_zscore(self, residuals_history: pd.DataFrame) -> pd.DataFrame:
        """
        Compute rolling z-scores for a panel of residuals.
        residuals_history: DataFrame (T x N) of residuals
        """
        rolling_mean = residuals_history.rolling(self.lookback).mean()
        rolling_std = residuals_history.rolling(self.lookback).std()
        zscores = (residuals_history - rolling_mean) / rolling_std
        return zscores

    def generate_signals(self, zscores: pd.DataFrame) -> pd.DataFrame:
        """
        Generate trading signals from z-scores.
        +1 = buy (cheap vol), -1 = sell (rich vol), 0 = flat
        """
        signals = pd.DataFrame(0, index=zscores.index, columns=zscores.columns)
        signals[zscores > self.z_entry] = -1  # Rich : short
        signals[zscores < -self.z_entry] = 1  # Cheap : long
        return signals

    def compute_spread_pnl(self, signals: pd.DataFrame, iv_changes: pd.DataFrame, vega_matrix: pd.DataFrame) -> pd.Series:
        """
        Approximate P&L from IV change for a vega-neutral portfolio.
        PnL_t = -signals_{t-1} * vega * delta_IV_t (sell high, profit when IV falls)
        """
        pnl = (-signals.shift(1) * vega_matrix * iv_changes).sum(axis=1)
        return pnl


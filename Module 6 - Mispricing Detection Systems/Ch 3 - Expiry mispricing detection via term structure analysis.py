import numpy as np
import pandas as pd
from scipy.interpolate import CubicSpline, interp1d
from scipy.optimize import brentq

class ExpiryMispricingDetector:
    """
    Detects mispricing in the volatility term structure.
    Key strategies:
    1. Event vol extraction and comparison to historical
    2. Forward variance curve analysis
    3. Calendar spread signal generation
    """

    def __init__(self, calendar_days_per_year=252):
        self.cdy = calendar_days_per_year

    def fit_smooth_term_structure(self, expiries: np.ndarray, atm_vols: np.ndarray) -> callable:
        """
        Fit a smooth vol term structure excluding event bumps.
        Uses cubic spline on total variance for no-arb interpolation.

        expiries: (N,) in years
        atm_vols: (N,) ATM implied vols
        """
        total_var = atm_vols ** 2 * expiries  # Must be non-decreasing

        # Monotone interpolation in total variance space
        cs = CubicSpline(expiries, total_var, bc_type='natural')

        def smooth_vol(T):
            """ Returns ATM vol for any expiry T. """
            w = cs(T)
            return np.sqrt(np.maximum(w / T, 0))

        return smooth_vol

    def extract_event_vol(self, T_before: float, T_after: float, atm_vol_before: float, atm_vol_after: float) -> float:
        """
        Extract the implied one-day event vol from two bracketing expiries.

        T_before: expiry just before event (in years)
        T_after: expiry just after event (in years)
        """
        w_before = atm_vol_before ** 2 * T_before
        w_after = atm_vol_after ** 2 * T_after

        # Variance must increase for event: delta_w = event variance
        delta_w = w_after - w_before
        if delta_w < 0:
            return 0.0  # Calendar arbitrage (no genuine event bump)

        # Event vol = annualized 1-day vol implied by the bump
        event_vol = np.sqrt(delta_w / (1 / 252))  # Annualize as if 1-day event
        return event_vol

    def compute_forward_variance_curve(self, expiries: np.ndarray, atm_vols: np.ndarray) -> dict:
        """
        Compute the term structure of forward variances.
        Returns forward var between consecutive expiries.
        """
        total_var = atm_vols ** 2 * expiries

        fwd_vars = {}
        for i in range(1, len(expiries)):
            T1, T2 = expiries[i - 1], expiries[i]
            w1, w2 = total_var[i - 1], total_var[i]

            fwd_var = (w2 - w1) / (T2 - T1)
            fwd_vol = np.sqrt(max(fwd_var, 0))

            fwd_vars[(T1, T2)] = {
                'fwd_var': fwd_var,
                'fwd_vol': fwd_vol * 100,  # in percentage
                'calendar_arb': fwd_var < 0  # Flag if negative
            }
        return fwd_vars

    def term_structure_signal(self, expiries: np.ndarray, atm_vols: np.ndarray, hist_vol_ratio_mean: float = 1.0, hist_vol_ratio_std: float = 0.05) -> dict:
        """
        Generate trading signals from term structure anomalies.
        Compares the 1M/3M vol ratio to its historical distribution.
        Rich front-end: sell near, buy far.
        """
        # Fit smooth term structure
        smooth_vol = self.fit_smooth_term_structure(expiries, atm_vols)

        # Extract 1M and 3M vols
        T1M = 1 / 12
        T3M = 3 / 12
        vol_1M = smooth_vol(T1M)
        vol_3M = smooth_vol(T3M)

        ratio = vol_1M / vol_3M if vol_3M > 0 else 1.0
        z_ratio = (ratio - hist_vol_ratio_mean) / hist_vol_ratio_std

        # Signal: positive z_ratio means near-term vol is rich -> sell short, buy long
        signal = {
            'vol_1M': vol_1M * 100,
            'vol_3M': vol_3M * 100,
            'ratio_1M_3M': ratio,
            'z_score': z_ratio,
            'trade': 'Sell 1M vol, Buy 3M vol' if z_ratio > 1.5 else 'Buy 1M vol, Sell 3M vol' if z_ratio < -1.5 else 'Flat',
            'signal_strength': min(abs(z_ratio) / 3.0, 1.0)
        }

        # Check forward variance for calendar arbitrage
        fwd_vars = self.compute_forward_variance_curve(expiries, atm_vols)
        cal_arb_exists = any(v['calendar_arb'] for v in fwd_vars.values())
        signal['calendar_arbitrage'] = cal_arb_exists

        return signal

    def event_mispricing_signal(self, event_date_years: float, implied_event_vol: float, historical_event_vols: np.ndarray, current_atm_vol: float) -> dict:
        """
        Assess whether the implied event vol is rich or cheap relative to historical event moves (adjusted for current vol regime).

        implied_event_vol: extracted from term structure (annualized)
        historical_event_vols: past realized 1-day vol on similar events
        current_atm_vol: current ATM vol (for scaling)
        """
        # Normalize historical vols
        hist_mean = np.mean(historical_event_vols)
        hist_std = np.std(historical_event_vols)

        # Scale implied event vol to same units
        z_event = (implied_event_vol - hist_mean) / hist_std

        return {
            'implied_event_vol': implied_event_vol * 100,
            'hist_mean_event_vol': hist_mean * 100,
            'hist_std_event_vol': hist_std * 100,
            'z_score': z_event,
            'assessment': 'Rich' if z_event > 1.5 else 'Cheap' if z_event < -1.5 else 'Fair',
            'trade': 'Sell event straddle (fade the move)' if z_event > 1.5 else 'Buy event straddle (play the move)' if z_event < -1.5 else 'No trade recommended'
        }


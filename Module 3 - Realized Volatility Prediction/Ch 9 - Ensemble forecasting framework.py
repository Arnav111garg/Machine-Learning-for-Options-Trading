import numpy as np
import pandas as pd
from sklearn.linear_model import Ridge, Lasso
from sklearn.model_selection import TimeSeriesSplit
from scipy.optimize import minimize

class VolatilityEnsemble:
    """
    Ensemble combining multiple volatility forecasters.
    Methods: simple average, optimal weights, time-varying, stacking.
    """

    def __init__(self, base_models: dict, method: str = 'simple_average'):
        """
        Args:
            base_models: dict of {name: fitted_model_object}
            method: 'simple_average', 'optimal', 'time_varying', 'stack'
        """
        self.base_models = base_models
        self.method = method
        self.weights_ = None
        self.meta_model_ = None

    def _collect_forecasts(self, X: pd.DataFrame) -> pd.DataFrame:
        """Get predictions from all base models."""
        fc_dict = {}
        for name, model in self.base_models.items():
            try:
                preds = model.predict(X)
                if hasattr(preds, 'values'):
                    preds = preds.values
                fc_dict[name] = preds
            except Exception as e:
                print(f"Warning: model {name} failed: {e}")
        return pd.DataFrame(fc_dict, index=X.index)

    def fit_optimal_weights(self, fc_matrix: pd.DataFrame,
                            realized: pd.Series) -> np.ndarray:
        """
        Estimate optimal combination weights via constrained OLS.
        Minimize MSE subject to weights summing to 1 and >= 0.
        """
        F = fc_matrix.values
        y = realized.loc[fc_matrix.index].values
        M = F.shape[1]

        def objective(w):
            return np.mean((y - F @ w) ** 2)

        def gradient(w):
            resid = y - F @ w
            return -2 * F.T @ resid / len(y)

        # Constrained optimization: sum(w)=1, w >=0
        constraints = [{'type': 'eq', 'fun': lambda w: np.sum(w) - 1}]
        bounds = [(0, None)] * M
        w0 = np.ones(M) / M

        result = minimize(objective, w0, jac=gradient,
                          method='SLSQP', bounds=bounds,
                          constraints=constraints,
                          options={'ftol': 1e-12, 'maxiter': 1000})
        return result.x

    def fit_time_varying_weights(self, fc_matrix: pd.DataFrame,
                                 realized: pd.Series,
                                 window: int = 63,
                                 kappa: float = 5.0) -> pd.DataFrame:
        """
        Compute time-varying weights based on recent QLIKE loss.
        """
        M = fc_matrix.shape[1]
        weights_history = []

        for t in range(window, len(fc_matrix)):
            # Recent QLIKE for each model
            rv_w = realized.iloc[t - window : t].values
            fc_w = fc_matrix.iloc[t - window : t].values

            losses = np.zeros(M)
            for m in range(M):
                fc_m = np.maximum(fc_w[:, m], 1e-10)
                rv_ = np.maximum(rv_w, 1e-10)
                losses[m] = np.mean(rv_ / fc_m - np.log(rv_ / fc_m) - 1)

            # Softmax weights
            scores = np.exp(-kappa * (losses - losses.min()))
            w = scores / scores.sum()
            weights_history.append(w)

        return pd.DataFrame(
            weights_history,
            columns=fc_matrix.columns,
            index=fc_matrix.index[window:]
        )

    def fit_stack(self, X: pd.DataFrame, realized: pd.Series,
                  n_splits: int = 5, alpha: float = 0.01) -> 'VolatilityEnsemble':
        """
        Fit a stacking ensemble with Ridge meta-learner.
        Uses time-series CV to generate out-of-fold meta-features.
        """
        tscv = TimeSeriesSplit(n_splits=n_splits)
        meta_features = pd.DataFrame(index=X.index,
                                     columns=list(self.base_models.keys()),
                                     dtype=float)

        for tr_idx, te_idx in tscv.split(X):
            X_tr = X.iloc[tr_idx]
            X_te = X.iloc[te_idx]
            y_tr = realized.iloc[tr_idx]

            for name, model in self.base_models.items():
                # Refit on training fold
                try:
                    model.fit(X_tr, y_tr)
                    preds = model.predict(X_te)
                    if hasattr(preds, 'values'):
                        preds = preds.values
                    meta_features.iloc[te_idx][name] = preds
                except Exception:
                    pass

        meta_features = meta_features.dropna()
        y_meta = realized.loc[meta_features.index]

        # Meta-learner: Ridge with non-negative weights
        self.meta_model_ = Ridge(alpha=alpha, fit_intercept=False, positive=True)
        self.meta_model_.fit(meta_features.values, y_meta.values)

        # Normalize weights to sum to 1
        w = self.meta_model_.coef_
        self.weights_ = pd.Series(w / w.sum(), index=list(self.base_models.keys()))

        print("Stacking weights:")
        print(self.weights_.sort_values(ascending=False))
        return self

    def predict(self, X: pd.DataFrame,
                realized_hist: pd.Series = None) -> pd.Series:
        """Generate ensemble forecast."""
        fc_matrix = self._collect_forecasts(X)

        if self.method == 'simple_average':
            return fc_matrix.mean(axis=1)

        elif self.method == 'optimal' and self.weights_ is not None:
            w = self.weights_.reindex(fc_matrix.columns).fillna(0).values
            return pd.Series(fc_matrix.values @ w, index=X.index)

        elif self.method == 'time_varying' and realized_hist is not None:
            tv_weights = self.fit_time_varying_weights(fc_matrix, realized_hist)
            aligned = fc_matrix.loc[tv_weights.index]
            result = (aligned.values * tv_weights.values).sum(axis=1)
            return pd.Series(result, index=tv_weights.index)

        elif self.method == 'stack' and self.meta_model_ is not None:
            preds = self.meta_model_.predict(fc_matrix.fillna(method='ffill').values)
            return pd.Series(preds, index=fc_matrix.index)

        else:
            return fc_matrix.mean(axis=1) # fallback


import numpy as np
import pandas as pd
import xgboost as xgb
import lightgbm as lgb
from sklearn.model_selection import TimeSeriesSplit
from sklearn.metrics import mean_squared_error

# QLIKE Loss for XGBoost (custom objective)
def qlike_gradient_hessian(y_pred: np.ndarray, dtrain: xgb.DMatrix):
    """
    QLIKE loss : L(y, y_hat) = y/y_hat - log(y/y_hat) - 1
    Gradient : dL/d(y_hat) = -y/y_hat^2 + 1/y_hat
    Hessian : d2L/d(y_hat)^2 = 2y/y_hat^3 - 1/y_hat^2
    """
    y_true = dtrain.get_label()
    y_pred = np.maximum(y_pred, 1e-8)  # numerical stability

    grad = -y_true / (y_pred ** 2) + 1.0 / y_pred
    hess = 2 * y_true / (y_pred ** 3) - 1.0 / (y_pred ** 2)
    hess = np.maximum(hess, 1e-6)  # ensure positive definite

    return grad, hess

def qlike_metric(y_pred: np.ndarray, dtrain: xgb.DMatrix):
    """QLIKE evaluation metric."""
    y_true = dtrain.get_label()
    y_pred = np.maximum(y_pred, 1e-8)
    loss = y_true / y_pred - np.log(y_true / y_pred) - 1
    return 'qlike', float(np.mean(loss))

class GradientBoostingVolModel:
    """
    Volatility forecasting with XGBoost or LightGBM.
    Designed for production use with proper time-series cross-validation.
    """
    def __init__(self, library: str = 'xgboost', use_qlike: bool = True):
        self.library = library
        self.use_qlike = use_qlike
        self.model_ = None
        self.best_iter_ = None

    def _default_params(self) -> dict:
        """Sensible defaults for volatility forecasting."""
        if self.library == 'xgboost':
            return {
                'n_estimators': 500,
                'learning_rate': 0.03,
                'max_depth': 4,
                'min_child_weight': 20,
                'subsample': 0.8,
                'colsample_bytree': 0.7,
                'reg_alpha': 0.1,
                'reg_lambda': 1.0,
                'random_state': 42,
            }
        else:  # lightgbm
            return {
                'n_estimators': 500,
                'learning_rate': 0.03,
                'num_leaves': 15,
                'min_child_samples': 20,
                'subsample': 0.8,
                'colsample_bytree': 0.7,
                'reg_alpha': 0.1,
                'reg_lambda': 1.0,
                'random_state': 42,
                'verbose': -1,
            }

    def fit(self, X: pd.DataFrame, y: pd.Series,
            val_X: pd.DataFrame = None, val_y: pd.Series = None,
            params: dict = None) -> 'GradientBoostingVolModel':
        """
        Fit model with optional early stopping on validation set.
        IMPORTANT: val_X / val_y should be strictly AFTER training period.
        """
        p = params or self._default_params()

        if self.library == 'xgboost':
            dtrain = xgb.DMatrix(X, label=y)
            evals = [(dtrain, 'train')]

            if val_X is not None:
                dval = xgb.DMatrix(val_X, label=val_y)
                evals.append((dval, 'val'))

            xgb_params = {k: v for k, v in p.items() if k not in ('n_estimators',)}
            xgb_params['tree_method'] = 'hist'

            if self.use_qlike:
                self.model_ = xgb.train(
                    xgb_params,
                    dtrain,
                    num_boost_round=p.get('n_estimators', 500),
                    obj=qlike_gradient_hessian,
                    custom_metric=qlike_metric,
                    evals=evals,
                    early_stopping_rounds=50,
                    verbose_eval=False,
                )
            else:
                self.model_ = xgb.train(
                    xgb_params,
                    dtrain,
                    num_boost_round=p.get('n_estimators', 500),
                    evals=evals,
                    early_stopping_rounds=50,
                    verbose_eval=False,
                )
        else:  # LightGBM
            callbacks = [lgb.early_stopping(50, verbose=False)]
            eval_set = [(val_X, val_y)] if val_X is not None else None

            self.model_ = lgb.LGBMRegressor(**p)
            self.model_.fit(X, y, eval_set=eval_set, callbacks=callbacks)
        return self

    def predict(self, X: pd.DataFrame) -> np.ndarray:
        if self.library == 'xgboost':
            dtest = xgb.DMatrix(X)
            return self.model_.predict(dtest)
        else:
            return self.model_.predict(X)

    def feature_importance(self) -> pd.Series:
        """Return feature importances as Series."""
        if self.library == 'xgboost':
            scores = self.model_.get_score(importance_type='gain')
            return pd.Series(scores).sort_values(ascending=False)
        else:
            return pd.Series(
                self.model_.feature_importances_,
                index=self.model_.feature_name_
            ).sort_values(ascending=False)

# Rolling Walk-Forward Forecasting
def rolling_forecast(X: pd.DataFrame, y: pd.Series,
                     train_size: int = 504,  # ~2 years
                     val_size: int = 63,    # ~3 months
                     step: int = 21,        # monthly refit
                     library: str = 'lightgbm') -> pd.Series:
    """
    Walk-forward out-of-sample forecast.
    Structure: [=== TRAIN ===|= VAL =|=== TEST (rolled) ===]
    At each step, retrain on all data up to t, forecast t+1.
    """
    forecasts = pd.Series(dtype=float, index=y.index)
    n = len(y)

    for start in range(train_size, n - val_size, step):
        # Training window: expanding (all data up to start)
        X_tr = X.iloc[:start]
        y_tr = y.iloc[:start]

        # Validation window (for early stopping)
        X_val = X.iloc[start : start + val_size]
        y_val = y.iloc[start : start + val_size]

        # Forecast window (post-validation)
        end = min(start + val_size + step, n)
        X_fc = X.iloc[start + val_size : end]

        if len(X_fc) == 0:
            break

        model = GradientBoostingVolModel(library=library, use_qlike=True)
        model.fit(X_tr, y_tr, val_X=X_val, val_y=y_val)
        preds = model.predict(X_fc)

        forecasts.iloc[start + val_size : end] = preds

    return forecasts.dropna()


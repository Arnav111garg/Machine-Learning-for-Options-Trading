import numpy as np
import pandas as pd
from scipy import stats

class VolatilityFeatureEngineer:
    """
    Comprehensive feature engineering for volatility forecasting.
    Covers all major feature categories: realized moments,
    signed variation, options signals, and microstructure.
    """

    def __init__(self, rv: pd.Series, bv: pd.Series = None,
                 intraday_returns: pd.DataFrame = None,
                 options_data: pd.DataFrame = None):
        self.rv = rv
        self.bv = bv if bv is not None else rv * 0.9  # approx fallback
        self.ret = intraday_returns
        self.opt = options_data

    # HAR Components
    def har_components(self) -> pd.DataFrame:
        """Compute daily, weekly, monthly RV averages."""
        df = pd.DataFrame(index=self.rv.index)
        df['rv_d'] = self.rv
        df['rv_w'] = self.rv.rolling(5).mean()
        df['rv_m'] = self.rv.rolling(22).mean()
        return df

    # Jump Features
    def jump_features(self) -> pd.DataFrame:
        df = pd.DataFrame(index=self.rv.index)
        df['jump_raw'] = np.maximum(self.rv - self.bv, 0)
        df['jump_ratio'] = df['jump_raw'] / self.rv
        df['bv'] = self.bv
        df['cont_var'] = self.bv  # continuous component
        return df

    # Signed Variation
    def signed_variation(self) -> pd.DataFrame:
        """Compute realized semivariances and signed jump."""
        if self.ret is None:
            return pd.DataFrame(index=self.rv.index)

        df = pd.DataFrame(index=self.rv.index)

        def rsv_pos(r):
            return (r[r > 0] ** 2).sum()

        def rsv_neg(r):
            return (r[r < 0] ** 2).sum()

        def r_skew(r):
            n = len(r)
            if n < 3:
                return np.nan
            rv_loc = (r ** 2).sum()
            if rv_loc == 0:
                return np.nan
            return np.sqrt(n) * (r ** 3).sum() / rv_loc ** 1.5

        df['rsv_pos'] = self.ret.apply(rsv_pos, axis=1)
        df['rsv_neg'] = self.ret.apply(rsv_neg, axis=1)
        df['signed_jump'] = df['rsv_pos'] - df['rsv_neg']
        df['r_skewness'] = self.ret.apply(r_skew, axis=1)
        return df

    # Variance Risk Premium
    def vrp_features(self, vix: pd.Series) -> pd.DataFrame:
        """
        Compute Variance Risk Premium and related features.
        VRP = IV^2 - E[RV] = VIX^2 - RV_22
        """
        df = pd.DataFrame(index=self.rv.index)
        vix_aligned = vix.reindex(self.rv.index).ffill()

        # VIX in variance units (VIX is in vol units, annualized %)
        iv_var = (vix_aligned / 100) ** 2 / 252  # daily variance units

        df['vix'] = vix_aligned / 100
        df['vix_sq'] = iv_var
        df['vrp'] = iv_var - self.rv.rolling(22).mean()
        df['vix_rv_ratio'] = iv_var / (self.rv + 1e-10)  # avoid div by zero
        return df

    # Lag Features
    def lag_features(self, max_lag: int = 5) -> pd.DataFrame:
        """Add lagged RV values as features."""
        df = pd.DataFrame(index=self.rv.index)
        for lag in range(1, max_lag + 1):
            df[f'rv_lag{lag}'] = self.rv.shift(lag)
        return df

    # Log Features
    def log_features(self, har: pd.DataFrame) -> pd.DataFrame:
        """Take log of all positive features."""
        log_df = np.log(har.clip(lower=1e-10))
        log_df.columns = ['log_' + c for c in log_df.columns]
        return log_df

    # Build Full Feature Matrix
    def build_features(self, vix: pd.Series = None) -> pd.DataFrame:
        """Assemble full feature matrix."""
        dfs = [
            self.har_components(),
            self.jump_features(),
            self.lag_features(max_lag=5),
        ]

        if self.ret is not None:
            dfs.append(self.signed_variation())
        if vix is not None:
            dfs.append(self.vrp_features(vix))

        X = pd.concat(dfs, axis=1)

        # Log-transform the RV features
        log_cols = ['rv_d', 'rv_w', 'rv_m', 'bv', 'cont_var']
        for col in log_cols:
            if col in X.columns:
                X[f'log_{col}'] = np.log(X[col].clip(lower=1e-10))

        return X.dropna()


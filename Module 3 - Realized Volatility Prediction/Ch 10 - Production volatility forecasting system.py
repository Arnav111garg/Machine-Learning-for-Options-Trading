import numpy as np
import pandas as pd
from datetime import datetime, timedelta
import logging
from dataclasses import dataclass, field
from typing import Optional, Dict, List

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger('VolForecastSystem')

@dataclass
class ForecastResult:
    """Container for volatility forecast output."""
    timestamp: datetime
    horizon: int # days ahead
    point_forecast: float # variance (daily)
    vol_forecast: float # volatility = sqrt(var), annualized
    lower_80: float # 80% PI lower
    upper_80: float # 80% PI upper
    lower_95: float # 95% PI lower
    upper_95: float # 95% PI upper
    regime: str # current vol regime
    model_weights: Dict[str, float] # ensemble weights used
    qlike_30d: float # recent model quality metric
    data_quality: str # 'GOOD', 'WARN', 'BAD'


class ProductionVolatilitySystem:
    """
    Production-grade volatility forecasting system.

    Implements:
    - Real-time RV computation with data quality checks
    - Multi-model ensemble with time-varying weights
    - Prediction intervals
    - Monitoring and alerting
    - Model lifecycle management
    """

    def __init__(self, config: dict = None):
        self.config = config or self._default_config()

        # Model registry
        self.models: Dict[str, object] = {}

        # State
        self.rv_history: pd.Series = None
        self.fc_history: pd.DataFrame = None
        self.weights_history: pd.DataFrame = None

        # Monitoring
        self.alerts: List[str] = []
        self.last_refit: Dict[str, datetime] = {}

    def _default_config(self) -> dict:
        return {
            'rv_freq': '5min',
            'min_obs_daily': 60, # min 5-min obs per day
            'outlier_threshold': 5.0, # sigma
            'refit_schedule': {
                'har': 7, # days
                'ml': 30,
                'weights': 1,
                'regime': 7,
            },
            'alert_thresholds': {
                'qlike_30d_max': 0.05, # QLIKE threshold
                'coverage_tol': 0.08, # 8% from nominal coverage
                'bias_zscore': 2.5, # standard errors
                'spike_ratio': 3.0, # max ratio vs HAR forecast
            },
            'ensemble_method': 'time_varying',
            'pi_method': 'quantile_forest',
            'trading_hours': ('09:30', '16:00'),
        }

    # Data Pipeline
    def ingest_tick_data(self, ticks: pd.DataFrame) -> pd.Series:
        """
        Process raw tick data to compute daily RV.

        Args:
            ticks: DataFrame with columns ['timestamp', 'price', 'volume']

        Returns:
            Daily realized variance series
        """
        ticks = ticks.set_index('timestamp').sort_index()

        # Market hours filter
        open_t, close_t = self.config['trading_hours']
        ticks = ticks.between_time(open_t, close_t)

        # Log prices
        log_prices = np.log(ticks['price'])

        # Detect and remove price spikes
        log_returns = log_prices.diff().dropna()
        roll_std = log_returns.rolling(20).std()
        spike_mask = np.abs(log_returns) > self.config['outlier_threshold'] * roll_std

        if spike_mask.sum() > 0:
            logger.warning(f"Removed {spike_mask.sum()} price spikes")
            log_returns[spike_mask] = np.nan

        # Resample to 5-min and compute RV
        log_ret_5min = (
            log_returns
            .resample(self.config['rv_freq'])
            .sum()
            .fillna(0)
        )

        daily_rv = log_ret_5min.resample('1D').apply(
            lambda x: (x**2).sum() if len(x) >= self.config['min_obs_daily'] else np.nan
        )

        return daily_rv.dropna()

    # Model Management
    def register_model(self, name: str, model_obj: object):
        """Register a base forecasting model."""
        self.models[name] = model_obj
        logger.info(f"Registered model: {name}")

    def refit_if_needed(self, as_of: datetime, X: pd.DataFrame, rv: pd.Series):
        """Check schedule and refit models if due."""
        for name, model in self.models.items():
            model_type = name.split('_')[0] # 'har', 'ml', etc.
            days_between = self.config['refit_schedule'].get(model_type, 30)

            last = self.last_refit.get(name)
            if last is None or (as_of - last).days >= days_between:
                try:
                    model.fit(X, rv)
                    self.last_refit[name] = as_of
                    logger.info(f"Refitted {name} at {as_of.date()}")
                except Exception as e:
                    logger.error(f"Failed to refit {name}: {e}")

    # Forecast Generation
    def generate_forecast(self, X_t: pd.DataFrame,
                          rv_hist: pd.Series,
                          vix: Optional[pd.Series] = None,
                          horizon: int = 1) -> ForecastResult:
        """
        Generate production volatility forecast.

        Args:
            X_t: Feature vector for time t (1 row)
            rv_hist: Historical RV for weight computation
            vix: Optional VIX series for regime detection
            horizon: Forecast horizon in days

        Returns:
            ForecastResult with point forecast, intervals, and metadata
        """
        # Collect base model forecasts
        base_fc = {}
        for name, model in self.models.items():
            try:
                pred = model.predict(X_t)
                if isinstance(pred, (pd.Series, np.ndarray)):
                    pred = float(pred.iloc[0] if hasattr(pred, 'iloc') else pred[0])
                base_fc[name] = max(pred, 1e-10) # floor at zero
            except Exception as e:
                logger.warning(f"Model {name} forecast failed: {e}")

        if not base_fc:
            raise RuntimeError("All models failed to generate forecasts")

        # Compute time-varying ensemble weights
        if len(rv_hist) >= 63 and self.fc_history is not None:
            weights = self._compute_tv_weights(rv_hist, kappa=5.0)
        else:
            # Equal weights as fallback
            weights = {k: 1/len(base_fc) for k in base_fc}

        # Ensemble point forecast
        point = sum(weights.get(k, 0) * v for k, v in base_fc.items())

        # Sanity check: alert if forecast spikes vs HAR
        if 'har' in base_fc:
            ratio = point / base_fc['har']
            if ratio > self.config['alert_thresholds']['spike_ratio']:
                self.alerts.append(
                    f"Forecast spike: ensemble={point:.6f}, "
                    f"HAR={base_fc['har']:.6f}, ratio={ratio:.2f}"
                )
                logger.warning(self.alerts[-1])

        # Regime detection
        regime = self._detect_regime(rv_hist, vix)

        # Prediction intervals (quantile approach)
        fc_array = np.array(list(base_fc.values()))
        q10, q25, q75, q90 = np.percentile(fc_array, [10, 25, 75, 90])

        # Expand intervals using residual variance from HAR
        sigma_eps = rv_hist.diff().std() # rough error estimate
        lower_95 = max(q10 - 1.96 * sigma_eps, 1e-6)
        upper_95 = q90 + 1.96 * sigma_eps
        lower_80 = max(q25 - 1.28 * sigma_eps, 1e-6)
        upper_80 = q75 + 1.28 * sigma_eps

        # Recent model quality
        qlike_30d = self._compute_recent_qlike(rv_hist, window=30)

        # Data quality assessment
        dq = self._assess_data_quality(rv_hist)

        return ForecastResult(
            timestamp=datetime.now(),
            horizon=horizon,
            point_forecast=point,
            vol_forecast=np.sqrt(point * 252), # annualized vol
            lower_80=lower_80,
            upper_80=upper_80,
            lower_95=lower_95,
            upper_95=upper_95,
            regime=regime,
            model_weights={k: round(v, 4) for k, v in weights.items()},
            qlike_30d=qlike_30d,
            data_quality=dq,
        )

    def _compute_tv_weights(self, rv_hist: pd.Series,
                            window: int = 63,
                            kappa: float = 5.0) -> dict:
        """Compute time-varying weights from recent QLIKE."""
        if self.fc_history is None or len(self.fc_history) < window:
            return {k: 1/len(self.models) for k in self.models}

        recent_fc = self.fc_history.iloc[-window:]
        recent_rv = rv_hist.reindex(recent_fc.index)

        losses = {}
        for name in recent_fc.columns:
            fc = np.maximum(recent_fc[name].values, 1e-10)
            rv = np.maximum(recent_rv.values, 1e-10)
            valid = ~(np.isnan(fc) | np.isnan(rv))
            if valid.sum() > 10:
                losses[name] = np.mean(rv[valid]/fc[valid] - np.log(rv[valid]/fc[valid]) - 1)
            else:
                losses[name] = np.inf

        min_loss = min(v for v in losses.values() if np.isfinite(v))
        scores = {k: np.exp(-kappa * (v - min_loss)) for k, v in losses.items()}
        total = sum(scores.values())

        return {k: v / total for k, v in scores.items()}

    def _detect_regime(self, rv_hist: pd.Series,
                       vix: Optional[pd.Series] = None) -> str:
        """Simple regime detection based on VIX or RV level."""
        if vix is not None and len(vix) > 0:
            current_vix = float(vix.iloc[-1])
            if current_vix < 15: return 'calm'
            if current_vix < 25: return 'normal'
            if current_vix < 40: return 'stressed'
            return 'crisis'

        # Fallback: percentile-based on recent RV
        if len(rv_hist) < 22:
            return 'unknown'
        current = float(rv_hist.iloc[-1])
        hist = rv_hist.iloc[-252:]
        if current < hist.quantile(0.33): return 'low_vol'
        if current < hist.quantile(0.67): return 'normal'
        if current < hist.quantile(0.90): return 'high_vol'
        return 'extreme'

    def _compute_recent_qlike(self, rv_hist: pd.Series,
                              window: int = 30) -> float:
        """Compute recent (30-day) average QLIKE."""
        if self.fc_history is None or len(self.fc_history) < window:
            return np.nan

        recent_fc = self.fc_history.iloc[-window:].mean(axis=1)
        recent_rv = rv_hist.reindex(recent_fc.index)

        valid = ~(recent_fc.isna() | recent_rv.isna())
        if valid.sum() < 5:
            return np.nan

        fc = np.maximum(recent_fc[valid].values, 1e-10)
        rv = np.maximum(recent_rv[valid].values, 1e-10)

        return float(np.mean(rv / fc - np.log(rv / fc) - 1))

    def _assess_data_quality(self, rv_hist: pd.Series) -> str:
        """Assess data quality flags."""
        if len(rv_hist) < 22:
            return 'BAD'
        # Check for recent NaN
        recent = rv_hist.iloc[-5:]
        nan_ratio = recent.isna().mean()

        if nan_ratio > 0.4: return 'BAD'
        if nan_ratio > 0.2: return 'WARN'

        # Check for suspicious zero variance
        if float(rv_hist.iloc[-1]) < 1e-8:
            return 'WARN'

        return 'GOOD'

    # Monitoring
    def run_monitoring_checks(self, rv_realized: pd.Series,
                              fc_history: pd.DataFrame) -> dict:
        """
        Daily monitoring checks. Returns dict of check results.
        Run end-of-day after realized variance is known.
        """
        results = {}

        # 1. QLIKE check
        qlike = self._compute_recent_qlike(rv_realized, window=30)
        results['qlike_30d'] = {
            'value': qlike,
            'status': 'OK' if qlike < self.config['alert_thresholds']['qlike_30d_max'] else 'ALERT',
        }

        # 2. Bias check
        window = min(63, len(rv_realized))
        rv_w = rv_realized.iloc[-window:]
        fc_ens = fc_history.iloc[-window:].mean(axis=1)
        common = rv_w.index.intersection(fc_ens.index)

        if len(common) > 10:
            d_bar = (rv_w.loc[common] - fc_ens.loc[common]).mean()
            d_se = (rv_w.loc[common] - fc_ens.loc[common]).std() / np.sqrt(len(common))
            z_bias = d_bar / (d_se + 1e-10)
            results['bias'] = {
                'value': d_bar,
                'z_score': z_bias,
                'status': 'OK' if abs(z_bias) < self.config['alert_thresholds']['bias_zscore'] else 'ALERT',
            }

        # Print summary
        for check, info in results.items():
            status = info['status']
            icon = '✅' if status == 'OK' else '🚨'
            logger.info(f"{icon} {check}: {status} | {info}")

        return results


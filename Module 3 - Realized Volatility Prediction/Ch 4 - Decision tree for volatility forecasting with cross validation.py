import numpy as np
import pandas as pd
from sklearn.tree import DecisionTreeRegressor, plot_tree
from sklearn.model_selection import TimeSeriesSplit, GridSearchCV
from sklearn.metrics import mean_squared_error
import matplotlib.pyplot as plt

def fit_vol_tree(X: pd.DataFrame, y: pd.Series, max_depth: int = 4,
                 min_samples_leaf: int = 20, cv_folds: int = 5) -> dict:
    """
    Fit and tune a regression tree for volatility forecasting.
    CRITICAL: Use TimeSeriesSplit (NOT standard k-fold) to avoid
    look-ahead bias. This is non-negotiable in financial applications.
    """
    # Time-series cross-validation (no shuffling, chronological splits)
    tscv = TimeSeriesSplit(n_splits=cv_folds, gap=1) # gap=1 avoids overlap

    param_grid = {
        'max_depth': [2, 3, 4, 5, 6],
        'min_samples_leaf': [10, 20, 50, 100],
        'min_impurity_decrease': [0.0, 1e-7, 1e-6],
    }

    tree = DecisionTreeRegressor(random_state=42)

    # Negative MSE because GridSearchCV maximizes by convention
    gs = GridSearchCV(tree, param_grid, cv=tscv,
                      scoring='neg_mean_squared_error',
                      n_jobs=-1, refit=True)
    gs.fit(X, y)

    best_tree = gs.best_estimator_
    best_params = gs.best_params_

    # Feature importances
    importances = pd.Series(
        best_tree.feature_importances_, index=X.columns
    ).sort_values(ascending=False)

    return {
        'model': best_tree,
        'best_params': best_params,
        'importances': importances,
        'cv_score': -gs.best_score_, # back to positive MSE
    }

def plot_feature_importances(importances: pd.Series, top_n: int = 15):
    """Visualize top-N feature importances."""
    fig, ax = plt.subplots(figsize=(10, 5))
    importances.head(top_n).plot.barh(ax=ax, color='steelblue')
    ax.set_xlabel('Impurity-Based Importance')
    ax.set_title(f'Top {top_n} Features for Volatility Forecasting')
    ax.invert_yaxis()
    plt.tight_layout()
    return fig


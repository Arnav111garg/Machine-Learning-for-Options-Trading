import numpy as np
import pandas as pd
from scipy import stats
from statsmodels.stats.sandwich_covariance import cov_hac
import statsmodels.api as sm

class VolatilityForecastEvaluator:
    """
    Complete forecast evaluation suite for realized volatility.
    Implements: MSE, MAE, QLIKE, DM test, MZ regression, MCS.
    """

    @staticmethod
    def mse(realized: np.ndarray, forecast: np.ndarray) -> float:
        return np.mean((realized - forecast) ** 2)

    @staticmethod
    def mae(realized: np.ndarray, forecast: np.ndarray) -> float:
        return np.mean(np.abs(realized - forecast))

    @staticmethod
    def qlike(realized: np.ndarray, forecast: np.ndarray) -> float:
        """QLIKE loss: E[RV/hat_sigma^2 - log(RV/hat_sigma^2) - 1]"""
        fc = np.maximum(forecast, 1e-10)
        rv = np.maximum(realized, 1e-10)
        return np.mean(rv / fc - np.log(rv / fc) - 1)

    @staticmethod
    def r2_oos(realized: np.ndarray, forecast: np.ndarray,
               benchmark: np.ndarray = None) -> float:
        """
        Out-of-sample R^2 (Campbell & Thompson 2008 / Welch & Goyal 2008).
        R^2_OOS = 1 - MSE(model) / MSE(benchmark)
        benchmark defaults to historical mean.
        """
        if benchmark is None:
            benchmark = np.full_like(realized, np.mean(realized))

        mse_model = np.mean((realized - forecast) ** 2)
        mse_bench = np.mean((realized - benchmark) ** 2)
        return 1 - mse_model / mse_bench

    @staticmethod
    def mincer_zarnowitz(realized: np.ndarray, forecast: np.ndarray) -> dict:
        """
        Mincer-Zarnowitz regression: RV = a + b * hat_sigma^2 + u
        Tests H0: a=0, b=1 (efficiency and unbiasedness).
        """
        X = sm.add_constant(forecast)
        ols = sm.OLS(realized, X).fit(cov_type='HAC', cov_kwds={'maxlags': 22})

        a_hat, b_hat = ols.params
        a_se, b_se = ols.bse

        # Joint test H0: a=0, b=1 (F-test)
        R = np.array([[1, 0], [0, 1]])
        q = np.array([0, 1])
        f_stat = ols.f_test((R, q))

        return {
            'a': a_hat, 'a_se': a_se,
            'b': b_hat, 'b_se': b_se,
            'R2': ols.rsquared,
            'F_stat': float(f_stat.fvalue),
            'F_pval': float(f_stat.pvalue),
            'unbiased_eff': float(f_stat.pvalue) > 0.05,
        }

    @staticmethod
    def diebold_mariano(realized: np.ndarray, fc1: np.ndarray, fc2: np.ndarray,
                        loss: str = 'QLIKE', h: int = 1) -> dict:
        """
        Diebold-Mariano test for equal predictive accuracy.
        H0: E[L1] = E[L2]
        """
        rv = np.maximum(realized, 1e-10)

        if loss == 'QLIKE':
            L1 = rv / np.maximum(fc1, 1e-10) - np.log(rv / np.maximum(fc1, 1e-10)) - 1
            L2 = rv / np.maximum(fc2, 1e-10) - np.log(rv / np.maximum(fc2, 1e-10)) - 1
        elif loss == 'MSE':
            L1 = (rv - fc1) ** 2
            L2 = (rv - fc2) ** 2
        else:
            raise ValueError(f"Unknown loss: {loss}")

        d = L1 - L2
        d_bar = np.mean(d)
        T = len(d)

        # HAC variance with Newey-West (h-1 lags for h-step forecasts)
        max_lag = h - 1 if h > 1 else 1
        nw_var = cov_hac(sm.OLS(d, np.ones(T)).fit(), maxlags=max_lag).params_cov[0, 0]

        dm_stat = d_bar / np.sqrt(nw_var / T)
        p_val = 2 * (1 - stats.norm.cdf(np.abs(dm_stat)))

        return {
            'DM_stat': dm_stat,
            'p_value': p_val,
            'preferred': 'Model 1' if dm_stat < 0 else 'Model 2',
            'significant': p_val < 0.05,
        }

    @classmethod
    def full_evaluation(cls, realized: np.ndarray, forecasts: dict) -> pd.DataFrame:
        """
        Evaluate multiple forecasts on all metrics.

        Args:
            realized: array of realized variances
            forecasts: dict of {model_name: forecast_array}
        """
        rows = []
        benchmark = np.full_like(realized, np.mean(realized))

        for name, fc in forecasts.items():
            mz = cls.mincer_zarnowitz(realized, fc)
            row = {
                'Model': name,
                'MSE': cls.mse(realized, fc),
                'MAE': cls.mae(realized, fc),
                'QLIKE': cls.qlike(realized, fc),
                'R2_OOS': cls.r2_oos(realized, fc, benchmark),
                'MZ_a': mz['a'],
                'MZ_b': mz['b'],
                'MZ_R2': mz['R2'],
                'MZ_Fpval': mz['F_pval'],
                'Efficient': mz['unbiased_eff'],
            }
            rows.append(row)

        df = pd.DataFrame(rows).set_index('Model')
        # Rank by QLIKE (lower is better)
        df['QLIKE_rank'] = df['QLIKE'].rank()

        return df.sort_values('QLIKE')
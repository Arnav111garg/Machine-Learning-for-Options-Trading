import numpy as np
import pandas as pd
from scipy import stats
import statsmodels.api as sm
from typing import Dict, Tuple

class HARModel:
    """
    Comprehensive HAR-RV model family implementation.
    Supports: HAR, LHAR, HAR-J, HAR-RS, CHAR.
    """

    def __init__(self, model_type: str = 'HAR'):
        self.model_type = model_type
        self.params_ = None
        self.residuals_ = None
        self.result_ = None
        self.feature_names_ = None

    def _build_matrix(self, rv: pd.Series, bv: pd.Series = None,
                      rsv_pos: pd.Series = None,
                      rsv_neg: pd.Series = None) -> Tuple[pd.DataFrame, pd.Series]:
        """Build design matrix X and target y."""
        df = pd.DataFrame(index=rv.index)

        # HAR components
        df['rv_d'] = rv
        df['rv_w'] = rv.rolling(5).mean()
        df['rv_m'] = rv.rolling(22).mean()

        if self.model_type == 'LHAR':
            # Log transform (clip to avoid log(0))
            df['rv_d'] = np.log(rv.clip(lower=1e-10))
            df['rv_w'] = np.log(rv.rolling(5).mean().clip(lower=1e-10))
            df['rv_m'] = np.log(rv.rolling(22).mean().clip(lower=1e-10))

        if self.model_type in ('HAR-J', 'CHAR') and bv is not None:
            jump = np.maximum(rv - bv, 0)
            df['jump'] = jump

        if self.model_type == 'HAR-RS' and rsv_pos is not None:
            df['rsv_pos'] = rsv_pos
            df['rsv_neg'] = rsv_neg

        # Target: next day's RV
        if self.model_type == 'LHAR':
            y = np.log(rv.shift(-1).clip(lower=1e-10))
        else:
            y = rv.shift(-1)

        # Add constant
        df.insert(0, 'const', 1.0)

        # Align and drop NaN
        combined = pd.concat([df, y.rename('target')], axis=1).dropna()
        X = combined.drop('target', axis=1)
        y = combined['target']

        return X, y

    def fit(self, rv: pd.Series, **kwargs) -> 'HARModel':
        """Fit HAR model using OLS with Newey-West standard errors."""
        X, y = self._build_matrix(rv, **kwargs)

        # OLS with HAC standard errors
        model = sm.OLS(y, X)
        result = model.fit(cov_type='HAC', cov_kwds={'maxlags': 22, 'use_correction': True})

        self.params_ = result.params
        self.residuals_ = result.resid
        self.result_ = result
        self.feature_names_ = X.columns.tolist()

        return self

    def predict(self, rv: pd.Series, **kwargs) -> pd.Series:
        """Generate forecasts from fitted model."""
        X, _ = self._build_matrix(rv, **kwargs)
        X = X[self.feature_names_]  # ensure column order

        preds = X.dot(self.params_)

        if self.model_type == 'LHAR':
            # Back-transform with Jensen's inequality correction
            sigma2_eps = self.residuals_.var()
            preds = np.exp(preds + 0.5 * sigma2_eps)

        return preds

    def summary(self):
        """Print model summary."""
        if self.result_ is not None:
            print(self.result_.summary())
        else:
            print("Model is not fitted yet.")

    def forecast_interval(self, rv: pd.Series, alpha: float = 0.05, **kwargs) -> pd.DataFrame:
        """
        Compute prediction intervals (approximate, Gaussian).
        Note: for log-models, intervals are in log space then exponentiated.
        """
        X, _ = self._build_matrix(rv, **kwargs)
        X_mat = X[self.feature_names_].values

        hat_mat = X_mat @ np.linalg.pinv(X_mat.T @ X_mat) @ X_mat.T
        var_pred = self.residuals_.var() * (1 + np.diag(hat_mat))

        preds = X.dot(self.params_)
        z = stats.norm.ppf(1 - alpha / 2)

        return pd.DataFrame({
            'forecast': preds,
            'lower': preds - z * np.sqrt(var_pred),
            'upper': preds + z * np.sqrt(var_pred),
        }, index=X.index)

# Example : Estimate and Compare HAR Specifications
def compare_har_specs(rv: pd.Series) -> pd.DataFrame:
    """
    Fit multiple HAR specifications and compare in-sample R^2.
    """
    results = {}
    for spec in ['HAR', 'LHAR']:
        model = HARModel(model_type=spec)
        model.fit(rv)
        r2 = model.result_.rsquared
        aic = model.result_.aic
        bic = model.result_.bic
        results[spec] = {'R2': r2, 'AIC': aic, 'BIC': bic}

    return pd.DataFrame(results).T


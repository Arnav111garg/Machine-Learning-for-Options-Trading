import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.mixture import GaussianMixture

class RegimeConditionalHAR:
    """
    Regime-switching HAR-RV model.
    Supports: VIX-based, threshold-based, and GMM-based regimes.
    """

    def __init__(self, regime_method: str = 'vix',
                 n_regimes: int = 2,
                 threshold: float = None):
        self.regime_method = regime_method
        self.n_regimes = n_regimes
        self.threshold = threshold
        self.models_ = {}
        self.regime_labels_ = {}

    def _assign_regimes(self, rv: pd.Series,
                        vix: pd.Series = None) -> pd.Series:
        """Assign regime labels to each time point."""
        if self.regime_method == 'vix' and vix is not None:
            # VIX-based regime classification
            regimes = pd.cut(
                vix.reindex(rv.index).ffill(),
                bins=[0, 15, 25, 40, np.inf],
                labels=['calm', 'normal', 'stressed', 'crisis']
            )

        elif self.regime_method == 'threshold':
            tau = self.threshold or rv.quantile(0.75)
            regimes = pd.Series(
                np.where(rv > tau, 'high_vol', 'low_vol'),
                index=rv.index
            )

        elif self.regime_method == 'gmm':
            # GMM on log-RV to identify latent regimes
            log_rv = np.log(rv.clip(lower=1e-10)).values.reshape(-1, 1)
            gmm = GaussianMixture(n_components=self.n_regimes, random_state=42)
            labels = gmm.fit_predict(log_rv)

            # Sort regimes by mean (regime 0 = lowest vol)
            means = [log_rv[labels == k].mean() for k in range(self.n_regimes)]
            order = np.argsort(means)
            relabel = {old: new for new, old in enumerate(order)}
            labels = np.array([relabel[l] for l in labels])

            regimes = pd.Series(
                [f'regime_{l}' for l in labels],
                index=rv.index
            )

        return regimes

    def _build_har_features(self, rv: pd.Series) -> pd.DataFrame:
        """Build HAR feature matrix."""
        X = pd.DataFrame({
            'const': 1.0,
            'rv_d': rv,
            'rv_w': rv.rolling(5).mean(),
            'rv_m': rv.rolling(22).mean(),
        }).dropna()
        return X

    def fit(self, rv: pd.Series, vix: pd.Series = None) -> 'RegimeConditionalHAR':
        """Fit regime-specific HAR models."""
        self.regimes_ = self._assign_regimes(rv, vix)
        X = self._build_har_features(rv)
        y = rv.shift(-1)

        # Align
        idx = X.index.intersection(y.dropna().index).intersection(self.regimes_.index)
        X_al = X.loc[idx]
        y_al = y.loc[idx]
        r_al = self.regimes_.loc[idx]

        for regime in r_al.unique():
            mask = r_al == regime
            if mask.sum() < 30: # skip tiny regimes
                continue

            m = LinearRegression(fit_intercept=False)
            m.fit(X_al[mask], y_al[mask])
            self.models_[regime] = m

            n = mask.sum()
            resid_std = np.std(y_al[mask].values - m.predict(X_al[mask]))

            print(f"Regime '{regime}': n={n}, "
                  f"R2={m.score(X_al[mask], y_al[mask]):.3f}, "
                  f"resid_std={resid_std:.6f}")
        return self

    def predict(self, rv: pd.Series,
                vix: pd.Series = None) -> pd.Series:
        """Generate regime-conditional forecasts."""
        regimes = self._assign_regimes(rv, vix)
        X = self._build_har_features(rv)
        idx = X.index.intersection(regimes.index)

        forecasts = pd.Series(np.nan, index=idx)

        for regime in regimes.loc[idx].unique():
            mask = regimes.loc[idx] == regime

            if regime in self.models_:
                m = self.models_[regime]
                forecasts[mask] = m.predict(X.loc[idx][mask])
            else:
                # Fallback: use nearest regime
                forecasts[mask] = np.nan

        return forecasts

# Regime Persistence Analysis
def analyze_regime_persistence(rv: pd.Series, n_regimes: int = 2) -> pd.DataFrame:
    """
    Estimate regime persistence and HAR parameters within each regime.
    Key insight: HAR beta coefficients vary dramatically across regimes.
    """
    model = RegimeConditionalHAR(regime_method='gmm', n_regimes=n_regimes)
    model.fit(rv)

    results = {}
    for regime, m in model.models_.items():
        coefs = pd.Series(m.coef_, index=['const', 'rv_d', 'rv_w', 'rv_m'])
        results[regime] = {
            'persistence': coefs['rv_d'] + coefs['rv_w'] + coefs['rv_m'],
            **coefs.to_dict(),
        }
    return pd.DataFrame(results).T


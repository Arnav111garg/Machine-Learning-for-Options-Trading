import numpy as np
import pandas as pd

def compute_rv(prices: pd.Series, freq: str = '5min') -> pd.Series:
    """
    Compute realized variance from high-frequency prices.

    Args:
        prices: High-frequency price series (DatetimeIndex)
        freq: Resampling frequency for returns

    Returns:
        Daily realized variance series
    """
    # Resample to desired frequency and compute log returns
    log_prices = np.log(prices.resample(freq).last().dropna())
    log_returns = log_prices.diff().dropna()

    # Realized variance = sum of squared intraday returns per day
    rv = log_returns.resample('1D').apply(lambda x: (x ** 2).sum())
    rv = rv[rv > 0]  # Remove non-trading days
    return rv

def compute_bipower_variation(prices: pd.Series, freq: str = '5min') -> pd.Series:
    """
    Compute Bipower Variation (jump-robust RV estimator).
    """
    log_prices = np.log(prices.resample(freq).last().dropna())
    log_returns = log_prices.diff().dropna()

    def bpv_daily(r):
        abs_r = np.abs(r.values)
        if len(abs_r) < 2:
            return np.nan
        return (np.pi / 2) * np.sum(abs_r[1:] * abs_r[:-1])

    bv = log_returns.resample('1D').apply(bpv_daily)
    return bv

def compute_jump_component(rv: pd.Series, bv: pd.Series) -> pd.Series:
    """
    Extract jump component from RV and BV.
    """
    return np.maximum(rv - bv, 0)

def volatility_signature_plot(prices: pd.Series, freqs: list) -> pd.Series:
    """
    Compute RV at multiple frequencies for signature plot.
    """
    results = {}
    for freq in freqs:
        results[freq] = compute_rv(prices, freq).mean()
    return pd.Series(results)


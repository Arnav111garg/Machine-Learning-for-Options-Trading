import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.inspection import permutation_importance
from sklearn.model_selection import TimeSeriesSplit
import warnings
warnings.filterwarnings('ignore')

class RandomForestVolModel:
    """
    Random Forest for volatility forecasting with:
    - Temporal cross-validation
    - Permutation feature importance
    - Prediction intervals via quantile forests
    """

    def __init__(self, n_estimators: int = 500,
                 max_features: str = 'sqrt',
                 min_samples_leaf: int = 20,
                 max_depth: int = None,
                 n_jobs: int = -1):
        self.params = {
            'n_estimators': n_estimators,
            'max_features': max_features,
            'min_samples_leaf': min_samples_leaf,
            'max_depth': max_depth,
            'n_jobs': n_jobs,
            'random_state': 42,
            'oob_score': True,
        }
        self.model_ = None

    def fit(self, X: pd.DataFrame, y: pd.Series) -> 'RandomForestVolModel':
        self.feature_names_ = X.columns.tolist()
        self.model_ = RandomForestRegressor(**self.params)
        self.model_.fit(X.values, y.values)

        print(f"OOB R2 = {self.model_.oob_score_:.4f}")
        return self

    def predict(self, X: pd.DataFrame) -> np.ndarray:
        return self.model_.predict(X[self.feature_names_].values)

    def predict_quantiles(self, X: pd.DataFrame,
                          q_low: float = 0.10,
                          q_high: float = 0.90) -> pd.DataFrame:
        """
        Prediction intervals using quantile regression forests.
        Get predictions from each individual tree, then take quantiles.
        """
        all_preds = np.column_stack([
            tree.predict(X[self.feature_names_].values)
            for tree in self.model_.estimators_
        ]) # shape: (n_samples, n_trees)

        return pd.DataFrame({
            'point': np.mean(all_preds, axis=1),
            'lower': np.quantile(all_preds, q_low, axis=1),
            'upper': np.quantile(all_preds, q_high, axis=1),
        }, index=X.index)

    def permutation_importance_scores(self, X_test: pd.DataFrame,
                                      y_test: pd.Series,
                                      n_repeats: int = 20) -> pd.Series:
        """Compute permutation importance on held-out test set."""
        result = permutation_importance(
            self.model_, X_test[self.feature_names_].values, y_test.values,
            n_repeats=n_repeats, random_state=42,
            scoring='neg_mean_squared_error'
        )
        return pd.Series(
            result.importances_mean,
            index=self.feature_names_,
            name='perm_importance'
        ).sort_values(ascending=False)

    def temporal_cv_score(self, X: pd.DataFrame, y: pd.Series,
                          n_splits: int = 5) -> dict:
        """Time-series cross-validation performance."""
        tscv = TimeSeriesSplit(n_splits=n_splits)
        scores = []

        for train_idx, test_idx in tscv.split(X):
            X_tr, X_te = X.iloc[train_idx], X.iloc[test_idx]
            y_tr, y_te = y.iloc[train_idx], y.iloc[test_idx]

            m = RandomForestRegressor(**self.params)
            m.fit(X_tr.values, y_tr.values)
            preds = m.predict(X_te.values)

            mse = np.mean((y_te.values - preds) ** 2)
            qlike = np.mean(y_te.values / np.maximum(preds, 1e-10)
                            - np.log(y_te.values / np.maximum(preds, 1e-10)) - 1)
            scores.append({'MSE': mse, 'QLIKE': qlike})

        df = pd.DataFrame(scores)
        return {
            'MSE_mean': df.MSE.mean(),
            'MSE_std': df.MSE.std(),
            'QLIKE_mean': df.QLIKE.mean(),
            'QLIKE_std': df.QLIKE.std(),
        }

# Hyperparameter Tuning Example
def tune_rf_hyperparams(X: pd.DataFrame, y: pd.Series) -> dict:
    """
    Simple grid search over key RF hyperparameters
    for volatility forecasting.
    """
    tscv = TimeSeriesSplit(n_splits=5)
    best_score = np.inf
    best_params = {}

    param_grid = {
        'max_features': ['sqrt', 0.33, 0.5],
        'min_samples_leaf': [10, 20, 50],
        'max_depth': [None, 8, 12],
    }

    from itertools import product
    keys = list(param_grid.keys())

    for values in product(*param_grid.values()):
        params = dict(zip(keys, values))
        scores = []

        for tr_idx, te_idx in tscv.split(X):
            m = RandomForestRegressor(
                n_estimators=300, n_jobs=-1, random_state=42,
                **params
            )
            m.fit(X.iloc[tr_idx].values, y.iloc[tr_idx].values)
            preds = m.predict(X.iloc[te_idx].values)
            y_te = y.iloc[te_idx].values
            qlike = np.mean(y_te / np.maximum(preds, 1e-10)
                            - np.log(y_te / np.maximum(preds, 1e-10)) - 1)
            scores.append(qlike)

        mean_score = np.mean(scores)
        if mean_score < best_score:
            best_score = mean_score
            best_params = params

    print(f"Best QLIKE: {best_score:.6f}")
    print(f"Best params: {best_params}")
    return best_params


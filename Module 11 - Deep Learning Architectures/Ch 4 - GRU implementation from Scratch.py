import torch
import torch.nn as nn
import torch.nn.functional as F

class GRUCell(nn.Module):
    """GRU cell implemented from first principles."""
    def __init__(self, input_size, hidden_size):
        super().__init__()
        self.hidden_size = hidden_size
        # Combined weight matrix for efficiency
        self.W_z = nn.Linear(input_size + hidden_size, hidden_size)
        self.W_r = nn.Linear(input_size + hidden_size, hidden_size)
        self.W_h = nn.Linear(input_size + hidden_size, hidden_size)

    def forward(self, x, h_prev):
        """
        x: (batch, input_size)
        h_prev: (batch, hidden_size)
        Returns h_t: (batch, hidden_size)
        """
        xh = torch.cat([x, h_prev], dim=-1)  # [batch, n+m]

        z = torch.sigmoid(self.W_z(xh))      # update gate
        r = torch.sigmoid(self.W_r(xh))      # reset gate

        xh_reset = torch.cat([x, r * h_prev], dim=-1)
        h_cand = torch.tanh(self.W_h(xh_reset))  # candidate

        h_t = (1 - z) * h_prev + z * h_cand  # update
        return h_t


class VolSkewGRU(nn.Module):
    """
    Predicts vol skew dynamics:
    Input: (batch, seq_len, features) where features = [ATM_vol, 25d_skew, 10d_bf, spot_ret]
    Output: (batch, 3) next-day [ATM_vol, 25d_skew, 10d_bf]
    """
    def __init__(self, input_size=4, hidden_size=64, num_layers=2, dropout=0.15):
        super().__init__()
        self.gru = nn.GRU(
            input_size,
            hidden_size,
            num_layers=num_layers,
            batch_first=True,
            dropout=dropout if num_layers > 1 else 0
        )
        self.norm = nn.LayerNorm(hidden_size)
        self.head = nn.Linear(hidden_size, 3)
        # No Softplus: skew can be negative

    def forward(self, x):
        out, _ = self.gru(x)
        last = self.norm(out[:, -1, :])
        return self.head(last)


def compare_lstm_gru():
    """Compare LSTM vs GRU parameter count and speed."""
    n, m, L = 4, 64, 2
    lstm = nn.LSTM(n, m, L, batch_first=True)
    gru = nn.GRU(n, m, L, batch_first=True)

    n_lstm = sum(p.numel() for p in lstm.parameters())
    n_gru = sum(p.numel() for p in gru.parameters())
    print(f"LSTM params: {n_lstm:,} | GRU params: {n_gru:,} | Ratio: {n_lstm / n_gru:.2f}x")

    import time
    x = torch.randn(256, 60, n)
    for name, model in [("LSTM", lstm), ("GRU", gru)]:
        t0 = time.time()
        for _ in range(100):
            out, _ = model(x)
        print(f"{name}: {(time.time() - t0):.3f}s for 100 forward passes")

compare_lstm_gru()


import torch
import torch.nn as nn
import torch.nn.functional as F

class VolSurfaceCNN(nn.Module):
    """
    CNN for volatility surface completion.
    Input: (batch, 2, n_K, n_T) - [observed_surface, mask]
    Output: (batch, 1, n_K, n_T) - completed surface
    """
    def __init__(self, n_K=21, n_T=10):
        super().__init__()
        # Encoder
        self.enc1 = nn.Sequential(
            nn.Conv2d(2, 32, kernel_size=3, padding=1),
            nn.BatchNorm2d(32),
            nn.SiLU()
        )
        self.enc2 = nn.Sequential(
            nn.Conv2d(32, 64, kernel_size=3, padding=1),
            nn.BatchNorm2d(64),
            nn.SiLU()
        )
        self.enc3 = nn.Sequential(
            nn.Conv2d(64, 128, kernel_size=3, padding=1),
            nn.BatchNorm2d(128),
            nn.SiLU()
        )
        # Residual block
        self.res = nn.Sequential(
            nn.Conv2d(128, 128, 3, padding=1),
            nn.SiLU(),
            nn.Conv2d(128, 128, 3, padding=1)
        )
        # Decoder
        self.dec3 = nn.Sequential(
            nn.Conv2d(128, 64, 3, padding=1),
            nn.SiLU()
        )
        self.dec2 = nn.Sequential(
            nn.Conv2d(64, 32, 3, padding=1),
            nn.SiLU()
        )
        self.dec1 = nn.Sequential(
            nn.Conv2d(32, 1, 3, padding=1),
            nn.Softplus()
        ) # Softplus: vol > 0

    def forward(self, x):
        # x: [B, 2, n_K, n_T]
        e1 = self.enc1(x)       # [B, 32, n_K, n_T]
        e2 = self.enc2(e1)      # [B, 64, n_K, n_T]
        e3 = self.enc3(e2)      # [B, 128, n_K, n_T]
        r = e3 + self.res(e3)
        d3 = self.dec3(r)       # [B, 64, n_K, n_T]
        d2 = self.dec2(d3 + e2) # skip connection
        d1 = self.dec1(d2 + e1) # [B, 1, n_K, n_T]
        return d1


def surface_loss(pred, target, mask, vega_weights=None):
    """Weighted MSE: penalize more on liquid (high-vega) points."""
    err = (pred - target) ** 2
    if vega_weights is not None:
        err = err * vega_weights
    # Only penalize on unobserved points for completion
    return (err * (1 - mask)).sum() / ((1 - mask).sum() + 1e-8)

# Demo
model = VolSurfaceCNN(21, 10)
batch_size = 8
x = torch.randn(batch_size, 2, 21, 10)  # [surface, mask]
y = model(x)

import numpy as np

class SimpleNet:
    """3-layer net with ReLU hidden, linear output, MSE loss."""
    def __init__(self, n_in, n_h1, n_h2, n_out, seed=42):
        np.random.seed(seed)
        # He initialization for ReLU
        self.W1 = np.random.randn(n_h1, n_in) * np.sqrt(2.0 / n_in)
        self.b1 = np.zeros((n_h1, 1))
        self.W2 = np.random.randn(n_h2, n_h1) * np.sqrt(2.0 / n_h1)
        self.b2 = np.zeros((n_h2, 1))
        self.W3 = np.random.randn(n_out, n_h2) * np.sqrt(2.0 / n_h2)
        self.b3 = np.zeros((n_out, 1))

    def relu(self, z):
        return np.maximum(0, z)

    def relu_prime(self, z):
        return (z > 0).astype(float)

    def forward(self, X):
        """X shape: (n_in, batch_size)"""
        self.X = X
        self.z1 = self.W1 @ X + self.b1
        self.h1 = self.relu(self.z1)
        self.z2 = self.W2 @ self.h1 + self.b2
        self.h2 = self.relu(self.z2)
        self.z3 = self.W3 @ self.h2 + self.b3
        return self.z3  # linear output

    def backward(self, y):
        """y shape: (n_out, batch_size). Returns gradients dict."""
        m = y.shape[1]
        dL_dz3 = (self.z3 - y) / m  # MSE gradient

        dW3 = dL_dz3 @ self.h2.T
        db3 = dL_dz3.sum(axis=1, keepdims=True)

        dL_dh2 = self.W3.T @ dL_dz3
        dL_dz2 = dL_dh2 * self.relu_prime(self.z2)
        dW2 = dL_dz2 @ self.h1.T
        db2 = dL_dz2.sum(axis=1, keepdims=True)

        dL_dh1 = self.W2.T @ dL_dz2
        dL_dz1 = dL_dh1 * self.relu_prime(self.z1)
        dW1 = dL_dz1 @ self.X.T
        db1 = dL_dz1.sum(axis=1, keepdims=True)

        return {
            'dW1': dW1, 'db1': db1,
            'dW2': dW2, 'db2': db2,
            'dW3': dW3, 'db3': db3
        }

# Gradient check
net = SimpleNet(5, 32, 16, 1)
X = np.random.randn(5, 10)
y = np.random.randn(1, 10)
y_hat = net.forward(X)
grads = net.backward(y)
print("dW1 shape:", grads['dW1'].shape)  # (32, 5)
print("dW3 shape:", grads['dW3'].shape)  # (1, 16)


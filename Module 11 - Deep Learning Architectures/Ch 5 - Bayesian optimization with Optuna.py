import optuna
import torch
import torch.nn as nn
import numpy as np

def objective(trial):
    """Optuna objective for vol surface LSTM hyperparameter search."""
    # Hyperparameter search space
    hidden_size = trial.suggest_categorical('hidden', [64, 128, 256, 512])
    num_layers = trial.suggest_int('num_layers', 1, 4)
    dropout = trial.suggest_float('dropout', 0.0, 0.4)
    lr = trial.suggest_float('lr', 1e-4, 1e-2, log=True)
    weight_decay = trial.suggest_float('wd', 1e-6, 1e-2, log=True)
    batch_size = trial.suggest_categorical('batch', [32, 64, 128])
    seq_len = trial.suggest_categorical('seq_len', [20, 40, 60, 120])

    # Build model
    model = nn.LSTM(
        input_size=10,
        hidden_size=hidden_size,
        num_layers=num_layers,
        batch_first=True,
        dropout=dropout if num_layers > 1 else 0
    )
    head = nn.Sequential(
        nn.Linear(hidden_size, 6),
        nn.Softplus()
    )

    # Simulate training (replace with real data)
    X = torch.randn(500, seq_len, 10)
    y = torch.abs(torch.randn(500, 6) * 0.05 + 0.20)
    split = 400
    X_tr, X_val = X[:split], X[split:]
    y_tr, y_val = y[:split], y[split:]

    optimizer = torch.optim.AdamW(
        list(model.parameters()) + list(head.parameters()),
        lr=lr,
        weight_decay=weight_decay
    )

    best_val = float('inf')
    for epoch in range(50):
        model.train()
        head.train()
        # Mini-batch loop
        idx = torch.randperm(len(X_tr))[:batch_size]
        out, _ = model(X_tr[idx])
        pred = head(out[:, -1, :])
        loss = nn.MSELoss()(pred, y_tr[idx])

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        model.eval()
        head.eval()
        with torch.no_grad():
            out_v, _ = model(X_val)
            pred_v = head(out_v[:, -1, :])
            val_loss = nn.MSELoss()(pred_v, y_val).item()

        if val_loss < best_val:
            best_val = val_loss

        # Optuna pruning: stop unpromising trials early
        trial.report(val_loss, epoch)
        if trial.should_prune():
            raise optuna.exceptions.TrialPruned()

    return best_val

# Run optimization
study = optuna.create_study(
    direction='minimize',
    pruner=optuna.pruners.MedianPruner(n_startup_trials=5, n_warmup_steps=10)
)
study.optimize(objective, n_trials=50, n_jobs=1)
print("Best params:", study.best_params)
print("Best val loss:", study.best_value)


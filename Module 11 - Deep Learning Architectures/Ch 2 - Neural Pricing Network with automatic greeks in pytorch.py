import torch
import torch.nn as nn
import numpy as np

class DeepPricingNet(nn.Module):
    """
    Deep Pricing Network: learns IV surface from (log-moneyness,
    time, vol-time).
    Output: implied volatility (positive via Softplus).
    """
    def __init__(self, n_in=6, hidden=[128, 128, 64], dropout=0.1):
        super().__init__()
        layers = []
        prev = n_in
        for h in hidden:
            layers += [
                nn.Linear(prev, h),
                nn.BatchNorm1d(h),
                nn.SiLU(),  # Swish activation
                nn.Dropout(dropout)
            ]
            prev = h
        layers += [nn.Linear(prev, 1), nn.Softplus()]
        self.net = nn.Sequential(*layers)

    def forward(self, x):
        return self.net(x).squeeze(-1)


def compute_greeks(model, S, K, T, r, q, sigma_atm):
    """Compute option price and greeks via autograd."""
    S = torch.tensor([S], requires_grad=True, dtype=torch.float32)
    K_t = torch.tensor([K], dtype=torch.float32)
    T_t = torch.tensor([T], requires_grad=True, dtype=torch.float32)
    r_t = torch.tensor([r], dtype=torch.float32)
    q_t = torch.tensor([q], dtype=torch.float32)
    sigma_t = torch.tensor([sigma_atm], dtype=torch.float32)

    # Feature engineering
    log_m = torch.log(S / K_t)
    vol_t = sigma_t * torch.sqrt(T_t)

    # Stack along a new dimension at the end to form shape (1, 6)
    x = torch.cat([
        log_m,
        T_t,
        r_t * T_t,
        q_t * T_t,
        vol_t,
        0.5 * sigma_t ** 2 * T_t
    ], dim=-1).unsqueeze(0)

    iv = model(x)

    # BSM price from predicted IV
    d1 = (log_m + (r_t - q_t + 0.5 * iv ** 2) * T_t) / (iv * torch.sqrt(T_t))
    d2 = d1 - iv * torch.sqrt(T_t)
    from torch.distributions import Normal
    N = Normal(0, 1)
    price = (S * torch.exp(-q_t * T_t) * N.cdf(d1)
             - K_t * torch.exp(-r_t * T_t) * N.cdf(d2))

    # Delta
    delta = torch.autograd.grad(price, S, create_graph=True)[0]
    # Gamma (2nd order)
    gamma = torch.autograd.grad(delta, S, create_graph=True)[0]
    # Theta
    theta = torch.autograd.grad(price, T_t)[0]

    return {
        'price': price.item(),
        'delta': delta.item(),
        'gamma': gamma.item(),
        'theta': theta.item(),
        'iv': iv.item()
    }

# Example usage
model = DeepPricingNet()
model.eval()  # Switch batch norm and dropout to evaluation mode
greeks = compute_greeks(
    model, S=100., K=100., T=0.25,
    r=0.05, q=0.0, sigma_atm=0.20
)
print(greeks)

